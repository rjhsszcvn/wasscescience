<h3>11.1 Definitions</h3>
<ul>
<li><strong>Growth:</strong> An increase in size, weight, or dimensions of the body or its parts. Growth is quantitative and measurable.</li>
<li><strong>Development:</strong> The progressive acquisition of skills, abilities, and functions. Development is qualitative and relates to the complexity of behaviour and function.</li>
<li><strong>Maturation:</strong> The genetically programmed sequence of changes in the body over time, independent of experience.</li>
</ul>

<h3>11.2 Principles of Growth and Development</h3>
<ul>
<li>Growth follows a predictable, orderly sequence (cephalocaudal: head to toe; proximodistal: centre to periphery)</li>
<li>Growth and development are continuous processes but occur at different rates at different times</li>
<li>Growth spurts occur in infancy and adolescence</li>
<li>Individual variation exists within normal ranges</li>
<li>Development is influenced by both heredity (nature) and environment (nurture)</li>
<li>Critical periods exist when specific stimulation is most important (e.g., language acquisition)</li>
</ul>

<h3>11.3 Stages of Human Growth and Development</h3>

<h4>11.3.1 Prenatal Period (Conception to Birth)</h4>
<ul>
<li><strong>Germinal period:</strong> Fertilization to implantation (0-2 weeks)</li>
<li><strong>Embryonic period:</strong> 3-8 weeks - critical period for organ formation (organogenesis); most vulnerable to teratogens</li>
<li><strong>Foetal period:</strong> 9 weeks to birth - growth and maturation of organs; foetus reaches viability around 24 weeks</li>
</ul>

<p><strong>Teratogens</strong> are agents that can cause birth defects:</p>
<ul>
<li>Alcohol (foetal alcohol syndrome)</li>
<li>Tobacco (low birth weight, preterm birth)</li>
<li>Rubella virus (congenital deafness, blindness, heart defects)</li>
<li>Certain drugs (thalidomide caused limb defects)</li>
<li>Radiation</li>
<li>Nutritional deficiencies (folic acid deficiency causes neural tube defects)</li>
</ul>

<h4>11.3.2 Neonatal/Newborn Period (0-4 weeks)</h4>
<ul>
<li>Rapid physiological adjustment to extrauterine life</li>
<li>Dependent entirely on caregivers</li>
<li>Reflexes present: rooting (turns head towards touch on cheek), sucking, Moro (startle), grasp, Babinski</li>
<li>Average birth weight: 2.5-4.0 kg; length: 48-52 cm</li>
</ul>

<h4>11.3.3 Infancy (0-1 year)</h4>
<p><strong>Physical growth:</strong> Birth weight doubles by 5 months, triples by 12 months; length increases by 50% in first year; head circumference increases by 12 cm</p>
<p><strong>Motor development milestones:</strong></p>
<ul>
<li>1-3 months: Holds head up briefly, smiles socially</li>
<li>4-6 months: Rolls over, sits with support, reaches for objects</li>
<li>7-9 months: Sits alone, crawls, pincer grasp developing</li>
<li>10-12 months: Stands with support, first words, waves bye-bye</li>
</ul>

<h4>11.3.4 Toddlerhood (1-3 years)</h4>
<ul>
<li>Walking independently achieved (usually 12-15 months)</li>
<li>Rapid language development (50+ words by 2 years, short sentences)</li>
<li>Toilet training (sphincter control develops)</li>
<li>Separation anxiety, autonomy vs. shame (Erikson)</li>
<li>Parallel play (play alongside, not with, other children)</li>
</ul>

<h4>11.3.5 Preschool Age (3-6 years)</h4>
<ul>
<li>Improved motor skills (runs, jumps, draws, dresses self)</li>
<li>Language skills develop rapidly; 2,000+ words by age 6</li>
<li>Magical thinking; vivid imagination</li>
<li>Social skills develop; cooperative play</li>
<li>Erikson stage: Initiative vs. Guilt</li>
</ul>

<h4>11.3.6 School Age (6-12 years)</h4>
<ul>
<li>Steady growth; girls begin puberty earlier than boys</li>
<li>Permanent teeth erupt (starts around age 6)</li>
<li>Logical thinking develops (Piaget: concrete operational stage)</li>
<li>Peer relationships become important</li>
<li>Erikson stage: Industry vs. Inferiority</li>
</ul>

<h4>11.3.7 Adolescence (12-18 years)</h4>
<p>Adolescence is the transition from childhood to adulthood, characterized by rapid physical, cognitive, and psychosocial changes triggered by puberty.</p>

<p><strong>Puberty</strong> is the process of physical changes through which a child becomes sexually mature and capable of reproduction.</p>

<p><strong>Hormonal control:</strong> The hypothalamus releases GnRH, which stimulates the pituitary to release LH and FSH, which stimulate the gonads to produce sex hormones.</p>

<p><strong>Puberty in Males:</strong></p>
<ul>
<li>Begins: 9-14 years; completed: 17-18 years</li>
<li>Testicular enlargement (first sign)</li>
<li>Pubic, axillary, facial hair growth</li>
<li>Penis and scrotal enlargement</li>
<li>Voice deepening (laryngeal growth)</li>
<li>Height spurt (peak: 13-14 years)</li>
<li>Spermarche (first ejaculation)</li>
<li>Increased muscle mass</li>
</ul>

<p><strong>Puberty in Females:</strong></p>
<ul>
<li>Begins: 8-13 years; completed: 15-17 years</li>
<li>Breast development (thelarche - first sign)</li>
<li>Pubic and axillary hair growth</li>
<li>Height spurt (peak: 11-12 years)</li>
<li>Widening of hips (pelvis growth)</li>
<li>Menarche (first menstrual period) - average age 12-13 years</li>
<li>Increased body fat percentage</li>
</ul>

<p><strong>Tanner Stages:</strong> A 5-stage classification system for physical development during puberty (Stage 1: prepubertal; Stage 5: adult)</p>

<p><strong>Psychosocial Development in Adolescence:</strong></p>
<ul>
<li>Identity formation (Erikson: Identity vs. Role Confusion)</li>
<li>Abstract thinking develops (Piaget: formal operational stage)</li>
<li>Peer group becomes primary social reference</li>
<li>Risk-taking behaviour; experimentation</li>
<li>Developing autonomy from parents</li>
</ul>

<h4>11.3.8 Adulthood and Ageing</h4>
<p><strong>Young adulthood (18-40):</strong> Peak physical performance; career and family formation (Erikson: Intimacy vs. Isolation)</p>
<p><strong>Middle adulthood (40-65):</strong> Gradual decline in physical abilities; menopause in women (cessation of menstruation); generativity (Erikson)</p>
<p><strong>Late adulthood (65+):</strong> Ageing process; decreased organ reserve; increased vulnerability to chronic diseases; sensory decline</p>

<h3>11.4 Assessment of Growth</h3>
<p><strong>Anthropometric measurements:</strong></p>
<ul>
<li><strong>Weight:</strong> Total body mass; measured in kg</li>
<li><strong>Height/Length:</strong> Measured in cm; length (lying) for under-2; standing height for over-2</li>
<li><strong>Head circumference:</strong> Important for assessing brain growth in children under 3</li>
<li><strong>Mid-upper arm circumference (MUAC):</strong> Used to assess nutritional status; below 12.5 cm indicates severe acute malnutrition</li>
<li><strong>Body Mass Index (BMI):</strong> Weight (kg) divided by height squared (m2); underweight below 18.5, normal 18.5-24.9, overweight 25-29.9, obese 30+</li>
</ul>

<p><strong>Growth charts:</strong> Plot weight, height, and head circumference against age on standardized curves; used to identify growth faltering.</p>

