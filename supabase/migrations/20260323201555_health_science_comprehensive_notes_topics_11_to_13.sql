<h3>13.1 Definition and Scope of Epidemiology</h3>
<p><strong>Epidemiology</strong> is the study of the distribution and determinants of health-related states and events in specified populations, and the application of this study to control health problems (Last, 2001).</p>

<p>Epidemiology answers three fundamental questions:</p>
<ol>
<li><strong>Who</strong> is affected? (Distribution by person: age, sex, ethnicity, occupation)</li>
<li><strong>Where</strong> are they affected? (Distribution by place: geographic patterns)</li>
<li><strong>When</strong> does it occur? (Distribution by time: trends, seasonal patterns)</li>
</ol>

<p>The "epidemiological triad" identifies three factors required for disease to occur:</p>
<ul>
<li><strong>Agent:</strong> The causative factor (pathogen, chemical, radiation)</li>
<li><strong>Host:</strong> The susceptible individual</li>
<li><strong>Environment:</strong> External factors that bring agent and host together</li>
</ul>

<h3>13.2 Epidemiological Measures</h3>

<h4>Measures of Disease Frequency</h4>
<ul>
<li><strong>Incidence:</strong> The number of new cases of a disease occurring in a population during a specific period
  <ul>
  <li>Incidence rate = (New cases / Population at risk) x multiplier (1,000 or 100,000)</li>
  <li>Useful for studying acute diseases and causes of disease</li>
  </ul>
</li>
<li><strong>Prevalence:</strong> The proportion of a population with a disease at a specific point in time (point prevalence) or during a period (period prevalence)
  <ul>
  <li>Prevalence = Cases / Total population x multiplier</li>
  <li>Useful for chronic diseases; helps plan healthcare resources</li>
  </ul>
</li>
</ul>

<p><strong>Relationship:</strong> Prevalence = Incidence x Duration of disease</p>

<h4>Mortality Measures</h4>
<ul>
<li><strong>Crude death rate (CDR):</strong> Total deaths per 1,000 population per year</li>
<li><strong>Cause-specific mortality rate:</strong> Deaths from a specific cause per 100,000 population</li>
<li><strong>Case fatality rate (CFR):</strong> Proportion of people diagnosed with a disease who die from it (measures severity)</li>
<li><strong>Infant mortality rate (IMR):</strong> Deaths under 1 year per 1,000 live births</li>
<li><strong>Under-5 mortality rate (U5MR):</strong> Deaths under 5 years per 1,000 live births; key child health indicator</li>
<li><strong>Maternal mortality ratio (MMR):</strong> Maternal deaths per 100,000 live births</li>
</ul>

<h3>13.3 Epidemiological Study Designs</h3>

<h4>Descriptive Studies</h4>
<p>Describe the distribution of disease by person, place, and time. Generate hypotheses but cannot establish causation.</p>
<ul>
<li><strong>Case reports/case series:</strong> Description of individual cases or a group of cases</li>
<li><strong>Cross-sectional surveys:</strong> Measure prevalence at a single point in time</li>
<li><strong>Ecological studies:</strong> Compare disease rates across different populations or time periods</li>
</ul>

<h4>Analytical Studies</h4>
<p>Test hypotheses about the relationship between exposure and disease.</p>

<table>
<tr><th>Study Type</th><th>Design</th><th>Strengths</th><th>Weaknesses</th></tr>
<tr><td>Case-Control Study</td><td>Compare past exposures in people with disease (cases) vs. without (controls); looks backward</td><td>Good for rare diseases; quick and cheap; multiple exposures studied</td><td>Recall bias; cannot calculate incidence; not good for rare exposures</td></tr>
<tr><td>Cohort Study</td><td>Follow exposed and unexposed groups forward over time to see who develops disease</td><td>Establishes temporal sequence; can calculate incidence and risk</td><td>Time-consuming, expensive; not good for rare diseases; loss to follow-up</td></tr>
<tr><td>Randomized Controlled Trial (RCT)</td><td>Participants randomly assigned to intervention or control group; gold standard</td><td>Eliminates confounding; strongest evidence for causation</td><td>Expensive; ethical limitations; may not reflect real world</td></tr>
</table>

<h4>Measures of Association</h4>
<ul>
<li><strong>Relative Risk (RR):</strong> Used in cohort studies; ratio of incidence in exposed vs. unexposed; RR above 1 = increased risk; RR below 1 = protective</li>
<li><strong>Odds Ratio (OR):</strong> Used in case-control studies; approximates RR when disease is rare</li>
</ul>

<h3>13.4 Outbreak Investigation</h3>
<p>An <strong>outbreak</strong> is an occurrence of cases of a disease in excess of normal expectation in a specific area and time period. An <strong>epidemic</strong> is a widespread outbreak; a <strong>pandemic</strong> is a global epidemic.</p>

<p><strong>Steps in Outbreak Investigation:</strong></p>
<ol>
<li>Confirm the diagnosis (laboratory testing)</li>
<li>Establish a case definition (clinical criteria + epidemiological criteria)</li>
<li>Find cases systematically (active case finding)</li>
<li>Describe cases by person, place, and time (epidemic curve)</li>
<li>Develop hypotheses about the source and mode of transmission</li>
<li>Test hypotheses (analytical study)</li>
<li>Implement control measures</li>
<li>Communicate findings</li>
</ol>

<p><strong>Epidemic Curves:</strong></p>
<ul>
<li><strong>Point source epidemic:</strong> Steep rise and fall; all cases exposed to source at one time (e.g., food poisoning at a single event)</li>
<li><strong>Propagated epidemic:</strong> Multiple peaks; person-to-person transmission (e.g., measles outbreak)</li>
<li><strong>Continuous source epidemic:</strong> Prolonged exposure to ongoing contaminated source (e.g., contaminated water supply)</li>
</ul>

<h3>13.5 Screening</h3>
<p><strong>Screening</strong> is the systematic application of a test to identify individuals at sufficient risk of a specific disorder to benefit from further investigation or preventive action.</p>

<p><strong>Criteria for a Good Screening Programme (Wilson and Jungner criteria):</strong></p>
<ul>
<li>The condition should be an important health problem</li>
<li>The natural history should be understood</li>
<li>There should be a recognizable early or latent stage</li>
<li>Treatment at an early stage should be more beneficial than treatment at a later stage</li>
<li>A suitable test should exist</li>
<li>The test should be acceptable to the population</li>
<li>Adequate facilities for diagnosis and treatment should be available</li>
<li>The cost should be economically balanced against benefits</li>
</ul>

<p><strong>Properties of a Good Screening Test:</strong></p>
<ul>
<li><strong>Sensitivity:</strong> Ability to correctly identify those WITH the disease (true positive rate); high sensitivity minimizes false negatives</li>
<li><strong>Specificity:</strong> Ability to correctly identify those WITHOUT the disease (true negative rate); high specificity minimizes false positives</li>
<li><strong>Positive Predictive Value (PPV):</strong> Proportion of positive test results that are true positives (depends on prevalence)</li>
<li><strong>Negative Predictive Value (NPV):</strong> Proportion of negative test results that are true negatives</li>
</ul>

<h3>13.6 Levels of Prevention (Detailed)</h3>

<h4>Primordial Prevention</h4>
<p>Prevention of the emergence of risk factors - addressing underlying social, economic, and cultural conditions that contribute to risk (e.g., policies to reduce poverty, obesity, tobacco use at population level).</p>

<h4>Primary Prevention</h4>
<p>Prevention in healthy people before disease occurs. Examples:</p>
<ul>
<li>Immunization programmes</li>
<li>Health education (nutrition, hygiene, safe sex)</li>
<li>Environmental sanitation</li>
<li>Tobacco and alcohol control policies</li>
<li>Fluoridation of water</li>
<li>Occupational safety measures</li>
</ul>

<h4>Secondary Prevention</h4>
<p>Early detection and treatment. Examples:</p>
<ul>
<li>Blood pressure screening</li>
<li>Mammography for breast cancer</li>
<li>Pap smear for cervical cancer</li>
<li>Newborn screening (sickle cell, PKU)</li>
<li>Vision and hearing testing in schools</li>
</ul>

<h4>Tertiary Prevention</h4>
<p>Reducing impact of established disease. Examples:</p>
<ul>
<li>Cardiac rehabilitation after heart attack</li>
<li>Physiotherapy after stroke</li>
<li>Dialysis for chronic kidney disease</li>
<li>Support groups for mental health conditions</li>
</ul>

