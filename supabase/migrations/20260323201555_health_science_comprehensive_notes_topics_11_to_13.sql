<h3>12.1 Fundamentals of Genetics</h3>
<p><strong>Genetics</strong> is the science of heredity - the study of genes, genetic variation, and how traits are passed from parents to offspring.</p>

<h4>Key Terms</h4>
<ul>
<li><strong>Gene:</strong> A segment of DNA that codes for a specific protein or trait</li>
<li><strong>Chromosome:</strong> A condensed structure made of DNA and proteins; humans have 46 chromosomes (23 pairs)</li>
<li><strong>Autosomes:</strong> The 22 pairs of non-sex chromosomes</li>
<li><strong>Sex chromosomes:</strong> The 23rd pair (XX = female, XY = male)</li>
<li><strong>Allele:</strong> Alternative forms of a gene at the same locus on homologous chromosomes</li>
<li><strong>Genotype:</strong> The genetic make-up of an organism (e.g., AA, Aa, aa)</li>
<li><strong>Phenotype:</strong> The observable physical/biochemical expression of genes</li>
<li><strong>Dominant allele:</strong> Expressed in heterozygous state; usually denoted by capital letter (A)</li>
<li><strong>Recessive allele:</strong> Only expressed when homozygous; denoted by lowercase letter (a)</li>
<li><strong>Homozygous:</strong> Two identical alleles (AA or aa)</li>
<li><strong>Heterozygous:</strong> Two different alleles (Aa)</li>
<li><strong>Carrier:</strong> A heterozygous individual who carries a recessive allele but does not express the trait</li>
</ul>

<h3>12.2 DNA Structure and Function</h3>
<p>DNA (Deoxyribonucleic acid) is the hereditary material in all living organisms. It is a double helix made of nucleotides, each consisting of a phosphate group, deoxyribose sugar, and a nitrogenous base.</p>

<p><strong>Nitrogenous Bases (complementary base pairing):</strong></p>
<ul>
<li>Adenine (A) pairs with Thymine (T)</li>
<li>Guanine (G) pairs with Cytosine (C)</li>
</ul>

<p><strong>Central Dogma of Molecular Biology:</strong> DNA is transcribed to RNA, which is translated into protein. Genes control traits through protein synthesis.</p>

<h3>12.3 Patterns of Inheritance</h3>

<h4>Autosomal Dominant</h4>
<p>Only one copy of the mutant allele is needed to express the condition. The condition appears in every generation.</p>
<p><strong>Examples:</strong> Huntington disease, Marfan syndrome, achondroplasia (dwarfism), neurofibromatosis, familial hypercholesterolaemia</p>
<p><strong>Key features:</strong> Affected individuals have one affected parent (usually); affects males and females equally; 50% risk of passing to each child if one parent affected</p>

<h4>Autosomal Recessive</h4>
<p>Two copies of the mutant allele are needed (homozygous) to express the condition. Carriers (heterozygous) are unaffected.</p>
<p><strong>Examples:</strong> Sickle cell disease, cystic fibrosis, phenylketonuria (PKU), albinism, Tay-Sachs disease</p>
<p><strong>Key features:</strong> Parents of affected children are usually unaffected carriers; risk of affected child when both parents are carriers: 25% (1 in 4); more common in consanguineous (related) couples and certain populations</p>

<h4>X-Linked Recessive</h4>
<p>Gene located on X chromosome; males are affected (only one X), females are carriers.</p>
<p><strong>Examples:</strong> Haemophilia A (factor VIII deficiency), Haemophilia B (factor IX deficiency), Duchenne muscular dystrophy, colour blindness, glucose-6-phosphate dehydrogenase deficiency (G6PD)</p>
<p><strong>Key features:</strong> Mostly affects males; females are carriers (X(carrier)X); carrier mother has 50% chance of affected son; affected father passes X chromosome to all daughters (who become carriers)</p>

<h4>X-Linked Dominant</h4>
<p>Dominant allele on X chromosome; affects both males and females but more severe in males.</p>
<p><strong>Example:</strong> Vitamin D-resistant rickets, Rett syndrome</p>

<h3>12.4 Major Hereditary Diseases in Ghana/West Africa</h3>

<h4>Sickle Cell Disease (SCD)</h4>
<p><strong>Genetics:</strong> Autosomal recessive; caused by a point mutation in the HBB gene (chromosome 11) - glutamic acid replaced by valine at position 6 of the beta-globin chain, producing haemoglobin S (HbS)</p>

<p><strong>Genotypes:</strong></p>
<ul>
<li>HbAA: Normal (no sickle alleles)</li>
<li>HbAS: Sickle cell trait (carrier) - usually asymptomatic; some protection against malaria</li>
<li>HbSS: Sickle cell disease - symptomatic</li>
<li>HbSC, HbS-beta thalassaemia: Other sickle cell conditions</li>
</ul>

<p><strong>Pathophysiology:</strong> Under low oxygen conditions, HbS polymerizes, causing red blood cells to become rigid and sickle-shaped. Sickled cells cause vaso-occlusion (blockage of blood vessels), haemolysis (destruction of red blood cells), chronic anaemia.</p>

<p><strong>Clinical Features:</strong></p>
<ul>
<li><strong>Vaso-occlusive crises:</strong> Severe pain in bones, joints, chest, abdomen - most common complication</li>
<li><strong>Acute chest syndrome:</strong> Chest pain, fever, respiratory distress - a medical emergency</li>
<li><strong>Stroke:</strong> 10% risk in children; leading cause of childhood stroke in Africa</li>
<li><strong>Splenic sequestration:</strong> Sudden pooling of blood in spleen; life-threatening in young children</li>
<li><strong>Aplastic crisis:</strong> Temporary bone marrow failure (often triggered by parvovirus B19 infection)</li>
<li><strong>Chronic organ damage:</strong> Kidney, liver, retina, bone (avascular necrosis)</li>
<li><strong>Increased infection risk:</strong> Functional asplenia (spleen loses function)</li>
<li><strong>Growth retardation, delayed puberty</strong></li>
</ul>

<p><strong>Precipitating factors for crises:</strong> Dehydration, infection, cold exposure, physical stress, hypoxia (e.g., at altitude)</p>

<p><strong>Management:</strong></p>
<ul>
<li>Hydroxyurea (increases HbF levels - protective)</li>
<li>Folic acid supplementation</li>
<li>Penicillin prophylaxis (prevent pneumococcal infection)</li>
<li>Pneumococcal and other vaccines</li>
<li>Adequate hydration, avoidance of triggers</li>
<li>Blood transfusion for severe anaemia, stroke prevention</li>
<li>Bone marrow transplant (curative but limited availability)</li>
</ul>

<p><strong>Prevention:</strong> Genetic counselling for couples at risk; newborn screening; premarital sickle cell testing</p>

<p><strong>Sickle Cell Genetics Example:</strong> If both parents are carriers (HbAS x HbAS):</p>
<ul>
<li>25% chance HbAA (normal)</li>
<li>50% chance HbAS (carrier)</li>
<li>25% chance HbSS (sickle cell disease)</li>
</ul>

<h4>G6PD Deficiency</h4>
<p><strong>Genetics:</strong> X-linked recessive; deficiency of glucose-6-phosphate dehydrogenase enzyme in red blood cells</p>
<p><strong>Clinical significance:</strong> Haemolytic anaemia triggered by oxidative stress (malaria drugs like primaquine, aspirin, fava beans, infections)</p>
<p><strong>Prevalence:</strong> High in malaria-endemic regions; provides some protection against malaria</p>

<h3>12.5 Chromosomal Abnormalities</h3>

<h4>Down Syndrome (Trisomy 21)</h4>
<p><strong>Cause:</strong> Extra copy of chromosome 21 (47 chromosomes); most common chromosomal abnormality</p>
<p><strong>Cause:</strong> Usually non-disjunction during meiosis (chromosomes fail to separate)</p>
<p><strong>Risk factor:</strong> Increases with advanced maternal age (especially after 35)</p>
<p><strong>Features:</strong> Intellectual disability, flat facial profile, upslanting eyes (epicanthal folds), single palmar crease, congenital heart defects (40-50%), hypotonia (low muscle tone), short stature</p>
<p><strong>Diagnosis:</strong> Karyotype analysis; prenatal screening (Down syndrome triple/quadruple test, nuchal translucency ultrasound, amniocentesis, chorionic villus sampling)</p>

<h4>Turner Syndrome (45, X)</h4>
<p>Affects females; missing one X chromosome. Features: short stature, webbed neck, shield chest, primary amenorrhoea (absent periods), infertility, coarctation of aorta</p>

<h4>Klinefelter Syndrome (47, XXY)</h4>
<p>Affects males; extra X chromosome. Features: tall stature, small testes, infertility, gynaecomastia (breast development), reduced testosterone</p>

<h3>12.6 Genetic Counselling</h3>
<p>A communication process that informs and supports individuals and families about hereditary conditions. It includes risk assessment, explanation of inheritance patterns, options for testing and management, and psychosocial support.</p>

<p><strong>When genetic counselling is recommended:</strong></p>
<ul>
<li>Family history of genetic disorder</li>
<li>Advanced maternal age (above 35 years)</li>
<li>Previous child with chromosomal or genetic condition</li>
<li>Consanguinity (closely related parents)</li>
<li>Recurrent miscarriages</li>
<li>Positive prenatal screening test</li>
</ul>

