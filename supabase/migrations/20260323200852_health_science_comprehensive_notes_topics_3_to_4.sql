<h3>4.1 Definition and Key Concepts</h3>
<p><strong>Communicable disease</strong> (also called infectious disease or contagious disease) is a disease caused by a pathogenic microorganism (bacteria, virus, parasite, or fungus) that can be transmitted directly or indirectly from one person to another, from animals to humans, or through vectors.</p>

<p><strong>Key Terms:</strong></p>
<ul>
<li><strong>Pathogen:</strong> A microorganism that causes disease</li>
<li><strong>Host:</strong> The organism that harbours the pathogen</li>
<li><strong>Reservoir:</strong> The natural habitat of a pathogen (humans, animals, environment)</li>
<li><strong>Incubation period:</strong> Time from exposure to pathogen until symptoms appear</li>
<li><strong>Infectivity:</strong> The ability of a pathogen to establish infection</li>
<li><strong>Virulence:</strong> The degree of pathogenicity (ability to cause disease)</li>
<li><strong>Carrier:</strong> A person who harbours a pathogen without showing symptoms but can transmit it</li>
<li><strong>Epidemic:</strong> Sudden increase in disease cases in a specific area above normal expected levels</li>
<li><strong>Pandemic:</strong> A global epidemic affecting multiple countries/continents</li>
<li><strong>Endemic:</strong> A disease constantly present at a baseline level in a population or area</li>
</ul>

<h3>4.2 The Chain of Infection</h3>
<p>Disease transmission requires an unbroken chain of six links. Breaking any link prevents transmission.</p>
<ol>
<li><strong>Infectious Agent:</strong> The pathogen (bacteria, virus, fungus, parasite)</li>
<li><strong>Reservoir:</strong> Where the pathogen normally lives (human, animal, environment)</li>
<li><strong>Portal of Exit:</strong> How the pathogen leaves the reservoir (respiratory tract, GI tract, skin, blood)</li>
<li><strong>Mode of Transmission:</strong> How the pathogen moves to a new host (contact, droplet, airborne, vehicle, vector)</li>
<li><strong>Portal of Entry:</strong> How the pathogen enters the new host (respiratory tract, GI tract, skin, mucous membranes)</li>
<li><strong>Susceptible Host:</strong> A person without immunity to the pathogen</li>
</ol>

<h3>4.3 Modes of Transmission</h3>

<h4>Direct Transmission</h4>
<ul>
<li><strong>Direct contact:</strong> Physical touching (skin-to-skin, sexual contact) - e.g., syphilis, gonorrhoea, ringworm</li>
<li><strong>Droplet spread:</strong> Large respiratory droplets within 1 metre - e.g., influenza, COVID-19, meningitis</li>
<li><strong>Vertical transmission:</strong> Mother to child (in utero, during birth, breastfeeding) - e.g., HIV, hepatitis B, syphilis</li>
</ul>

<h4>Indirect Transmission</h4>
<ul>
<li><strong>Airborne:</strong> Droplet nuclei (small particles) suspended in air for long distances - e.g., tuberculosis, measles, chickenpox</li>
<li><strong>Vehicle-borne:</strong> Through contaminated inanimate objects (fomites), water, food, or blood - e.g., cholera (water), salmonella (food), hepatitis B (blood)</li>
<li><strong>Vector-borne:</strong> Through living organisms (biological: pathogen multiplies in vector; mechanical: pathogen carried on surface) - e.g., malaria (Anopheles mosquito), dengue (Aedes mosquito)</li>
</ul>

<h3>4.4 Major Communicable Diseases</h3>

<h4>4.4.1 Malaria</h4>
<p><strong>Causative agent:</strong> Plasmodium species (P. falciparum is most dangerous)</p>
<p><strong>Vector:</strong> Female Anopheles mosquito (bites at dusk and dawn)</p>
<p><strong>Transmission:</strong> Bite of infected female Anopheles mosquito</p>
<p><strong>Incubation period:</strong> 7-14 days (P. falciparum), longer for other species</p>
<p><strong>Signs and Symptoms:</strong></p>
<ul>
<li>Cyclical fever (every 48 hours for P. falciparum), chills, rigors (shivering attacks)</li>
<li>Headache, muscle aches, fatigue</li>
<li>Nausea, vomiting, anaemia, splenomegaly (enlarged spleen)</li>
<li>Severe malaria: cerebral malaria (coma, convulsions), severe anaemia, respiratory distress</li>
</ul>
<p><strong>Prevention:</strong> Insecticide-treated nets (ITNs), indoor residual spraying (IRS), environmental management (draining stagnant water), chemoprophylaxis, intermittent preventive treatment in pregnancy (IPTp)</p>
<p><strong>Treatment:</strong> Artemisinin-based combination therapy (ACT) is first-line; intravenous artesunate for severe malaria</p>

<h4>4.4.2 Tuberculosis (TB)</h4>
<p><strong>Causative agent:</strong> Mycobacterium tuberculosis (gram-positive, acid-fast bacillus)</p>
<p><strong>Transmission:</strong> Airborne (inhaling droplet nuclei from coughing, sneezing, or talking of infected person)</p>
<p><strong>Incubation period:</strong> 2-10 weeks (though infection may remain latent for years)</p>
<p><strong>Signs and Symptoms (Pulmonary TB):</strong></p>
<ul>
<li>Persistent cough lasting more than 2 weeks</li>
<li>Blood-stained sputum (haemoptysis)</li>
<li>Night sweats, fever</li>
<li>Weight loss, fatigue, loss of appetite</li>
<li>Chest pain, shortness of breath</li>
</ul>
<p><strong>Diagnosis:</strong> Sputum smear microscopy (ZN staining), GeneXpert MTB/RIF, chest X-ray, Mantoux test</p>
<p><strong>Treatment:</strong> DOTS (Directly Observed Treatment, Short-course) - 6 months of combination antibiotics (Isoniazid, Rifampicin, Pyrazinamide, Ethambutol)</p>
<p><strong>Prevention:</strong> BCG vaccination in infancy, early diagnosis and treatment, improved ventilation, nutritional support</p>

<h4>4.4.3 HIV/AIDS</h4>
<p><strong>Causative agent:</strong> Human Immunodeficiency Virus (HIV) - type 1 and type 2</p>
<p><strong>Transmission:</strong></p>
<ul>
<li>Unprotected sexual intercourse with infected person</li>
<li>Blood transfusion with infected blood or sharing of needles</li>
<li>Mother to child (vertical transmission) - during pregnancy, childbirth, or breastfeeding</li>
</ul>
<p><strong>NOT transmitted by:</strong> casual contact, shaking hands, sharing utensils, mosquito bites, coughing, or sneezing</p>
<p><strong>Pathophysiology:</strong> HIV attacks and destroys CD4+ T lymphocytes (helper T cells), progressively weakening the immune system. AIDS (Acquired Immunodeficiency Syndrome) is the final stage, diagnosed when CD4 count falls below 200 cells/microlitre or when AIDS-defining illnesses occur.</p>
<p><strong>Stages of HIV Infection:</strong></p>
<ol>
<li>Acute HIV infection (2-4 weeks after exposure): flu-like symptoms, high viral load</li>
<li>Clinical latency (asymptomatic stage): may last years; virus still active but controlled</li>
<li>AIDS: CD4 count below 200, opportunistic infections (TB, PCP, candidiasis, CMV)</li>
</ol>
<p><strong>Prevention (ABCDE):</strong></p>
<ul>
<li><strong>A</strong>bstinence from sexual intercourse</li>
<li><strong>B</strong>e faithful to one uninfected partner</li>
<li><strong>C</strong>ondom use consistently and correctly</li>
<li><strong>D</strong>on not share needles or syringes</li>
<li><strong>E</strong>ducation and testing</li>
</ul>
<p>Additional prevention: Prevention of Mother-to-Child Transmission (PMTCT), Pre-Exposure Prophylaxis (PrEP), Post-Exposure Prophylaxis (PEP)</p>
<p><strong>Treatment:</strong> Antiretroviral therapy (ART) - suppresses viral load, preserves immune function, not a cure. Common regimens include nucleoside reverse transcriptase inhibitors (NRTIs), non-nucleoside reverse transcriptase inhibitors (NNRTIs), and protease inhibitors.</p>

<h4>4.4.4 Cholera</h4>
<p><strong>Causative agent:</strong> Vibrio cholerae (gram-negative comma-shaped bacterium)</p>
<p><strong>Transmission:</strong> Faecal-oral route (contaminated water and food)</p>
<p><strong>Incubation period:</strong> 2 hours to 5 days</p>
<p><strong>Signs and Symptoms:</strong></p>
<ul>
<li>Sudden onset of profuse watery diarrhoea ("rice water stools")</li>
<li>Vomiting</li>
<li>Rapid dehydration leading to sunken eyes, decreased skin turgor, muscle cramps</li>
<li>Severe dehydration can cause hypovolemic shock and death within hours</li>
</ul>
<p><strong>Treatment:</strong> Oral Rehydration Salts (ORS) is the cornerstone of treatment; antibiotics (doxycycline) reduce duration; IV fluids for severe cases</p>
<p><strong>Prevention:</strong> Safe water supply, sanitation, hand hygiene, food safety, cholera vaccine</p>

<h4>4.4.5 Typhoid Fever</h4>
<p><strong>Causative agent:</strong> Salmonella typhi (gram-negative bacillus)</p>
<p><strong>Transmission:</strong> Faecal-oral route (contaminated water and food, "5 Fs": Flies, Fingers, Food, Faeces, Fluid)</p>
<p><strong>Incubation period:</strong> 1-3 weeks</p>
<p><strong>Signs and Symptoms:</strong></p>
<ul>
<li>Week 1: Stepwise rising fever, headache, malaise, dry cough</li>
<li>Week 2: High fever (39-40 degrees C), rose spots on abdomen, splenomegaly, bradycardia (slow pulse despite high fever)</li>
<li>Week 3: Possible complications - intestinal perforation, haemorrhage</li>
</ul>
<p><strong>Diagnosis:</strong> Widal test (antibody test), blood culture (definitive)</p>
<p><strong>Treatment:</strong> Fluoroquinolones (ciprofloxacin), cephalosporins</p>
<p><strong>Prevention:</strong> Safe water and food, sanitation, hand hygiene, typhoid vaccine</p>

<h4>4.4.6 Measles</h4>
<p><strong>Causative agent:</strong> Measles virus (paramyxovirus)</p>
<p><strong>Transmission:</strong> Airborne and respiratory droplets (highly contagious)</p>
<p><strong>Incubation period:</strong> 10-14 days</p>
<p><strong>Signs and Symptoms:</strong></p>
<ul>
<li>Prodromal phase: High fever, cough, coryza (runny nose), conjunctivitis (red eyes), Koplik spots (white spots on buccal mucosa - pathognomonic for measles)</li>
<li>Rash: Maculopapular rash starts on face and spreads downward</li>
<li>Complications: Pneumonia (most common cause of death), encephalitis, blindness (vitamin A deficiency), otitis media</li>
</ul>
<p><strong>Treatment:</strong> Supportive care, vitamin A supplementation</p>
<p><strong>Prevention:</strong> MMR (Measles-Mumps-Rubella) vaccine - 2 doses in childhood</p>

<h3>4.5 Immunization Programme</h3>
<p><strong>Immunization</strong> is the process of making an individual immune to an infectious disease by administering a vaccine.</p>
<p><strong>Types of Immunity:</strong></p>
<ul>
<li><strong>Active immunity:</strong> Produced by the body after exposure to antigen (infection or vaccine) - long-lasting</li>
<li><strong>Passive immunity:</strong> Antibodies transferred from another source (maternal antibodies, immunoglobulin injection) - short-term</li>
</ul>

