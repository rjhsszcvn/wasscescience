<h3>3.1 Definition of Key Terms</h3>
<ul>
<li><strong>Nutrition:</strong> The science of food and its relationship to health; the process by which the body uses food for growth, repair, energy, and maintenance of life processes.</li>
<li><strong>Dietetics:</strong> The application of nutritional science to human health, including the planning of diets for health maintenance and disease management.</li>
<li><strong>Nutrient:</strong> A chemical substance in food that provides energy, promotes growth and repair, or regulates body processes.</li>
<li><strong>Diet:</strong> The total food and drink regularly consumed by a person.</li>
<li><strong>Balanced diet:</strong> A diet that contains all essential nutrients in the correct proportions to meet the requirements of the body.</li>
</ul>

<h3>3.2 Classes of Nutrients</h3>
<p>There are six major classes of nutrients essential for human health:</p>

<h4>3.2.1 Carbohydrates</h4>
<p>Carbohydrates are the primary source of energy for the body, particularly for the brain and red blood cells.</p>
<p><strong>Types:</strong></p>
<ul>
<li><strong>Simple carbohydrates (sugars):</strong> Monosaccharides (glucose, fructose, galactose) and disaccharides (sucrose, lactose, maltose) - rapidly absorbed and provide quick energy</li>
<li><strong>Complex carbohydrates (starches and fibres):</strong> Polysaccharides - slowly digested, providing sustained energy and aiding digestion</li>
</ul>
<p><strong>Functions:</strong> Primary energy source (4 kcal/g), sparing protein for other functions, essential for brain function, dietary fibre promotes bowel health</p>
<p><strong>Sources:</strong> Cassava, yam, rice, bread, maize, plantain, potatoes, fruits, vegetables</p>
<p><strong>Deficiency:</strong> Kwashiorkor (protein-energy malnutrition), fatigue, hypoglycaemia</p>
<p><strong>Excess:</strong> Obesity, type 2 diabetes, dental caries</p>

<h4>3.2.2 Proteins</h4>
<p>Proteins are made up of amino acids and are essential for growth, repair, and regulation.</p>
<p><strong>Essential amino acids (cannot be synthesized by the body):</strong> Leucine, isoleucine, valine, lysine, methionine, phenylalanine, threonine, tryptophan, histidine (in children)</p>
<p><strong>Functions:</strong> Growth and repair of tissues, enzyme production, hormone synthesis (insulin, growth hormone), antibody production (immune function), transport proteins (haemoglobin), energy source (4 kcal/g when carbohydrates are insufficient)</p>
<p><strong>Sources:</strong></p>
<ul>
<li><strong>Complete proteins (all essential amino acids):</strong> Meat, fish, poultry, eggs, dairy products</li>
<li><strong>Incomplete proteins (lacking one or more essential amino acids):</strong> Legumes, nuts, cereals, vegetables</li>
</ul>
<p><strong>Deficiency:</strong> Kwashiorkor (oedema, skin lesions, hair colour change), marasmus (severe wasting)</p>

<h4>3.2.3 Fats and Oils (Lipids)</h4>
<p><strong>Types:</strong></p>
<ul>
<li><strong>Saturated fats:</strong> Solid at room temperature; found in animal products (butter, lard, palm oil) - excess linked to cardiovascular disease</li>
<li><strong>Unsaturated fats:</strong> Liquid at room temperature; found in vegetable oils (olive, sunflower) - protective against heart disease</li>
<li><strong>Trans fats:</strong> Artificially hydrogenated unsaturated fats; found in margarine, fried/processed foods - most harmful to health</li>
</ul>
<p><strong>Functions:</strong> Concentrated energy source (9 kcal/g), fat-soluble vitamin carrier (A, D, E, K), insulation and protection of organs, cell membrane structure, steroid hormone synthesis</p>
<p><strong>Sources:</strong> Palm oil, coconut oil, groundnuts, meat, fish, avocado, dairy products</p>
<p><strong>Deficiency:</strong> Fat-soluble vitamin deficiencies, hormonal imbalances, poor brain development</p>
<p><strong>Excess:</strong> Obesity, cardiovascular disease, type 2 diabetes</p>

