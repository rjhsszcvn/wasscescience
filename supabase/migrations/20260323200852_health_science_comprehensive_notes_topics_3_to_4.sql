<h3>3.4 Dietary Guidelines and Special Diets</h3>
<h4>Food Guide Plate Model</h4>
<p>Modern dietary guidelines recommend:</p>
<ul>
<li>Fill half the plate with fruits and vegetables</li>
<li>Quarter with whole grains</li>
<li>Quarter with lean protein</li>
<li>Include dairy or calcium source</li>
<li>Limit sugar, salt, and unhealthy fats</li>
</ul>

<h4>Special Dietary Needs</h4>
<ul>
<li><strong>Pregnant women:</strong> Increased iron (prevent anaemia), folic acid (prevent neural tube defects), calcium, and iodine</li>
<li><strong>Children:</strong> Adequate protein for growth, calcium and vitamin D for bone development</li>
<li><strong>Elderly:</strong> Reduced calories but increased calcium, vitamin D, and B12</li>
<li><strong>Athletes:</strong> Increased carbohydrates, protein, fluids, and electrolytes</li>
<li><strong>Diabetics:</strong> Low glycaemic index foods, controlled carbohydrates, high fibre</li>
</ul>

