</table>

<h4>3.2.6 Water</h4>
<p>Water constitutes about 60-70% of body weight and is essential for all metabolic processes.</p>
<p><strong>Functions:</strong></p>
<ul>
<li>Solvent for biochemical reactions</li>
<li>Temperature regulation through sweating</li>
<li>Transport medium for nutrients and waste products</li>
<li>Lubricant for joints and organs</li>
<li>Component of blood and lymph</li>
</ul>
<p><strong>Daily requirement:</strong> Adults need 2.0-2.5 litres per day from all sources; needs increase with exercise, heat, and illness.</p>
<p><strong>Dehydration signs:</strong> Dark urine, dry mouth, headache, dizziness, confusion, reduced urine output</p>

<h3>3.3 Malnutrition</h3>
<p><strong>Malnutrition</strong> refers to deficiencies, excesses, or imbalances in a person intake of energy and/or nutrients.</p>

<h4>Types of Malnutrition</h4>
<ul>
<li><strong>Undernutrition:</strong> Insufficient intake of calories and/or specific nutrients
  <ul>
  <li><strong>Wasting:</strong> Low weight for height - acute malnutrition</li>
  <li><strong>Stunting:</strong> Low height for age - chronic malnutrition affecting growth</li>
  <li><strong>Underweight:</strong> Low weight for age</li>
  </ul>
</li>
<li><strong>Overnutrition:</strong> Excessive caloric intake leading to overweight and obesity</li>
<li><strong>Micronutrient deficiency:</strong> Insufficient vitamins and minerals despite adequate calories ("hidden hunger")</li>
</ul>

<h4>Protein-Energy Malnutrition (PEM)</h4>
