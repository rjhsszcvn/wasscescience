### Overview
A formal letter is written to someone you do not know personally, or in an official capacity. It is used in professional, governmental, and institutional contexts. WASSCE tests formal letter writing in Paper 2 (Directed Writing) and expects you to demonstrate correct format, formal register, and organised content.

---

### When to Write a Formal Letter
- **Application letters:** Jobs, scholarships, admissions
- **Complaint letters:** To organisations, government bodies, newspapers
- **Request/Inquiry letters:** Asking for information or permission
- **Recommendation/Reference letters:** Supporting another person's application
- **Letters to editors:** Sharing views on a public issue
- **Letters to government officials/organisations**

---

### Full Formal Letter Format

```
[Your Full Address — top right]        [Do not include your name here]
[Town/City]
[Date in full: 20th March, 2025]

[Recipient's Name]                     [Left-aligned, below date, with a gap]
[Recipient's Title/Position]
[Organisation Name]
[Organisation's Address]

Dear Sir/Madam,                        [If name not known]
Dear Mr./Mrs./Dr./Prof. [Surname],     [If name is known]

Re: [SUBJECT HEADING — underlined or in caps, briefly stating the purpose]

[BODY — 3 to 5 paragraphs]

Yours faithfully,                      [If "Dear Sir/Madam" used]
Yours sincerely,                       [If recipient's name used — "Dear Mr. Mensah"]

[Handwritten or typed Signature]
[FULL NAME IN CAPITALS or printed clearly]
[Position/Title if relevant, e.g., Head Girl, Class Representative]
```

---

### The Five-Paragraph Letter Structure

**Paragraph 1 — Purpose**
State clearly and briefly why you are writing.
*"I am writing to apply for the position of laboratory assistant advertised in the Daily Graphic of 15th March, 2025."*
*"I am writing to respectfully bring to your attention a persistent problem affecting residents of this community."*

**Paragraph 2 — Your Qualifications/Background/Context**
Provide relevant background information.
*"I am currently a final-year student at Achimota Senior High School, where I have studied the sciences to Advanced Level..."*

**Paragraphs 3–4 — Main Content**
Develop your points with specific details, evidence, and examples. Each paragraph covers one main point.

**Final Paragraph — Closing**
Summarise your request and state the action you expect.
*"I sincerely hope this matter will receive your urgent attention. I am available for further discussion at your earliest convenience."*
*"I look forward to a favourable response and thank you for your time and consideration."*

---

### Language of Formal Letters

**Formal opening phrases:**
- *I am writing to inquire about / to express / to request / to draw your attention to...*
- *I am writing with reference to...*
- *I write on behalf of...*

**Making a request politely:**
- *I would be grateful if you could...*
- *I would appreciate it if...*
- *I respectfully request that...*
- *Could you kindly...*

**Making a complaint:**
- *I wish to express my dissatisfaction with...*
- *I am deeply concerned about...*
- *I would like to bring to your attention the fact that...*
- *I regret to inform you that...*

**Referring to attachments:**
- *Please find enclosed / attached...*
- *I enclose a copy of my certificate for your reference.*

**Closing phrases:**
- *I look forward to your prompt response.*
- *I would be grateful for your consideration of this matter.*
- *Please do not hesitate to contact me should you require further information.*
- *Thanking you in advance.*

---

### Types of Formal Letters — Key Features

#### Application Letter (Job/Scholarship)
**Must include:**
- Why you are applying
- Your qualifications and relevant experience
- Why you are the best candidate
- What you can offer to the organisation

**Tone:** Confident but not arrogant; professional; enthusiastic but controlled.

#### Complaint Letter
**Must include:**
- Clear description of the problem
- When and where it occurred
- Impact of the problem
- What you want done (resolution)

**Tone:** Firm, factual, polite. Do NOT be rude or threatening.
*Avoid:* "Your organisation is terrible and incompetent."
*Use:* "I am disappointed with the level of service received and would appreciate a prompt resolution."

#### Letter to the Editor (of a newspaper)
**Must include:**
- Reference to the issue being addressed
- Your position/view clearly stated
- Supporting arguments or evidence
- A call to action or conclusion

**Typical opening:** *"I write with reference to the article published in your esteemed newspaper on [date] regarding [topic]. I wish to..."*

---

### Common Formal Letter Mistakes

| Error | Correction |
|-------|-----------|
| Writing address on left | Sender's address is on the **right** (top) |
| Using "Dear Friend" | Use "Dear Sir/Madam" or the recipient's title and name |
| "Yours Faithfully" after "Dear Mr. Mensah" | Use "Yours Sincerely" when you used the name |
| Contractions (don't, can't) | Write in full: do not, cannot |
| Informal vocabulary (kids, loads, get) | Use: children, numerous, obtain |
| No subject line | Always include a brief subject/heading |
| First-person opening ("I am Kofi Mensah") | Begin with purpose: "I am writing to..." |
| Writing "looking forward to hear from you" | "Looking forward to **hearing** from you" (gerund required) |

---

### Sample WASSCE Prompt and Outline

**Question:** *"You are the head prefect of your school. Write a letter to the District Education Officer drawing attention to the need for a new school library. Use the following points: no current library, students use personal phones for research, exam results are declining, request for funding."*

**Outline:**
- Para 1: Purpose — writing to draw attention to the urgent need for a school library
- Para 2: Current situation — no library; students rely on phones (unreliable, distracting)
- Para 3: Impact — declining exam results; insufficient research resources
- Para 4: Specific request — appeal for funding/support to build/stock a library
- Para 5: Close — express hope for favourable action; offer to provide further information

