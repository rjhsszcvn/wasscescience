### What Is a Report?
A report is a **factual, organised, and objective** document that presents information about an event, situation, problem, or findings — and often makes recommendations. Reports are written for a specific audience (e.g., a headmaster, committee, manager) who needs the information for decision-making.

---

### Key Features of a Report
- **Objective:** No personal opinion unless specifically a recommendation
- **Formal register:** Third person, passive voice frequently used
- **Clear structure:** Headings and sub-headings
- **Accurate and specific:** Facts, dates, figures
- **Purpose-driven:** Ends with conclusions and/or recommendations

---

### Report Format (Standard)

```
REPORT ON [TOPIC IN CAPITALS]

To:      [Recipient's name and title]
From:    [Your name and position]
Date:    [Full date]
Re/Subject: [Brief description — optional if heading is clear]

---

1.0  INTRODUCTION / PURPOSE
     Brief statement of why the report was written and what it covers.

2.0  FINDINGS / OBSERVATIONS / BACKGROUND
     2.1  [Sub-heading]
          [Details / facts / evidence]
     2.2  [Sub-heading]
          [Details]
     (Continue as needed)

3.0  DISCUSSION / ANALYSIS
     Interpretation and analysis of the findings.

4.0  CONCLUSIONS
     Summary of the key points; what the findings mean.

5.0  RECOMMENDATIONS
     Specific, numbered suggestions for action.
     5.1  The school should...
     5.2  The committee is advised to...

[Signature / Name]
[Date (if not given above)]
```

---

### Types of Reports (WASSCE-relevant)

#### 1. Incident Report
**Purpose:** To document an incident (an accident, fight, theft, fire) objectively.
**Key questions to answer:** What happened? When? Where? Who was involved? What were the consequences? What action was taken?

#### 2. Investigative Report
**Purpose:** To report findings from an investigation into a problem (e.g., declining academic performance, poor sanitation).
**Key sections:** Background, Findings from investigation, Analysis, Recommendations.

#### 3. Trip/Visit Report
**Purpose:** To report on an educational excursion or official visit.
**Key sections:** Purpose of visit, What was observed/learned, Benefits, Recommendations.

#### 4. Committee/Meeting Report
**Purpose:** Minutes or report of what occurred in a meeting.
**Key sections:** Attendance, Agenda items discussed, Decisions made, Next steps.

---

### Language of Report Writing

**Impersonal / Passive constructions:**
- *"It was observed that..."*
- *"It has been found that..."*
- *"The investigation revealed..."*
- *"Three main problems were identified..."*

**Introducing findings:**
- *"The following findings were made..."*
- *"The inspection revealed several areas of concern..."*
- *"Upon examination, it was noted that..."*

**Making recommendations:**
- *"It is recommended that the school..."*
- *"The committee should consider..."*
- *"Urgent attention should be given to..."*
- *"Steps should be taken to ensure..."*

**Transition words for reports:**
- *Furthermore / In addition / Additionally*
- *However / Nevertheless / On the other hand*
- *As a result / Consequently / Therefore*
- *In conclusion / To summarise*

---

### Tone and Style

| Do | Do Not |
|----|--------|
| Use formal, objective language | Express personal emotions |
| Use third person ("it was found") | Use first person unnecessarily ("I think") |
| Be specific (dates, numbers, names) | Be vague ("some students," "a while ago") |
| Use headings for each section | Write in one continuous unstructured block |
| Make realistic, actionable recommendations | Make vague recommendations ("things should improve") |

---

### Common Report Writing Mistakes

| Mistake | Correction |
|---------|-----------|
| No headings | Always use numbered headings for each section |
| Missing "To/From/Date" | These are essential in the header |
| Narrating like a story | Reports present facts, not a story |
| Personal opinions in findings | Findings = facts; opinions go in recommendations |
| No recommendations | Most WASSCE report questions expect them |
| Too emotional/informal | Use formal, impersonal language throughout |

---

### Sample WASSCE Report Scenario and Plan

**Question:** *"As the senior prefect of your school, write a report to the headmaster on the state of the school's sanitation facilities."*

**Plan:**
- **To:** The Headmaster, [School Name] | **From:** Senior Prefect | **Date:** [Date]
- **Heading:** REPORT ON THE STATE OF SANITATION FACILITIES
- **1.0 Introduction:** Purpose of report
- **2.0 Findings:**
  - 2.1 Toilets: Number of working toilets, hygiene condition
  - 2.2 Refuse disposal: Presence/absence of bins; waste management
  - 2.3 Water supply: Running water for handwashing
  - 2.4 Drainage: Condition of drains
- **3.0 Impact:** Effect on students' health; absenteeism
- **4.0 Recommendations:** Repair toilets; provide refuse bins; improve water supply; regular cleaning schedule
- **Signature**

