### Sentence Transformation (Common in WASSCE)

**Active → Passive:**
- Active: *The teacher **praised** the students.*
- Passive: *The students **were praised** by the teacher.*

**Direct → Indirect Speech:**
- Direct: *He said, "I am tired."*
- Indirect: *He said **(that) he was tired**.* (tense shifts back; pronoun changes)

**Positive → Comparative/Superlative:**
- *She is tall. → She is taller than Ama. → She is the tallest in the class.*

**Combining sentences:**
- *The boy is tall. He plays football. → The tall boy plays football.*
- *She failed. She worked hard. → Although she worked hard, she failed.*

