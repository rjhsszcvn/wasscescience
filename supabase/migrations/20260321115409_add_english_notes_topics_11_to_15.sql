### Subject-Verb Agreement Quick Rules

| Rule | Example |
|------|---------|
| Singular subject + singular verb | *The teacher **is** here.* |
| Plural subject + plural verb | *The teachers **are** here.* |
| "Each/every/either/neither" = singular | *Every student **has** a book.* |
| Collective nouns (class, team) = singular (usually) | *The team **is** ready.* |
| Indefinite pronouns (everyone, nobody) = singular | *Everyone **knows** the answer.* |
| Compound subject with "and" = plural | *Kofi and Ama **are** ready.* |
| "Neither...nor / Either...or" = agree with nearer | *Neither the students nor the teacher **was** informed.* |

