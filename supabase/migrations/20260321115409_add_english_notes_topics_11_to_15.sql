### What Is an Argumentative Essay?
An argumentative essay presents a **position on a controversial issue** and defends it with evidence, reasoning, and counterargument. It differs from a discursive essay in that argumentative essays take a **clear, consistent position**, while discursive essays may present both sides more equally.

**WASSCE Purpose:** To test your ability to form and defend opinions clearly, using formal language and logical structure.

---

### Argumentative Essay Structure

#### Introduction (1 paragraph)
1. **Hook:** Startling statistic, rhetorical question, bold statement, or relevant quotation
2. **Background/Context:** Brief explanation of the issue
3. **Thesis Statement:** Your clear position — the claim you will defend throughout the essay
   - *"This essay argues that social media, if left unregulated, does far more harm than good to the youth."*
   - *"Despite the arguments of those who support it, capital punishment is a barbaric practice that must be abolished."*

**Avoid:** Starting with "In this essay I will argue that..." — too mechanical.

#### Body Paragraphs (3–4 paragraphs)
Each paragraph develops ONE argument in support of your thesis.

**Use the PEEL structure:**
- **P — Point:** State your argument clearly in the topic sentence
- **E — Evidence:** Provide facts, statistics, examples, expert opinion, or real-world cases
- **E — Explanation:** Explain how your evidence proves your point
- **L — Link:** Connect back to the thesis or transition to the next point

**Example paragraph (PEEL):**
**(P)** "One of the most damaging effects of social media on the youth is the alarming rise in cyberbullying. **(E)** According to a 2022 UNICEF report, over 37% of young people in 30 countries have experienced online bullying, with a significant proportion reporting depression and anxiety as a result. **(E)** These statistics reveal that the anonymity of social media enables users to inflict emotional harm with far less inhibition than in face-to-face interaction, leaving victims isolated and vulnerable. **(L)** This demonstrates that the unrestricted use of social media poses a genuine and measurable threat to the mental health of young people."*

#### Counter-Argument Paragraph (1 paragraph)
Acknowledge the strongest opposing view, then refute it.

**Why include this?** It shows you have considered the issue from all angles, strengthening your argument rather than weakening it.

**Structure:** 
- *"Proponents of social media argue that... [opposing view]"*
- *"However / Nevertheless, this argument is flawed because..."*
- *"While it is true that..., one cannot overlook the fact that..."*

**Example:**
*"Supporters of capital punishment argue that it acts as a powerful deterrent against violent crime. However, this claim is not supported by evidence: countries that have abolished the death penalty have not experienced a corresponding rise in murder rates. Indeed, the 2023 Amnesty International report notes that murder rates in abolitionist countries are generally lower than in those that retain the death penalty, suggesting that fear of execution does not significantly reduce violent crime."*

#### Conclusion (1 paragraph)
1. **Restate thesis** in different words — do NOT copy your introduction
2. **Summarise key arguments** briefly (1 sentence each)
3. **Call to action or broader implication:** *"It is imperative that governments take immediate steps to..."* / *"Society as a whole must recognise that..."*
4. **Memorable final sentence** — leave an impression

---

### Language Features of Argumentative Writing

**Discourse markers for argument:**
| Function | Words/Phrases |
|----------|--------------|
| Adding a point | Furthermore, Moreover, In addition, Additionally, What is more |
| Contrasting | However, Nevertheless, On the other hand, Despite this, Conversely |
| Conceding | While it is true that, Admittedly, Although, Even though |
| Giving evidence | According to, Research shows, Studies indicate, Evidence suggests |
| Concluding | Therefore, Consequently, As a result, In conclusion, Ultimately |
| Emphasising | Indeed, Undoubtedly, It is clear that, Without doubt |

**Persuasive techniques:**
- **Rhetorical questions:** *"Can we afford to ignore this growing crisis?"*
- **Tricolon (rule of three):** *"Social media corrupts, misleads, and isolates."*
- **Emotive language** (used carefully in formal writing): *"the devastating consequences", "the silent suffering"*
- **Modal verbs for persuasion:** *must, should, ought to, cannot afford to*
- **Statistics and authority:** *"According to WHO data..."*

---

### Debate Writing
A **debate** is a formal argument between two opposing sides. In WASSCE, you may be asked to write a speech for or against a motion.

**Format of a Debate Speech:**

```
Mr./Madam Chairman
Honourable judges
Distinguished guests
The proposers/opposers of this motion
Ladies and gentlemen

[Self-introduction if required:]
"My name is [Name]. I stand [for / against] the motion that [state the motion]."

[Body — arguments with evidence]

[Refutation of opposing side — optional but impressive]

"For these reasons, I urge this house to [support / oppose] this motion."
"Mr. Chairman, I submit."
```

**Addressing the audience:**
- Use direct address: *"Fellow students, ask yourselves..."*
- Second person is encouraged: *"Consider this scenario — you are walking home and..."*

**Key debate skills in writing:**
- **Clarity of position:** Always clear whether you are for or against
- **Strength of argument:** Well-supported, logical points
- **Refutation:** Anticipate and pre-empt the opposing side
- **Persuasive delivery language:** *"I urge you...", "Make no mistake...", "The facts speak for themselves..."*

---

### Common Argumentative Writing Errors

| Error | How to Avoid |
|-------|-------------|
| Weak thesis (no clear position) | State your position directly and specifically |
| Points without evidence | Every argument needs support — facts, examples, statistics |
| No counter-argument | Always acknowledge and refute the opposing view |
| Contradicting yourself | Plan your outline; maintain consistent position |
| Emotional language without logic | Balance emotion with evidence and reasoning |
| Informal language | Formal register throughout; avoid contractions |
| No transitions between paragraphs | Use discourse markers to link ideas |

