### Overview
Narrative and descriptive writing are two forms tested in WASSCE Paper 2. Narrative tells a story; descriptive paints a picture with words. Both demand vivid language, strong organisation, and the ability to engage a reader.

---

### PART 1: NARRATIVE WRITING

#### What Is a Narrative?
A narrative is a **story** — real or imagined — that presents a sequence of events with a beginning, middle, and end. Good narratives involve compelling characters, a clear plot, rising tension, and a meaningful resolution.

---

### Elements of a Good Narrative

#### 1. Plot
The sequence of events. A well-constructed plot follows:
- **Exposition:** Introduction of characters, setting, and initial situation
- **Rising Action:** Events build toward the conflict
- **Climax:** The most intense or decisive moment
- **Falling Action:** Events following the climax
- **Resolution/Denouement:** How the situation resolves; lesson or reflection

#### 2. Setting
The **time and place** of the story. Good setting:
- Uses specific details rather than generalities
- Creates atmosphere and mood
- Can reflect the emotional state of characters

*Compare:*
- *Weak:* "It was a nice day in a village."
- *Strong:* "The harmattan had draped the village in a thin layer of red dust, and the air carried the smell of dried grass and smoke from cooking fires."

#### 3. Character
Bring characters to life through:
- **Direct description:** "He was a stout man of fifty with deep-set, watchful eyes."
- **Dialogue:** What they say reveals personality
- **Action:** What they do
- **Thoughts and feelings:** Internal monologue

Avoid flat, one-dimensional characters. Give them motivation, flaws, and authenticity.

#### 4. Conflict
The central problem or challenge. Types of conflict:
- **Person vs. person:** A fight, rivalry, or confrontation
- **Person vs. nature:** Surviving a flood, forest, or drought
- **Person vs. society:** Resisting peer pressure, tradition, or injustice
- **Person vs. self:** Internal struggle, moral dilemma

#### 5. Theme
The **underlying message or lesson** — what the story is really about:
- Perseverance, betrayal, the value of education, courage, family, identity

---

### Narrative Techniques

#### Show, Don't Tell
The most important technique. Instead of stating emotions directly, **show** them through sensory details, action, and dialogue.

| "Tell" (Weak) | "Show" (Strong) |
|---------------|----------------|
| She was nervous | Her fingers twisted the hem of her uniform, and she could not meet the headmaster's gaze. |
| He was very angry | He slammed the door so hard the windows rattled, and when he turned, his jaw was set hard. |
| The market was busy | The market was a storm of voices and colour — women calling prices, children darting between legs, the smell of fish and spice thick in the air. |

#### Dialogue
- Brings characters to life
- Advances the plot
- Reveals character and relationships
- **Correctly punctuated dialogue:**
  - *"I told you not to go," she whispered.*
  - *"Where have you been?" he demanded, rising from his chair.*
  - *She said, "I am sorry." He did not reply.*

#### Sentence Variety
Mix **short, punchy sentences** (tension) with **longer, descriptive ones** (atmosphere):
*"She ran. Her lungs burned and her legs screamed with every stride, but she did not stop. She could not. The sound behind her grew louder — heavy feet crashing through the undergrowth."*

#### Sensory Details
Engage **all five senses** — sight, sound, smell, taste, touch:
*"The cassava pottage sat thick and steaming in the bowl. The coconut oil glistened on the surface, and the aroma of smoked fish filled the kitchen."*

#### Foreshadowing
Hints of what is to come: *"I should have noticed the dark clouds gathering on the horizon, but at the time, I was too happy to care."*

#### Flashback
Interrupting the chronological narrative to show an earlier event that explains the present.

---

### Opening and Closing a Narrative

**Strong openings:**
- **In medias res (in the middle of action):** Begin mid-event for immediate impact.
  *"The scream cut through the silence of the night before I even knew I was awake."*
- **Descriptive scene-setting:** Draw the reader into the world.
  *"The village of Nkonya sits on a ridge where the harmattan wind arrives first, and the night sky looks so close you could reach up and stir the stars."*
- **Intriguing statement:** Create curiosity.
  *"The day I almost drowned changed everything I thought I knew about myself."*

**Effective conclusions:**
- Reflect on the significance of events
- Show character change or growth
- Circle back to the opening for structural unity
- Leave a final, resonant image or thought

---

### PART 2: DESCRIPTIVE WRITING

#### What Is Descriptive Writing?
Descriptive writing creates a **vivid, detailed impression** of a person, place, object, event, or experience. Its goal is to make the reader see, feel, hear, smell, and taste what you are describing.

---

### Organisation of Description

**Spatial order:** Describe from a physical perspective — near to far, left to right, top to bottom.
*"The room was small and dim. To the left stood a sagging wooden desk; across from it, a narrow bed with a faded kente cover. Above, a single bulb hung from the ceiling on a fraying cord."*

**General to specific:** Start with overall impression, then zoom in to details.
*"The market was chaos at first glance. But looking more carefully, a order revealed itself — the fish sellers clustered near the waterfront, the cloth merchants in the centre, and the food sellers lining the main paths."*

**Chronological (for events):** Move through time during the description.
*"As dawn broke, the village woke slowly. First the cockerels, then the sound of mortar and pestle, then children's voices..."*

---

### Language for Description

**Precise adjectives:** Not just *"a tall tree"* but *"a towering iroko tree, its bark rough as elephant hide."*

**Figurative language:**
- Simile: *"The river moved like a sleeping giant."*
- Metaphor: *"The marketplace was a battlefield of colour and sound."*
- Personification: *"The ancient walls of the fort seemed to breathe the memory of history."*

**Strong verbs:** Replace weak verbs with powerful ones.
- *walked* → **strode, shuffled, trudged, sauntered**
- *said* → **murmured, snapped, pleaded, declared**
- *moved* → **glided, lurched, darted, crept**

**The dominant impression:** Every sentence should contribute to the central mood or atmosphere. Decide the feeling you want to create (awe, sadness, excitement, unease) and choose details that reinforce it.

---

### Narrative vs. Descriptive: Key Differences

| Feature | Narrative | Descriptive |
|---------|-----------|-------------|
| Focus | A sequence of events (plot) | Creating an image or impression |
| Movement | Through time | Through space or layers of detail |
| Key element | Conflict and resolution | Sensory detail and atmosphere |
| Characters | Central | Secondary or incidental |
| Primary goal | Tell a compelling story | Make the reader visualise/experience |

