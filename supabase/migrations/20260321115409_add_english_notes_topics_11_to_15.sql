### What Is Syntax?
**Syntax** is the set of rules governing how words are combined to form grammatical sentences. Understanding sentence structure helps you write with clarity, variety, and correctness.

---

### Parts of a Sentence

#### Subject
The **who or what** the sentence is about. It performs the action or is described.
- *The **teacher** explained the lesson.*
- *A heavy **rain** fell overnight.*
- *Working hard every day **is** the key to success.* (gerund phrase as subject)

#### Predicate
Everything **apart from the subject** — the verb and anything that follows it.
- *The teacher **explained the lesson clearly**.*

#### Object
**What/who** receives the action.
- **Direct object:** Directly receives the action — *She wrote **a letter**.*
- **Indirect object:** The recipient of the direct object — *She wrote him **a letter**.* ("him" = indirect object)

#### Complement
Follows a linking verb; **describes or renames the subject**.
- *She is **a doctor**.* (noun complement)
- *The sky looks **dark**.* (adjective complement)

#### Modifier
Words, phrases, or clauses that **add detail** to nouns (adjective modifiers) or verbs (adverb modifiers).

---

### Types of Sentences by Structure

#### 1. Simple Sentence
Contains **one independent clause** (subject + verb, complete thought).
- *The boy ran.*
- *She passed all her examinations.*

#### 2. Compound Sentence
Contains **two or more independent clauses** joined by a **coordinating conjunction (FANBOYS)** or a semicolon.
- *She studied hard, **and** she passed.* (+ and)
- *He wanted to go, **but** he had no money.* (+ but)
- *I love reading; **however**, I rarely have time.* (semicolon + conjunctive adverb)

#### 3. Complex Sentence
Contains **one independent clause + one or more dependent (subordinate) clauses**.
- ***Because** it was raining, we stayed indoors.* (adverbial clause)
- *The man **who won the prize** is my teacher.* (relative clause)
- *She knew **that she had made a mistake**.* (noun clause)

#### 4. Compound-Complex Sentence
Contains **at least two independent clauses** and **at least one dependent clause**.
- ***Although** he was tired, he continued working, **and** he eventually finished the project.*

---

### Types of Clauses

#### Independent Clause
A complete thought that can stand alone as a sentence.
- *The rain fell.*

#### Dependent (Subordinate) Clause
**Cannot stand alone** — it depends on the main clause for its full meaning.

| Type | Function | Introduced by | Example |
|------|----------|--------------|---------|
| **Adverbial** | Modifies verb (when, why, how, condition) | when, because, if, although, while, before | *She cried **when she heard the news**.* |
| **Relative/Adjective** | Modifies a noun | who, whom, whose, which, that | *The book **that she wrote** is excellent.* |
| **Noun clause** | Functions as noun (subject/object/complement) | that, whether, what, who | *He knew **that he had failed**.* |

---

### Phrases

A **phrase** is a group of related words **without** a subject-verb combination.

| Phrase type | Example |
|-------------|---------|
| Noun phrase | *The tall, intelligent student* |
| Verb phrase | *has been working* |
| Prepositional phrase | *at the end of the road* |
| Participial phrase | *Running fast, she fell.* |
| Infinitive phrase | *To succeed requires hard work.* |
| Gerund phrase | *Swimming daily keeps you fit.* |

---

### Sentence Variety — Key to Good Writing

Using only simple sentences makes writing dull. Mix structures for effect:

**Effective use of short sentences:** Create drama or emphasis.
*"He entered the room. Silence fell. Everyone stared."*

**Long, complex sentences:** Build detail and explanation.
*"Although the odds were heavily stacked against her, and despite the lack of resources that had plagued her throughout her education, she managed to excel in every subject, ultimately earning a scholarship to study abroad."*

---

### Common Sentence Errors

#### 1. Sentence Fragment
An incomplete sentence presented as a complete one.
- **Fragment:** *Running down the road without stopping.*
- **Corrected:** *She was running down the road without stopping.*

How to check: Does it have a subject AND a finite verb? Does it express a complete thought?

#### 2. Run-On Sentence
Two independent clauses joined without proper punctuation or conjunction.
- **Run-on:** *I went to school it was raining heavily.*
- **Corrected options:**
  - *I went to school**. It** was raining heavily.*
  - *I went to school**, although** it was raining heavily.*
  - *I went to school**; it** was raining heavily.*

#### 3. Comma Splice
Using a comma to join two independent clauses without a conjunction.
- **Comma splice:** *She worked hard, she passed all her exams.*
- **Corrected:** *She worked hard, **and** she passed all her exams.* OR *She worked hard**; she** passed all her exams.*

#### 4. Dangling Modifier
A modifier that is not logically connected to what it modifies.
- **Dangling:** *Running fast, the bus was missed.* (The bus wasn't running)
- **Corrected:** *Running fast, **she** missed the bus.*

#### 5. Misplaced Modifier
A modifier placed too far from the word it modifies, causing confusion.
- **Misplaced:** *She almost drove her children to school every day.* (almost drove? or almost every day?)
- **Corrected:** *She drove her children to school almost every day.*

