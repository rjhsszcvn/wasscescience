### Words Commonly Confused (WASSCE Traps)

| Pair | Meanings |
|------|---------|
| affect / effect | *affect* (verb) = to influence; *effect* (noun) = result |
| accept / except | *accept* = to receive; *except* = excluding |
| principal / principle | *principal* = head/main; *principle* = rule/belief |
