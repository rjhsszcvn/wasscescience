### Contextual Vocabulary Questions (WASSCE Strategy)

**Question type:** *"As used in paragraph 2, the word 'plagued' most nearly means..."*

**Strategy:**
1. Find the word in the context — read the full sentence and neighbouring sentence
2. Determine the part of speech
3. Understand the overall meaning of the sentence
4. Substitute each answer option — which makes the best sense?
5. Watch for connotation (positive/negative/neutral) — the answer must match the tone

