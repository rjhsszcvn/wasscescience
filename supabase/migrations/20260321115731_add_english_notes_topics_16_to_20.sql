### What Is Concord?
**Concord** (also called subject-verb agreement) means that the **verb must agree with its subject** in **number** (singular or plural) and **person** (first, second, or third). This is one of the most heavily tested areas in WASSCE grammar.

---

### Basic Rule
**Singular subject → singular verb**
**Plural subject → plural verb**

- *The **boy runs** fast.* (singular)
- *The **boys run** fast.* (plural)
- *She **works** hard.* (third person singular → -s on verb)
- *They **work** hard.* (plural → no -s)

---

### Rules for Concord — Comprehensive Guide

#### Rule 1: Collective Nouns
Collective nouns (team, committee, class, family, government, jury, staff, crowd) can take either singular or plural verbs depending on whether they act as a unit or as individuals.

- **As a unit (singular):** *The team **has** won the championship.*
- **As individuals (plural):** *The team **are** arguing among themselves.*

**WASSCE standard:** In formal writing, treat collective nouns as **singular**.
*The committee **has** reached a decision.*

---

#### Rule 2: Indefinite Pronouns
These pronouns take **singular verbs**:
*everyone, everybody, everything, someone, somebody, something, anyone, anybody, anything, no one, nobody, nothing, each, either, neither, one*

- *Everyone **is** welcome.* ✓
- *Everybody **has** a role to play.* ✓
- *Neither of them **was** present.* ✓
- *Each of the students **has** a book.* ✓

**Common error:** *"Everybody **are** ready."* → Should be *"Everybody **is** ready."*

---

#### Rule 3: Compound Subjects with "and"
When two subjects are joined by **"and"**, use a **plural verb**.

- *Kofi **and** Ama **are** coming.*
- *The teacher **and** the students **were** informed.*

**Exception — when "and" joins items seen as ONE unit:**
- *Bread **and** butter **is** a simple meal.* (one food item)
- *The CEO **and** founder **is** attending.* (same person wearing two hats)

---

#### Rule 4: Either/Or — Neither/Nor
The verb agrees with the **subject NEARER** to the verb (proximity rule).

- *Either the teacher or the students **are** to blame.* (students — nearer — is plural)
- *Either the students or the teacher **is** to blame.* (teacher — nearer — is singular)
- *Neither the principal nor the teachers **were** present.*
- *Neither the teachers nor the principal **was** present.*

---

#### Rule 5: Subjects with "Each" and "Every"
*Each* and *every* make the subject **singular**, even with plural-sounding phrases.

- *Each boy **has** a pencil.*
- *Every student **is** expected to attend.*
- *Each of the girls **was** given a prize.*

---

#### Rule 6: "None"
*None* can be singular or plural depending on the noun it refers to:
- *None of the water **was** wasted.* (uncountable — singular)
- *None of the students **have** finished.* (countable plural — plural acceptable)

---

#### Rule 7: Relative Clause Subjects (who/which/that)
The verb in a relative clause agrees with the **antecedent** (the noun the relative pronoun replaces).

- *She is one of the students who **have** passed.* (who = students — plural)
- *He is the only one of the students who **has** failed.* (only one — singular)

---

#### Rule 8: Subjects Separated from Verbs
Do not be distracted by phrases between the subject and the verb.

- *The quality of the goods **was** poor.* (subject = quality, singular)
- *The results of the examination **have** been released.* (subject = results, plural)
- *One of the teachers **is** absent.* (subject = one, singular)
- *A box of chocolates **was** given to her.* (subject = box, singular)

---

#### Rule 9: Inverted Sentences
When the verb comes before the subject (questions, "there is/are" structures), the verb still agrees with the **subject**.

- *There **is** a problem.* (one problem — singular)
- *There **are** many problems.* (many problems — plural)
- *Here **come** the students.* (students — plural)
- *Here **comes** the principal.* (principal — singular)

---

#### Rule 10: Titles, Names of Subjects, and Sums
These take **singular verbs** even if they appear plural.

- *"Things Fall Apart" **is** a novel by Chinua Achebe.*
- *Mathematics **is** a compulsory subject.*
- *The news **is** disturbing.* (uncountable)
- *Ten thousand cedis **is** a lot of money.* (sum as one amount)

---

#### Rule 11: Quantifiers
- *More than one* → singular: *More than one student **has** complained.*
- *A number of* → plural: *A number of students **have** failed.*
- *The number of* → singular: *The number of students **has** increased.*
- *A lot of* → depends on noun: *A lot of money **was** wasted.* / *A lot of people **were** injured.*
- *Plenty of, a great deal of* + uncountable → singular; + countable plural → plural

---

### Pronoun-Antecedent Agreement
Pronouns must agree with the nouns they replace in gender, number, and person.

- *Every student must bring **his or her** book.* (or: "their" — now widely accepted)
- *The committee issued **its** report.* (singular)
- *The students submitted **their** work.*

**Common error:** *"Everyone should do **their** best."*
→ Technically, "everyone" is singular, so "his or her" is formally correct — but "their" is now widely accepted as gender-neutral.

---

### Verb Agreement After "As Well As", "Together With", "Along With"
These phrases do NOT change the grammatical number of the subject — the verb agrees with the **first subject only**.

- *The headmaster, **as well as** the teachers, **is** expected to attend.*
- *She, **together with** her friends, **was** arrested.*

(Note: the intervening phrase is typically set off by commas)

---

### Common Concord Errors in WASSCE

| Error | Correction | Rule |
|-------|-----------|------|
| *Everyone are invited* | Everyone **is** invited | Indefinite pronouns = singular |
| *The news are shocking* | The news **is** shocking | News = uncountable singular |
| *A number of students has failed* | A number of students **have** failed | "A number of" = plural |
| *Mathematics are interesting* | Mathematics **is** interesting | Subject names = singular |
| *The team are winning* | The team **is** winning (as unit) | Collective noun = singular (unit) |
| *Neither of them were present* | Neither of them **was** present | "Neither" = singular |
| *He and I was there* | He and I **were** there | "and" = compound = plural |
| *Each of the boys have a book* | Each of the boys **has** a book | "Each" = singular |

---

### Additional Agreement: Adjective + Noun

Adjectives in English do NOT change form with plural nouns:
- *a **tall** man → two **tall** men* (NOT "talls men")
