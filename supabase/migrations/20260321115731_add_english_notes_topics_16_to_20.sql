### Why Vocabulary Matters in WASSCE
A strong vocabulary allows you to express ideas precisely, choose the right word for a context, understand complex texts, and score highly in all language sections. WASSCE Paper 1 directly tests vocabulary through synonyms, antonyms, contextual meaning, word formation, and idioms.

---

### Word Formation Processes

#### 1. Derivation (Adding Affixes)

**Prefixes** change meaning:

| Prefix | Meaning | Examples |
|--------|---------|---------|
| un- | not / reverse | unhappy, undo, uncertain |
| in-/im-/ir-/il- | not | incomplete, impossible, irregular, illegal |
| dis- | opposite / apart | disagree, disconnect, dishonest |
| mis- | wrongly | misuse, misguide, mislead |
| re- | again | redo, rebuild, reconsider |
| over- | too much | overwork, overcome, overlook |
| under- | insufficient / below | underestimate, underpay, undermine |
| pre- | before | predict, preview, precede |
| post- | after | postgraduate, postpone, postwar |
| anti- | against | antibody, anticlockwise, antisocial |
| co- | together | cooperate, coordinate, coexist |
| inter- | between | international, interact, interdependent |
| trans- | across | transplant, transport, transcribe |
| super- | above / greater | supernatural, supersede, superior |
| semi- | half | semicircle, semifinal, semicolon |

**Suffixes** change the word class:

| Suffix | Creates | Examples |
|--------|---------|---------|
| -tion / -sion / -ation | noun | education, decision, organisation |
| -ment | noun | development, government, achievement |
| -ness | noun | happiness, darkness, awareness |
| -ity | noun | ability, clarity, complexity |
| -er / -or / -ist | noun (agent) | teacher, director, journalist |
| -ism | noun (system/belief) | capitalism, nationalism, racism |
| -ful | adjective | careful, hopeful, beautiful |
| -less | adjective | careless, homeless, speechless |
| -ous / -ious | adjective | famous, religious, ambitious |
| -able / -ible | adjective | reliable, flexible, responsible |
| -al / -ial | adjective | national, commercial, presidential |
| -ive | adjective | creative, destructive, progressive |
| -ify / -ise / -ize | verb | simplify, organise, modernise |
| -en | verb | strengthen, broaden, lengthen |
| -ly | adverb | quickly, carefully, deliberately |

#### 2. Compounding
Two or more words combined to form a new word:
- *football, blackboard, headmaster, classroom, self-confidence, mother-in-law*

#### 3. Conversion (Zero Derivation)
A word shifts to a different word class without any change in form:
- *"Can you **Google** it?"* (noun → verb)
- *"a **walk** in the park"* (verb → noun)
- *"a **fast** car"* (adverb → adjective)

#### 4. Clipping
Shortening a word:
- *examination → exam, photograph → photo, telephone → phone, advertisement → advert*

#### 5. Blending
Combining parts of two words:
- *breakfast + lunch = brunch, smoke + fog = smog, motor + hotel = motel*

#### 6. Acronyms and Initialisms
- *UNESCO, WAEC, WHO, HIV, AIDS*

