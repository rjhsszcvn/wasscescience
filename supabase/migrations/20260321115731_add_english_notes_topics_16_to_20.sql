| complement / compliment | *complement* = complete/go well with; *compliment* = praise |
| imply / infer | *imply* = to suggest (speaker does this); *infer* = to deduce (listener does this) |
| disinterested / uninterested | *disinterested* = impartial; *uninterested* = not interested |
