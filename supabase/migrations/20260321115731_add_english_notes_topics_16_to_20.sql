### Sample Valedictory Speech Outline

**Title:** Valedictory Speech — Final Year Students' Speech Day

**Protocol:** Mr. Principal, Vice Principal, Board of Governors, distinguished teachers, proud parents, and my fellow final year students...

**Hook:** *"Someone once told me that school days are the best days of your life. I did not believe them — until now, standing here on our final day, I understand what they meant."*

**Body:**
1. Gratitude to teachers and school for knowledge and values imparted
2. Reflection on the challenges faced and lessons learned as a class
3. The importance of taking the values of this school into the world
4. A charge to classmates — be ambassadors of excellence

**Conclusion:**
*"We leave these gates today not as finished products, but as works in progress — committed to continuous growth. Go, represent your school, your families, and your nation with honour. The world is waiting for you. Thank you."*

