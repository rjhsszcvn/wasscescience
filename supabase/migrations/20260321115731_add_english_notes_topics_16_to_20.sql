### What Is Inference?
**Inference** is the ability to **read between the lines** — to understand what a writer means beyond what is literally stated. Inferential reading involves using clues in the text, combined with your own knowledge, to draw logical conclusions.

This is one of the highest-order skills tested in WASSCE comprehension — questions that ask what the writer *implies*, *suggests*, or what you can *deduce* from the text.

---

### Literal vs. Inferential Reading

| Literal Reading | Inferential Reading |
|----------------|-------------------|
| What is directly stated | What is implied or suggested |
| Facts and explicit information | Hidden meanings, attitudes, tone |
| "According to the passage..." | "What does the writer suggest/imply?" |
| Answer found directly in text | Answer constructed from context clues |

---

### Types of Inference

#### 1. Factual Inference
Deducing information that logically follows from stated facts.
*"The class had only one textbook for forty students."*
→ Inference: *The school is poorly resourced / students lack sufficient learning materials.*

#### 2. Character Inference
Deducing a person's character, emotions, or motivation from their actions, words, or the way they are described.
*"She paused at the door, took a long breath, straightened her tie, and knocked."*
→ Inference: *She was nervous / preparing herself emotionally / approaching a situation with anxiety.*

#### 3. Tonal Inference
Identifying the **writer's attitude** toward the subject from language choices.
*"Despite years of promises, the government has once again failed to address this crisis."*
→ Tone: *Critical / frustrated / cynical*

#### 4. Cause-and-Effect Inference
Connecting an implied cause to a stated effect, or vice versa.
*"The village well had dried up. That morning, the children did not go to school."*
→ Inference: *The children stayed home to help fetch water from a distant source.*

#### 5. Vocabulary Inference (Contextual meaning)
Deducing what an unusual or difficult word means from its context.

---

### Clues Readers Use for Inference

| Clue type | What to look for |
|-----------|----------------|
| **Diction (word choice)** | Does the writer choose positive or negative words? Formal or emotional? |
| **Comparisons** | Similes and metaphors reveal attitude |
| **What is described** | Details deliberately chosen by the writer carry meaning |
| **What is omitted** | Sometimes what the writer doesn't say is telling |
| **Character actions** | Actions reveal emotions and motivation |
| **Setting details** | Environment can reflect character or mood |
| **Tone of dialogue** | How people speak reveals their relationship and feelings |

---

### Recognising Tone and Attitude

When asked about a writer's tone or attitude, look for:

**Vocabulary clues:**
- Emotive words: *devastating, scandalous, heartbreaking, astounding, deplorable*
- Evaluative adjectives: *brilliant, inadequate, reckless, inspiring*

**Structural clues:**
- Rhetorical questions suggest frustration, urgency, or challenge
- Short, punchy sentences may suggest anger or urgency
- Long, balanced sentences suggest careful, analytical approach

**Common tones to identify:**

| Tone | What it looks like |
|------|------------------|
| Admiring | Positive vocabulary; details that highlight achievements |
| Critical | Negative vocabulary; pointing out flaws or failures |
| Ironic | Says one thing but clearly means another |
| Pessimistic | Focuses on negatives; no solution offered |
| Optimistic | Highlights possibilities; forward-looking |
| Concerned | Signals danger or problem; calls for attention |
| Neutral/Objective | Facts presented without emotional language |
| Humorous | Amusing descriptions; lighthearted tone |
| Satirical | Mocking through exaggeration and irony |

---

### Inference from Figurative Language

When a writer uses figurative language, you must infer the deeper meaning:

*"The politician's promises were a beautiful mirage, shimmering with hope on the surface but dissolving into nothing the moment anyone reached out for them."*

**Literal meaning of metaphor:** Promises like a mirage
**Inference:** The writer is deeply cynical about the politician's honesty; the promises were deliberately deceptive and never intended to be kept.

---

### Answering Inference Questions — Method

**Question:** *"What does the writer suggest about the state of education in the country?"*

**Poor answer:** *"The writer says the school had only one textbook."* (Too literal — just repeats a fact)

**Good answer:** *"The writer implies that the education system is severely underfunded and neglected. The detail of forty students sharing a single textbook suggests a critical shortage of resources, pointing to a systemic failure to invest adequately in schools."*

**Formula for inference answers:**
1. **State the inference clearly** — what is implied or suggested
2. **Refer to the specific text detail** that led to the inference
3. **Explain the connection** — why does that detail lead to that conclusion?

---

### Distinguishing Inference from Opinion

**Inference:** A logical deduction based on evidence in the text
**Opinion:** A personal view not necessarily supported by the text

In comprehension answers, all inferences must be **grounded in the passage**. Do not introduce personal opinions or external knowledge unless specifically asked.

---

### Practice Passage and Questions

**Passage:**
*"The clinic stood at the edge of the town, its white paint faded and peeling, a single rusty tap outside offering the only running water. Inside, two nurses served a queue that stretched past the door and around the corner. The doctor, it was announced, would not be in until Thursday — it was Monday. Several of the women in the queue had been there since dawn."*

**Question 1:** *What can you infer about the healthcare provision in this town?*
**Answer:** The passage implies that healthcare provision in the town is grossly inadequate. The dilapidated state of the building ("faded and peeling"), the overworked minimal staff (only two nurses), the long wait for a doctor (absent until Thursday), and the fact that patients had already been waiting since dawn all suggest a severely under-resourced health system unable to cope with demand.

**Question 2:** *What does the phrase "stretched past the door and around the corner" suggest?*
**Answer:** The phrase suggests that the demand for healthcare far exceeds the clinic's capacity. The queue's length implies that large numbers of people are in need of medical attention, but the limited staff and resources mean most will have to wait for a very long time or go without care.

---

### Reading for Inference Across Text Types

**Narrative texts:** Infer character motivation, mood, and what happened before/after
**Argumentative texts:** Infer the writer's bias, unstated assumptions, and intended audience
**Descriptive texts:** Infer mood, setting in time/place, attitude toward subject
**News articles:** Infer writer's perspective, what facts may have been omitted

