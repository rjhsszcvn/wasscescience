### What Is a Speech?
A **speech** is a formal oral presentation delivered to an audience on a specific topic, for a specific purpose. In WASSCE Paper 2 (Directed Writing), you may be required to write a speech — not deliver it — demonstrating that you understand the conventions, structure, and language appropriate to the occasion.

---

### Types of Speeches Tested in WASSCE

| Type | Purpose | Occasion |
|------|---------|---------|
| **Valedictory speech** | Farewell and appreciation | Graduation/leaving ceremony |
| **Welcome speech** | Welcome guests to an event | School events, community gatherings |
| **Debate speech** | Argue for or against a motion | Debate competition |
| **Persuasive/campaign speech** | Convince audience to act or support something | School elections, community campaigns |
| **Award/Prize-giving speech** | Congratulate and motivate | Prize-giving day |
| **Keynote/guest lecture** | Inform, inspire, or present research | Academic events |

---

### Full Speech Format

```
[Opening address — acknowledge dignitaries in order of rank]

[Brief self-introduction if required]

[Introduction — hook and announcement of topic]

[Body — 3–5 main points, well-organised]

[Conclusion — memorable closing, call to action or reflection]

[Formal closing — thank the audience]
```

---

### Opening Address (Protocol)

The order of address should follow **rank** — most senior first.

**School speech examples:**
*"Mr. Principal, Vice Principal, honourable parents, distinguished teachers, and my fellow students..."*

**Official/government event:**
*"The Honourable Minister of Education, our respected District Director, members of the school board, teachers, parents, and students..."*

**Competition/debate:**
*"Mr./Madam Chairman, honourable judges, worthy opponents, and gentlemen/ladies of the floor..."*

---

### Speech Structure in Detail

#### 1. Opening / Introduction
- **Greet the audience** (protocol above)
- **Hook:** Engage the audience immediately
  - A surprising fact: *"Did you know that 10 million children in sub-Saharan Africa never set foot in a classroom?"*
  - A rhetorical question: *"What would you do if you had only one day left to change something in this school?"*
  - A brief relevant story or anecdote
  - A quotation: *"Nelson Mandela once said, 'Education is the most powerful weapon which you can use to change the world.'"*
- **State your topic/purpose clearly**

#### 2. Body (3–4 paragraphs/points)
- Each paragraph addresses **one main point**
- Use evidence, examples, and anecdotes to support points
- Use discourse markers for coherence: *"Firstly..., Secondly..., Furthermore..., On the other hand..., Most importantly..."*
- **Involve the audience:** Use "we," "you," "us" — shared language
- **Repetition for emphasis** (tricolon/anaphora): *"We must study harder. We must act with integrity. We must make our families proud."*

#### 3. Conclusion
- **Summarise** key points briefly (1–2 sentences)
- **Call to action:** Tell the audience what you want them to do or think
  *"I urge each of you, as you leave this hall today, to..."*
- **Memorable closing:** End with a powerful image, quotation, or challenge
  *"The world does not need more brilliant minds — it needs brilliant minds who act. Be that person."*
- **Formal closing:** *"Thank you for your time and attention."* / *"I submit."* (debate)

---

### Language Features of Speeches

#### Direct Address
Speak TO the audience, not about them:
- *"You, my fellow students, have the power to..."*
- *"Ask yourself: what kind of leader do you want to be?"*

#### Inclusive Pronouns
Create shared identity:
*"We must all take responsibility... Together, we can change this... Our school, our community..."*

#### Rhetorical Questions
*"Can we truly afford to remain silent in the face of this?"*
*"Is this the future we want to leave our children?"*

#### Tricolon (Rule of Three)
Three parallel phrases for rhythm and impact:
*"We came here to learn, to grow, and to become the best versions of ourselves."*
*"Education gives us knowledge, purpose, and freedom."*

#### Repetition (Anaphora)
Repeating a phrase at the beginning of successive sentences:
*"This school has given me courage. This school has given me lifelong friends. This school has given me a reason to dream."*

#### Contrast (Antithesis)
*"We did not come here to just pass examinations — we came here to pass through life with integrity."*

#### Emotive Language (appropriate to occasion)
*"I am filled with gratitude... I stand before you today with a heart full of pride..."*

---

### Valedictory Speech — Special Features
- **Express gratitude:** To teachers, parents, the school
- **Reflect on shared memories and growth** during the years
- **Acknowledge challenges overcome**
- **Inspire your peers:** Encourage them for the future ahead
- **Personal and warm** tone — semi-formal to formal

---

### Debate Speech — Special Features

**Addressing the house:**
*"Mr. Chairman, honourable judges, worthy members of the floor, I rise to [support/oppose] the motion that [state the motion]."*

**Stating your position:**
*"I stand firmly [for/against] this motion for the following reasons..."*

**Presenting arguments:**
Use strong connectives: *"My first argument is...", "Furthermore...", "Most critically..."*

**Refuting the opposition:**
*"My learned colleagues have argued that... However, this argument fails to consider..."*
*"While it is true that..., this does not negate the fact that..."*

**Formal close:**
*"For these compelling reasons, I urge this distinguished house to [support/reject] this motion. Mr. Chairman, I submit."*

---

### Common Speech Writing Mistakes

| Mistake | How to Avoid |
|---------|-------------|
| No opening protocol | Always address dignitaries in order of rank |
| Jumping straight into topic | Hook the audience first — interest them before informing |
| No call to action in conclusion | Always close with what you want the audience to think, feel, or do |
| Stiff, essay-like writing | Speeches use inclusive pronouns, rhetorical questions, direct address |
| No transitions between points | Use discourse markers for smooth flow |
| Too formal (no audience involvement) | Address the audience directly; use "we," "you," "us" |
| Too informal/casual | Maintain appropriate formality for the occasion |

