### Overview
Tenses show **when an action occurs** — in the past, present, or future. WASSCE tests tense usage extensively in grammar questions, cloze tests, sentence transformation, and writing. Incorrect tense use is one of the most common errors in student writing.

---

### The Twelve Main Tenses

English has **12 main tenses** organised into 3 time frames × 4 aspects:

| Time | Simple | Continuous | Perfect | Perfect Continuous |
|------|--------|-----------|---------|-------------------|
| **Present** | She **writes** | She **is writing** | She **has written** | She **has been writing** |
| **Past** | She **wrote** | She **was writing** | She **had written** | She **had been writing** |
| **Future** | She **will write** | She **will be writing** | She **will have written** | She **will have been writing** |

---

### Present Tenses in Detail

#### 1. Simple Present
**Form:** Base verb (add -s for he/she/it)
**Uses:**
- Habitual actions: *She **walks** to school every day.*
- Facts and general truths: *Water **boils** at 100°C.*
- Scheduled future events: *The train **leaves** at 6 a.m.*
- Narrative present (literary use): *The hero **enters** the village and **sees** the devastation.*

#### 2. Present Continuous (Progressive)
**Form:** am/is/are + verb-ing
**Uses:**
- Actions happening NOW: *I **am studying** right now.*
- Temporary situations: *She **is living** with her aunt this month.*
- Definite future arrangements: *We **are meeting** tomorrow at noon.*
- Changing/developing situations: *The climate **is getting** warmer.*

**Stative verbs NOT used in continuous:** know, believe, love, hate, want, need, own, contain, seem, appear, understand
- **Wrong:** ~~*I am knowing the answer.*~~
- **Correct:** *I know the answer.*

#### 3. Present Perfect
**Form:** have/has + past participle
**Uses:**
- Actions with results relevant NOW: *She **has finished** the assignment.* (it is now done)
- Life experience (unspecified time): *I **have visited** Accra.*
- Actions that started in the past and continue: *He **has lived** here for ten years.*
- Recent events: *The president **has just resigned**.*

**Signal words:** just, already, yet, ever, never, for, since, so far, recently

#### 4. Present Perfect Continuous
**Form:** have/has been + verb-ing
**Uses:**
- Actions that started in the past, continued to present, and may still be ongoing:
  *She **has been studying** for three hours.* (she may still be studying)
- Emphasis on duration and ongoing nature

---

### Past Tenses in Detail

#### 5. Simple Past
**Form:** Past tense form of verb (regular: +ed; irregular: changed form)
**Uses:**
- Completed actions at a specific past time: *He **arrived** yesterday.*
- Sequence of past events: *She **opened** the door and **saw** him.*
- Narrative: main tense for storytelling

**Common irregular past forms:**
| Base | Past Simple | Past Participle |
|------|------------|----------------|
| go | went | gone |
| write | wrote | written |
| see | saw | seen |
| take | took | taken |
| break | broke | broken |
| know | knew | known |
| give | gave | given |
| speak | spoke | spoken |
| teach | taught | taught |
| bring | brought | brought |
| buy | bought | bought |
| catch | caught | caught |

#### 6. Past Continuous
**Form:** was/were + verb-ing
**Uses:**
- Actions in progress at a specific past time: *At 8 p.m., she **was cooking**.*
- Background action interrupted by a shorter one: *She **was studying** when the light went out.*
- Two simultaneous past actions: *While he **was reading**, she **was cooking**.*

#### 7. Past Perfect
**Form:** had + past participle
**Uses:**
- Action completed BEFORE another past action: *When we **arrived**, the show **had already started**.*
- Cause of a past situation: *She **had not slept**, so she was exhausted.*
- In reported speech (tense backshift): *He said he **had finished** the work.*

#### 8. Past Perfect Continuous
**Form:** had been + verb-ing
**Uses:**
- Emphasises duration of an action that continued up to a past point:
  *She **had been waiting** for two hours before the doctor arrived.*

---

### Future Tenses in Detail

#### 9. Simple Future
**Form:** will + base verb
**Uses:**
- Decisions made at the moment of speaking: *"I **will help** you."*
- Predictions: *It **will rain** tomorrow.*
- Promises and offers: *I **will call** you.*

#### 10. Going to (Future Intention)
**Form:** am/is/are + going to + base verb
**Uses:**
- Plans/intentions made before the moment of speaking: *She **is going to study** medicine.*
- Predictions based on visible evidence: *Look at those clouds — it **is going to rain**.*

**will vs. going to:**
- *"I **will** open the window."* (decides at the moment of speaking)
- *"I **am going to** open the window."* (had already decided)

#### 11. Future Continuous
**Form:** will be + verb-ing
**Uses:**
- Action in progress at a specific future time: *This time tomorrow, we **will be travelling**.*

#### 12. Future Perfect
**Form:** will have + past participle
**Uses:**
- Action completed before a specific future time: *By 5 p.m., she **will have finished** the report.*

---

### Sequence of Tenses in Reported Speech

When reporting what someone said, tenses shift backward:

| Direct Speech | Reported Speech (tense backshift) |
|---------------|----------------------------------|
| Present simple: *"I work"* | Past simple: *She said she **worked*** |
| Present continuous: *"I am working"* | Past continuous: *She said she **was working*** |
| Present perfect: *"I have finished"* | Past perfect: *She said she **had finished*** |
| Past simple: *"I worked"* | Past perfect: *She said she **had worked*** |
| Will: *"I will go"* | Would: *She said she **would go*** |
| Can: *"I can help"* | Could: *She said she **could help*** |

**No tense shift when:** Reporting universal truths (*"He said the earth **revolves** around the sun."*)

---

### Conditionals (If-Sentences)

| Type | Form | Meaning | Example |
|------|------|---------|---------|
| **Zero** | If + simple present, simple present | Always true (fact/habit) | *If you heat ice, it **melts**.* |
| **First** | If + simple present, will + base | Real possibility (future) | *If it rains, we **will stay** home.* |
| **Second** | If + simple past, would + base | Unreal/hypothetical present | *If I **had** a car, I **would drive** to work.* |
| **Third** | If + past perfect, would have + pp | Unreal past; regret | *If she **had studied**, she **would have passed**.* |
| **Mixed** | If + past perfect, would + base | Past condition, present result | *If he **had listened**, he **would know** now.* |

**Subjunctive in conditionals:** Use *"were"* not *"was"* for all persons:
*"If I **were** you, I would apologise."*

---

### Common Tense Errors (WASSCE)

| Error | Correct |
|-------|---------|
| *She has arrived yesterday* | She **arrived** yesterday (specific past = simple past, not present perfect) |
| *I am knowing the answer* | I **know** the answer (stative verb — no continuous) |
| *He said he **will** come* | He said he **would** come (backshift in reported speech) |
| *By the time she came, he already left* | ...he **had already left** (past perfect for earlier past event) |
| *If I was you* | If I **were** you (subjunctive) |
| *She has been to Accra last year* | She **went** to Accra last year |

