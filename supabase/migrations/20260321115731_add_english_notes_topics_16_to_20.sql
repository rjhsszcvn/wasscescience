### Collocations and Fixed Expressions

A **collocation** is a natural word combination that sounds right to a native speaker:

**Verb + Noun:**
- *make* a decision, an effort, a mistake, progress
- *take* action, responsibility, a risk, advantage
- *do* research, damage, justice, your best
- *give* a speech, advice, permission, a warning

