**Question 5:** Describe and explain the factors that determine the distribution of rainfall in West Africa. (10 marks)

**Model Answer:**

**1. The ITCZ (Inter-Tropical Convergence Zone):**
The single most important factor. The ITCZ is a belt of low pressure, rising air, and heavy rainfall that migrates north in the northern summer and south in the northern winter, following the overhead sun. Areas over which the ITCZ passes experience their rainy season; areas away from the ITCZ experience dry season (dominated by the Harmattan). The ITCZ's migration explains:
- Southern Ghana and Nigeria have 2 rainy seasons per year
- The Sahel has only 1 short rainy season
- The Sahara receives virtually no rain

**2. Distance from the coast:**
