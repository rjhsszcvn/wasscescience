UPDATE topic_sections SET content = $$## Coastal Landforms Vocabulary

**Wave:** An oscillation of energy in water, generated by wind. Waves transport energy (not water) across the ocean surface.

**Constructive (depositional) waves:** Waves with a strong swash and weak backwash. They push material up the beach and deposit it. Typically have low energy, long wavelength, and low frequency. Characteristic of sheltered, gently sloping shores.

**Destructive (erosional) waves:** Waves with a weak swash but powerful backwash. They pull material back into the sea, eroding the shore. Typically high energy, short wavelength, and high frequency. Characteristic of exposed, steep shores with powerful ocean waves.

**Hydraulic action:** Erosion by the sheer force of waves hitting a cliff face. The impact compresses air in cracks, eventually forcing rock apart and shattering it.

**Abrasion (Corrasion):** The scraping and grinding of the cliff face by pebbles and rock fragments carried by waves — like sandpaper. Very effective erosion process.

**Attrition:** The wearing down of the rock load as pieces collide with each other, becoming smaller and rounder.

**Solution (Corrosion):** Chemical dissolving of soluble rocks (limestone, chalk) by seawater.

**Longshore drift:** The movement of sediment (sand, pebbles) along a coastline in a zig-zag pattern, driven by waves breaking at an angle to the shore. Key process in building beaches, spits, and bars.
- **Swash** carries sediment diagonally up the beach (in direction of prevailing wind/waves).
- **Backwash** returns sediment straight down the beach (perpendicular to shore, by gravity).
- Net movement is in the direction the waves approach from.

**Beach:** An accumulation of sediment (sand, shingle, pebbles) deposited along the shoreline. Forms where deposition exceeds erosion.

**Spit:** A narrow ridge of sediment projecting out into the sea from the coastline, with one end attached to the land. Formed by longshore drift depositing material at a point where the coastline changes direction (e.g., at a river mouth). The end often curves (recurves) due to secondary wave action.

**Bay bar (Bay barrier):** A spit that has grown across the mouth of a bay, completely enclosing it. The enclosed water body becomes a lagoon.

**Lagoon:** A shallow body of water separated from the sea by a beach or barrier. Very common along the West African coast — e.g., Sakumo Lagoon, Korle Lagoon (Ghana); Lagos Lagoon (Nigeria).

**Tombolo:** A sand or shingle bar connecting an island to the mainland or to another island.

**Headland:** A promontory — a point of resistant rock that juts out into the sea, flanked by bays.

**Bay:** A curved indentation of a coastline, where softer rock has been eroded more quickly than the harder rock forming the surrounding headlands.

**Cliff:** A steep, often vertical rock face at the coast, formed by wave erosion at the base and weathering/mass movement of rock above.

**Wave-cut platform (Shore platform):** A flat, rocky surface extending from the base of a cliff into the sea, formed by wave erosion at the base of the cliff. As the cliff retreats, the platform widens.

**Cave:** A hollow carved into a cliff face at sea level by hydraulic action and abrasion along a line of weakness (joint, fault, or softer rock).

**Arch:** Formed when a cave is eroded through a headland so that sea can pass through. Waves erode caves on both sides of the headland until they meet.

**Stack:** An isolated column of rock standing in the sea just offshore, separated from the headland when an arch collapses.

**Stump:** The remains of a stack after further erosion reduces it to a low, wave-washed platform.

**Mangrove:** Salt-tolerant trees and shrubs that grow in sheltered tropical coastal areas (estuaries, lagoons, deltas). Their prop roots trap sediment and build up land. Ecologically vital — nursery for fish, protection against coastal erosion, carbon storage.
