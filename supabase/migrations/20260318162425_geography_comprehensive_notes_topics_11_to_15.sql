## Worked Example 2: Explaining Longshore Drift and Spit Formation

**Question:** Using a diagram, explain how longshore drift operates and how it leads to the formation of a spit.

**Answer:**

**How Longshore Drift Works:**
- Waves generated by the **prevailing wind** approach the shore at an oblique angle (not straight on).
- The **swash** (rush of water up the beach after breaking) carries sediment diagonally up the beach in the direction of wave approach.
- **Gravity** then pulls the **backwash** (water returning down the beach) straight back to the sea, perpendicular to the shore.
- This creates a **zig-zag movement** of sediment along the beach — in the direction from which the waves approach.
- Large quantities of sand, pebbles, and shell can be transported many kilometres along a coast over time.

**Spit Formation:**
- Where the coastline changes direction sharply (e.g., at a bay, estuary, or river mouth), the water suddenly deepens and waves lose energy.
- Sediment being transported by longshore drift is **deposited** in the deeper water.
- This deposit grows outward from the coast, parallel to the original shoreline — building a **spit**.
- The tip of the spit may curve if secondary waves approach from a different direction.
- A protected **lagoon** forms in the sheltered water behind the spit.

**West African example:** The **Keta Spit** along Ghana's coast — formed by westward longshore drift of sediment.
