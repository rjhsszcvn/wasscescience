## Mass Movement in West Africa

Mass movements are triggered by:
1. **Heavy rainfall:** Saturates soil, increases weight and reduces friction between soil particles.
2. **Deforestation:** Removal of tree roots reduces slope stability.
3. **Slope angle:** Steeper slopes are more prone to failure.
4. **Earthquake shaking:** Can trigger landslides instantaneously.
5. **Undercutting by rivers or waves:** Removes support from the base of a slope.

**West African examples:**
- **Freetown, Sierra Leone:** Built on steep, geologically unstable hills. Rapid deforestation and heavy rainfall have led to catastrophic landslides. In August 2017, a major landslide killed over 1,000 people.
- **Accra, Ghana:** Flash floods and mud slides occur during heavy rainfall, especially in low-lying and steep areas.
- **Jos Plateau, Nigeria:** Landslides and erosion are common.

