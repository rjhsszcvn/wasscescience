## Landforms of the West African Interior

### The African Surface (Gondwana Surface)
Much of West Africa is a vast, ancient **peneplain** — evidence of millions of years of erosion. This is why West Africa's interior is dominated by low, flat plains with isolated hills.

### Inselbergs
- Isolated hills rising abruptly above a flat plain.
- Form where hard, resistant rock (e.g., granite) is surrounded by softer rock that has been eroded away over millions of years.
- The hard rock survives as an island of high land.
- **Examples in West Africa:** Larabanga Rocks (northern Ghana), Zuma Rock (Nigeria — a famous landmark near Abuja, approximately 725 m above surrounding plain).

