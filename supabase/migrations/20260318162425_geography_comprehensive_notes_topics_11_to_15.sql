**Coastal geography** studies the zone where the land and sea interact — a dynamic environment shaped by the power of waves, tides, currents, and the material that makes up the coast.

West Africa has approximately 6,000 km of coastline stretching from Mauritania in the north to Cameroon in the south. This coastline includes:
- Sandy beaches (Gold Coast of Ghana)
- Mangrove swamps (Niger Delta, Guinea Coast)
- Rocky cliffs (Cape Verde Peninsula, parts of Sierra Leone)
