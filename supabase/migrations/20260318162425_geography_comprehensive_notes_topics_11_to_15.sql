**Question:** With the aid of a labelled diagram, explain the sequence of landforms produced by wave erosion on a headland.

**Model Answer:**

**Diagram should show:** A headland projecting into the sea; caves on each side at the base; an arch through the headland; a stack standing isolated in the sea; and a low stump beyond.

**Explanation:**

**Stage 1 — Cave formation:**
- Waves identify lines of weakness (joints, bedding planes, faults) in the headland's rocky base.
- **Hydraulic action** (force of waves compressing air in cracks) and **abrasion** (scraping by rock fragments) erode these weaknesses, forming one or more **sea caves** at the base of the headland.

**Stage 2 — Arch formation:**
- If caves develop on opposite sides of the headland, erosion continues until the two caves meet.
- Alternatively, a single cave may be enlarged until the roof becomes very thin and then collapses.
- The result is a **natural arch** — a bridge of rock through which the sea can pass.

**Stage 3 — Stack formation:**
- The arch's base continues to be eroded and the roof is weakened by weathering and gravity.
- Eventually, the arch **collapses**, leaving behind an isolated pillar of rock in the sea — a **stack**.

**Stage 4 — Stump formation:**
- The stack is attacked from all sides by waves.
- **Hydraulic action** and **abrasion** erode the base of the stack.
- The stack becomes shorter and more unstable.
- Eventually, the stack is reduced to a low, rocky **stump** at or below sea level.

