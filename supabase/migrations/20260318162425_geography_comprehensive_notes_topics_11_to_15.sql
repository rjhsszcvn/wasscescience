## Worked Example 2: Formation of an Inselberg

**Question:** Explain how an inselberg is formed. Name a specific inselberg in West Africa.

**Answer:**
An **inselberg** forms through a process of **differential weathering** and **stripping**:

1. Deep **chemical weathering** penetrates the subsurface rock (often granite or gneiss).
2. Weathering is not uniform — areas with more joints (cracks), more water, or softer rock weather MORE rapidly. Areas with fewer joints, more resistant rock (e.g., massive, joint-free granite) weather LESS rapidly.
3. This creates an uneven weathering front deep underground — "masses" of unweathered, resistant rock surrounded by deeply weathered rock.
4. Over millions of years, **erosion removes the overlying weathered material** (regolith), exposing the unweathered resistant masses at the surface.
5. These exposed masses stand as isolated hills — **inselbergs** — rising abruptly above the surrounding flat plain.
6. Continued **exfoliation** on the exposed surface rounds the inselberg's shape.

**Named example:** **Zuma Rock**, located in Niger State, Nigeria, near Abuja. It rises approximately 725 m above the surrounding plain and is a major Nigerian landmark, visible from a great distance. It is a massive, dome-shaped inselberg composed of resistant granite.
