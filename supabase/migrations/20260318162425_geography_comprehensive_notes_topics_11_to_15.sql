**Weathering:** The breakdown of rocks IN PLACE (without significant movement) by physical, chemical, or biological processes. No transportation of material — the rock is broken down where it is.

**Mechanical (Physical) Weathering:** The physical breaking of rock into smaller pieces WITHOUT any change in chemical composition. Key processes:
- **Exfoliation (Onion-skin weathering):** Alternating heating (expansion) and cooling (contraction) causes the outer layers of rock to peel off like an onion skin. Common in tropical deserts and on exposed granite domes (e.g., Dome Rock, Paga — Ghana).
- **Freeze-thaw (Frost action):** Water in rock cracks freezes, expands, and forces cracks wider. Less relevant in West Africa (limited freezing temperatures).
- **Salt crystallisation (Haloclasty):** Salt crystals growing in rock pores exert pressure that widens cracks. Common in coastal and desert areas.
- **Pressure release (Dilatation):** As overlying rock is removed by erosion, the underlying rock expands and cracks (sheet joints).

**Chemical Weathering:** Decomposition of rock through chemical reactions, changing the chemical composition of the minerals. Key processes:
- **Hydrolysis:** Water reacts chemically with rock minerals, breaking them down. The most important chemical weathering process; decomposes feldspars in granite.
- **Oxidation:** Oxygen in air or water reacts with minerals (especially iron), producing iron oxides (rust). Gives many West African soils their reddish colour.
- **Solution (Carbonation):** Carbon dioxide dissolves in water to form weak carbonic acid (H₂CO₃). This dissolves limestone and other carbonate rocks. Responsible for cave formation (karst landscapes).
- **Hydration:** Some minerals absorb water molecules, swelling and eventually breaking apart.

**Biological Weathering:** Rock breakdown caused by the activities of living organisms.
- Plant roots grow into cracks, widening them (mechanical action)
- Organic acids produced by roots and decomposing organic matter cause chemical weathering
- Burrowing animals disturb soil

**Mass Movement (Mass Wasting):** The downslope movement of rock, soil, and other material under the influence of gravity, often triggered by water saturation.
- **Soil creep:** Very slow (cm/year), almost imperceptible movement of soil downslope. Evidence: curved fence posts, tilted trees.
- **Solifluction:** Saturated soil flows downslope like a fluid. Common where water cannot drain.
- **Mudflow:** Rapid flow of saturated soil and debris — can travel tens of km at high speed.
- **Landslide:** Rapid movement of a mass of rock or soil down a slope along a clear failure plane.
- **Rockfall:** Detachment and free fall of rock fragments from a steep cliff face.
- **Slump:** Rotation of material downslope along a curved failure surface.

**Erosion:** The removal and transportation of material by a moving agent (river, wave, wind, glacier). Distinct from weathering (which is in-place breakdown).

**Transportation:** The movement of eroded material (sediment/load) from one place to another by an agent.

**Deposition:** The dropping of transported material when a transporting agent loses energy.

**Peneplain:** A vast, nearly flat plain formed by long-term denudation of a mountainous area.

**Inselberg:** An isolated, steep-sided hill or rock mass rising abruptly from a surrounding plain (also called a "bornhardt" or "monadnock"). Very common in West Africa — formed by differential weathering. **Examples:** Aburi Hills, Nzulezu Hills (Ghana); Zuma Rock (Nigeria).

**Etchplain:** A flat or gently undulating landscape formed by deep chemical weathering (etching) beneath the surface, then exposed when the overlying rock is removed. Much of West Africa's landscape is an etchplain.

**Laterite / Duricrust:** A hard, iron-rich crust formed when leached iron and aluminium oxides concentrate near the surface during weathering. Very common across West Africa; can form resistant caps on hills.
