### Chemical Weathering (The Dominant Process in West Africa)

West Africa's hot, humid equatorial/tropical climate is ideal for intense chemical weathering:
- **High temperatures** speed up chemical reactions (reaction rate roughly doubles for every 10°C rise).
- **High rainfall** provides abundant water for hydrolysis, oxidation, and solution.

As a result, chemical weathering can penetrate to depths of 30–100 m or more in West Africa, creating deep **regolith** (weathered rock material) over millions of years.

**Hydrolysis** is the most important process: feldspars (the most common mineral in rocks like granite and gneiss) react with water to form **clay minerals** and soluble ions that are washed away. This leaves behind clay-rich soil.

**Result:** West Africa has some of the world's deepest weathering profiles. Rivers carry enormous quantities of dissolved minerals to the sea.

---

### Mechanical Weathering in West Africa

Though less dominant than chemical weathering, mechanical processes include:

**Exfoliation (insolation weathering):**
- The large daily temperature range in the Sahel and Sahara (from 5°C at night to 45°C by day) causes rocks to expand and contract repeatedly.
- The outer layers crack and peel off like an onion skin, leaving rounded rocks called **core stones** or smooth, dome-shaped **inselbergs**.
- This process is most prominent in semi-arid and arid areas.

**Salt weathering:**
- Common in coastal areas and deserts.
- Salt crystals grow in rock pores and crevices, exerting pressure that shatters rock.
- Particularly effective on sandstone and limestone.

