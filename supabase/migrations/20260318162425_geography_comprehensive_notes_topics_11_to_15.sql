**Landforms** are the natural physical features of the Earth's surface. They include mountains, plains, valleys, plateaus, hills, cliffs, and many others. The study of landforms and the processes that create and modify them is called **geomorphology**.

## What is Denudation?

**Denudation** comes from the Latin word meaning "to strip bare." It is the collective term for all the processes that wear down and lower the Earth's surface over time. It includes:
- **Weathering:** Breaking down rock in place
- **Mass movement (mass wasting):** Downslope movement of material under gravity
- **Erosion:** Wearing away and removal of material by agents (water, wind, ice)

Together, these processes gradually reduce highlands to lower and lower elevations over millions of years — ultimately producing flat plains called **peneplains**.

## Major Agents of Denudation

| Agent | Process | Landforms Created |
|-------|---------|-------------------|
| Running water (rivers) | Erosion, transportation, deposition | V-valleys, gorges, meanders, deltas |
| Wind | Deflation, abrasion, deposition | Desert landforms |
| Waves (sea) | Erosion, transportation, deposition | Cliffs, beaches, spits |
| Ice (glaciers) | Erosion, transportation, deposition | U-valleys, fjords, moraines |
| Gravity | Mass movement | Landslides, slumps, creep |

Note: In West Africa, **running water** is the dominant agent of denudation (glaciation does not occur; wind is significant in the Sahara/Sahel; waves operate along the coast).
