## Coastal Deposition Landforms — In Detail

### How Beaches Form

1. Waves break on the shore, losing energy and depositing their sediment load.
2. **Constructive waves** (long, low, high swash) build up material on the shore.
3. The beach profile changes with seasons: summer beaches are wider and higher (constructive waves dominate); winter beaches are narrower (destructive waves dominate).

**Beach sediment:** Sand or pebbles, transported by longshore drift from eroding cliffs or brought by rivers.

### How Spits Form (Longshore Drift Process)

1. Waves approach the shore at an angle (driven by prevailing winds).
2. Swash carries sediment diagonally up the beach.
3. Backwash returns sediment straight back (perpendicular to shore).
4. This zig-zag movement = **longshore drift**.
5. At a point where the coastline changes direction abruptly (e.g., a bay, river mouth, or estuary), the water depth suddenly increases and the waves refract (bend).
6. The sediment being transported can no longer reach the far shore — it is deposited in the open water.
7. Over time, this deposit builds outward from the coast as a **spit**.
8. The tip of the spit may curve due to secondary waves from a different direction = **recurved spit**.
9. A sheltered **lagoon** forms behind the spit.

**West African examples:**
- **Keta Spit (Ghana):** Extending from the eastern coast, with the Keta Lagoon behind it.
- **Dahomey Gap coast:** Series of spits and lagoons along the southern Benin/Togo/Ghana coast.
- **Lagos Bar Beach area (Nigeria):** Lagos Lagoon separated from the ocean by a beach barrier.

### The West African Coast: Lagoons

The coast of West Africa from Ghana to Nigeria is characterised by a remarkable series of **lagoons and lagoon systems**:
- The coast is low-lying with gentle gradient.
- Longshore drift (westward from the Niger Delta, eastward from the Volta) deposits sand, forming beach ridges and barriers.
- These barriers enclose lagoons.
- **Major lagoons:** Lagos Lagoon (Nigeria), Keta Lagoon (Ghana), Aby Lagoon (Côte d'Ivoire).

