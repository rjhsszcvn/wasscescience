### How Cliffs Form and Retreat

1. Waves attack the base of a sloping hillside or headland.
2. **Hydraulic action** and **abrasion** erode a **notch** at the waterline.
3. As the notch deepens, the rock above is left unsupported and eventually collapses (often accelerated by weathering and mass movement from above).
4. The collapsed material is broken up by waves and either carried away or forms temporary protection for the cliff base.
5. The cliff face retreats landward, and a **wave-cut platform** develops at its base.
6. As the platform widens, waves must travel further and expend more energy crossing it before reaching the cliff — the cliff's retreat rate slows.

### Cave → Arch → Stack → Stump Sequence

On a headland with alternating hard and soft rock bands:

1. **Caves:** Waves erode zones of weakness (joints, faults, softer rock) at the base of the headland, forming caves.
2. **Arch:** If a cave is eroded through from both sides of the headland, or if a cave becomes very large, a rock **arch** forms — the sea passes beneath the bridge of rock above.
3. **Stack:** Continued erosion weakens the arch's base until the roof collapses. The isolated pillar of rock that remains is a **stack**.
4. **Stump:** Further erosion by waves and weathering reduces the stack to a low, flat, wave-washed **stump**, submerged at high tide.

**Famous example (outside West Africa but useful for illustration):** The Twelve Apostles, Port Campbell, Australia. Similar sequences can be observed along rocky sections of West Africa's coast.

### Bays and Headlands

- Where a coastline has alternating bands of hard and soft rock (running parallel to the coast):
  - Soft rock erodes faster → forms **bays**
  - Hard rock resists erosion → forms **headlands**
- The headlands protect the bays from direct wave attack.
- **Example:** The alternating rocky headlands and sandy bays along the Ghana coast.

