## 1. Introduction

**Statistical methods** in geography allow geographers to:
- Organise and summarise large amounts of data.
- Identify patterns and trends.
- Compare different places or time periods.
- Present findings clearly.

**Graphical methods** allow data to be presented visually — making patterns easier to understand at a glance.

This topic covers the most important statistical and graphical techniques examined in WASSCE Geography.

---

## 2. Statistical Measures

### A. Mean (Arithmetic Average)

**Definition:** The sum of all values divided by the number of values.

**Formula:** Mean = Sum of all values ÷ Number of values

**Example:** Calculate the mean annual rainfall for a town with monthly rainfalls:
Jan: 20, Feb: 30, Mar: 80, Apr: 150, May: 200, Jun: 250, Jul: 300, Aug: 280, Sep: 200, Oct: 100, Nov: 40, Dec: 15

Sum = 1,665 mm
Mean = 1,665 ÷ 12 = **138.75 mm per month**

**Uses:** Gives a typical or average value; useful for comparing places (e.g., average temperature, average income).

**Limitation:** Can be distorted by extreme values (outliers).

---

### B. Median

**Definition:** The middle value when all values are arranged in order.

- If odd number of values: the middle value.
- If even number: average of the two middle values.

**Example:** Population of 7 towns (thousands): 5, 8, 12, 15, 22, 35, 80
Ordered: 5, 8, 12, **15**, 22, 35, 80
Median = **15,000**

**Uses:** Less affected by extreme values than the mean; useful when data is skewed.

---

### C. Mode

**Definition:** The value that appears most frequently in a data set.

**Example:** Crop yield (tonnes/ha) for 10 farms: 2, 3, 3, 4, 3, 5, 2, 3, 4, 6
Mode = **3** (appears 4 times)

---

### D. Range

**Definition:** The difference between the highest and lowest values.

**Formula:** Range = Maximum value − Minimum value

**Example:** Annual temperatures: Highest = 35°C, Lowest = 18°C
Range = 35 − 18 = **17°C**

**Uses:** Shows the spread or variability of data; e.g., temperature range tells us about the continentality of a climate.

---

## 3. Graphs and Diagrams

### A. Bar Graphs

**Used for:** Comparing quantities at different times or places.

**Types:**
- **Simple bar graph:** One bar per category; bars are equal width, separated by gaps; height represents value.
- **Compound (multiple/grouped) bar graph:** Two or more bars side by side for each category — allows comparison of two variables.
- **Divided (stacked) bar graph:** Each bar is divided into segments showing the composition of the total.

**Rules for drawing bar graphs:**
1. Always draw on graph paper.
2. Give the graph a title.
3. Label both axes with units.
4. Use a ruler; bars should be equal width with equal spacing.
5. Include a key if more than one variable is shown.
6. Bars should not touch each other (unless a histogram).

---

### B. Line Graphs

**Used for:** Showing changes over time (trends); temperature on climate graphs.

**Rules:**
1. Plot points accurately.
2. Join points with a smooth line (or straight lines between points).
3. Label axes with units.
4. Include a title and key.

**Climate graphs:** Use a line graph for temperature (monthly average) and a bar graph for rainfall — both on the same diagram.

---

### C. Pie Charts (Divided Circles)

**Used for:** Showing proportions/percentages of a whole.

**Method:**
1. Convert each percentage to degrees: Degrees = (Percentage ÷ 100) × 360°
2. Draw a circle.
3. Mark the centre. Draw a line to the circumference (start point).
4. Using a protractor, measure each angle from the starting line and mark segments.
5. Label each segment (or use a key with colours/shading).
6. Include percentages or values on each segment.

**Example:**
Ghana's export earnings: Gold 37%, Cocoa 20%, Oil 28%, Other 15%

Gold: (37/100) × 360 = 133.2°
Cocoa: (20/100) × 360 = 72°
Oil: (28/100) × 360 = 100.8°
Other: (15/100) × 360 = 54°
Total: 133.2 + 72 + 100.8 + 54 = 360° ✓

---

### D. Histograms

**Used for:** Showing the distribution of continuous data in class intervals.

**Differences from bar graphs:**
- Bars touch each other (no gaps) — continuous data.
- The x-axis shows continuous class intervals (e.g., 0–10, 10–20, etc.).
- Area of bar (not just height) represents frequency when class intervals are unequal.

---

### E. Scatter Diagrams (Scatter Graphs)

**Used for:** Showing the relationship (correlation) between two variables.

**Method:**
1. Draw two axes — one for each variable.
2. Plot each pair of values as a point (dot).
3. Draw a line of best fit (a straight line through the middle of the plotted points, with roughly equal numbers of points on each side).

**Interpreting correlation:**
- **Positive correlation:** As one variable increases, the other increases. Points slope upward (↗). Example: rainfall vs crop yield.
- **Negative correlation:** As one variable increases, the other decreases. Points slope downward (↘). Example: altitude vs temperature.
- **No correlation:** Points are scattered randomly; no trend. Example: rainfall vs population density (no clear link).

**Strength of correlation:**
- Strong: Points are close to the line of best fit.
- Weak: Points are widely scattered around the line.

---

### F. Population Pyramids

**Used for:** Showing the age and sex structure of a population.

**Structure:**
- Two horizontal bar graphs, back to back (males on left, females on right).
- Age groups on the vertical axis (0–4, 5–9, 10–14, etc.).
- Population (number or %) on the horizontal axis.
- Width of bars represents population in each age group.

**Interpretation:**
- Wide base = high birth rate; narrow base = low birth rate.
- Narrow top = low life expectancy; wide top = high life expectancy.
- Triangular shape = Stage 2 (developing country, high growth).
- Rectangular shape = Stage 4 (developed country, stable population).

---

### G. Flow-line Maps (Flow Maps)

**Used for:** Showing movement or flow of goods, people, or other phenomena between places.

- Lines are drawn between origin and destination.
- The **width** of the line is proportional to the volume of flow.
- Arrows show direction of movement.

**Example:** Lines showing migration from northern Ghana to Accra; trade flows from Ghana to the EU.

---

### H. Choropleth Maps

**Used for:** Showing the distribution of a variable across areas using shading or colour.

- Areas are shaded according to a data category.
- Darker shading usually = higher values.
- Must include a key showing what each shade represents.

**Example:** Map of West Africa shaded to show population density (persons/km²) by country.

**Advantages:** Easy to read; shows spatial distribution.
**Disadvantages:** Conceals variation within areas; boundaries appear sharp but are gradual in reality.

---

### I. Proportional Symbols (Proportional Circles)

**Used for:** Showing quantities at specific locations.

- Symbols (circles, squares) are drawn at each location.
- The size (area) of the symbol is proportional to the value.
- Common for showing city population sizes, export values, production quantities.

**Method:**
- Calculate the area of the circle: Area = πr²
- Choose a scale (e.g., 1 mm² represents 100,000 people).
- Radius = √(Area ÷ π) → draw circle at correct size.

---

## 4. Measures of Dispersion (Spread)

### Interquartile Range (IQR)

- Divide ordered data into four equal groups (quartiles).
- Q1 = 25th percentile (lower quartile).
- Q2 = 50th percentile (median).
- Q3 = 75th percentile (upper quartile).
- IQR = Q3 − Q1
- Shows the spread of the middle 50% of data.

---

## 5. Comparing Data Sets

When comparing two data sets:
1. Compare the **mean** (which is larger/smaller?).
2. Compare the **range** or **IQR** (which is more variable?).
3. Consider if the difference is significant.

**Example:** Compare rainfall in Accra and Tamale over a year.

| Month | Accra (mm) | Tamale (mm) |
|-------|-----------|-------------|
| Jan | 15 | 0 |
| Feb | 38 | 3 |
| Mar | 56 | 12 |
| Apr | 81 | 30 |
| May | 142 | 100 |
| Jun | 178 | 140 |
| Jul | 46 | 150 |
| Aug | 15 | 175 |
| Sep | 36 | 180 |
| Oct | 64 | 105 |
| Nov | 36 | 10 |
| Dec | 23 | 1 |

Accra total: 730 mm/year (bimodal — two peaks)
Tamale total: 906 mm/year (unimodal — one peak)
