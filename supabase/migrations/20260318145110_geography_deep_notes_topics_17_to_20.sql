## 1. Introduction to Desert Environments

**Desert:** An area that receives less than 250 mm of rainfall per year, with extreme temperatures and sparse vegetation.

**Arid:** An area that receives less than 500 mm of rainfall per year (includes semi-arid areas).

### Types of Deserts:

| Type | Cause | Example |
|------|-------|---------|
| **Hot desert** | Subtropical high pressure; trade winds | Sahara (Africa), Arabian Desert |
| **Cold desert** | Cold ocean current on west coast | Namib Desert (Namibia) |
| **Rain shadow desert** | Mountain blocks moisture | Atacama (South America) |
| **Continental desert** | Far from sea moisture | Gobi (Central Asia) |

**The Sahara Desert** — the world's largest hot desert:
- Covers approximately 9.2 million km².
- Spans North Africa from Mauritania/Senegal to Sudan/Egypt.
- Its southern fringe — the **Sahel** — is spreading southward (desertification).

---

## 2. Why Deserts Are Hot and Dry

**Subtropical high pressure system:**
- At about 25–30°N and 25–30°S latitude, large areas of high pressure (descending, stable air) exist.
- Descending air warms (compression) and dries → clouds cannot form → little rainfall.
- This is why the Sahara and Arabian deserts are located at ~25–30°N.

**Trade winds:**
- Dry trade winds blow from the subtropical high-pressure belts toward the equator.
- In the Sahara, the **Harmattan** (NE trade wind) carries dry Saharan air across West Africa.

**Distance from ocean (continentality):**
- Interior deserts far from the sea receive little moisture.

**Cold ocean currents (cold desert):**
- Cold currents (e.g., Benguela Current off Namibia) cool air → no evaporation → no clouds → no rain.

---

## 3. Weathering in Deserts

### Physical Weathering Dominates in Deserts:

**1. Exfoliation (insolation weathering / onion-skin weathering):**
- Extreme temperature variations between day (50°C+) and night (near freezing) cause rock surfaces to expand and contract.
- The outer shell peels away in thin layers.
- Produces rounded boulders and smooth rock surfaces.

**2. Salt weathering (salt crystallisation):**
- Water in rock pores evaporates in extreme heat.
- Salt crystals grow in pores and cracks, forcing them apart.
- Very effective in desert environments; causes rock to crumble.

**3. Freeze-thaw:**
- In cold deserts or at night in hot deserts.

**Chemical weathering is very limited** in deserts because there is little water.

---

## 4. Agents of Erosion in Deserts

### A. Wind (Aeolian Processes)

Wind is the dominant agent of erosion and deposition in deserts.

**Wind erosion processes:**

| Process | How it works |
|---------|-------------|
| **Deflation** | Wind lifts and removes fine sand and dust particles from the surface, lowering it over time |
| **Abrasion** | Wind-borne sand blasts and polishes rock surfaces (like sandpaper) |
| **Attrition** | Sand particles collide with each other, becoming smaller and more rounded |

**Transport by wind (saltation and suspension):**
- **Surface creep:** Large grains rolled along the surface by wind pressure.
- **Saltation:** Medium grains bounced along the surface.
- **Suspension:** Very fine dust carried high in the air for hundreds of kilometres (harmattan dust reaches Europe!).

### B. Water (Ephemeral Rivers)

Even in deserts, **flash floods** from occasional heavy rain are very important:
- Rain falls on hard, impermeable rock and bare soil → rapid runoff.
- Ephemeral streams flow for short periods after rain, carrying large amounts of sediment.
- Responsible for much of the erosion in semi-arid regions.

---

## 5. Desert Landforms

### A. Landforms Produced by Wind Erosion:

**1. Desert pavement (reg / hammada):**
- Deflation removes all fine material (sand, silt, dust).
- Only large pebbles and boulders remain — forming a flat, stony desert surface.
- The pebbles protect the surface below from further deflation (desert armour).

**2. Yardang:**
- Streamlined, ridge-like landform of rock, aligned parallel to the prevailing wind.
- Formed by wind abrasion; the softer rock between ridges is eroded away.
- The hard rock ridges remain.

**3. Zeugen:**
- Tabletop hills — hard, resistant rock sits on a softer rock layer below.
- Wind abrasion is most powerful near the ground (where sand concentration is highest).
- Soft rock at the base is undercut; hard rock forms a cap/table.
- Eventually the cap collapses → isolated mesas or buttes.

**4. Mushroom rocks (pedestal rocks):**
- Rock pillars that are wider at the top than at the bottom.
- Sand abrasion is concentrated near the ground → base is eroded more than the top.
- The top overhangs, resembling a mushroom.

### B. Landforms Produced by Wind Deposition:

**1. Sand dune:**
- A mound or ridge of sand deposited by wind.
- Form where wind loses energy or meets an obstacle.

**Types of sand dunes:**

| Type | Shape | Wind condition |
|------|-------|----------------|
| **Barchan dune** | Crescent-shaped; points downwind | Unidirectional wind; limited sand supply |
| **Seif (longitudinal) dune** | Long, sharp ridges parallel to wind | Bidirectional wind; ample sand |
| **Transverse dune** | Ridges perpendicular to wind | Abundant sand; constant wind |
| **Star dune** | Multi-pointed; radiating arms | Variable wind direction |

**Barchan dune formation:**
1. Wind blows sand grains up the gentle windward slope.
2. Grains fall over the steep slip face (leeward side) — avalanching.
3. The dune migrates downwind.
4. The two horns (tips) advance faster than the centre.
5. Result: crescent shape, with the concave side facing downwind.

**2. Ergs (sand seas):**
- Vast areas of shifting sand dunes.
- Cover about 25% of the Sahara.

### C. Landforms Produced by Water Erosion in Deserts:

**1. Wadi (Oued):**
- A dry river valley or channel in a desert, formed by past water erosion or flash floods.
- Flat-floored, steep-sided valleys.
- Remain dry most of the year but may fill with fast-flowing water during rare rainstorms.

**2. Alluvial fan:**
- Formed where an ephemeral stream suddenly leaves a mountain valley and spreads onto a flat plain.
- Velocity drops → sediment is deposited in a fan-shaped pattern.
- Several fans can merge to form a **bajada**.

**3. Playa (Pan):**
- A flat, dry lake bed.
- Formed where water collects in a desert basin after rare rainfall.
- When water evaporates, it leaves behind salt deposits (**salt flat/salt pan**).
- Playas are the flattest natural surfaces on Earth.

**4. Mesas and Buttes:**
- Isolated, flat-topped hills with steep sides.
- Remnants of a larger plateau, gradually eroded by water and wind.
- Mesa: broader, table-like top.
- Butte: narrower, column-like top (a further eroded mesa).
- Common in the Sahara and the American Southwest (Colorado Plateau).

---

## 6. Oases

**Definition:** An oasis is a fertile spot in a desert where water is available (from an underground spring, artesian well, or river).

- Water is sourced from **groundwater** — often from rain that fell hundreds or thousands of kilometres away in a wetter region, which slowly percolated through permeable rock.
- Oases support vegetation (date palms, other crops), animals, and human settlement.
- Critical stopping points on ancient trans-Saharan trade routes.

---

## 7. Human Life in Arid Environments

**Traditional adaptations:**

| Adaptation | Example |
|-----------|---------|
| **Nomadic pastoralism** | Following seasonal rains with herds of camels, goats, cattle; Tuareg people (Sahara) |
| **Oasis agriculture** | Farming date palms, vegetables, and crops around natural water sources |
| **Underground irrigation (foggara)** | Ancient underground channels bringing mountain water to desert communities |

**Modern exploitation of deserts:**
- Oil extraction (Sahara has vast oil deposits — Libya, Algeria, Nigeria north).
- Solar energy farms (very high solar irradiation).
- Tourism (desert safaris, dune driving).
- Mining (phosphate, uranium in Niger Sahara).

**Desertification (human-induced spread of desert conditions):**
- Overgrazing, deforestation, and climate change cause formerly productive Sahel land to become desert-like.
- Already addressed in the Environmental Issues topic.

