## 1. Globalisation

**Definition:** Globalisation is the process by which the world's economies, cultures, and populations have become increasingly interconnected and interdependent through trade, investment, migration, communication, and the spread of ideas.

In simple terms: the world is becoming a "global village" — events in one country quickly affect others.

### Causes of Globalisation:

1. **Improved transport:** Containerisation of shipping (cheaper bulk transport), air travel (fast movement of people and goods), improved road and rail networks.
2. **Technology and communications:** Internet, mobile phones, social media, satellite TV — instant communication anywhere in the world.
3. **Trade liberalisation:** Reduction of trade barriers (tariffs, quotas) through organisations like the **World Trade Organisation (WTO)**.
4. **Transnational corporations (TNCs):** Large companies that operate in many countries spread production and consumption globally.
5. **International finance:** Global banking, foreign direct investment (FDI), international stock markets.
6. **Migration:** Movement of people between countries spreads cultures, ideas, and skills.

