| **NGO aid** | From non-governmental organisations | OXFAM, MSF (Médecins Sans Frontières) |

### The Aid Debate:

**Arguments FOR aid:**
- Provides immediate relief in emergencies.
- Builds infrastructure (schools, hospitals, wells).
- Funds healthcare → reduces mortality.
- Supports education → raises literacy.

**Arguments AGAINST aid:**
- Creates dependency — countries become reliant on external assistance.
- Conditions attached to aid (structural adjustment) can harm local economies.
- Aid can be misused by corrupt governments.
- Disrupts local markets (cheap food aid may undercut local farmers).
- Does not address root causes of poverty.

### Trade vs Aid Debate:

Many economists and African leaders argue: **"Trade, not aid"** — what developing countries need is fair access to global markets, not charity.

**Fairtrade:** A movement that ensures producers in developing countries get fair prices for their goods (e.g., Fairtrade cocoa from Ghana).

