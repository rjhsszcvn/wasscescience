## 4. Fishing Industry

West Africa has a rich fishing heritage, supported by:
- **Marine fisheries:** The Gulf of Guinea and Atlantic Ocean provide rich fishing grounds (upwelling of cold, nutrient-rich water supports abundant fish stocks).
- **Inland fisheries:** Rivers (Niger, Volta, Senegal), lakes, and reservoirs.

**Types of fishing:**
- **Artisanal fishing:** Small-scale, traditional methods; dugout canoes, hand-thrown nets; primarily for subsistence and local sale.
