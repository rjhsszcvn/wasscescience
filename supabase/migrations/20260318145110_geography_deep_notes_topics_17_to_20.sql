## 8. Economic Development Concepts

**GDP (Gross Domestic Product):** The total value of all goods and services produced within a country in a year.

**GNI (Gross National Income):** GDP plus income from abroad minus income paid to foreign residents.

**GDP per capita:** GDP divided by population — gives a measure of average income per person.

**Human Development Index (HDI):** A composite measure of development combining:
1. Life expectancy (health).
2. Education level (literacy, school enrolment).
3. Income (GNI per capita).

**LDC (Least Developed Country):** Countries with very low income, poor human development, and economic vulnerability.

| Country | HDI classification | Key Challenge |
|---------|--------------------|---------------|
| Nigeria | Medium HDI | Inequality; oil dependence |
| Ghana | Medium HDI | Debt; commodity prices |
| Sierra Leone | Low HDI | Post-war recovery; infrastructure |
| Liberia | Low HDI | Post-war; underdevelopment |
| Niger | Very low (bottom 5 globally) | Sahel drought; high fertility |

