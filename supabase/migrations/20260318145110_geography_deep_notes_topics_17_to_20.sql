## 1. What is Economic Geography?

**Economic geography** is the branch of geography that studies the location, distribution, and organisation of economic activities — how people use resources to produce wealth.

It examines:
- Where economic activities take place and why.
- How resources are extracted, processed, and traded.
- How countries develop economically.
- Differences in development between regions and countries.

---

## 2. Economic Activities

Economic activities are grouped into four sectors:

| Sector | Description | Examples in West Africa |
|--------|-------------|------------------------|
| **Primary** | Extracting raw materials from nature | Farming, fishing, mining, forestry, livestock rearing |
| **Secondary** | Processing/manufacturing raw materials into goods | Food processing, cement production, textile manufacturing, oil refining |
| **Tertiary** | Providing services | Banking, education, healthcare, retail trade, transport |
| **Quaternary** | Knowledge and information industries | IT, research, telecommunications, media |

**West Africa's economy is dominated by the primary sector** — the majority of the workforce is engaged in farming, fishing, or mining. However, secondary and tertiary sectors are growing, especially in Nigeria, Ghana, Côte d'Ivoire, and Senegal.

