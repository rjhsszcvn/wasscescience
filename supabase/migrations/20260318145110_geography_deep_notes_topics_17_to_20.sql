## 5. Causes of Underdevelopment in West Africa

### Historical causes:
- **Slavery:** Millions of young, able-bodied people taken from West Africa — devastating for population and productivity.
- **Colonialism:** Resources extracted for European benefit; transport built for export; indigenous industries suppressed.
- **Colonial borders:** Artificial borders split ethnic groups and combined hostile groups → post-independence conflict.

### Economic causes:
- **Unfavourable terms of trade:** Raw material prices fall relative to manufactured goods.
- **Debt:** Many West African countries owe billions in loans (to World Bank, IMF, foreign governments) — debt repayments drain budgets.
- **Dependence on a few commodities:** Price shocks devastate entire economies.
- **Lack of investment** in manufacturing and value-added industries.

### Political causes:
- **Corruption:** Misuse of public funds; "kleptocracy" (rulers steal state wealth).
- **Political instability / coups:** Frequent changes of government deter investment.
- **Conflict:** Wars destroy infrastructure, drive away investment, create refugees.

### Physical/environmental causes:
- Drought, desertification, and soil infertility limit agricultural productivity.
- Tropical diseases (malaria, river blindness) reduce workforce productivity.
- Landlocked countries (Mali, Burkina Faso, Niger) face higher transport costs.

