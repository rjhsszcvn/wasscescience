<h3>20.4 Global Health Governance and Organizations</h3>

<h4>World Health Organization (WHO)</h4>
<p>The directing and coordinating authority for international health within the United Nations system. Established 1948. Headquarters: Geneva, Switzerland.</p>
<p><strong>Key functions:</strong> Setting international health standards and guidelines, providing technical assistance to countries, coordinating responses to health emergencies, monitoring global health trends</p>
<p><strong>Current WHO Director-General:</strong> Dr Tedros Adhanom Ghebreyesus (since 2017)</p>

<h4>Other Key Global Health Organizations</h4>
<ul>
<li><strong>UNICEF:</strong> United Nations Children Fund - focuses on child health, nutrition, water/sanitation, education</li>
<li><strong>UNFPA:</strong> United Nations Population Fund - sexual and reproductive health, maternal health, gender equality</li>
<li><strong>World Bank:</strong> Largest source of development finance for health in low-income countries</li>
<li><strong>Global Fund:</strong> International financing institution to fight AIDS, TB, and Malaria</li>
<li><strong>Gavi (Vaccine Alliance):</strong> International vaccine financing organisation; increased immunization coverage in developing countries</li>
<li><strong>Doctors Without Borders (MSF):</strong> Emergency medical humanitarian organization</li>
</ul>

<h3>20.5 Global Health Security</h3>
<p>The International Health Regulations (IHR, 2005) are a legally binding instrument for 196 countries to build capacities to detect, report, and respond to acute public health threats, including epidemics and pandemics.</p>

<p><strong>Public Health Emergency of International Concern (PHEIC):</strong> The highest level of WHO alarm, declared when an event poses a public health risk to other states through international spread and may require a coordinated international response. Examples: COVID-19, Ebola, Zika, polio outbreaks.</p>

<h3>20.6 Millennium Development Goals (MDGs) - Background</h3>
<p>The MDGs were 8 international development goals established following the UN Millennium Declaration (2000) to be achieved by 2015. Health-related MDGs:</p>
<ul>
<li>MDG 4: Reduce child mortality (under-5 mortality by two-thirds)</li>
<li>MDG 5: Improve maternal health (MMR by three-quarters; universal reproductive healthcare)</li>
<li>MDG 6: Combat HIV/AIDS, malaria, and other diseases</li>
</ul>
<p>Progress: Under-5 mortality fell 53%; maternal mortality fell 44%; HIV/AIDS treatment expanded. SDGs build on and extend the MDG framework.</p>

