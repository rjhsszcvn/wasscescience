<h3>19.1 Definition of a Health System</h3>
<p>The <strong>WHO</strong> defines a health system as all organizations, people, and actions whose primary intent is to promote, restore, or maintain health. A health system includes both personal and population health services and activities to influence the determinants of health.</p>

<h3>19.2 Goals of a Health System</h3>
<p>According to the WHO World Health Report 2000, a health system has three fundamental goals:</p>
<ol>
<li><strong>Good health:</strong> Improving population health and reducing inequalities</li>
<li><strong>Responsiveness:</strong> Meeting the legitimate expectations of the population (dignity, autonomy, confidentiality)</li>
<li><strong>Fair financial contribution:</strong> Ensuring financial protection so people are not impoverished by health costs</li>
</ol>

<h3>19.3 Building Blocks (Functions) of a Health System</h3>
<p>The WHO identifies six building blocks of a health system:</p>

<table>
<tr><th>Building Block</th><th>Description</th></tr>
<tr><td>Service delivery</td><td>Delivery of personal and population health services that are safe, effective, quality, accessible, and equitable</td></tr>
<tr><td>Health workforce</td><td>Sufficient, competent, responsive, and productive health workers; includes doctors, nurses, midwives, pharmacists, CHWs</td></tr>
<tr><td>Health information systems</td><td>Reliable, timely data on health status, system performance, and health determinants for policy and planning</td></tr>
<tr><td>Essential medicines and technologies</td><td>Equitable access to essential medicines, vaccines, diagnostics, and medical devices</td></tr>
<tr><td>Health financing</td><td>Adequate funding from appropriate sources; financial protection; efficient resource allocation</td></tr>
<tr><td>Leadership and governance</td><td>Oversight, regulations, policies, and accountability for national health systems</td></tr>
</table>

<h3>19.4 Levels of Healthcare</h3>
<p>Healthcare is organized into three levels to provide a coordinated continuum of care:</p>

<h4>Primary Level (First Contact Care)</h4>
<p>The first point of contact between individuals and the health system. Provides basic, essential health services close to where people live and work.</p>
<ul>
<li>Health centres, community clinics, polyclinics, CHPS (Community-based Health Planning and Services) compounds in Ghana</li>
<li>Services: Outpatient care, maternal and child health, immunization, health education, basic treatment</li>
<li>Staff: Nurses, midwives, physician assistants, community health workers</li>
</ul>

<h4>Secondary Level (District Hospital)</h4>
<p>More specialized care requiring referral from primary level.</p>
<ul>
<li>District hospitals</li>
<li>Services: Surgery, internal medicine, obstetrics, paediatrics, laboratory, radiology</li>
<li>Staff: Doctors (general practitioners and some specialists), nurses, allied health professionals</li>
</ul>

<h4>Tertiary Level (Specialist/Teaching Hospitals)</h4>
<p>Highly specialized and complex care requiring referral from secondary level.</p>
<ul>
<li>Teaching hospitals, regional hospitals, specialist centres</li>
<li>Services: Specialized surgery, oncology, cardiac surgery, neurosurgery, advanced diagnostics</li>
<li>Staff: Specialist doctors, subspecialists, advanced nurses</li>
<li>Also serve as training facilities for health professionals</li>
</ul>

<p><strong>Referral system:</strong> Patients move from primary to secondary to tertiary level based on complexity of their condition; reverse referral (step-down) returns patients to lower levels for continued care.</p>

<h3>19.5 Ghana Health System</h3>
<p>Ghana operates a three-tier health system:</p>
<ul>
<li><strong>National level:</strong> Teaching hospitals (Korle-Bu Teaching Hospital, Komfo Anokye Teaching Hospital, University of Ghana Medical Centre)</li>
<li><strong>Regional level:</strong> Regional hospitals in each of the 16 regions</li>
<li><strong>District level:</strong> District hospitals and health centres</li>
<li><strong>Sub-district level:</strong> CHPS compounds, clinics, polyclinics</li>
</ul>

<p><strong>Key Organizations:</strong></p>
<ul>
<li><strong>Ministry of Health (MOH):</strong> Policy-making and regulation</li>
<li><strong>Ghana Health Service (GHS):</strong> Implementation of health services</li>
<li><strong>National Health Insurance Authority (NHIA):</strong> Manages the National Health Insurance Scheme (NHIS)</li>
</ul>

<h3>19.6 Health Financing</h3>

<h4>Sources of Health Financing</h4>
<ul>
<li><strong>Government/Tax revenue:</strong> Public financing from general taxation</li>
<li><strong>Social health insurance:</strong> Compulsory insurance contributions (e.g., NHIS in Ghana)</li>
<li><strong>Private health insurance:</strong> Voluntary private schemes</li>
<li><strong>Out-of-pocket payments:</strong> Direct payments by patients at point of care - most inequitable; causes financial hardship</li>
<li><strong>Donor/external funding:</strong> International aid and development assistance</li>
</ul>

<h4>National Health Insurance Scheme (NHIS) - Ghana</h4>
<p>Established in 2003 under the National Health Insurance Act (Act 650); aims to provide universal health coverage to Ghanaians.</p>
<p><strong>Funding sources:</strong> 2.5% National Health Insurance Levy (on VAT-able goods), 2.5% SSNIT (Social Security) contribution from workers, government subvention, premiums from informal sector</p>
<p><strong>Benefits package:</strong> Covers about 95% of common diseases treated in Ghana; excludes some specialized services</p>
<p><strong>Challenges:</strong> Sustainability, inadequate funding, claims management, provider quality</p>

<h3>19.7 Universal Health Coverage (UHC)</h3>
<p>The concept that all people and communities can access the quality health services they need without suffering financial hardship.</p>

<p><strong>Three dimensions of UHC:</strong></p>
<ol>
<li><strong>Population coverage:</strong> Who is covered? (everyone)</li>
<li><strong>Service coverage:</strong> What services are covered? (all needed services)</li>
<li><strong>Financial protection:</strong> How much financial risk is covered? (no catastrophic expenditure)</li>
</ol>

<h3>19.8 Health Workforce Challenges in Africa</h3>
<ul>
<li>Critical shortage of health workers (WHO minimum: 44.5 health workers per 10,000 population)</li>
<li>Brain drain: Migration of trained health workers to higher-income countries</li>
<li>Maldistribution: Urban concentration of health workers; rural areas underserved</li>
<li>Inadequate training infrastructure</li>
<li>Poor working conditions and low salaries</li>
</ul>

