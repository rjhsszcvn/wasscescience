<h3>20.1 Global Health Overview</h3>
<p><strong>Global health</strong> is an area of study, research, and practice that places a priority on improving health and achieving equity in health for all people worldwide. It emphasizes transnational health issues, determinants, and solutions.</p>

<h3>20.2 Major Global Health Issues</h3>

<h4>20.2.1 Infectious Diseases</h4>
<p>Despite advances, infectious diseases remain a leading cause of death, especially in low-income countries.</p>

<p><strong>HIV/AIDS:</strong></p>
<ul>
<li>38 million people living with HIV globally (2021)</li>
<li>Sub-Saharan Africa accounts for about 70% of global burden</li>
<li>Progress: Antiretroviral therapy has transformed HIV from a death sentence to a chronic manageable condition</li>
<li>UNAIDS 90-90-90 targets (now 95-95-95): 95% of people with HIV know their status; 95% of those who know their status are on treatment; 95% of those on treatment have viral suppression</li>
</ul>

<p><strong>Malaria:</strong></p>
<ul>
<li>241 million cases globally (2020); 627,000 deaths (mostly children under 5 in Africa)</li>
<li>RTS,S/AS01 vaccine (Mosquirix) approved by WHO in 2021 - first malaria vaccine</li>
<li>Roll Back Malaria campaign; Global Fund for AIDS, TB and Malaria</li>
</ul>

<p><strong>Tuberculosis:</strong></p>
<ul>
<li>10 million new TB cases annually; 1.5 million deaths</li>
<li>Stop TB Partnership and WHO End TB Strategy</li>
<li>Multi-drug resistant TB (MDR-TB) is a growing threat</li>
</ul>

<p><strong>COVID-19 Pandemic:</strong></p>
<ul>
<li>Caused by SARS-CoV-2; declared pandemic by WHO in March 2020</li>
<li>Over 6 million deaths recorded</li>
<li>Demonstrated the importance of global health security, surveillance, and equitable vaccine distribution</li>
<li>Accelerated development of mRNA vaccines</li>
<li>COVAX initiative: Aimed to ensure equitable global vaccine access</li>
</ul>

<h4>20.2.2 Non-Communicable Diseases (NCDs)</h4>
<ul>
<li>NCDs account for 74% of global deaths (WHO, 2021)</li>
<li>Cardiovascular disease, cancer, diabetes, and chronic respiratory diseases are the big four</li>
<li>NCDs are increasing in low- and middle-income countries (double burden of disease)</li>
<li>WHO Global Action Plan for the Prevention and Control of NCDs 2013-2030: 9 voluntary global targets including 25% reduction in premature NCD mortality</li>
</ul>

<h4>20.2.3 Mental Health</h4>
<ul>
<li>1 in 4 people globally will experience a mental health condition in their lifetime</li>
<li>Depression is the leading cause of disability worldwide</li>
<li>Large "treatment gap": Over 75% of people with mental disorders in low-income countries receive no treatment</li>
<li>WHO Mental Health Action Plan 2013-2030</li>
</ul>

<h4>20.2.4 Antimicrobial Resistance (AMR)</h4>
<p>AMR occurs when bacteria, viruses, fungi, and parasites evolve to resist the medicines that kill them, making infections harder to treat.</p>
<ul>
<li>Estimated 1.27 million deaths directly attributable to AMR in 2019</li>
<li>Causes: Overuse and misuse of antibiotics in humans and agriculture</li>
<li>Consequences: Common infections become untreatable; procedures like surgery and chemotherapy become more dangerous</li>
<li>Prevention: Rational use of antibiotics, infection prevention, surveillance, antibiotic stewardship programmes</li>
</ul>

<h4>20.2.5 Health Inequities</h4>
<p>Unfair and avoidable differences in health outcomes between different population groups.</p>
<ul>
<li>Life expectancy varies by over 30 years between richest and poorest countries</li>
<li>Under-5 mortality rate in sub-Saharan Africa is 20 times higher than in high-income countries</li>
<li>Health inequities driven by social determinants: income, education, race, gender, geography</li>
</ul>

<h3>20.3 Sustainable Development Goals (SDGs)</h3>
<p>The SDGs are 17 global goals adopted by all UN member states in September 2015 as part of the 2030 Agenda for Sustainable Development. They replaced the Millennium Development Goals (MDGs) which covered 2000-2015.</p>

<p><strong>The 17 SDGs:</strong></p>
<ol>
<li>No Poverty</li>
<li>Zero Hunger</li>
<li>Good Health and Well-Being</li>
<li>Quality Education</li>
<li>Gender Equality</li>
<li>Clean Water and Sanitation</li>
<li>Affordable and Clean Energy</li>
<li>Decent Work and Economic Growth</li>
<li>Industry, Innovation and Infrastructure</li>
<li>Reduced Inequalities</li>
<li>Sustainable Cities and Communities</li>
<li>Responsible Consumption and Production</li>
<li>Climate Action</li>
<li>Life Below Water</li>
<li>Life on Land</li>
<li>Peace, Justice and Strong Institutions</li>
<li>Partnerships for the Goals</li>
</ol>

<h4>SDG 3: Good Health and Well-Being</h4>
<p>The primary health SDG with 13 specific targets, including:</p>
<ul>
<li>3.1: Reduce global maternal mortality to less than 70 per 100,000 live births</li>
<li>3.2: End preventable deaths of newborns and children under 5</li>
<li>3.3: End epidemic of AIDS, TB, malaria, and neglected tropical diseases; combat hepatitis, water-borne diseases, and other communicable diseases</li>
<li>3.4: Reduce premature mortality from NCDs by one-third through prevention and treatment</li>
<li>3.5: Strengthen prevention and treatment of substance abuse</li>
<li>3.6: Halve the number of global deaths and injuries from road traffic accidents</li>
<li>3.7: Ensure universal access to sexual and reproductive healthcare services</li>
<li>3.8: Achieve universal health coverage</li>
<li>3.9: Reduce illnesses and deaths from hazardous chemicals and air, water, and soil pollution</li>
<li>3.d: Strengthen the capacity for early warning, risk reduction and management of national and global health risks</li>
</ul>

