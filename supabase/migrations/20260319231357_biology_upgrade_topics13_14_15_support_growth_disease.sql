### Plant Growth Regulators (Phytohormones)

**1. Auxins (IAA — Indole Acetic Acid)**
- Produced in shoot tips (apical meristem)
- Promote cell elongation on the SHADED side → shoots bend toward light (phototropism)
- High concentration INHIBITS root growth; low concentration PROMOTES root growth
- Cause apical dominance (side branches suppressed while main shoot grows)
- Used commercially: rooting powder, weed killers (2,4-D)

```
Phototropism (bending toward light):
Light from left:
         Auxin moves to SHADED side (right)
         ↓
Cells on right elongate MORE than left side
         ↓
Shoot BENDS toward light (left)
```

**2. Gibberellins**
- Promote stem elongation (internode elongation)
- Break seed dormancy → promote germination
- Promote fruit development (seedless fruit)
- Used in brewing (barley malting)

**3. Cytokinins**
- Promote cell division
- Delay leaf aging (senescence)
- Work with auxins in tissue culture

**4. Abscisic acid (ABA)**
- Inhibitor hormone
- Causes stomata to close (water stress/drought)
- Induces seed dormancy
- Causes leaf and fruit drop (abscission)

