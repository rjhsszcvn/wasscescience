### Worked Example 1: Malaria Control
Q: A community in Ghana has a high incidence of malaria. Suggest FOUR methods to reduce the spread.

**Answer:**
1. **Insecticide-treated bed nets (ITNs):** Prevent mosquito bites at night when Anopheles feeds
2. **Indoor residual spraying (IRS):** Apply insecticide to walls; kills resting mosquitoes
3. **Elimination of breeding sites:** Remove standing water (old tyres, pots, blocked gutters)
4. **Larval source management:** Apply larvicides (e.g., Bacillus thuringiensis) to standing water
5. **Community education:** Teach people to use nets, seek treatment, recognise symptoms
6. **Early diagnosis and treatment:** Use ACT (Artemisinin-based Combination Therapy)

