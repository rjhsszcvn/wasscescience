### Lines of Defence Against Disease

**First Line of Defence — Physical and Chemical Barriers:**
```
Skin → physical barrier; slightly acidic (pH 5.5) → inhibits bacteria
Mucus → traps pathogens in respiratory tract
Cilia → sweeps mucus (and trapped pathogens) upward and out
Stomach acid (HCl, pH 2) → kills most swallowed pathogens
Tears, saliva → contain lysozyme (enzyme that breaks down bacterial cell walls)
Cerumen (earwax) → traps pathogens in ear canal
```

**Second Line of Defence — Non-specific Immune Response:**
- **Phagocytosis:** Neutrophils and macrophages engulf and destroy pathogens
  ```
  Pathogen detected → phagocyte moves toward it (chemotaxis) →
  Phagocyte engulfs pathogen (phagocytosis) →
  Lysosomes fuse → digestive enzymes destroy pathogen
  ```
- **Inflammation:** Blood vessels dilate; more white blood cells recruited
- **Fever:** Elevated temperature inhibits pathogen reproduction; speeds up immune reactions

**Third Line of Defence — Specific Immune Response (Adaptive Immunity):**

```
Pathogen (has antigens on surface)
        ↓
Antigen-presenting cells show antigens to lymphocytes
        ↓
     ┌──────────────┬──────────────┐
  B lymphocytes               T lymphocytes
