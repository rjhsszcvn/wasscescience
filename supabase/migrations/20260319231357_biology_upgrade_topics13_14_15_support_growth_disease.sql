### Worked Example 2: Immune Response Scenario
Q: A person has measles and recovers. 5 years later they are exposed to measles again but do not get sick. Explain.

**Answer:**
- First exposure: Measles virus enters body → antigens recognised by lymphocytes → specific antibodies produced; memory cells formed
- On second exposure: Memory B cells and T cells recognise measles antigens immediately
- Rapid and massive antibody production (secondary immune response — faster and stronger)
- Virus destroyed before it can cause significant infection → person does not develop symptoms
- This is called **acquired active immunity**

