### Where Does Photosynthesis Occur?
- In **chloroplasts** (mainly in palisade mesophyll cells of leaves)
- The green pigment **chlorophyll** absorbs light energy
- Chlorophyll absorbs **red and blue** light best; reflects **green** light (why leaves look green)

