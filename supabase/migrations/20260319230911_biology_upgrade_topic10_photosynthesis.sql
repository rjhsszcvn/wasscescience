### Significance of Photosynthesis
- **Food production:** Provides the entry point of energy into all food chains
- **Oxygen production:** Produces all the O₂ in Earth''s atmosphere
- **CO₂ removal:** Helps regulate atmospheric CO₂ → reduces greenhouse effect
- **Fossil fuels:** Ancient photosynthesis stored energy in coal, oil, gas

