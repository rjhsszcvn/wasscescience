### Experiment 1: Testing a Leaf for Starch (Proving Photosynthesis Occurred)
**Principle:** Photosynthesis produces glucose → stored as starch

**Procedure:**
1. Boil leaf in water for 1-2 minutes (to kill cells and stop reactions)
2. Boil leaf in ethanol (using water bath — NEVER direct flame — ethanol is flammable) → removes chlorophyll
3. Rinse leaf in warm water → soften leaf
4. Add iodine solution to leaf

**Result:** Leaf turns blue-black → starch is present → photosynthesis occurred

---

### Experiment 2: Showing That Light Is Needed for Photosynthesis (Variegated Leaf)
- Use a variegated leaf (green and white/yellow parts)
