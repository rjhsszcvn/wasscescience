### Worked Example 1: Interpreting a Rate Graph
Q: A student measured the rate of photosynthesis in Elodea at different CO₂ concentrations, at two light intensities (dim and bright). At low CO₂, both curves plateau at the same low rate. At higher CO₂, the bright light curve increases but dim light curve plateaus earlier. Explain.

**Answer:**
- At very low CO₂: CO₂ is the limiting factor — both light intensities give the same low rate
- At higher CO₂ with bright light: light is sufficient → more photosynthesis possible → rate increases
- At higher CO₂ with dim light: dim light becomes the limiting factor → rate cannot increase further despite more CO₂
- Conclusion: at higher CO₂ concentrations, LIGHT becomes the limiting factor in the dim light curve

---

### Worked Example 2: Compensation Point
**Compensation point:** The light intensity at which photosynthesis rate equals respiration rate.
- Below compensation point: more CO₂ produced (by respiration) than absorbed (by photosynthesis)
- Above compensation point: more CO₂ absorbed than produced → net photosynthesis

```
CO₂ exchange
     │            /  ← net photosynthesis
     │           /
─────│──────────/──────────────── 0 line
     │         ↑
     │  Compensation
     │     point
     │  ← net respiration
```

---

### Worked Example 3: Calculating Photosynthesis Rate
Q: Elodea produced 40 bubbles in 2 minutes. Calculate the rate of O₂ production.

**Rate = 40 ÷ 2 = 20 bubbles per minute**

If each bubble has a volume of 0.02 cm³:
**Volume of O₂ = 20 × 0.02 = 0.4 cm³ per minute**

