### The Two Stages of Photosynthesis

**Stage 1: Light-Dependent Reactions (in thylakoid membranes)**
```
Light energy + Water → ATP + NADPH + O₂
                               ↓
              Products used in Stage 2
              O₂ released as waste (byproduct)
```
- Occurs in **thylakoids** (grana) of chloroplast
- Chlorophyll absorbs light → light energy converted to chemical energy (ATP)
- Water is split (photolysis): H₂O → 2H⁺ + ½O₂ + 2e⁻
- O₂ is a **byproduct** (released through stomata)

**Stage 2: Light-Independent Reactions / Calvin Cycle (in stroma)**
```
CO₂ + ATP + NADPH → Glucose (C₆H₁₂O₆)
                    (occurs in stroma)
```
- Occurs in the **stroma** of chloroplast
- CO₂ is fixed (combined with RuBP by enzyme RuBisCO) → produces 3-carbon compounds
- ATP and NADPH from stage 1 used to reduce CO₂ to glucose
- Does NOT directly require light (but needs products of stage 1)

