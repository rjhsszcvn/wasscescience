### Factors Affecting the Rate of Photosynthesis

**Limiting factors** — factors that can slow down or stop photosynthesis:

| Factor | Effect on Rate | Explanation |
|---|---|---|
| **Light intensity** | Increases rate up to a point | More light → more ATP and NADPH from stage 1 |
| **CO₂ concentration** | Increases rate up to a point | More substrate for Calvin cycle |
| **Temperature** | Increases up to optimum (~25-35°C) then falls | Enzymes work faster → then denature at high temp |
| **Water availability** | Low water → stomata close → less CO₂ enters → rate falls | |
| **Chlorophyll amount** | More chlorophyll → more light absorbed | |

**Law of limiting factors:** The rate of photosynthesis is limited by the factor that is in shortest supply.

```
Rate of
photosynthesis
     │               ─────────────  ← CO₂ becomes limiting
     │            ──/
     │          ─/
     │        ─/
     │      ─/
     │    ─/
     └──────────────────────────── Light intensity

Even with more light, rate cannot increase further without more CO₂
```

