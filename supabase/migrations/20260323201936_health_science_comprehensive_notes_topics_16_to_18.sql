<h3>17.1 Definition and Importance</h3>
<p>A <strong>school health programme</strong> is a coordinated set of planned health-related activities designed to promote, protect, and maintain the health of students and school staff, and to prevent disease and injury in the school community.</p>

<p>Schools are an ideal setting for health promotion because:</p>
<ul>
<li>Children spend a significant portion of their time at school</li>
<li>Schools provide access to a large proportion of the child and adolescent population</li>
<li>Health habits and behaviours are forming during school years</li>
<li>Schools have a trained workforce (teachers, nurses)</li>
<li>Health education can be integrated into the curriculum</li>
</ul>

<h3>17.2 Components of a School Health Programme</h3>
<p>The WHO Health-Promoting Schools framework identifies eight components:</p>

<h4>17.2.1 School Health Services</h4>
<p>Health care provided to students and staff at school.</p>
<ul>
<li><strong>Health screening:</strong> Regular assessments to detect health problems early
  <ul>
  <li>Vision screening (detect refractive errors)</li>
  <li>Hearing screening (detect hearing loss)</li>
  <li>Nutritional assessment (growth monitoring)</li>
  <li>Dental screening (caries, periodontal disease)</li>
  <li>Scoliosis screening (spinal curvature)</li>
  <li>Blood pressure measurement</li>
  </ul>
</li>
<li><strong>Immunization services:</strong> Ensure all children are fully immunized; provide catch-up doses; school-based campaigns (e.g., HPV vaccine)</li>
<li><strong>First aid services:</strong> Treatment of minor injuries and illnesses; referral of serious cases</li>
<li><strong>Mental health services:</strong> School counsellors for students with psychological difficulties</li>
<li><strong>Referral system:</strong> Links with local health facilities for students needing further care</li>
</ul>

<h4>17.2.2 Health Education</h4>
<p>Integration of health education into the school curriculum to develop health knowledge, attitudes, and skills.</p>
<p><strong>Topics include:</strong></p>
<ul>
<li>Personal hygiene and sanitation</li>
<li>Nutrition and healthy eating</li>
<li>Prevention of communicable diseases</li>
<li>Mental health and stress management</li>
<li>Substance abuse prevention</li>
<li>Sexual and reproductive health education</li>
<li>First aid</li>
<li>Road safety and accident prevention</li>
</ul>

<h4>17.2.3 Healthy School Environment</h4>
<p>Both physical and psychosocial environments that support health.</p>

<p><strong>Physical environment:</strong></p>
<ul>
<li>Safe, clean water supply for drinking and handwashing</li>
<li>Adequate, hygienic toilet facilities (separate for boys and girls)</li>
<li>Proper waste disposal</li>
<li>Adequate classroom space and ventilation</li>
<li>Safe playground and sports facilities</li>
<li>Free from environmental hazards (dust, noise, chemicals)</li>
<li>Adequate lighting</li>
</ul>

<p><strong>Psychosocial environment:</strong></p>
<ul>
<li>Positive, inclusive school climate</li>
<li>Zero tolerance for bullying, violence, and discrimination</li>
<li>Supportive teacher-student relationships</li>
<li>Safe space for students to express concerns</li>
</ul>

<h4>17.2.4 School Nutrition Policies and Services</h4>
<ul>
<li>School feeding programmes (e.g., Ghana School Feeding Programme) - improve nutrition and attendance</li>
<li>Nutrition standards for tuck shops and canteens</li>
<li>Prohibition of junk food and sugary drinks in schools</li>
<li>Nutritional education</li>
<li>Deworming programmes (reduce intestinal parasites that impair nutrition and cognition)</li>
<li>Micronutrient supplementation (vitamin A, iron)</li>
</ul>

<h4>17.2.5 Physical Activity and Recreation</h4>
<ul>
<li>Adequate physical education classes (minimum 60 minutes of moderate-vigorous activity daily - WHO recommendation for children)</li>
<li>Safe sports facilities and equipment</li>
<li>Extracurricular sports programmes</li>
<li>Active breaks between classes</li>
<li>Physical activity reduces obesity, improves mental health, academic performance, and sleep quality</li>
</ul>

<h4>17.2.6 Health-Related Staff Policies</h4>
<ul>
<li>Pre-employment health checks for school staff</li>
<li>Teacher training in health education and first aid</li>
<li>Tobacco-free policy on school premises</li>
<li>Staff wellness programmes</li>
</ul>

<h4>17.2.7 Community Partnerships</h4>
<ul>
<li>Collaboration between schools, families, health services, and communities</li>
<li>Parental involvement in health education</li>
<li>Health facility-school referral linkages</li>
<li>NGO partnerships for health programmes</li>
</ul>

<h4>17.2.8 School Health Policies</h4>
<p>Written policies that govern health-related issues in schools.</p>
<ul>
<li>Tobacco-free/alcohol-free/drug-free policies</li>
<li>Healthy food policies</li>
<li>Anti-bullying policy</li>
<li>Infection control policy</li>
<li>Injury prevention policy</li>
</ul>

<h3>17.3 The School Nurse/Health Teacher</h3>
<p>The school health professional plays a central role in the school health programme.</p>

<p><strong>Roles:</strong></p>
<ul>
<li>Providing first aid and basic treatment to sick students</li>
<li>Conducting health screenings</li>
<li>Referring students for follow-up care</li>
<li>Administering immunizations</li>
