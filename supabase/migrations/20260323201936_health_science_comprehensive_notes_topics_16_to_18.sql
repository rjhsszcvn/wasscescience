<h3>16.1 Definition and Concepts</h3>
<p><strong>Community health</strong> refers to the health status of a defined group of people and the collective actions they take to promote, protect, and improve their health.</p>

<p><strong>Community:</strong> A group of people who share a geographic location, common interests, values, or social bonds.</p>

<p><strong>Public health</strong> is the science and art of preventing disease, prolonging life, and promoting health through organized efforts of society (Winslow, 1920).</p>

<p><strong>Primary Health Care (PHC):</strong> Based on the <strong>Declaration of Alma-Ata (1978)</strong> which declared "Health for All by the Year 2000" and promoted primary health care as the key to achieving equitable health globally.</p>

<h4>8 Elements of Primary Health Care (from Alma-Ata)</h4>
<ol>
<li>Health education about prevailing health problems and methods of prevention</li>
<li>Promotion of proper nutrition and food supply</li>
<li>Adequate supply of safe water and basic sanitation</li>
<li>Maternal and child health care, including family planning</li>
<li>Immunization against major infectious diseases</li>
<li>Prevention and control of locally endemic diseases</li>
<li>Appropriate treatment of common diseases and injuries</li>
<li>Provision of essential drugs</li>
</ol>

<h3>16.2 Health Promotion</h3>
<p>Health promotion is the process of enabling people to increase control over, and to improve, their health (Ottawa Charter, 1986).</p>

<h4>Ottawa Charter for Health Promotion (5 Action Areas)</h4>
<ol>
<li><strong>Build healthy public policy:</strong> Policy changes in all sectors that affect health (e.g., tobacco taxes, seat belt laws)</li>
<li><strong>Create supportive environments:</strong> Make health-enabling choices the easy choices (safe workplaces, green spaces)</li>
<li><strong>Strengthen community action:</strong> Empower communities to set priorities and take action</li>
<li><strong>Develop personal skills:</strong> Health education, life skills training</li>
<li><strong>Reorient health services:</strong> Focus on prevention and health promotion, not just treatment</li>
</ol>

<h4>Approaches to Health Education</h4>
<ul>
<li><strong>Medical/preventive approach:</strong> Focuses on disease prevention through individual behaviour change (e.g., immunization campaigns)</li>
<li><strong>Behaviour change approach:</strong> Persuades individuals to adopt healthier lifestyles (e.g., anti-smoking campaigns)</li>
<li><strong>Educational approach:</strong> Provides knowledge and develops skills to make informed decisions</li>
<li><strong>Empowerment approach:</strong> Helps communities identify their own health needs and take action</li>
<li><strong>Social change approach:</strong> Addresses social, economic, and environmental determinants of health</li>
</ul>

<h3>16.3 Community Health Workers (CHWs)</h3>
<p>Community health workers are lay members of the community who receive training to provide basic health services, health education, and act as a link between the community and the formal health system.</p>

<p><strong>Roles of CHWs:</strong></p>
<ul>
<li>Health education and promotion in homes and communities</li>
<li>Disease surveillance and reporting</li>
<li>Immunization support</li>
<li>Maternal and child health support</li>
<li>Referral of patients to health facilities</li>
<li>Distribution of essential medicines (e.g., antimalarials, oral rehydration salts)</li>
</ul>

<h3>16.4 Maternal and Child Health (MCH)</h3>
<p>Maternal and child health programmes address the health needs of women and children as priority populations.</p>

<h4>Antenatal Care (ANC) - Key Components</h4>
<ul>
<li>Blood pressure monitoring (detection of hypertension/pre-eclampsia)</li>
<li>Weight monitoring</li>
<li>Urine testing (protein - pre-eclampsia; glucose - gestational diabetes)</li>
<li>Blood tests (anaemia, blood group, HIV, syphilis, hepatitis B)</li>
<li>Foetal heart rate and position assessment</li>
<li>Ultrasound scanning</li>
<li>Tetanus toxoid immunization</li>
<li>Iron and folic acid supplementation</li>
<li>Intermittent preventive treatment for malaria in pregnancy (IPTp)</li>
<li>Health education (nutrition, danger signs, breastfeeding, birth preparedness)</li>
</ul>

<h4>Postnatal Care</h4>
<p>Care provided to mother and newborn after delivery during the critical first 6 weeks.</p>
<ul>
<li>Monitoring for postpartum haemorrhage (major cause of maternal death)</li>
<li>Breastfeeding support and promotion</li>
<li>Newborn assessments (APGAR score, birth weight, congenital defect screening)</li>
<li>Immunization (BCG, OPV, Hep B at birth)</li>
<li>Family planning counselling</li>
</ul>

<h4>Child Health - Key Indicators and Services</h4>
<ul>
<li>Growth monitoring (regular weight and height measurement)</li>
<li>Immunization (EPI schedule)</li>
<li>Prevention and management of malnutrition</li>
<li>Integrated Management of Childhood Illness (IMCI) - covers pneumonia, diarrhoea, malaria, malnutrition, measles</li>
<li>Vitamin A supplementation</li>
<li>Deworming</li>
</ul>

<h4>Breastfeeding</h4>
<p>WHO recommends exclusive breastfeeding for the first 6 months and continued breastfeeding with complementary foods up to 2 years or beyond.</p>
<p><strong>Benefits of breastfeeding:</strong></p>
<ul>
<li>For infant: Optimal nutrition, passive immunity (colostrum rich in antibodies), reduced risk of infections, SIDS, obesity, and diabetes</li>
<li>For mother: Reduced risk of breast and ovarian cancer, natural child spacing (lactational amenorrhoea), bonding, cost-effective</li>
</ul>
<p><strong>Colostrum:</strong> First milk produced (days 1-3); thick, yellow, rich in antibodies (secretory IgA), growth factors, and nutrients - extremely valuable</p>

<h3>16.5 Social Determinants of Health</h3>
<p>The conditions in which people are born, grow, live, work, and age (WHO). These circumstances are shaped by distribution of money, power, and resources.</p>

<h4>Key Social Determinants</h4>
<ul>
<li><strong>Education:</strong> Higher education associated with better health literacy, employment, and health behaviours</li>
<li><strong>Income and social status:</strong> Poverty is strongly associated with poor health</li>
<li><strong>Employment and working conditions:</strong> Unemployment and poor working conditions negatively affect health</li>
<li><strong>Social support networks:</strong> Social isolation is a risk factor for poor health</li>
<li><strong>Housing:</strong> Overcrowded, poor-quality housing increases disease risk</li>
<li><strong>Food security:</strong> Access to nutritious, affordable food</li>
<li><strong>Access to health services:</strong> Geographic, financial, and cultural barriers</li>
<li><strong>Gender equity:</strong> Gender inequality affects women health and access to care</li>
</ul>

