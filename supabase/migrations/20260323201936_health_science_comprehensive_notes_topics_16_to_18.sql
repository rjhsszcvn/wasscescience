<h3>18.1 Adolescent Health Overview</h3>
<p>Adolescence (10-19 years, WHO definition; often extended to 10-24 years for "young people") is a critical period of physical, psychological, and social development. Adolescents constitute over 1.2 billion globally - the largest generation in history.</p>

<p><strong>Key health issues affecting adolescents:</strong></p>
<ul>
<li>Unintended pregnancy and unsafe abortion</li>
<li>Sexually transmitted infections including HIV</li>
<li>Mental health disorders (depression, anxiety)</li>
<li>Substance use and abuse</li>
<li>Nutrition problems (anaemia, eating disorders, obesity)</li>
<li>Injuries and violence</li>
<li>Menstrual disorders</li>
</ul>

<h3>18.2 Human Sexuality</h3>
<p><strong>Sexuality</strong> is a central aspect of being human throughout life and encompasses sex, gender identities and roles, sexual orientation, eroticism, pleasure, intimacy, and reproduction (WHO).</p>

<h4>Components of Sexuality</h4>
<ul>
<li><strong>Biological sex:</strong> The biological characteristics (chromosomes, hormones, anatomy) that define males, females, and intersex individuals</li>
<li><strong>Gender identity:</strong> A person internal sense of their own gender (man, woman, non-binary)</li>
<li><strong>Gender role:</strong> The social and cultural expectations of behaviour for men and women in a given society</li>
<li><strong>Sexual orientation:</strong> The pattern of emotional, romantic, and/or sexual attraction to others</li>
</ul>

<h4>Sexual Orientation</h4>
<ul>
<li><strong>Heterosexual (straight):</strong> Attracted to people of the opposite sex</li>
<li><strong>Homosexual (gay/lesbian):</strong> Attracted to people of the same sex</li>
<li><strong>Bisexual:</strong> Attracted to people of both sexes</li>
</ul>
<p>Sexual orientation is not a choice and cannot be changed. All sexual orientations are normal variants of human sexuality.</p>

<h3>18.3 Sexual and Reproductive Health of Adolescents</h3>

<h4>Adolescent Pregnancy</h4>
<p>Pregnancy in girls aged 10-19 years. Teen pregnancy rates remain high in sub-Saharan Africa, including Ghana.</p>

<p><strong>Risk factors:</strong></p>
<ul>
<li>Early marriage</li>
<li>Poverty and lack of educational opportunities</li>
<li>Lack of access to family planning services</li>
<li>Peer pressure and coercion</li>
<li>Limited knowledge about contraception</li>
<li>Gender inequality</li>
</ul>

<p><strong>Health consequences of adolescent pregnancy:</strong></p>
<ul>
<li>Obstetric complications: Anaemia, malnutrition, obstructed labour (due to immature pelvis), obstetric fistula, haemorrhage, eclampsia</li>
<li>Maternal death: Complications of pregnancy and childbirth are the leading cause of death in girls aged 15-19 globally</li>
<li>Infant complications: Low birth weight, preterm birth, neonatal death</li>
<li>Social consequences: School dropout, reduced lifetime earnings, cycle of poverty</li>
</ul>

<p><strong>Prevention:</strong></p>
<ul>
<li>Comprehensive sexuality education in schools</li>
<li>Access to youth-friendly family planning services</li>
<li>Keeping girls in school</li>
<li>Addressing gender inequality and poverty</li>
<li>Delayed age at marriage (legal minimum age)</li>
</ul>

<h4>Unsafe Abortion</h4>
<p>A major cause of maternal mortality in adolescents in settings where abortion is restricted. Adolescents are more likely to delay seeking abortion services and to access unsafe providers.</p>

<p><strong>Complications of unsafe abortion:</strong> Sepsis (infection), haemorrhage, uterine perforation, infertility, death</p>

<h4>Adolescent-Friendly Health Services (AFHS)</h4>
<p>Health services specifically designed to be accessible, acceptable, and appropriate for adolescents.</p>
<p><strong>Characteristics of AFHS:</strong></p>
<ul>
<li>Confidentiality and privacy</li>
<li>Non-judgmental attitude of providers</li>
<li>Convenient location and opening hours</li>
<li>Affordable</li>
<li>Staffed by trained youth-friendly providers</li>
<li>Provide integrated services (sexual health, mental health, substance abuse)</li>
</ul>

<h3>18.4 Comprehensive Sexuality Education (CSE)</h3>
<p>CSE is an age-appropriate, culturally relevant approach to teaching about sex and relationships by providing scientifically accurate, realistic, non-judgmental information. Evidence shows that CSE does NOT increase sexual activity; it helps adolescents make safer, more informed decisions.</p>

<p><strong>Components of CSE:</strong></p>
<ul>
<li>Human development (puberty, reproduction, sexual orientation)</li>
<li>Relationships (family, peer, romantic, communication)</li>
<li>Personal skills (decision-making, communication, negotiation, refusal skills)</li>
<li>Sexual behaviour (abstinence, safer sex, contraception)</li>
<li>Sexual health (STIs/HIV prevention, pregnancy prevention)</li>
<li>Society and culture (gender roles, power, rights, media literacy)</li>
</ul>

<h3>18.5 Consent and Healthy Relationships</h3>
<p><strong>Consent</strong> is a freely given, reversible, informed, enthusiastic, and specific agreement to engage in a sexual activity. Consent must be:</p>
<ul>
<li><strong>Freely given:</strong> Without coercion, manipulation, or intoxication</li>
<li><strong>Reversible:</strong> Can be withdrawn at any time</li>
<li><strong>Informed:</strong> Both parties must understand what they are agreeing to</li>
<li><strong>Enthusiastic:</strong> Both parties want to participate</li>
<li><strong>Specific:</strong> Agreeing to one activity does not mean agreeing to all</li>
</ul>

<p><strong>Sexual abuse and assault:</strong> Any sexual activity without consent. Includes rape, sexual harassment, child sexual abuse. Survivors should seek immediate medical care (72-hour window for PEP, emergency contraception) and psychosocial support.</p>

<h4>Characteristics of Healthy Relationships</h4>
<ul>
<li>Mutual respect and equality</li>
<li>Open, honest communication</li>
<li>Trust and honesty</li>
<li>Personal space and independence</li>
<li>Support for each other goals</li>
<li>Shared responsibility</li>
<li>Safety (physical and emotional)</li>
</ul>

<h4>Signs of Unhealthy/Abusive Relationships</h4>
<ul>
<li>Control and jealousy</li>
<li>Isolation from friends and family</li>
<li>Physical, verbal, or emotional abuse</li>
<li>Pressure for sex</li>
<li>Humiliation or put-downs</li>
<li>Threats</li>
</ul>

<h3>18.6 Menstrual Health</h3>
<p><strong>Menstrual hygiene management (MHM)</strong> is essential for girls health, dignity, and school attendance.</p>

<p><strong>Common menstrual problems:</strong></p>
<ul>
<li><strong>Dysmenorrhoea:</strong> Painful periods; primary (no underlying pathology) or secondary (e.g., endometriosis); managed with NSAIDs (ibuprofen), heat, exercise</li>
<li><strong>Amenorrhoea:</strong> Absence of periods; primary (no period by age 16) or secondary (period stops for 3+ months); causes include pregnancy, hormonal issues, low body weight, stress</li>
<li><strong>Menorrhagia:</strong> Heavy or prolonged bleeding; can cause iron-deficiency anaemia</li>
<li><strong>Irregular cycles:</strong> Common in early adolescence as hormonal regulation is established</li>
<li><strong>Premenstrual syndrome (PMS):</strong> Physical and emotional symptoms in the days before menstruation</li>
</ul>

