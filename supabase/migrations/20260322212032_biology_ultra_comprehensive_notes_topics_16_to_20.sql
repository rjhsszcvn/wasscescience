## 1. What is Evolution?

Evolution: The gradual change in the inherited characteristics of populations over successive generations.

Macroevolution: Large-scale changes leading to new species.
Microevolution: Small-scale changes in allele frequencies within a population.

Key concepts:
- Populations (not individuals) evolve
- Evolution occurs over many generations
- Evolution is driven by natural selection acting on variation
- All life on Earth shares a common ancestor

---

## 2. Evidence for Evolution

### 2.1 Fossil Record
- Fossils: Preserved remains or traces of ancient organisms
- Show progression from simple to complex forms
- Transitional fossils show intermediate forms (e.g., Tiktaalik — fish-tetrapod transition; Archaeopteryx — dinosaur-bird transition)
- Relative and absolute dating (radiometric dating with carbon-14, uranium-lead)

### 2.2 Comparative Anatomy

Homologous structures:
- Same basic structure but different functions
- Suggest common ancestry
- Example: Forelimb bones of human, whale, bat, horse (same bones — humerus, radius, ulna, carpals, phalanges — modified for different uses)

Analogous structures:
- Different structure but same function (convergent evolution)
- Not evidence of common ancestry
- Example: Wings of birds and insects (same function, different structure)

Vestigial organs:
- Remnants of structures that were functional in ancestors but are reduced/functionless now
- Example: Human appendix, coccyx (tail bone), wisdom teeth, ear-moving muscles
- Strong evidence for evolution

### 2.3 Molecular Evidence
- DNA sequences: More similar DNA → more closely related
- Protein sequences: Cytochrome c, haemoglobin — similar in related organisms
- rRNA sequences: Used in phylogenetics
- More similar sequences → more recent common ancestor

### 2.4 Biogeography
- Distribution of species around the world
- Related species found in geographically close regions
- Darwin''s finches: 13 species in Galapagos; all descended from one South American ancestor; beak shapes adapted to different foods (adaptive radiation)
- Marsupials concentrated in Australia (isolated from rest of world)

### 2.5 Comparative Embryology
- Embryos of different vertebrates look very similar in early stages
- All vertebrate embryos have gill pouches, tails, similar somites
- Suggests common ancestry

