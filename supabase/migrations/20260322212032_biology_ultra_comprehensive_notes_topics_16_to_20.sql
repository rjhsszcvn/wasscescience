## 8. Stem Cell Technology

Embryonic stem cells:
- Harvested from inner cell mass of blastocyst (4-5 day embryo)
- Pluripotent: Can become any cell type
- Ethical controversy: Destruction of embryo

Adult stem cells:
- Found in bone marrow, blood, brain, etc.
- More limited differentiation potential (multipotent)
- Used in bone marrow transplants (treat leukemia)

Induced Pluripotent Stem Cells (iPSCs):
- Adult cells reprogrammed back to pluripotent state
- Avoids embryo destruction
- Can make patient-matched cell lines (no immune rejection)

Medical applications:
- Bone marrow transplant (leukemia, sickle cell)
- Skin grafts (burns)
- Research: Model diseases in lab, test drugs
- Future potential: Grow organs for transplant; treat Parkinson''s, diabetes, spinal cord injuries

