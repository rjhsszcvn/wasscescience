## 2. Trophic Levels

Trophic level: Each step in a food chain representing a feeding level.

Level 1: Producers (Autotrophs)
- Make own food via photosynthesis or chemosynthesis
- Plants, algae, phytoplankton, cyanobacteria
- Capture solar energy and store as chemical energy

Level 2: Primary Consumers (Herbivores)
- Eat producers directly
- Examples: Grass → grasshopper; plankton → zooplankton; leaves → caterpillar; grass → cow

Level 3: Secondary Consumers (First-level carnivores / Omnivores)
- Eat primary consumers
- Examples: Grasshopper → frog; caterpillar → small bird; zooplankton → small fish

Level 4: Tertiary Consumers (Second-level carnivores)
- Eat secondary consumers
- Examples: Frog → snake; small bird → hawk; small fish → large fish

Decomposers (Detritivores/Saprotrophs):
- Break down dead organic matter from ALL trophic levels
- Bacteria and fungi
- Return nutrients to soil/water
- Not a trophic level in traditional sense but essential for nutrient cycling

