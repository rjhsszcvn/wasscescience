## 5. Photoperiodism

Photoperiodism: Biological response of organisms to the length of day and night (photoperiod).

Plants use photoperiod to time flowering.

Types of plants:
- Short-day plants (SDP): Flower when days are SHORT (nights are long)
  - Examples: Chrysanthemum, poinsettia, soybean, cannabis
  - Critical night length: Night must exceed a minimum length
- Long-day plants (LDP): Flower when days are LONG (nights are short)
  - Examples: Wheat, barley, spinach, lettuce, clover
- Day-neutral plants: Flower regardless of photoperiod (controlled by other factors)
  - Examples: Tomato, cucumber, sunflower

Phytochrome:
- Photoreceptor pigment that detects light
- Pr (Phytochrome Red): Absorbs red light (660 nm) → converted to Pfr
- Pfr (Phytochrome Far-red): Absorbs far-red light (730 nm) → converted to Pr
- Sunlight (rich in red) → most phytochrome converted to Pfr form
- In darkness: Pfr slowly converts back to Pr

How phytochrome regulates flowering:
- Short-day plants: Need long nights (continuous darkness) → Pfr converts back to Pr → triggers flowering
- Long-day plants: Short nights → Pfr levels stay high → triggers flowering
- Brief light flash during night: Converts Pr → Pfr → inhibits short-day plant flowering

