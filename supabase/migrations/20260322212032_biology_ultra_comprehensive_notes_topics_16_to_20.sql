## 7. Investigating Photosynthesis

### 7.1 DCPIP Decolorization
- DCPIP is a blue dye → decolorized when electrons transferred (reduced)
- Illuminated chloroplasts + DCPIP → decolorizes (shows light reactions transfer electrons)
- Dark control: No decolorization

### 7.2 Investigating Effect of Light Intensity on Photosynthesis (Elodea)
Materials: Aquatic plant (Elodea/Cabomba), light source, ruler, beaker, sodium bicarbonate (CO₂ source)

Procedure:
1. Place plant in beaker of sodium bicarbonate solution
2. Illuminate at different distances from light source
3. Count bubbles per minute (or volume of O₂ collected)
4. Light intensity proportional to 1/distance²

Results: As light intensity increases → rate of O₂ production increases → then levels off (another factor becomes limiting)

### 7.3 Leaf Disc Method (More quantitative)
- Leaf discs sink in syringe (air removed by syringe)
- Placed in sodium bicarbonate solution under different light intensities
- Photosynthesis produces O₂ → discs float → count floating discs over time

