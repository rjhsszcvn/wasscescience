## 4. Food Webs

A food web shows the complex network of feeding relationships in an ecosystem.

More realistic than food chains because:
- Most organisms eat more than one type of food
- Most organisms are eaten by more than one predator
- Shows interconnections and dependencies

Reading a food web:
- Follow arrows to trace energy flow
- Identify producers, consumers at each level
- Identify keystone species (removal causes collapse)

Implications of food webs:
- Removing one species affects entire web (trophic cascade)
- Example: Remove wolves from Yellowstone → deer population explodes → overgrazing → vegetation loss → erosion → stream changes
- Reintroducing wolves → trophic cascade reversed

