## 6. Ecological Pyramids

### 6.1 Pyramid of Numbers
- Represents number of organisms at each trophic level
- Usually decreases from bottom to top
- Can be INVERTED:
  - Parasite food chain: Many parasites on one host (one tree → many caterpillars → many parasitic wasps)
  - One large producer → many small consumers

### 6.2 Pyramid of Biomass
- Represents total mass (usually dry mass) of organisms at each trophic level per unit area
- Usually decreases from base to top (more mass at lower levels)
- Can be inverted: Marine ecosystems (phytoplankton reproduce so rapidly that at any instant, zooplankton biomass > phytoplankton biomass)

### 6.3 Pyramid of Energy
- Represents the amount of energy flowing through each trophic level per unit area per unit time
- ALWAYS decreases from base to top — NEVER INVERTED
- Most accurate representation of ecosystem structure
- Unit: kJ m⁻² year⁻¹

Why pyramid of energy is most useful:
- Accounts for time (productivity, not just what is present at one moment)
- Not affected by variation in organism size
- Truly reflects energy available at each level

