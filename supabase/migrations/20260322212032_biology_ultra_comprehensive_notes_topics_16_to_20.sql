## 3. Darwin''s Theory of Natural Selection

Charles Darwin (1809-1882):
- Voyaged on HMS Beagle (1831-1836); visited Galapagos Islands
- Published "On the Origin of Species" (1859)

Alfred Russel Wallace: Independently developed similar theory; prompted Darwin to publish.

### 3.1 Darwin''s Observations and Inferences

Observations:
1. Organisms produce more offspring than can survive (overproduction)
2. Population sizes remain relatively stable over time
3. Variation exists among individuals in a population

Inferences:
4. There is a struggle for existence (competition for limited resources)
5. Individuals with advantageous variations are more likely to survive and reproduce
6. Advantageous traits are passed on to offspring (heritability)

### 3.2 Natural Selection — Key Principles

1. Variation: Individuals in a population vary in their traits.
   - Sources: Mutation, sexual reproduction (crossing over, independent assortment, random fertilization)

2. Inheritance: Traits can be passed from parents to offspring.

3. Differential survival and reproduction: Individuals with advantageous traits are more likely to survive and reproduce ("survival of the fittest").
   - Fitness: Ability to survive and reproduce in a given environment

4. Accumulation of favorable traits: Over generations, proportion of individuals with advantageous traits increases.

### 3.3 Types of Natural Selection

Directional selection:
- Selection favors one extreme phenotype
- Population mean shifts in one direction
- Example: Antibiotic resistance in bacteria; dark moths in industrial areas (industrial melanism)

Stabilizing selection:
- Selection favors average/intermediate phenotype
- Extremes selected against
- Reduces variation
- Example: Human birth weight (very small or very large babies have higher mortality)

Disruptive selection:
- Selection favors both extremes; middle phenotype disadvantaged
- Can lead to speciation
- Example: Darwin''s finches — medium beak size disadvantaged (different food sources)

