## 7. Nutrient Cycling in Ecosystems

Unlike energy (which flows through and is lost as heat), nutrients are CYCLED.

### 7.1 Carbon Cycle (Summary)

CO₂ pool in atmosphere
↓ Photosynthesis → Organic carbon in producers
↓ Consumption → Organic carbon in consumers
↓ Respiration → CO₂ returned to atmosphere
↓ Death → Organic carbon in dead matter
↓ Decomposition → CO₂ returned to atmosphere
↓ Fossilization (long-term) → Fossil fuels
↓ Combustion → CO₂ released (greenhouse gas)

### 7.2 Nitrogen Cycle

Nitrogen is essential for proteins, nucleic acids, ATP.

Atmospheric N₂ (78% of atmosphere; unusable by most organisms)
↓ Nitrogen fixation (Rhizobium in legume root nodules; Azotobacter in soil; lightning)
↓ Ammonium (NH₄⁺) in soil
↓ Nitrification (Nitrosomonas bacteria: NH₄⁺ → NO₂⁻; then Nitrobacter: NO₂⁻ → NO₃⁻)
↓ Plant uptake of NO₃⁻ through roots (active transport)
↓ Assimilation into amino acids, proteins
↓ Consumption by animals → proteins in animal tissues
↓ Death → ammonification by decomposers → NH₄⁺ back to soil
↓ Denitrification (Pseudomonas denitrificans in waterlogged, anaerobic soils): NO₃⁻ → N₂

Important organisms:
- Rhizobium: Mutualistic bacteria in root nodules of legumes (beans, peas, groundnuts)
- Azotobacter: Free-living nitrogen-fixing bacteria in soil
- Nitrosomonas, Nitrobacter: Nitrifying bacteria
- Pseudomonas: Denitrifying bacteria (reduce soil fertility in waterlogged conditions)

