## 5. Energy Flow Through Ecosystems

### 5.1 Energy Input

Energy enters most ecosystems as sunlight (solar energy).
- Photosynthesis converts light energy to chemical energy (glucose)

Productivity:
- Gross Primary Productivity (GPP): Total energy fixed by photosynthesis per unit area per unit time
- Net Primary Productivity (NPP): GPP - energy used by plant for respiration
  - NPP = GPP - R (respiration)
  - NPP represents energy available to consumers

### 5.2 Energy Transfer Between Trophic Levels

Energy lost at each trophic level:
- Not all organisms consumed (parts uneaten — dead leaves, bones, hair)
- Not all consumed material digested and absorbed (undigested food → feces = egestion)
- Energy used for respiration (metabolic processes — heat)
- Energy used for movement, maintenance, growth

Ecological efficiency:
- Typically only about 10% of energy transfers to next trophic level
- 90% lost as heat (respiration), undigested material (egestion), uneaten material

Example:
- Grass captures 10,000 kJ from sun (NPP)
- Grasshoppers obtain ~1,000 kJ from grass (10%)
- Frogs obtain ~100 kJ from grasshoppers (10%)
- Snakes obtain ~10 kJ from frogs (10%)

Why food chains are short:
- By the 4th or 5th trophic level, so little energy remains that further levels are unsupported
- Typically 3-5 levels maximum

### 5.3 Production Efficiency

Assimilation efficiency = (Energy assimilated / Energy consumed) × 100
Ecological efficiency = (Energy available at trophic level n+1 / Energy at trophic level n) × 100

