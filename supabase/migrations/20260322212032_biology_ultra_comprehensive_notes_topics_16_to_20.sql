## 3. Food Chains

A food chain shows linear transfer of energy from one organism to another.

Format: Producer → Primary consumer → Secondary consumer → Tertiary consumer

Examples:

Terrestrial:
- Grass → Grasshopper → Frog → Snake → Hawk
- Oak leaves → Caterpillar → Blue tit → Sparrowhawk

Aquatic:
- Phytoplankton → Zooplankton → Small fish (sardine) → Large fish (tuna) → Shark

Arrows: Show direction of energy flow (from eaten to eater).

