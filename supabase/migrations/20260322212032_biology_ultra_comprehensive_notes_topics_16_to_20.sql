## 4. Industrial Melanism (Peppered Moth)

Classic example of natural selection in action.

Before Industrial Revolution:
- Pale-colored moths (common) well-camouflaged on lichen-covered trees → birds cannot see them
- Dark (melanic) moths rare → easily seen by birds → eaten

After Industrial Revolution:
- Pollution killed lichens; tree bark covered with soot → dark
- Dark moths now camouflaged; pale moths visible → pale moths eaten
- Dark moths reproduced more → frequency of melanic allele increased
- When pollution controls introduced → lichens returned → pale moths again became common

Lesson: Natural selection can act rapidly; environment determines which variants are "fit".

---

## 5. Antibiotic Resistance — Natural Selection in Action

1. Random mutation produces a bacterium with resistance to antibiotic
2. Antibiotic applied → kills susceptible bacteria
3. Resistant bacterium survives, reproduces rapidly
4. All descendants carry resistance gene
5. Resistance spreads through population (and can spread between species via plasmids)

Examples:
- MRSA (Methicillin-resistant Staphylococcus aureus): Resistant to many antibiotics
- MDR-TB (Multi-drug resistant tuberculosis)

Prevention:
- Complete antibiotic courses
- No unnecessary antibiotic use
- Develop new antibiotics
- International surveillance

---

## 6. Speciation

Speciation: Formation of new species from existing ones.

Biological species concept: Species = group that can interbreed and produce fertile offspring.

### 6.1 Allopatric Speciation (Geographic isolation)
1. Original population separated by geographic barrier (mountain, river, ocean)
2. Each isolated population faces different environmental pressures
3. Natural selection and genetic drift cause populations to diverge
4. Eventually become so different they cannot interbreed even if barrier removed
5. New species formed

Example: Galapagos finches; different lizard populations on different islands

### 6.2 Sympatric Speciation
- Speciation within the same geographic area
- Reproductive isolation without physical barrier
- Examples: Polyploidy in plants (chromosome doubling → different species); different mating seasons/behaviors

---

## 7. Genetic Drift

Genetic drift: Random changes in allele frequencies in small populations (not due to natural selection).

Bottleneck effect:
- Population reduced dramatically (disease, disaster)
- Surviving population''s gene pool is smaller and may not represent original population
- Some alleles may be lost entirely; rare alleles may become common by chance

Founder effect:
- Small group splits from original population to found new colony
- New population has reduced genetic diversity
- May differ significantly from original population
- Example: High frequency of certain genetic diseases in isolated communities

---

## 8. Human Evolution

Timeline:
- ~7 million years ago: Divergence from chimpanzee ancestor
- ~4 million years ago: Australopithecus (bipedal; small brain)
- ~2.5 million years ago: Homo habilis (first tool use; larger brain)
- ~1.8 million years ago: Homo erectus (fire; left Africa)
- ~300,000 years ago: Homo sapiens (modern brain; complex culture)
- ~40,000 years ago: Modern Homo sapiens replace Neanderthals

Evidence for human evolution:
- Fossil skulls (progressively larger brain case)
- Bipedalism (upright walking): S-shaped spine, bowl-shaped pelvis, foramen magnum position
- Reduced facial prognathism
- Tool development (Oldowan → Acheulean → Mousterian)
- Molecular data: ~98.7% DNA shared with chimpanzees' 
