## 7. Human Genome Project (HGP)

- International collaboration (1990-2003)
- Goal: Map and sequence all ~3 billion base pairs of human genome; identify all ~20,000-25,000 genes

Outcomes:
- Complete sequence of human genome published
- Most human DNA is non-coding ("junk DNA" — actually regulatory)
- Humans share ~99.9% of DNA; variation in ~0.1%
- Opened doors to personalized medicine, gene therapy, understanding genetic diseases

