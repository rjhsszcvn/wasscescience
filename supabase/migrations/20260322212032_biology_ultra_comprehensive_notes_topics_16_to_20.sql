## 1. Scientific Method

The scientific method is a systematic approach to investigating biological questions.

Steps:
1. Observation: Note something interesting
2. Question: Form a testable question
3. Hypothesis: Propose a testable explanation (if... then... because...)
4. Experiment: Design to test hypothesis; control variables
5. Data collection: Record results accurately
6. Analysis: Interpret data; statistical analysis
7. Conclusion: Accept or reject hypothesis
8. Communication: Publish/share results; peer review

---

## 2. Variables in Experiments

Independent variable: The one you deliberately change (e.g., temperature, concentration)
Dependent variable: What you measure/observe (e.g., enzyme activity, rate of photosynthesis)
Control variables: All other factors kept constant (e.g., volume, pH, time)

Control experiment:
- Identical to experimental setup but without the independent variable
- Allows comparison; eliminates other explanations

---

## 3. Microscopy

### 3.1 Light Microscope (Optical Microscope)
- Uses visible light
- Maximum magnification: ~1500×
- Resolution: ~200 nm
- Can view living specimens
- Staining: Uses dyes (e.g., iodine for starch, methylene blue for nuclei)

Calculating magnification:
Magnification = Image size / Actual size
Actual size = Image size / Magnification

Units: 1 mm = 1000 μm; 1 μm = 1000 nm

### 3.2 Electron Microscope
- Uses beam of electrons (shorter wavelength → better resolution)
- Maximum resolution: ~0.1 nm
- Maximum magnification: ~500,000×
- Cannot view living specimens
- TEM (Transmission): Passes electrons through specimen → internal structures
- SEM (Scanning): Scans surface → 3D images of surface

### 3.3 Preparing Microscope Slides

Temporary wet mount:
1. Clean glass slide
2. Place specimen in drop of water on slide
3. Carefully lower coverslip at angle (avoid air bubbles)
4. Stain if needed (add drop beside coverslip; draw through with filter paper)

Stains:
- Iodine: Starch (blue-black); nuclei (pale yellow)
- Methylene blue: Nuclei (blue)
- Aceto-carmine/orcein: Chromosomes (red)
- Eosin: Cytoplasm (pink)
- Crystal violet: Bacteria (Gram stain)

