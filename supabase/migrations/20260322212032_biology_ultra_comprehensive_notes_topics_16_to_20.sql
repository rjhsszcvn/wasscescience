## 3. Tropisms

Tropism: Growth response of a plant to a directional stimulus.

### 3.1 Phototropism (Response to Light)
- Positive phototropism: Shoot grows TOWARD light
- Negative phototropism: Root grows AWAY from light

Mechanism:
- Unilateral light → auxin migrates from lit side to dark side
- Dark side has more auxin → greater cell elongation → bends toward light (shoot)

Evidence (Boysen-Jensen experiments):
1. Cut shoot tip → no bending
2. Replace tip → bending restored
3. Mica inserted on dark side → no bending
4. Mica on light side → bending occurs
- Confirms: Chemical (auxin) moves from light to dark side; must pass through moist tissue

### 3.2 Geotropism (Response to Gravity)
- Positive geotropism: Root grows DOWN
- Negative geotropism: Shoot grows UP

Mechanism:
- Statoliths (starch-filled plastids) settle under gravity
- Signal transduction → auxin redistribution to lower side
- Shoot: Lower side elongates more → grows up
- Root: Lower side more auxin → inhibits elongation → upper side elongates more → grows down

### 3.3 Thigmotropism (Response to Touch)
- Growth in response to contact with solid object
- Tendrils coil around support
- Cells on contact side grow slower; cells on opposite side grow faster → curling

Examples: Pea tendril, bean tendrils

### 3.4 Hydrotropism (Response to Water)
- Roots grow toward water source
- Important in soil with uneven water distribution

### 3.5 Chemotropism (Response to Chemical)
- Pollen tube grows toward chemicals released by ovule (positive chemotropism)
- Some roots show chemotropism toward nutrients

