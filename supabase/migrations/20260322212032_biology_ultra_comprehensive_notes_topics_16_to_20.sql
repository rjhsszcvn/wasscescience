### 4.3 Thermonasty (Response to Temperature)
- Tulip: Opens at higher temperatures; closes at lower
- Due to unequal growth on upper and lower petal surfaces

### 4.4 Epinasty (Downward Curling)
- Upper surface cells grow faster → leaf/organ curves downward
