## 4. Food Testing Practicals

### 4.1 Testing for Starch
- Add a few drops of iodine solution to food sample
- Positive result: Blue-black color

### 4.2 Testing for Reducing Sugars (Glucose, Maltose)
- Add equal volume of Benedict''s solution to food sample
- Heat in boiling water bath for 5 minutes
- Positive result: Brick-red/orange precipitate forms
- Negative result: Solution remains blue
- Quantitative: Greater concentration → more red precipitate

### 4.3 Testing for Non-Reducing Sugars (Sucrose)
- First confirm no reducing sugar present
- Boil with dilute HCl (hydrolyze sucrose to glucose + fructose)
- Neutralize with sodium hydroxide
- Test with Benedict''s → brick-red if sucrose was present

### 4.4 Testing for Proteins (Biuret Test)
- Add NaOH solution to sample
- Add a few drops of dilute copper sulfate (CuSO₄)
- Positive result: Purple/violet color
- Negative result: Blue (from CuSO₄)

### 4.5 Testing for Lipids (Emulsion Test)
- Dissolve sample in ethanol
- Add to equal volume of water in test tube
- Shake
- Positive result: Milky white emulsion
- Alternatively: Grease spot test (food sample rubbed on paper → translucent spot if fat present)

