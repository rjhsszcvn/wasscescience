## 6. DNA Technology

### 6.1 Polymerase Chain Reaction (PCR)
- Amplifies (copies) specific DNA sequences millions of times
- Uses: DNA fingerprinting, diagnosis, research

Steps:
1. Denaturation: DNA heated to ~95°C → double helix separates
2. Annealing: Temperature lowered to ~55°C → specific primers bind to target sequence
3. Extension: DNA polymerase (Taq polymerase) extends primers at ~72°C → new DNA strands
4. Repeat ~30-40 cycles → exponential amplification

### 6.2 Gel Electrophoresis
- Separates DNA fragments by size
- DNA loaded into wells in gel; electric current applied
- DNA is negatively charged → migrates toward positive electrode
- Smaller fragments move faster/farther
- Staining makes fragments visible as bands

Uses: DNA fingerprinting, checking PCR products, genetic testing

### 6.3 DNA Fingerprinting (DNA Profiling)
Uses unique patterns of repeated sequences (STRs — short tandem repeats) in DNA.

Process:
1. DNA extracted from sample (blood, hair, saliva, semen)
2. PCR amplifies STR regions
3. Gel electrophoresis → unique banding pattern (DNA profile)
4. Profiles compared

Uses:
- Criminal identification (forensics)
- Paternity testing
- Identifying disease-carrying genes
- Species identification

