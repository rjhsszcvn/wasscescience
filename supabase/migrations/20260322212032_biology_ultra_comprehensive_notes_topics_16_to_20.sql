## 6. Investigating Osmosis

### 6.1 Visking Tubing (Dialysis Tubing) Experiment
- Visking tubing is selectively permeable (semi-permeable)
- Fill with sugar solution; place in distilled water
- Water enters by osmosis → tubing expands/level rises
- Demonstrates osmosis principle

### 6.2 Potato Experiment (Quantitative Osmosis)
Materials: Potato cylinders, range of sucrose concentrations

Procedure:
1. Cut potato cylinders; measure length and mass
2. Place in sucrose solutions of different concentrations for 30-60 min
3. Remove; dry gently; re-measure mass and length
4. Calculate % change in mass

Results:
- Distilled water: Mass/length increases (water enters)
- Concentrated sucrose: Mass/length decreases (water leaves)
- At one concentration: No change = isotonic concentration of potato cells

