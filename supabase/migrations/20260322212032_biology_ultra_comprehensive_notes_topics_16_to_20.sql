## 1. Introduction to Biotechnology

Biotechnology: Use of biological systems, living organisms, or their derivatives to develop or modify products and processes for specific use.

Traditional biotechnology:
- Fermentation: Brewing beer, wine; making bread
- Selective breeding: Improving crops and livestock

Modern biotechnology:
- Genetic engineering (recombinant DNA technology)
- Tissue culture
- Cloning
- Genomics and proteomics
- Medical biotechnology

---

## 2. Fermentation

Fermentation: Use of microorganisms (bacteria, yeast, fungi) to produce useful products.

### 2.1 Brewing (Alcoholic Fermentation)
Yeast (Saccharomyces cerevisiae) converts sugars to ethanol and CO₂:
Glucose → Ethanol + CO₂ (+ 2 ATP)

Beer brewing process:
1. Malting: Barley seeds germinate → starch converted to maltose (amylase enzymes)
2. Mashing: Ground malt mixed with hot water → amylases break down starch further
3. Boiling: Hops added (flavor, preservation)
4. Fermentation: Yeast added → anaerobic conditions → ethanol produced
5. Conditioning/Filtering/Carbonating

Wine: Yeast ferments grape juice

Bread making:
- Yeast ferments sugars in dough
- CO₂ produced → dough rises
- Alcohol evaporated on baking

### 2.2 Yogurt and Cheese Making
Lactobacillus bacteria ferment lactose → lactic acid
- Lactic acid lowers pH → milk proteins denature (curdle) → yogurt/cheese texture
- Different bacteria and aging → different cheese flavors

### 2.3 Vinegar (Acetic acid fermentation)
Acetobacter bacteria oxidize ethanol → acetic acid

### 2.4 Industrial Fermentation
- Large-scale bioreactors (fermenters)
- Products: Antibiotics (penicillin from Penicillium), insulin, enzymes, single-cell protein
- Controlled conditions: Temperature, pH, nutrient supply, O₂

---

## 3. Selective Breeding (Artificial Selection)

Definition: Humans choose parents with desirable traits for breeding.

How it works:
1. Select individuals with desired traits
2. Breed them together
3. Select offspring with enhanced desired traits
4. Repeat over many generations

Examples in plants:
- High-yielding crop varieties (wheat, rice, maize)
- Disease-resistant crops
- Crops adapted to specific climates
- Bigger, sweeter fruits (bananas, strawberries)

Examples in animals:
- Cattle: High milk yield (Holstein), high meat production (Angus)
- Dogs: Different breeds for different purposes (herding, hunting, companionship)
- Sheep: Improved wool production, meat

Inbreeding depression:
- Selective breeding reduces genetic diversity
- Related animals bred → harmful recessive alleles more likely to be expressed
- Reduced fertility, health problems

---

## 4. Genetic Engineering (Recombinant DNA Technology)

Definition: Manipulating an organism''s DNA to introduce new genes or change existing ones.

Basic tools:
- Restriction enzymes: "Molecular scissors" — cut DNA at specific sequences (restriction sites)
  - Leave "sticky ends" — short single-stranded overhangs
- DNA ligase: "Molecular glue" — joins DNA fragments
- Vectors: Carrier of gene into host cell (plasmids, viruses/phages)
- Polymerase Chain Reaction (PCR): Amplifies DNA

### 4.1 Steps in Genetic Engineering

1. Isolate the desired gene:
   - Use restriction enzymes to cut out gene from donor DNA
   - OR synthesize gene from mRNA using reverse transcriptase (→ cDNA)
   - OR chemically synthesize gene

2. Insert gene into vector:
   - Open plasmid with same restriction enzyme → matching sticky ends
   - Mix gene and plasmid + DNA ligase → recombinant plasmid

3. Introduce vector into host cell:
   - Transformation: Bacteria take up plasmid (heat shock, electroporation)
   - OR viral transfection (phage)

4. Select transformed cells:
   - Use antibiotic resistance markers on plasmid
   - Screen for gene expression

5. Clone and express:
   - Transformed bacteria cultured → all copies carry recombinant gene
   - Gene expressed → protein produced

### 4.2 Applications of Genetic Engineering

Medical applications:
- Insulin production: Human insulin gene inserted into E. coli or yeast → bacteria produce human insulin
  - Before: Pig/cow insulin (slightly different; allergic reactions)
  - Now: Recombinant human insulin (safer, identical to human insulin)
- Growth hormone: Produced by recombinant E. coli
- Factor VIII: Clotting factor for haemophiliacs
- Erythropoietin (EPO): Stimulates red blood cell production
- Vaccines: Recombinant antigens (hepatitis B vaccine)
- Gene therapy: Replacing defective genes with functional copies

Agricultural applications (Genetically Modified Organisms — GMOs):
- Bt crops: Bacillus thuringiensis gene inserted into cotton/maize → produce insecticidal toxin → pest resistance
- Herbicide-resistant crops (Roundup Ready — glyphosate resistant): Allows herbicide use to kill weeds without harming crop
- Golden Rice: Beta-carotene (Vitamin A precursor) gene inserted into rice → helps prevent Vitamin A deficiency
- Disease-resistant crops: Papaya ringspot virus-resistant papaya
- Drought/salt-tolerant crops
- Improved nutritional content (high-protein crops)

Controversies over GMOs:
- Potential ecological risks: Gene flow to wild relatives; harm to non-target organisms
- Unknown long-term health effects
- Biodiversity concerns
- Corporate control of food supply
- Ethical concerns

---

## 5. Cloning

Cloning: Production of genetically identical copies of an organism (or gene).

### 5.1 Natural Clones
- Identical twins
- Asexual reproduction (bacteria, plants via vegetative propagation)

### 5.2 Therapeutic Cloning (Nuclear Transfer)
- Somatic cell nuclear transfer (SCNT)
- Nucleus of adult cell transferred into enucleated egg cell
- Embryo develops → stem cells harvested (not for reproduction)
- Purpose: Produce patient-matched stem cells for therapy (no immune rejection)

### 5.3 Reproductive Cloning — Dolly the Sheep (1996)
- First mammal cloned from adult cell
- Nucleus from mammary gland cell of Finn Dorset sheep transferred into enucleated egg of Scottish Blackface sheep
- Surrogate mother carried pregnancy
- Dolly was genetically identical to Finn Dorset donor

Ethical issues of cloning:
- Human reproductive cloning: Widely banned; deep ethical concerns (identity, abuse)
- Therapeutic cloning: Controversial; involves embryo destruction

### 5.4 Plant Cloning — Tissue Culture (Micropropagation)
- Small piece of plant tissue (explant) placed on sterile nutrient medium with growth hormones
- Callus forms (undifferentiated mass of cells)
- Different hormone ratios induce roots then shoots
- Plantlets transferred to soil

Uses:
- Rapid production of many identical plants
- Production of disease-free plants
- Preservation of rare species
- Year-round production regardless of season

