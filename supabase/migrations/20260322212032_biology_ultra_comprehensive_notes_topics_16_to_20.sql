## 8. Investigating Transpiration

### 8.1 Potometer
- Measures rate of water uptake (closely related to transpiration rate)
- Leafy shoot inserted in water; cut end sealed in water

Bubble potometer:
- Air bubble introduced into capillary tube
- Bubble moves as shoot absorbs water
- Distance moved per minute = rate of water uptake

Variables to investigate:
- Wind (fan): Increases rate (removes humid air)
- Humidity (humid air chamber): Decreases rate
- Light (bright light): Increases rate (opens stomata)
- Temperature: Higher temperature → increases rate

### 8.2 Cobalt Chloride Paper (Detecting Stomata)
- Cobalt chloride paper: Blue when dry; pink when moist (water present)
- Place on upper and lower leaf surfaces
- Lower surface: Paper turns pink faster → more stomata on lower surface
- Compare different leaf types

---

## 9. Investigating Respiration

### 9.1 Respirometer
- Measures O₂ consumption or CO₂ production

Woodlice/germinating seeds in sealed chamber:
- KOH absorbs CO₂
- O₂ consumed → gas volume decreases → fluid in manometer moves
- Compare with dead control

### 9.2 Comparing Aerobic and Anaerobic Respiration
- Yeast + glucose + water (sealed, no air) → CO₂ collected
- Yeast + glucose + water (open, with air) → both CO₂ and less ethanol

Test CO₂: Lime water turns milky
Test ethanol: Acidified potassium dichromate → turns green

