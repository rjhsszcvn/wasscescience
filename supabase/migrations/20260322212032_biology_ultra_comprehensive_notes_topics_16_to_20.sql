## 1. Introduction

Unlike animals, plants lack a nervous system. They coordinate their activities through:
- Plant hormones (phytohormones): Chemical messengers
- Direct responses to environmental stimuli (tropisms, nastic responses)

Plant responses are generally slower than animal nervous responses but more sustained.

---

## 2. Plant Hormones (Phytohormones)

### 2.1 Auxins (Indole Acetic Acid — IAA)

Site of production: Apical meristems (shoot and root tips), young leaves, developing seeds

Transport: Polar auxin transport (primarily from shoot tip downward)

Effects:
- Promotes cell elongation (at low concentrations in shoots)
- INHIBITS cell elongation at high concentrations in roots (roots more sensitive)
- Promotes root formation
- Promotes apical dominance (suppresses lateral bud growth)
- Involved in fruit development
- Delays leaf abscission (leaf fall)
- Promotes development of adventitious roots in cuttings

Mechanism of action:
- Auxin activates H⁺ pumps in cell membrane → H⁺ pumped out of cell → cell wall becomes more acidic
- Acidic pH activates enzymes that loosen cell wall (expansins)
- Water enters by osmosis → cell enlarges

Role in phototropism:
- Light from one side → auxin migrates to shaded side
- Higher auxin on shaded side → more elongation on shaded side → shoot bends toward light
- Negative phototropism in roots (same redistribution → roots bend away from light)

Role in geotropism:
- Gravity → auxin accumulates on lower side
- In shoots: Lower side elongates more → shoot grows upward (negative geotropism)
- In roots: Higher concentration on lower side → inhibits elongation → roots grow downward (positive geotropism)

Apical dominance:
- Auxin from apical bud diffuses downward → suppresses growth of lateral buds
- Remove apex → lateral buds grow (bushier plant)
- Used in horticulture (pinching out tips)

### 2.2 Gibberellins

Site of production: Young leaves, root tips, developing seeds

Effects:
- Promote stem elongation (internode elongation) → dwarf plants become tall when treated
- Stimulate seed germination (activates amylase → breaks down endosperm)
- Promotes flowering in some plants (vernalization response)
- Fruit development
- Breaks dormancy in seeds and buds

Commercial uses:
- Brewing: Gibberellins stimulate amylase production in malting barley → faster malting
- Seedless grapes: Gibberellin application increases fruit size
- Delayed fruit ripening
- Grass elongation

### 2.3 Cytokinins

Site of production: Roots (primary site), developing fruits, growing buds

Transport: Through xylem from roots to shoots

Effects:
- Promote cell division (cytokinesis)
- Promote cell differentiation
- Promote bud growth (antagonize auxin in apical dominance)
- Delay leaf senescence (aging) — keep cut flowers and detached leaves green longer
- Promote chloroplast development

Auxin:Cytokinin ratio:
- High auxin:low cytokinin → root formation (from callus in tissue culture)
- Low auxin:high cytokinin → shoot formation

### 2.4 Abscisic Acid (ABA)

Site of production: Mature leaves, roots, seeds

"Stress hormone" — responds to unfavorable conditions.

Effects:
- Promotes stomatal closure (water stress): ABA released from mesophyll cells when short of water → guard cells lose turgidity → stomata close → reduce transpiration
- Promotes seed dormancy (prevents premature germination)
- Promotes leaf abscission (leaf fall — with ethylene)
- Inhibits growth (antagonizes gibberellins and auxins)
- Promotes storage of food in seeds

Mechanism of stomatal closure:
1. Water deficit → ABA produced
2. ABA binds to receptor on guard cell
3. K⁺ channels open → K⁺ leaves guard cell
4. Water follows by osmosis → guard cell becomes flaccid
5. Stomata close

### 2.5 Ethylene (Ethene)

A gas (only gaseous plant hormone).

Site of production: Ripening fruits, senescing tissues, nodes, aging flowers, damaged tissues

Effects:
- Promotes fruit ripening: Stimulates production of cellulases (break down cell walls → fruit softens) and color changes
- Promotes leaf/fruit abscission: Stimulates abscission zone formation
- Promotes senescence (aging) of plant organs
- Inhibits elongation growth
- Promotes seed germination in some species
- Triple response to mechanical stress: Inhibit elongation, promote lateral expansion, horizontal growth (in seedlings)

Commercial uses:
- Fruit ripening: Treat unripe fruit with ethylene to ripen uniformly
- Delay ripening: Store fruit in low O₂ / high CO₂ → reduces ethylene production
- Banana ripening: Shipped unripe; ripened in warehouses with ethylene gas
- Defoliant: Cotton plants treated to shed leaves before harvesting

