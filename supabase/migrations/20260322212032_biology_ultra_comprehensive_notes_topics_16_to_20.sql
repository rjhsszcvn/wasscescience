## 5. Enzyme Investigations

### 5.1 Effect of Temperature on Enzyme Activity
- Use catalase (from potato) + hydrogen peroxide
- Or amylase + starch
- Measure rate (O₂ bubbles, disappearance of starch with iodine) at different temperatures
- Plot rate vs temperature → optimal temperature visible

### 5.2 Effect of pH on Enzyme Activity
- Buffer solutions at different pH values
- Add to enzyme + substrate
- Measure rate of reaction

### 5.3 Effect of Substrate Concentration
- Vary concentration of substrate; keep enzyme constant
- Measure initial rate at each concentration
- Rate increases → plateau (enzyme becomes saturated = all active sites occupied = Vmax)

### 5.4 Effect of Enzyme Concentration
- Vary concentration of enzyme; keep substrate constant in excess
- Rate increases proportionally

