## 8. Gas Exchange in Other Organisms

### 8.1 Fish — Gills
- Water enters mouth → passes over gill filaments → exits through operculum
- Countercurrent exchange: Water and blood flow in opposite directions → maintains maximum concentration gradient
- Gill filaments: Thin, many, moist, richly supplied with blood

### 8.2 Insects — Tracheal System
- Network of air tubes (tracheae and tracheoles)
- Spiracles: Pores on body surface that open/close to allow air in and prevent water loss
- O₂ diffuses directly to cells; no blood transport needed
- Limits maximum body size of insects

### 8.3 Plants — Stomata and Lenticels
- Gas exchange through stomata (in leaves)
- Guard cells control stomatal opening
  - Open: When turgid (day; high light; low CO₂)
  - Close: When flaccid (night; water stress)
- Lenticels: Gas exchange in woody stems

