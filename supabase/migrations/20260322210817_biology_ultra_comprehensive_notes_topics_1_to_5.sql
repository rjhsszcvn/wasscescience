## 1. Introduction to Genetics

Genetics is the study of heredity and variation. It explains how traits are passed from parents to offspring.

Key terms:
- Gene: A segment of DNA that codes for a specific protein/trait
- Allele: Alternative forms of a gene (e.g., T for tall, t for short)
- Locus: Position of a gene on a chromosome
- Genome: Complete set of genetic information in an organism
- Genotype: Genetic makeup (e.g., TT, Tt, tt)
- Phenotype: Physical expression of genes (e.g., tall, short)
- Homozygous: Two identical alleles (TT or tt)
- Heterozygous: Two different alleles (Tt)
- Dominant allele: Expressed when present (usually written with capital letter)
- Recessive allele: Only expressed when homozygous (written in lowercase)

---

## 2. DNA Structure

DNA (Deoxyribonucleic Acid) is the molecule of heredity.

Structure (Watson-Crick double helix model, 1953):
- Two polynucleotide strands twisted into double helix
- Each nucleotide contains: deoxyribose sugar + phosphate group + nitrogenous base
- Bases: Adenine (A), Thymine (T), Guanine (G), Cytosine (C)
- Base pairing rules: A pairs with T (2 hydrogen bonds); G pairs with C (3 hydrogen bonds)
- Strands are antiparallel (run in opposite directions: 5'' to 3'')

RNA (Ribonucleic Acid):
- Single-stranded
- Contains ribose sugar instead of deoxyribose
- Uracil (U) replaces Thymine
- Types: mRNA (messenger), tRNA (transfer), rRNA (ribosomal)

---

## 3. DNA Replication

Process by which DNA is copied before cell division.
- Semi-conservative: Each new DNA molecule has one original and one new strand
- Occurs during S phase of interphase

Steps:
1. Helicase enzyme unwinds and unzips the double helix (breaks hydrogen bonds)
2. Each strand acts as a template
3. DNA polymerase adds complementary nucleotides (A-T, G-C)
4. Two identical DNA molecules are formed

---

## 4. Protein Synthesis

Genes control traits by directing protein synthesis.

### 4.1 Transcription (DNA → mRNA)
- Occurs in the nucleus
- RNA polymerase reads the DNA template strand
- mRNA is produced (complementary copy of gene)
- mRNA leaves nucleus through nuclear pores to ribosomes

### 4.2 Translation (mRNA → Protein)
- Occurs at ribosomes in cytoplasm
- mRNA codons (triplets of 3 bases) code for specific amino acids
- tRNA brings amino acids; anticodon pairs with codon
- Polypeptide chain grows until stop codon is reached
- Polypeptide folds into functional protein

Genetic code:
- Each codon = 3 bases = 1 amino acid
- 64 possible codons; 20 amino acids (code is degenerate/redundant)
- Start codon: AUG (codes for methionine)
- Stop codons: UAA, UAG, UGA

---

## 5. Mendel''s Laws

Gregor Mendel (1866) discovered the principles of heredity using pea plants.

### 5.1 Law of Segregation (First Law)
Each organism carries two alleles for each gene. These alleles separate during gamete formation so each gamete carries only one allele.

### 5.2 Law of Independent Assortment (Second Law)
Genes for different traits assort independently of each other during gamete formation (applies to genes on different chromosomes).

---

## 6. Monohybrid Inheritance

Cross involving ONE gene/trait.

Example: Tall (T) is dominant; short (t) is recessive.

Cross 1: TT × tt (Parental generation)
- Parents: TT × tt
- Gametes: T and T × t and t
- F1 offspring: All Tt (all tall — 100% tall phenotype)

Cross 2: F1 × F1 → Tt × Tt
- Gametes: T, t × T, t
- Punnett square:
  - TT : Tt : Tt : tt
  - Genotype ratio: 1 TT : 2 Tt : 1 tt
  - Phenotype ratio: 3 tall : 1 short

Testcross:
- Cross of unknown genotype with homozygous recessive (tt)
- If offspring are all tall → parent is TT
- If offspring are half tall, half short → parent is Tt

---

## 7. Dihybrid Inheritance

Cross involving TWO genes/traits on different chromosomes.

Example: T = tall (dominant), t = short (recessive); R = round seeds (dominant), r = wrinkled seeds (recessive)

Cross: TTRR × ttrr
- F1: All TtRr (tall, round)
- F1 × F1: TtRr × TtRr
- Gametes: TR, Tr, tR, tr × TR, Tr, tR, tr
- F2 phenotype ratio: 9 tall round : 3 tall wrinkled : 3 short round : 1 short wrinkled

---

## 8. Incomplete Dominance

Neither allele is completely dominant; heterozygote shows intermediate phenotype.

Example: Red flower (RR) × White flower (WW) → Pink flower (RW) in F1
- F1 × F1: RW × RW
- Offspring: 1 RR (red) : 2 RW (pink) : 1 WW (white)
- Phenotype ratio = genotype ratio (1:2:1)

---

## 9. Codominance

Both alleles are fully expressed in heterozygote.

Example: ABO blood groups (IA, IB, i alleles)
- IA IA or IA i → Blood group A
- IB IB or IB i → Blood group B
- IA IB → Blood group AB (both A and B antigens expressed)
- ii → Blood group O

---

## 10. Sex Determination and Sex-Linked Inheritance

### 10.1 Sex Chromosomes
- Humans: 46 chromosomes (23 pairs)
- Females: XX; Males: XY
- Y chromosome determines maleness
- Sex ratio is approximately 1:1

### 10.2 Sex-Linked Traits
Genes located on the X chromosome (X-linked).

Examples: Colour blindness, haemophilia

Colour blindness:
- XB = normal vision (dominant); Xb = colour blind (recessive)
- Females can be: XBXB (normal), XBXb (carrier), XbXb (colour blind)
- Males can be: XBY (normal), XbY (colour blind)
- Males are more commonly affected because they only have one X chromosome

Haemophilia:
- Blood clotting disorder
- X-linked recessive
- Queen Victoria was a famous carrier

Cross: Carrier female × Normal male
- Mother: XBXb × Father: XBY
- Offspring: XBXB (normal female), XBXb (carrier female), XBY (normal male), XbY (haemophilic male)

