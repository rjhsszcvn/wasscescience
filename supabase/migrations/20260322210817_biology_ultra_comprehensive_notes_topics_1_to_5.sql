## 6. Breathing and Gas Exchange (Ventilation)

Though different from cellular respiration, breathing supports it by supplying O₂ and removing CO₂.

### 6.1 Human Respiratory System
Structures:
- Nasal cavity: Warms, moistens, filters air
- Pharynx: Common pathway for air and food
- Larynx: Voice box; contains vocal cords
- Trachea: Reinforced with C-shaped cartilage rings; lined with ciliated epithelium
- Bronchi: Two branches (one per lung)
- Bronchioles: Smaller branches; no cartilage
- Alveoli: Tiny air sacs; site of gas exchange

### 6.2 Alveoli — Adaptations for Gas Exchange
- Very large number (~300 million per lung) → huge total surface area (~70 m²)
- Very thin walls (one cell thick — squamous epithelium)
- Moist lining → gases dissolve
- Rich blood supply (capillary network)
- Short diffusion distance between air and blood

Gas exchange:
- O₂ diffuses from alveoli (high O₂) into blood (low O₂)
- CO₂ diffuses from blood (high CO₂) into alveoli (low CO₂)

### 6.3 Mechanism of Breathing

Inhalation (Breathing in):
- Intercostal muscles contract → ribs move up and out
- Diaphragm contracts → flattens and moves down
- Thoracic volume increases
- Pressure in thorax decreases (below atmospheric)
- Air flows into lungs

Exhalation (Breathing out):
- Intercostal muscles relax → ribs move down and in
- Diaphragm relaxes → dome shape returns
- Thoracic volume decreases
- Pressure in thorax increases (above atmospheric)
- Air flows out of lungs

Forced exhalation (exercise): Internal intercostal muscles and abdominal muscles contract

### 6.4 Lung Volumes
- Tidal volume: Volume breathed in/out at rest (~500 mL)
- Vital capacity: Maximum air that can be breathed in after maximum exhalation (~4500 mL)
- Residual volume: Air remaining after maximum exhalation (~1200 mL)
- Total lung capacity: ~5700 mL

### 6.5 Control of Breathing
- Medullary respiratory center in brainstem controls breathing rhythm
- Chemoreceptors detect CO₂ levels (not primarily O₂)
- High CO₂ → stimulates breathing rate increase
- Low CO₂ → breathing rate decreases

