## 4. Human Digestive System

### 4.1 Overview
Digestion converts food into small, soluble molecules that can be absorbed into the blood.

Types of digestion:
- Physical (mechanical) digestion: Breaking food into smaller pieces (chewing, churning) — increases surface area
- Chemical digestion: Enzymes break down food molecules into monomers

### 4.2 Parts of the Digestive System

Mouth (Buccal Cavity):
- Teeth mechanically break down food
- Tongue mixes food with saliva
- Salivary glands produce saliva containing:
  - Salivary amylase: Breaks starch → maltose
  - Mucin: Lubricates food
- Food formed into bolus
- Swallowing: Epiglottis closes larynx; food enters oesophagus

Oesophagus:
- Muscular tube connecting mouth to stomach
- Peristalsis: Wave-like muscular contractions move food downward
- No digestion occurs here

Stomach:
- Muscular, J-shaped organ
- Gastric glands produce gastric juice containing:
  - Pepsin (protease): Breaks proteins into polypeptides
  - Hydrochloric acid (HCl): Creates acidic pH (~2); kills bacteria; activates pepsin
