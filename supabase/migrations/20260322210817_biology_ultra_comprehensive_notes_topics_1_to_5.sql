## 11. Mutations

Mutation: Permanent change in DNA sequence.

### 11.1 Gene Mutations
- Change in DNA base sequence
- Substitution: One base replaced by another → may change amino acid (e.g., sickle cell anaemia)
- Insertion: Extra base added → frameshift → all codons downstream change
- Deletion: Base removed → frameshift

Sickle Cell Anaemia:
- Caused by substitution mutation: Adenine replaced by Thymine in haemoglobin gene
- Glutamic acid replaced by valine in haemoglobin protein
- Red blood cells become sickle-shaped
- Cannot carry oxygen efficiently
- Sickle cell trait: HbA HbS (heterozygous carrier — some protection against malaria)
- Sickle cell disease: HbS HbS (homozygous)

### 11.2 Chromosomal Mutations
- Changes in chromosome number or structure
- Non-disjunction: Failure of chromosomes to separate during meiosis

Down Syndrome (Trisomy 21):
- Three copies of chromosome 21 (47 chromosomes)
- Caused by non-disjunction
- Features: intellectual disability, characteristic facial features, heart defects

Other conditions:
- Turner syndrome (45,X): Female with one X chromosome
- Klinefelter syndrome (47,XXY): Male with extra X chromosome

### 11.3 Mutagens
Agents that cause mutations:
- Physical: UV radiation, X-rays, gamma rays
- Chemical: Mustard gas, benzene, nitrous acid, tobacco smoke
- Biological: Certain viruses

---

## 12. Variation

Variation: Differences between individuals of the same species.

Types:
1. Continuous variation: Range of values; influenced by many genes and environment
   - Examples: Height, weight, skin color, intelligence
   - Shows normal distribution curve

2. Discontinuous variation: Distinct groups; controlled by one or few genes; little environmental influence
   - Examples: Blood groups, tongue rolling, attached/free earlobes, sickle cell

Causes of variation:
- Genetic: Mutation, sexual reproduction (crossing over, independent assortment, random fertilization)
- Environmental: Nutrition, temperature, sunlight, disease

---

## 13. Genetic Diseases and Counseling

Common genetic disorders:
- Cystic fibrosis: Autosomal recessive; thick mucus; affects lungs and digestive system
- Huntington''s disease: Autosomal dominant; progressive neurological disorder
- PKU (Phenylketonuria): Autosomal recessive; cannot metabolize phenylalanine
- Albinism: Autosomal recessive; no melanin production

Genetic counseling:
- Advises parents about risk of passing genetic conditions to children
- Uses pedigree analysis to determine inheritance patterns

Pedigree analysis:
- Squares = males; circles = females
- Filled shapes = affected individuals
- Horizontal line = mating; vertical lines = offspring' 
