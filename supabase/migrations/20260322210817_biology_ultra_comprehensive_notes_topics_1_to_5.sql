- Churning (physical digestion) mixes food with gastric juice
- Food becomes semi-liquid chyme
- Pyloric sphincter controls movement into small intestine

Small Intestine:
Duodenum (first section):
- Receives chyme from stomach
- Bile enters from liver (via bile duct)
  - Bile: Emulsifies fats (breaks large fat droplets into small ones — increases surface area for lipase)
  - Does NOT contain enzymes
  - Bile is alkaline — neutralizes acid chyme
- Pancreatic juice enters from pancreas:
  - Pancreatic amylase: Starch → maltose
  - Trypsin: Proteins → smaller polypeptides
  - Lipase: Fats → fatty acids + glycerol
  - Pancreatic juice is alkaline (sodium bicarbonate neutralizes acid)

Ileum (second section):
- Intestinal enzymes (from wall):
  - Maltase: Maltose → glucose + glucose
  - Sucrase: Sucrose → glucose + fructose
  - Lactase: Lactose → glucose + galactose
  - Peptidases: Polypeptides → amino acids
- Absorption: Products of digestion absorbed into blood
- Structure adapted for absorption:
  - Very long (6-7 meters)
  - Villi: Finger-like projections; increase surface area
  - Microvilli: Tiny projections on villi surface (brush border); further increase surface area
  - Rich blood supply (capillaries in each villus)
  - Lacteals (lymph capillaries): Absorb fatty acids and glycerol
  - Thin walls (one cell thick) — short diffusion distance

Absorption of nutrients:
- Glucose and amino acids → absorbed into capillaries → blood → portal vein → liver
- Fatty acids and glycerol → absorbed into lacteals → lymph → blood

Large Intestine (Colon):
- Absorbs water and mineral salts
- Bacteria in colon ferment undigested material; produce some vitamins (B12, K)
- Compacts undigested material into feces

Rectum and Anus:
- Rectum stores feces
- Anus expels feces (defecation/egestion)

