## 1. Introduction to Ecology

Ecology: The scientific study of the relationships between living organisms and their environment.

Key terms:
- Organism: Any individual living thing
- Population: Group of organisms of the same species living in the same area at the same time
- Community: All populations of different species living in the same area
- Ecosystem: Community of organisms plus their non-living (abiotic) environment
- Biosphere: All ecosystems on Earth; the zone of life on our planet
- Habitat: The specific place where an organism lives
- Niche: The role an organism plays in its ecosystem (what it eats, where it lives, when it is active)

---

## 2. Abiotic and Biotic Factors

### 2.1 Abiotic (Non-living) Factors
Physical and chemical factors that affect organisms:
- Temperature: Affects enzyme activity and metabolic rate
- Light intensity and duration (photoperiod): Affects photosynthesis and animal behavior
- Water availability: Essential for all life processes
- Humidity: Affects transpiration and water loss
- pH of soil/water: Affects enzyme activity and nutrient availability
- Salinity: Concentration of dissolved salts
- Wind speed: Affects transpiration
- Altitude: Affects temperature and oxygen availability
- Edaphic factors (soil): Texture, composition, mineral content, drainage
- Topography: Slope, aspect, elevation

### 2.2 Biotic (Living) Factors
Effects of one organism on another:
- Predation: One organism kills and eats another
- Competition: Organisms compete for same resources
- Parasitism: One benefits, one is harmed (host)
- Mutualism: Both organisms benefit (e.g., nitrogen-fixing bacteria in legume roots)
- Commensalism: One benefits, other unaffected
- Disease: Pathogens affect organism health
- Decomposition: Bacteria and fungi break down dead matter

---

## 3. Feeding Relationships

### 3.1 Trophic Levels
- Producer (Autotroph): Makes own food by photosynthesis (plants, algae)
- Primary Consumer (Herbivore): Eats producers (grasshopper, rabbit, cow)
- Secondary Consumer: Eats primary consumers (frog, fox)
- Tertiary Consumer: Eats secondary consumers (hawk, snake)
- Decomposer: Breaks down dead organic matter (bacteria, fungi) — recycle nutrients

### 3.2 Food Chains
Linear sequence showing energy flow from one organism to next.

Example:
Grass → Grasshopper → Frog → Snake → Eagle

Rules:
- Always starts with producer
- Arrows show direction of energy flow (who eats whom)
- Each step is a trophic level

### 3.3 Food Webs
Network of interconnected food chains in an ecosystem.
- More realistic representation of feeding in nature
- Show that most organisms eat more than one type of food

### 3.4 Energy Flow in Ecosystems
- Energy enters ecosystem as sunlight
- Photosynthesis converts light energy to chemical energy (glucose)
- Only about 10% of energy is passed from one trophic level to the next
- 90% is lost as heat (respiration), feces, and uneaten parts
- This is why food chains rarely have more than 4-5 levels

### 3.5 Ecological Pyramids

Pyramid of Numbers:
- Number of organisms at each trophic level
- Usually narrows toward the apex
- Can be inverted (e.g., many insects on one tree)

Pyramid of Biomass:
- Mass of organisms at each trophic level
- Usually narrows toward apex
- More accurate than pyramid of numbers

Pyramid of Energy:
- Amount of energy at each trophic level
- Always narrows toward apex (never inverted)
- Most accurate representation

