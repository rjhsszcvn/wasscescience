## 7. Cell Specialization

Differentiation: Process by which cells become specialized

Levels of organization: Cell → Tissue → Organ → Organ System → Organism

Examples of specialized cells:
- Red blood cells: Biconcave, no nucleus, haemoglobin → carry oxygen
- Nerve cells: Long axon, dendrites → transmit impulses
- Muscle cells: Actin and myosin → contraction
- Root hair cells: Long extensions → water absorption
- Guard cells: Control stomatal opening
- Sperm cells: Flagellum; many mitochondria
- Egg cells: Large; rich in nutrients

---

## 8. Enzymes

Enzymes are biological catalysts made of protein.
- Speed up chemical reactions without being used up
- Are specific (lock-and-key model and induced fit model)
- Have an active site where substrate binds
- Form enzyme-substrate complex

Factors affecting enzyme activity:
- Temperature: Optimal ~37°C in humans; above optimum → denaturation
- pH: Each enzyme has optimal pH; extremes denature enzyme
- Substrate concentration: More substrate → faster reaction (up to saturation)
- Enzyme concentration: More enzyme → faster reaction

Important enzymes in Biology:
- Amylase: Breaks starch into maltose
- Protease: Breaks proteins into amino acids
- Lipase: Breaks fats into fatty acids and glycerol
- DNA polymerase: Replicates DNA
- Catalase: Breaks down hydrogen peroxide into water and oxygen' 
