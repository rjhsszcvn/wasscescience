## 5. Respiratory Substrates

Glucose is the primary respiratory substrate, but others can be used:

- Fats: Broken into glycerol and fatty acids; fatty acids enter Krebs cycle as acetyl CoA
  - More energy per gram than glucose (high H:O ratio)
  - Used during prolonged exercise or starvation
- Proteins: Amino acids deaminated; carbon skeleton enters respiration
  - Used as last resort (during starvation)
- Glycogen: Stored in liver and muscle; broken down to glucose

Respiratory Quotient (RQ):
RQ = CO₂ produced / O₂ consumed
- Carbohydrates: RQ = 1.0
- Fats: RQ = ~0.7
- Proteins: RQ = ~0.9

