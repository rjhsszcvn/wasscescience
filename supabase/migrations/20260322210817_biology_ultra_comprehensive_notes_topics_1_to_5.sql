## 5. Movement Across Cell Membranes

### 5.1 Diffusion
- Movement from high to low concentration (down concentration gradient)
- Passive (no energy needed)
- Factors: concentration gradient, temperature, surface area, diffusion distance, molecule size
- Examples: CO₂ and O₂ exchange; urea leaving cells

### 5.2 Osmosis
- Movement of water from low solute concentration (high water potential) to high solute concentration (low water potential) through semi-permeable membrane
- Passive process

Effects on cells:
- Hypotonic solution: Lower solute → cell swells (animal: lysis; plant: turgid)
- Hypertonic solution: Higher solute → cell shrinks (animal: crenation; plant: plasmolysis)
- Isotonic solution: Equal solute → no net movement

### 5.3 Active Transport
- Movement against concentration gradient (low to high)
- Requires ATP and carrier proteins
- Examples: Na⁺/K⁺ pump; glucose absorption in gut; mineral uptake in roots

### 5.4 Facilitated Diffusion
- Passive movement through specific protein channels
- No energy needed; moves down concentration gradient
- Faster than simple diffusion
- Examples: Glucose into red blood cells; ion channels

### 5.5 Endocytosis and Exocytosis
- Endocytosis: Cell engulfs material
  - Phagocytosis: Engulfs solid particles (white blood cells eating bacteria)
  - Pinocytosis: Takes in liquid
- Exocytosis: Cell releases materials (secretion of enzymes, hormones)

