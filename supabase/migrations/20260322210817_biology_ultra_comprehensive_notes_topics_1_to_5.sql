## 1. Types of Nutrition

Nutrition: The process by which organisms obtain and use food for energy, growth, and repair.

### 1.1 Autotrophic Nutrition
Organisms that make their own food from inorganic materials.

Photosynthesis (Photoautotrophs):
- Use light energy to synthesize food from CO₂ and water
- Example: Green plants, algae, cyanobacteria

Chemosynthesis (Chemoautotrophs):
- Use chemical energy (from oxidation of inorganic compounds) to make food
- Example: Nitrifying bacteria (convert NH₃ to NO₃⁻)

### 1.2 Heterotrophic Nutrition
Organisms that obtain food by consuming other organisms.

Types:
- Holozoic: Ingest solid food, digest internally (humans, animals)
- Saprophytic: Feed on dead/decaying organic matter (fungi, most bacteria)
- Parasitic: Live on/in host, feeding at host''s expense (tapeworm, malaria parasite)

---

## 2. Food Nutrients

### 2.1 Carbohydrates
- Elements: Carbon, hydrogen, oxygen (ratio CH₂O)
- Monomer: Simple sugars (monosaccharides)

Types:
- Monosaccharides (simple sugars): Glucose, fructose, galactose — soluble, sweet, used directly for energy
- Disaccharides: Sucrose (glucose + fructose), maltose (glucose + glucose), lactose (glucose + galactose)
- Polysaccharides: Long chains of monosaccharides
  - Starch: Storage in plants; branched and unbranched chains of glucose
  - Glycogen: Storage in animals (liver, muscle)
  - Cellulose: Structural in plant cell walls; cannot be digested by humans (dietary fiber)

Functions:
- Primary energy source (4 kcal/g)
- Structural component (cellulose)
- Storage (starch, glycogen)

### 2.2 Proteins
- Elements: Carbon, hydrogen, oxygen, nitrogen (and sometimes sulfur, phosphorus)
- Monomer: Amino acids (20 different types)
- Joined by peptide bonds

Structure levels:
- Primary: Sequence of amino acids
- Secondary: Alpha helix or beta pleated sheet
- Tertiary: 3D folding
- Quaternary: Multiple polypeptide chains

Functions:
- Growth and repair of tissues
- Enzymes (catalysts)
- Hormones (e.g., insulin)
- Antibodies (immunity)
- Transport proteins (haemoglobin)
- Structural proteins (collagen, keratin)

Essential amino acids: Must be obtained from diet (cannot be synthesized by body) — there are 8 in adults
Complete proteins: Contain all essential amino acids (meat, eggs, fish)
