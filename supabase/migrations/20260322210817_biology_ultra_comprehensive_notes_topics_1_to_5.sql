## 1. The Cell: Basic Unit of Life

All living organisms are made of cells. The cell is the smallest structural and functional unit of life. Cells carry out all life processes: nutrition, respiration, excretion, growth, reproduction, sensitivity, and movement.

### Cell Theory
- All living things are composed of one or more cells
- The cell is the basic unit of structure and function in living organisms
- All cells come from pre-existing cells (cell division)
- Proposed by Schleiden (1838) for plants, Schwann (1839) for animals, Virchow (1855) for cell reproduction

---

## 2. Types of Cells

### 2.1 Prokaryotic Cells
- Found in bacteria and blue-green algae (cyanobacteria)
- No true membrane-bound nucleus
- DNA is a circular chromosome in the nucleoid region
- No membrane-bound organelles
- Smaller (1–10 micrometers)
- Ribosomes present but smaller (70S)
- Cell wall made of peptidoglycan (in bacteria)
- May have flagella, pili, capsule

Examples: Escherichia coli, Streptococcus, Anabaena

### 2.2 Eukaryotic Cells
- Found in plants, animals, fungi, protists
- True membrane-bound nucleus containing DNA
- Have membrane-bound organelles
- Larger (10–100 micrometers)
- Larger ribosomes (80S)
- More complex internal organization

---

## 3. Cell Organelles and Their Functions

### 3.1 Cell Membrane (Plasma Membrane)
Structure: Fluid mosaic model — phospholipid bilayer with embedded proteins
Composition: Phospholipids, proteins (intrinsic and extrinsic), cholesterol, glycoproteins

Functions:
- Controls what enters and leaves the cell (selective permeability)
- Provides structural support
- Contains receptor proteins for cell signaling
- Cell recognition via glycoproteins

Phospholipid structure: Hydrophilic (water-loving) head faces outward; hydrophobic (water-fearing) tails face inward

### 3.2 Nucleus
Structure: Double-membrane nuclear envelope with nuclear pores; contains chromatin (DNA + proteins); nucleolus inside

Functions:
- Controls all cell activities — the "control center"
- Contains genetic information (DNA) for protein synthesis
- Nucleolus produces rRNA and assembles ribosomes
- Nuclear pores allow movement of RNA and proteins

### 3.3 Mitochondria
Structure: Double membrane; outer smooth membrane; inner folded into cristae; matrix inside

Functions:
- Site of aerobic respiration (ATP production)
- "Powerhouse of the cell"
- Produce ATP through oxidative phosphorylation
- Have their own DNA and ribosomes (endosymbiotic theory)

More mitochondria found in: muscle cells, liver cells, sperm cells (high energy demand)

### 3.4 Chloroplasts (Plant Cells Only)
Structure: Double membrane; thylakoids stacked into grana; stroma surrounds thylakoids

Functions:
- Site of photosynthesis
- Light reactions in thylakoids
- Dark reactions (Calvin cycle) in stroma
- Have own DNA and ribosomes

Pigments: Chlorophyll a, chlorophyll b, carotenoids

### 3.5 Endoplasmic Reticulum (ER)

Rough ER (RER):
- Has ribosomes on surface
- Synthesizes and transports proteins
- Produces membrane and secretory proteins

Smooth ER (SER):
- No ribosomes
- Synthesizes lipids and steroids
- Detoxifies drugs and poisons (liver)
- Stores calcium ions in muscle cells

### 3.6 Golgi Apparatus
- Stack of flattened membrane sacs (cisternae)
- Receives proteins from RER
- Modifies, packages, and sorts proteins
- Produces lysosomes
- Secretes materials outside cell (exocytosis)
- Called the "post office" or "packaging center" of the cell

### 3.7 Ribosomes
- Small, not membrane-bound
- Found free in cytoplasm or on RER
- Composed of rRNA and proteins
- Site of protein synthesis (translation)
- 80S in eukaryotes; 70S in prokaryotes

### 3.8 Lysosomes
- Contain digestive enzymes (hydrolases)
- Break down old organelles (autophagy)
- Digest foreign particles (phagocytosis)
- Involved in programmed cell death (apoptosis)
- Called "suicide bags" of the cell

### 3.9 Vacuoles
- Plant cells: Large central vacuole maintains turgor pressure; stores water, pigments, waste
- Animal cells: Small, temporary vacuoles
- Food vacuoles: Digest food (in protists)
- Contractile vacuoles: Regulate water (in freshwater protists)

### 3.10 Cell Wall (Plant Cells, Fungi, Bacteria)
- Plant cell wall: Made of cellulose fibers
- Fungal cell wall: Made of chitin
- Bacterial cell wall: Made of peptidoglycan
- Provides structural support and rigidity
- Prevents cell from bursting
- Freely permeable to water and small molecules

### 3.11 Centrioles (Animal Cells)
- Paired structures (centrosome)
- Organize spindle fibers during cell division
- Involved in formation of cilia and flagella

