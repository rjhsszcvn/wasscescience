## 4. Anaerobic Respiration

Occurs in absence of oxygen.
Glycolysis still occurs (in cytoplasm).
Pyruvate is processed differently.

### 4.1 In Animals (and some bacteria) — Lactic Acid Fermentation
Pyruvate + NADH → Lactic acid + NAD⁺

- Occurs in muscle cells during intense exercise
- Lactic acid builds up → muscle fatigue and soreness
- Oxygen debt: Extra oxygen needed after exercise to oxidize lactic acid back to pyruvate (then enter aerobic pathway)
- Yield: 2 ATP per glucose

### 4.2 In Yeast and Plants — Alcoholic Fermentation
Pyruvate → Ethanol + CO₂ (using enzyme pyruvate decarboxylase and alcohol dehydrogenase)
Ethanol + CO₂ produced
NADH → NAD⁺ regenerated

- Used in brewing (beer, wine) and baking (bread rising from CO₂)
- Ethanol is toxic; kills yeast at high concentrations (~15%)
- Yield: 2 ATP per glucose

### Comparison: Aerobic vs. Anaerobic Respiration

| Feature | Aerobic | Anaerobic |
|---|---|---|
| Oxygen required | Yes | No |
| ATP yield | ~36-38 ATP | 2 ATP |
| End products | CO₂ + H₂O | Lactic acid OR Ethanol + CO₂ |
| Location | Cytoplasm + Mitochondria | Cytoplasm only |
| Duration | Can continue indefinitely | Short-term (substrate limited) |

