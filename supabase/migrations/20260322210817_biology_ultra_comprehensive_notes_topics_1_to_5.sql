## 1. Introduction to Respiration

Respiration: The process by which living organisms break down food molecules (primarily glucose) to release energy in the form of ATP.

Important distinctions:
- Cellular respiration ≠ Breathing (ventilation)
- Cellular respiration occurs in ALL living cells
- Breathing only in organisms with lungs/gills

Overall equation for aerobic respiration:
C₆H₁₂O₆ + 6O₂ → 6CO₂ + 6H₂O + ATP (energy)
Glucose + Oxygen → Carbon dioxide + Water + Energy

Energy released: Approximately 2870 kJ/mol (38 ATP molecules)

---

## 2. ATP (Adenosine Triphosphate)

ATP is the universal energy currency of cells.

Structure:
- Adenosine (adenine + ribose sugar) + 3 phosphate groups
- High-energy bonds between phosphate groups

ATP → ADP + Pi + Energy
ADP + Pi + Energy → ATP (during respiration)

Why ATP is important:
- Direct energy source for cell processes
- Muscle contraction, active transport, synthesis reactions, nerve impulses
- Small, soluble, easily transported in cell
- Releases energy in small, manageable amounts

---

## 3. Aerobic Respiration

Occurs in presence of oxygen.
Location: Cytoplasm (glycolysis) and mitochondria (Krebs cycle and electron transport chain)
Yield: ~36-38 ATP per glucose molecule

### Stage 1: Glycolysis (in cytoplasm)
- Glucose (6C) split into 2 pyruvate molecules (3C)
- Net yield: 2 ATP + 2 NADH
- Does NOT require oxygen
- Occurs in cytoplasm

Steps:
1. Glucose activated by 2 ATP → glucose-6-phosphate
2. Rearranged to fructose-1,6-bisphosphate
3. Split into 2 triose phosphate (3C) molecules
4. Each triose phosphate oxidized → pyruvate
5. 4 ATP produced (net: +2 ATP); 2 NADH produced

### Stage 2: Link Reaction / Pyruvate Oxidation (in mitochondrial matrix)
- Each pyruvate → Acetyl CoA (2C) + CO₂ + NADH
- Pyruvate dehydrogenase enzyme
- 2 CO₂ released per glucose
- 2 NADH produced

### Stage 3: Krebs Cycle / Citric Acid Cycle (in mitochondrial matrix)
- Acetyl CoA (2C) combines with oxaloacetate (4C) → citrate (6C)
- Series of reactions regenerates oxaloacetate
- Per turn of cycle (per acetyl CoA):
  - 2 CO₂ released
  - 3 NADH produced
  - 1 FADH₂ produced
  - 1 ATP produced
- Per glucose (2 turns): 4 CO₂, 6 NADH, 2 FADH₂, 2 ATP

### Stage 4: Electron Transport Chain (ETC) and Oxidative Phosphorylation (inner mitochondrial membrane)
- NADH and FADH₂ donate electrons to ETC
- Electrons pass through protein complexes (I, II, III, IV)
- Energy released used to pump H⁺ ions across inner membrane
- H⁺ ions flow back through ATP synthase → ATP produced (chemiosmosis)
- Oxygen is final electron acceptor → forms water (H₂O)
- NADH produces ~2.5 ATP; FADH₂ produces ~1.5 ATP
- ~32-34 ATP produced here

Total ATP from aerobic respiration: ~36-38 ATP per glucose

