## 7. Transport of Gases in Blood

### 7.1 Oxygen Transport
- 97% carried by haemoglobin in red blood cells
- Haemoglobin (Hb) + 4O₂ → Oxyhaemoglobin (HbO₈)
- Association (in lungs): High O₂ → Hb binds O₂
- Dissociation (in tissues): Low O₂ → Hb releases O₂

Factors promoting O₂ release in tissues:
- Low O₂ concentration
- High CO₂ concentration (Bohr effect)
- High temperature
- Low pH

### 7.2 Carbon Dioxide Transport
- 70% as bicarbonate ions (HCO₃⁻) in plasma
  - CO₂ + H₂O → H₂CO₃ → H⁺ + HCO₃⁻ (catalyzed by carbonic anhydrase in RBCs)
- 23% combined with haemoglobin as carbaminohaemoglobin
- 7% dissolved in plasma

