## 6. Cell Division

### 6.1 Mitosis
Produces two genetically identical daughter cells
Used for: growth, repair, asexual reproduction

Stages:
1. Interphase (preparation): DNA replication; cell grows
2. Prophase: Chromosomes condense; spindle forms; nuclear envelope breaks down
3. Metaphase: Chromosomes line up at equator
4. Anaphase: Chromatids pulled to opposite poles
5. Telophase: Nuclear envelopes reform; cytokinesis begins
Result: 2 identical diploid cells

### 6.2 Meiosis
Produces four genetically unique haploid cells
Used for: gamete (sex cell) formation

Meiosis I (Reductional):
- Prophase I: Homologous chromosomes pair; crossing over at chiasmata
- Metaphase I: Bivalents align at equator
- Anaphase I: Homologous chromosomes separate
- Telophase I: Two haploid cells form

Meiosis II (Equational):
- Similar to mitosis
- Chromatids separate
- Result: 4 haploid cells

Genetic variation sources:
- Crossing over (Prophase I): Exchange of genetic material
- Independent assortment: Random alignment of chromosomes

| Feature | Mitosis | Meiosis |
|---|---|---|
| Divisions | 1 | 2 |
| Daughter cells | 2 | 4 |
| Chromosome no. | Diploid (2n) | Haploid (n) |
| Genetic identity | Identical | Unique |
| Purpose | Growth/repair | Reproduction |
| Crossing over | No | Yes |

