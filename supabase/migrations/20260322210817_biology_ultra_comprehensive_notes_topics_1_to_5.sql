## 5. Population Ecology

### 5.1 Population Size and Growth
Factors affecting population size:
- Birth rate: New individuals added
- Death rate: Individuals removed
- Immigration: Individuals move in
- Emigration: Individuals move out

Population change = (Birth rate + Immigration) - (Death rate + Emigration)

### 5.2 Population Growth Curves

J-shaped (exponential) growth:
- Unlimited resources
- Population grows rapidly
- Not sustainable in nature
- Example: Bacteria in laboratory

S-shaped (logistic) growth:
- Resources become limiting
- Population levels off at carrying capacity (K)
- Carrying capacity: Maximum population an environment can sustain
- Phases: Lag phase → Exponential phase → Stationary phase

### 5.3 Limiting Factors
- Density-dependent factors: Effect increases with population size
  - Food and water availability, disease, predation, competition
- Density-independent factors: Effect independent of population size
  - Temperature, floods, fires, drought

---

## 6. Succession

Succession: Gradual change in community composition over time.

Primary succession:
- Colonization of bare, lifeless area (e.g., bare rock, volcanic island)
- Pioneer species: First to colonize (lichens, mosses)
- Over time: Soil develops; more complex communities form
- Climax community: Stable final stage (e.g., forest)

Secondary succession:
- Occurs after disturbance of established community (fire, flood, farming)
- Faster than primary succession (soil already present)

---

## 7. Pollution and Human Impact

### 7.1 Air Pollution
Sources:
- Burning fossil fuels → SO₂, NO₂, CO, CO₂, soot
- Industrial emissions → heavy metals, dust

Effects:
- Acid rain: SO₂ and NO₂ dissolve in rain → sulfuric/nitric acid → damages plants, aquatic life, buildings
- Greenhouse effect and global warming: CO₂ traps heat in atmosphere
- Smog: Mixture of smoke and fog → respiratory problems
- Ozone depletion: CFCs destroy ozone layer → increased UV radiation → skin cancer

### 7.2 Water Pollution
Sources:
- Sewage and domestic waste
- Agricultural runoff (fertilizers, pesticides)
- Industrial effluents
- Oil spills

Effects:
- Eutrophication: Excess nitrates and phosphates → algal bloom → algae die → bacteria decompose → O₂ depleted → aquatic organisms die
- Waterborne diseases: Cholera, typhoid (from sewage)
- Bioaccumulation: Toxins accumulate in food chain (DDT in birds of prey)
- Reduction in biodiversity

### 7.3 Soil Pollution
Sources: Pesticides, herbicides, heavy metals, industrial waste

Effects: Reduces soil fertility; kills beneficial soil organisms; enters food chain

### 7.4 Deforestation
Causes: Agriculture, timber, urbanization

Effects:
- Loss of biodiversity
- Soil erosion
- Disruption of water cycle
- Increased CO₂ (fewer trees to absorb it)
- Climate change

### 7.5 Conservation
- In-situ conservation: Protecting species in their natural habitat (national parks, game reserves, biosphere reserves)
- Ex-situ conservation: Protecting species outside natural habitat (zoos, botanical gardens, seed banks)
- Sustainable development: Meeting present needs without compromising future generations

---

## 8. Biodiversity

Biodiversity: Variety of life on Earth.

Three levels:
1. Genetic diversity: Variation within species
2. Species diversity: Variety of species in an area
3. Ecosystem diversity: Variety of habitats and ecosystems

Threats to biodiversity:
- Habitat destruction
- Pollution
- Overexploitation (overhunting, overfishing)
- Introduction of invasive species
- Climate change

Importance of biodiversity:
- Ecosystem stability
- Food security (gene pool for crop improvement)
- Medicine (many drugs derived from plants/animals)
- Economic value (ecotourism, timber, fisheries)
- Aesthetic and cultural value' 
