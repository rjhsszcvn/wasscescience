## 4. Nutrient Cycles

### 4.1 Carbon Cycle
Carbon moves between atmosphere, living organisms, and the Earth.

Processes:
- Photosynthesis: CO₂ absorbed by plants → organic carbon
- Respiration: Organic carbon → CO₂ released
- Decomposition: Dead organisms → CO₂ released
- Combustion: Burning fossil fuels → CO₂ released
- Fossilization: Organisms become fossil fuels over millions of years

Importance:
- Maintains CO₂ levels in atmosphere
- Carbon is basis of all organic molecules

### 4.2 Nitrogen Cycle
Nitrogen is essential for proteins, nucleic acids, and ATP.

Processes:
1. Nitrogen fixation: N₂ gas → NH₃ (ammonia)
   - By nitrogen-fixing bacteria in soil (Azotobacter)
   - By bacteria in root nodules of legumes (Rhizobium)
   - By lightning
2. Nitrification: NH₃ → NO₂⁻ → NO₃⁻ (by Nitrosomonas then Nitrobacter bacteria)
3. Assimilation: Plants absorb NO₃⁻ through roots → proteins
4. Ammonification: Dead organisms decomposed by bacteria → NH₃
5. Denitrification: NO₃⁻ → N₂ gas (by denitrifying bacteria in waterlogged soils)

Importance:
- Makes nitrogen available for plant growth
- Leguminous plants (beans, groundnuts) increase soil fertility

### 4.3 Water Cycle
- Evaporation: Water → water vapor
- Transpiration: Water lost from plant leaves
- Condensation: Water vapor → water droplets (clouds)
- Precipitation: Rain, snow, hail
- Runoff: Water flows over land surface
- Infiltration: Water enters soil

