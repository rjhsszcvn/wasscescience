**Key features:**
- **Four chambers:** 2 atria (upper, thin-walled) + 2 ventricles (lower, thick-walled)
- **Left ventricle wall is thicker** than right — pumps blood around the entire body (higher pressure)
- **Septum:** divides left and right sides (prevents mixing of oxygenated and deoxygenated blood)
- **Valves:** prevent backflow of blood
  - **Atrioventricular (AV) valves:** between atria and ventricles (bicuspid left, tricuspid right)
  - **Semilunar valves:** at exits of ventricles (in aorta and pulmonary artery)

---

### Cardiac Cycle (Heartbeat)
1. **Diastole:** Heart muscle relaxes; blood fills atria from veins
2. **Atrial systole:** Atria contract → blood pushed into ventricles
3. **Ventricular systole:** Ventricles contract → blood pumped to arteries; AV valves close (lub sound); semilunar valves open
4. **Valves close:** Semilunar valves close (dub sound) as ventricles relax

**Heart rate:** Average 70 beats/minute (higher in athletes can mean stronger heart)

---

