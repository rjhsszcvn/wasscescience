### Worked Example 3: Blood Vessel Identification
Q: A scientist examines a blood vessel and finds it has thick muscular walls and a narrow lumen. Identify the vessel and explain its features.

**Answer:**
- The vessel is an **artery**
- Thick muscular walls allow it to withstand and maintain **high blood pressure** from the heart
- Elastic tissue in wall allows it to **stretch and recoil** with each heartbeat (creates pulse)
- Narrow lumen maintains high pressure of blood flow

