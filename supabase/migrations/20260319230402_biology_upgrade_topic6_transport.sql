### Worked Example 1: Tracing Blood Flow
Q: Trace the path of a red blood cell from the right atrium to the big toe and back.

Right atrium → tricuspid valve → right ventricle → pulmonary artery → lungs (oxygenated) → pulmonary vein → left atrium → bicuspid valve → left ventricle → aorta → arteries → arterioles → capillaries in big toe → venules → veins → inferior vena cava → right atrium

