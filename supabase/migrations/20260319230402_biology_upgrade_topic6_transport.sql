All living organisms need to transport materials (nutrients, gases, waste) around their bodies.

### Why Transport Systems Are Needed
- Single-celled organisms (e.g., Amoeba): diffusion is sufficient — short distances
- Large multicellular organisms: diffusion alone is too slow → need specialised transport systems

---

### The Human Circulatory System
The human circulatory system is a **closed, double circulatory** system.

**Double circulation:**
```
Pulmonary circulation:         Systemic circulation:
Right side of heart            Left side of heart
      ↓                              ↓
Blood pumped to LUNGS         Blood pumped to BODY
  (to pick up O₂)             (to deliver O₂/nutrients)
      ↓                              ↓
Returns to heart               Returns to heart
(left side with oxygenated)    (right side with deoxygenated)
```

**Advantage:** Blood reaches body tissues at HIGH pressure (more efficient delivery)

