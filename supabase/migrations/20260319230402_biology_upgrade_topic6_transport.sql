Plants have two transport systems: **xylem** (water/minerals) and **phloem** (food/organic compounds).

---

### Xylem
- **Carries:** Water and dissolved mineral salts
- **Direction:** Upward only (roots → stem → leaves)
- **Structure:** Dead cells (no living contents); walls reinforced with lignin; hollow tubes (vessels and tracheids)
- **Process:** Transpiration stream

```
Water uptake in roots:
Soil water → root hair cell → cortex cells → xylem vessel
             (by osmosis)     (by osmosis)    (up stem)
```

**Transpiration:** Loss of water vapour from plant surfaces (mainly through stomata of leaves)

**Factors affecting transpiration rate:**
| Factor | Effect on Transpiration |
|---|---|
| High temperature | Increases (more evaporation) |
| High humidity | Decreases (less evaporation gradient) |
| Wind | Increases (removes water vapour) |
| Light | Increases (stomata open for photosynthesis) |
| Drought/water stress | Decreases (stomata close) |

**How water moves up xylem (Cohesion-Tension Theory):**
1. Water evaporates from leaf cells → creates tension
2. Cohesion between water molecules (hydrogen bonds) → pulls water up as a column
3. Root pressure (created by active uptake of minerals) also pushes water up

---

### Phloem
- **Carries:** Sucrose and amino acids (products of photosynthesis and metabolism)
- **Direction:** Up AND down (bidirectional) — source to sink
- **Structure:** Living cells — sieve tube cells (no nucleus) + companion cells (have nucleus, control sieve tube)
- **Process:** Translocation

```
Source (where food is made or stored):
  Leaves (photosynthesis) → load sucrose into phloem
  Storage organs → unload stored sugars

Sink (where food is used or stored):
  Roots, fruits, growing shoots → receive sucrose from phloem
```

---

### Comparison: Xylem vs Phloem
| Feature | Xylem | Phloem |
|---|---|---|
| Substance transported | Water + mineral salts | Sucrose + amino acids |
| Direction | Upward only | Both directions |
| Cell type | Dead cells | Living cells |
| Cell wall | Lignified (thick) | Thin |
| Main cells | Vessels, tracheids | Sieve tubes + companion cells |
| Process | Transpiration | Translocation |

---

