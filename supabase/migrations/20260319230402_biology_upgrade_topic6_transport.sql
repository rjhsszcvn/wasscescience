### Worked Example 2: Transpiration Experiment
**Potometer experiment** measures water uptake (as proxy for transpiration):
- Cut shoot placed in water-filled tube
- As shoot transpires, water is drawn up → air bubble moves along scale
- Test: move shoot to different conditions (wind, bright light, high humidity)
- **Expected results:**
  - Fan blowing → faster movement (wind increases transpiration)
  - Lamp → faster movement (light opens stomata)
  - Plastic bag over leaves → slower (high humidity reduces transpiration)

