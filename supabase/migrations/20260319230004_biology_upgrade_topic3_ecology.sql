**Ecology** is the scientific study of the relationships between living organisms and their environment.

### Key Ecological Terms
| Term | Definition |
|---|---|
| **Ecosystem** | All living organisms in an area plus their non-living environment (e.g., a pond, forest) |
| **Habitat** | The place where an organism lives |
| **Niche** | The role and position of an organism in its ecosystem (what it eats, where it lives, how it reproduces) |
| **Population** | All individuals of the SAME species in a given area at the same time |
| **Community** | All populations of DIFFERENT species living together in an area |
| **Biosphere** | All ecosystems on Earth |
| **Biome** | A large region with a characteristic climate and community (e.g., tropical rainforest, savanna) |

