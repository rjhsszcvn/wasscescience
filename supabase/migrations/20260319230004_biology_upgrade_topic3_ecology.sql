### Population Growth
A population grows when birth rate + immigration > death rate + emigration.

**Growth Curve (Sigmoid/S-shaped):**
```
Population
size
  │                    ─────────── ← Carrying capacity (K)
  │                  /
  │                 /  ← Exponential growth
  │                /
  │              /
  │            /
  │          /
  │________/  ← Lag phase (slow start)
  └──────────────────── Time
```

**Phases:**
1. **Lag phase:** Slow growth — small population, few reproducing
2. **Exponential (log) phase:** Rapid growth — resources abundant
3. **Stationary phase:** Growth levels off — population at carrying capacity
4. **Decline phase:** (in some cases) Resources exhausted

**Limiting factors** prevent unlimited growth:
- Food/water availability
- Predation
- Disease
- Competition for space
- Climate change

---

### Human Impact on the Environment

**1. Deforestation**
- Clearing of forests for farming, timber, urbanisation
- Effects: soil erosion, loss of biodiversity, climate change, flooding
- West African example: Destruction of Nigerian/Ghanaian rainforests

**2. Pollution**
| Type | Cause | Effect |
|---|---|---|
| Water pollution | Industrial waste, sewage, agricultural chemicals | Kills aquatic life; eutrophication |
| Air pollution | Vehicles, burning fossil fuels, bush burning | Acid rain; respiratory diseases |
| Soil pollution | Chemical fertilisers, pesticides | Kills soil organisms; enters food chain |
| Noise pollution | Vehicles, machines | Stress; hearing loss |

**3. Eutrophication**
```
Excess fertilisers → enter water → algae bloom rapidly
         ↓
Algae block sunlight → aquatic plants die
         ↓
Decomposers break down dead matter → use up O₂
         ↓
Fish and other aquatic animals die (deoxygenation)
```

