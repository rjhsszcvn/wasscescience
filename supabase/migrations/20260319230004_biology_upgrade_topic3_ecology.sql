### Carbon Cycle (Brief Overview)
```
       Photosynthesis
CO₂ ←─────────────── Plants
 ↑                      ↓
 └──── Respiration ────── All organisms
 ↑
 └──── Decomposition ─── Dead matter (bacteria/fungi)
 ↑
 └──── Combustion ─────── Fossil fuels
```

**Key processes:**
- **Photosynthesis:** Removes CO₂ from atmosphere
- **Respiration:** Returns CO₂ to atmosphere
- **Decomposition:** Releases CO₂ from dead organisms
- **Combustion:** Releases stored CO₂ from fossil fuels

