### Biotic vs Abiotic Factors

**Biotic factors** — living components that affect organisms:
- Predation, competition, disease, parasitism, symbiosis, food availability

**Abiotic factors** — non-living components:
- Temperature, light intensity, rainfall, soil pH, humidity, wind speed, altitude

