### Worked Example 2: Pyramid of Energy
If grass produces 50,000 kJ of energy:
- Grasshoppers receive: 50,000 × 10% = 5,000 kJ
- Frogs receive: 5,000 × 10% = 500 kJ
- Snakes receive: 500 × 10% = 50 kJ
- Eagles receive: 50 × 10% = 5 kJ

This explains why large predators are always fewer in number than small prey.

