### Feeding Relationships

**Food Chain:** Shows direction of energy flow from one organism to another.
```
Grass → Grasshopper → Frog → Snake → Eagle
 ↑
Producer → Primary → Secondary → Tertiary → Quaternary
           consumer   consumer    consumer    consumer
```
- Arrow means "is eaten by" or "energy flows to"
- Always starts with a **producer** (green plant/photosynthetic organism)

---

### Trophic Levels
| Level | Organism | Role |
|---|---|---|
| 1st (Trophic level 1) | Green plants, algae | Producers — make food by photosynthesis |
| 2nd | Herbivores (goat, rabbit) | Primary consumers |
| 3rd | Carnivores (frog, small fish) | Secondary consumers |
| 4th | Larger carnivores (eagle, lion) | Tertiary consumers |
| — | Decomposers (bacteria, fungi) | Break down dead organisms |

---

### Food Web
A **food web** is an interconnected network of food chains in an ecosystem.

```
         Eagle
        ↗     ↖
     Snake      Owl
      ↑           ↑
    Frog        Rat
      ↑           ↑
Grasshopper   Caterpillar
       ↖         ↗
          Grass
```

In a food web:
- If one species is removed, it affects ALL connected species
- More complex food webs = more stable ecosystems

---

### Ecological Pyramids

**Pyramid of Numbers:** Shows number of organisms at each trophic level
```
        ▲       ← few top predators (eagles)
       ▲▲▲      ← more secondary consumers (snakes)
      ▲▲▲▲▲     ← many primary consumers (frogs)
    ▲▲▲▲▲▲▲▲    ← very many herbivores (grasshoppers)
  ▲▲▲▲▲▲▲▲▲▲   ← enormous numbers of producers (grass plants)
```
Can be inverted (e.g., one large tree supports many insects)

**Pyramid of Biomass:** Shows dry mass of organisms at each level
- More reliable than pyramid of numbers
- Almost always pyramid-shaped

**Pyramid of Energy:** Shows energy content at each level
- ALWAYS pyramid-shaped (energy is always lost at each level)
- Most useful of the three pyramids

---

### Energy Loss at Each Trophic Level
Only about **10%** of energy is transferred from one trophic level to the next.
Energy is lost as:
- **Heat** (from respiration)
- **Excretion** (urine, faeces)
- **Movement**
- Parts not eaten (bones, shells)

```
Producers: 100,000 kJ
               ↓ 10% transfer
Primary consumers: 10,000 kJ
               ↓ 10% transfer
Secondary consumers: 1,000 kJ
               ↓ 10% transfer
Tertiary consumers: 100 kJ
```
