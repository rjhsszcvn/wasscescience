<h3>9.1 Mental Health</h3>
<p>According to the WHO, <strong>mental health</strong> is a state of well-being in which every individual realizes their own potential, can cope with the normal stresses of life, can work productively and fruitfully, and is able to contribute to their community.</p>

<h4>9.1.1 Common Mental Health Disorders</h4>

<h4>Depression</h4>
<p>A mood disorder characterized by persistent feelings of sadness, emptiness, hopelessness, and loss of interest in activities. It is one of the leading causes of disability worldwide.</p>
<p><strong>Symptoms (lasting 2 weeks or more):</strong></p>
<ul>
<li>Persistent sad, anxious, or "empty" mood</li>
<li>Loss of interest or pleasure in activities (anhedonia)</li>
<li>Sleep disturbances (insomnia or hypersomnia)</li>
<li>Changes in appetite and weight (increase or decrease)</li>
<li>Fatigue and decreased energy</li>
<li>Feelings of worthlessness or excessive guilt</li>
<li>Difficulty concentrating, remembering, or making decisions</li>
<li>Thoughts of death or suicide</li>
<li>Physical symptoms: headaches, digestive problems</li>
</ul>
<p><strong>Treatment:</strong> Psychotherapy (cognitive behavioural therapy), antidepressant medications (SSRIs, SNRIs), lifestyle changes (exercise, social support), combination therapy</p>

<h4>Anxiety Disorders</h4>
<p>A group of disorders characterized by excessive, persistent worry and fear that interferes with daily activities.</p>
<p><strong>Types:</strong></p>
<ul>
<li><strong>Generalized Anxiety Disorder (GAD):</strong> Excessive worry about everyday things</li>
<li><strong>Panic Disorder:</strong> Recurrent unexpected panic attacks (heart racing, sweating, shortness of breath)</li>
<li><strong>Phobias:</strong> Intense fear of specific objects or situations</li>
<li><strong>Social Anxiety Disorder:</strong> Fear of social situations and being judged</li>
<li><strong>Post-Traumatic Stress Disorder (PTSD):</strong> Following exposure to traumatic events</li>
</ul>
<p><strong>Treatment:</strong> Cognitive behavioural therapy (CBT), exposure therapy, anxiolytic medications</p>

<h4>Schizophrenia</h4>
<p>A severe, chronic mental disorder characterized by distortions in thinking, perception, emotions, language, sense of self, and behaviour.</p>
<p><strong>Symptoms:</strong></p>
<ul>
<li><strong>Positive symptoms:</strong> Hallucinations (hearing voices), delusions (false beliefs), disorganized thinking and speech</li>
<li><strong>Negative symptoms:</strong> Flat affect, poverty of speech, social withdrawal, lack of motivation</li>
<li><strong>Cognitive symptoms:</strong> Poor working memory, attention deficits</li>
</ul>
<p><strong>Treatment:</strong> Antipsychotic medications (first-line), psychosocial support, rehabilitation</p>

<h4>Bipolar Disorder</h4>
<p>Characterized by extreme mood swings between mania (elevated mood, increased energy, reduced need for sleep) and depression.</p>

<h3>9.2 Stress</h3>
<p><strong>Stress</strong> is the body physical and emotional response to demands or threats (stressors).</p>

<h4>Types of Stress</h4>
<ul>
<li><strong>Acute stress:</strong> Short-term; caused by specific events; can be energizing in small amounts</li>
<li><strong>Chronic stress:</strong> Long-term, ongoing stress; damaging to health</li>
<li><strong>Eustress:</strong> Positive stress that motivates performance</li>
<li><strong>Distress:</strong> Negative stress that overwhelms coping capacity</li>
</ul>

<h4>The Stress Response (Fight-or-Flight)</h4>
<p>When faced with a threat, the sympathetic nervous system activates the adrenal glands to release adrenaline (epinephrine) and cortisol, causing: increased heart rate and blood pressure, faster breathing, dilated pupils, increased muscle tension, reduced digestive activity, release of glucose into blood.</p>

<h4>Effects of Chronic Stress on Health</h4>
<ul>
<li>Cardiovascular: Hypertension, increased risk of heart disease and stroke</li>
<li>Immune: Weakened immune response, increased susceptibility to infections</li>
<li>Mental: Depression, anxiety, burnout</li>
<li>Digestive: Ulcers, irritable bowel syndrome</li>
<li>Endocrine: Disrupted blood sugar regulation</li>
<li>Musculoskeletal: Tension headaches, muscle pain</li>
</ul>

<h4>Coping Strategies for Stress</h4>
<ul>
<li><strong>Adaptive (healthy) coping:</strong> Exercise, meditation, deep breathing, time management, social support, problem-solving, adequate sleep</li>
<li><strong>Maladaptive (unhealthy) coping:</strong> Substance abuse, overeating, isolation, aggression, excessive screen time</li>
</ul>

<h3>9.3 Substance Abuse</h3>
<p><strong>Substance abuse</strong> (also called drug abuse) is the harmful or hazardous use of psychoactive substances, including alcohol and illicit drugs.</p>

<p><strong>Key Terms:</strong></p>
<ul>
<li><strong>Drug:</strong> Any substance that causes a change in body function</li>
<li><strong>Dependence:</strong> Physical and/or psychological need to continue taking a substance</li>
<li><strong>Tolerance:</strong> The body adapts so that higher doses are needed to achieve the same effect</li>
<li><strong>Withdrawal:</strong> Physical and mental symptoms when substance use is stopped</li>
<li><strong>Addiction:</strong> Compulsive drug-seeking behaviour despite harmful consequences</li>
</ul>

<h4>Categories of Psychoactive Substances</h4>
<table>
<tr><th>Category</th><th>Effect</th><th>Examples</th></tr>
<tr><td>Stimulants</td><td>Speed up CNS activity; increase alertness and energy</td><td>Cocaine, amphetamines, nicotine, caffeine</td></tr>
<tr><td>Depressants</td><td>Slow down CNS activity; reduce inhibition; cause sedation</td><td>Alcohol, barbiturates, benzodiazepines, cannabis (also)</td></tr>
<tr><td>Opioids/Narcotics</td><td>Pain relief; euphoria; sedation</td><td>Heroin, morphine, codeine, tramadol</td></tr>
<tr><td>Hallucinogens</td><td>Distort perception; cause hallucinations</td><td>LSD, psilocybin mushrooms, PCP</td></tr>
<tr><td>Cannabis</td><td>Combined depressant and mild hallucinogen effects</td><td>Marijuana, hashish</td></tr>
<tr><td>Inhalants</td><td>Brief CNS depression/stimulation via inhaled vapours</td><td>Glue, petrol, solvents, aerosols</td></tr>
</table>

<h4>Effects and Consequences of Substance Abuse</h4>
<p><strong>Health Effects:</strong></p>
<ul>
<li>Liver disease (cirrhosis from alcohol), lung cancer (tobacco), brain damage</li>
<li>Malnutrition, cardiovascular disease, immune suppression</li>
<li>Mental health disorders (depression, psychosis)</li>
<li>Overdose and death</li>
</ul>
<p><strong>Social Consequences:</strong></p>
<ul>
<li>Family breakdown, domestic violence, child neglect</li>
<li>Academic failure and unemployment</li>
<li>Crime and violence (to fund habit or due to disinhibition)</li>
<li>Financial difficulties</li>
</ul>

<h4>Alcohol Abuse</h4>
<p><strong>Immediate effects:</strong> Impaired judgement, reduced coordination, slurred speech, lowered inhibitions, aggressive behaviour</p>
<p><strong>Long-term effects:</strong> Cirrhosis (liver scarring), alcoholic hepatitis, pancreatitis, cardiomyopathy, neuropathy, Wernicke-Korsakoff syndrome (thiamine deficiency causing memory loss), foetal alcohol syndrome (if used during pregnancy)</p>
<p><strong>Safe limits:</strong> WHO recommends no more than 14 units/week for adults; no amount is considered safe during pregnancy</p>

<h4>Tobacco/Nicotine Abuse</h4>
<p><strong>Tobacco smoke contains:</strong> Nicotine (addictive), tar (carcinogenic), carbon monoxide (reduces oxygen carrying capacity of blood), and 4,000+ other chemicals</p>
<p><strong>Health effects:</strong> Lung cancer (90% of cases caused by smoking), COPD, cardiovascular disease, oral/throat cancer, peripheral artery disease, impotence, premature ageing of skin</p>

<h4>Prevention and Treatment of Substance Abuse</h4>
<ul>
<li><strong>Prevention:</strong> Education in schools and communities, anti-drug campaigns, reducing availability and access, peer resistance skills training, addressing social determinants (poverty, unemployment)</li>
<li><strong>Treatment:</strong> Detoxification (medically supervised withdrawal), behavioural therapies (CBT, motivational interviewing), medication-assisted treatment (methadone for opioid dependence), support groups (AA, NA), rehabilitation programmes</li>
</ul>

