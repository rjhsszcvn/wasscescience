<h3>10.1 Definition and Scope</h3>
<p><strong>Environmental health</strong> encompasses the assessment, correction, control, and prevention of environmental factors that can adversely affect human health and the quality of life. The WHO defines it as "all the physical, chemical, biological, social, and psychosocial factors external to a person, and all the related factors impacting behaviours."</p>

<h3>10.2 Air Pollution</h3>
<p><strong>Air pollution</strong> refers to the presence of substances in the atmosphere at concentrations that are harmful to human health, other living organisms, or the environment.</p>

<h4>Types of Air Pollutants</h4>
<table>
<tr><th>Pollutant</th><th>Sources</th><th>Health Effects</th></tr>
<tr><td>Carbon monoxide (CO)</td><td>Incomplete combustion (vehicle exhaust, charcoal burning indoors)</td><td>Binds to haemoglobin (forms carboxyhaemoglobin), reducing oxygen transport; headache, dizziness, death at high levels</td></tr>
<tr><td>Sulphur dioxide (SO2)</td><td>Burning fossil fuels (coal, oil), industrial processes</td><td>Respiratory irritation, asthma attacks, acid rain</td></tr>
<tr><td>Nitrogen oxides (NOx)</td><td>Vehicle engines, industrial combustion</td><td>Respiratory damage, smog formation, acid rain</td></tr>
<tr><td>Particulate matter (PM)</td><td>Dust, vehicle exhaust, burning biomass</td><td>Respiratory disease, cardiovascular disease, lung cancer</td></tr>
<tr><td>Ozone (O3) - ground level</td><td>Reaction between NOx and volatile organic compounds in sunlight</td><td>Lung irritation, asthma exacerbation</td></tr>
<tr><td>Lead</td><td>Leaded petrol (now banned in most countries), lead paint, industry</td><td>Neurological damage especially in children, anaemia</td></tr>
</table>

<h4>Indoor Air Pollution</h4>
<p>A major health concern, particularly in low-income settings where biomass fuels (wood, charcoal, crop waste) are burned indoors for cooking and heating.</p>
<p><strong>Sources:</strong> Biomass fuel combustion, tobacco smoke, building materials (asbestos, formaldehyde), radon gas, mould</p>
<p><strong>Effects:</strong> Acute lower respiratory infections (leading cause of child deaths), COPD, lung cancer, cardiovascular disease</p>
<p><strong>Solutions:</strong> Clean cooking fuels (LPG, biogas, solar), improved cook stoves, ventilation, tobacco-free indoor environments</p>

<h3>10.3 Water Pollution</h3>
<p>Contamination of water bodies with substances that make it unsuitable for drinking, recreation, or ecological functions.</p>

<h4>Sources of Water Pollution</h4>
<ul>
<li><strong>Agricultural runoff:</strong> Fertilizers (nitrates causing eutrophication), pesticides</li>
<li><strong>Industrial effluents:</strong> Heavy metals (mercury, lead, cadmium), chemicals</li>
<li><strong>Sewage and excreta:</strong> Faecal pathogens causing waterborne diseases</li>
<li><strong>Mining activities:</strong> Acid mine drainage, heavy metal contamination (mercury in artisanal gold mining)</li>
<li><strong>Oil spills:</strong> Petroleum contamination</li>
<li><strong>Solid waste dumping:</strong> Leaching of toxins into groundwater</li>
</ul>

<h4>Health Effects of Water Pollution</h4>
<ul>
<li>Waterborne diseases: cholera, typhoid, dysentery, hepatitis A (from pathogens)</li>
<li>Heavy metal poisoning: neurological damage (lead, mercury), kidney failure (cadmium)</li>
<li>Fluorosis from excess fluoride</li>
<li>Nitrate poisoning ("blue baby syndrome"/methaemoglobinaemia in infants)</li>
<li>Cancer risk from chemical carcinogens</li>
</ul>

<h3>10.4 Soil Pollution</h3>
<p>Contamination of soil with chemicals, heavy metals, or biological agents that adversely affect soil quality and human health.</p>

<p><strong>Sources:</strong> Agricultural chemicals (pesticides, herbicides, fertilizers), industrial waste, improper waste disposal, oil spills, mining activities</p>

<p><strong>Health Effects:</strong> Skin and respiratory problems from direct contact/inhalation; food chain contamination (bioaccumulation of toxins in food crops); groundwater contamination; cancer from persistent organic pollutants (POPs)</p>

<h3>10.5 Noise Pollution</h3>
<p>Unwanted or harmful sound that interferes with communication, sleep, or causes hearing damage.</p>

<p><strong>Sources:</strong> Traffic, industrial machinery, construction, aircraft, loud music</p>
<p><strong>Measurement:</strong> Decibels (dB). Hearing damage begins with prolonged exposure above 85 dB; painful above 120 dB; conversation is about 60 dB.</p>

<p><strong>Health Effects:</strong></p>
<ul>
<li>Noise-induced hearing loss (NIHL) - preventable and permanent</li>
<li>Tinnitus (ringing in ears)</li>
<li>Sleep disturbance</li>
<li>Cardiovascular effects (hypertension, increased heart rate)</li>
<li>Psychological stress, reduced concentration</li>
</ul>

<p><strong>Prevention:</strong> Ear protection (earplugs, earmuffs) in noisy environments, noise barriers, regulations on noise levels, turn down music volume</p>

<h3>10.6 Climate Change and Health</h3>
<p>Climate change is the greatest global health threat of the 21st century (Lancet Countdown on Health and Climate Change).</p>

<h4>Health Impacts of Climate Change</h4>
<ul>
<li><strong>Extreme heat:</strong> Heat stroke, dehydration, cardiovascular and respiratory diseases</li>
<li><strong>Extreme weather events:</strong> Injuries, deaths, displacement, mental health impacts from floods, storms</li>
<li><strong>Changing disease patterns:</strong> Expansion of malaria, dengue, and other vector-borne diseases to new areas</li>
<li><strong>Food insecurity:</strong> Reduced crop yields, malnutrition</li>
<li><strong>Water scarcity:</strong> Droughts reducing fresh water availability, increasing waterborne disease risk</li>
<li><strong>Air quality:</strong> Increased wildfires and pollen, worsening respiratory disease</li>
</ul>

<h3>10.7 Occupational Health</h3>
<p>The promotion and maintenance of physical, mental, and social well-being of workers in all occupations.</p>

<h4>Occupational Hazards</h4>
<table>
<tr><th>Type</th><th>Examples</th><th>Diseases/Conditions</th></tr>
<tr><td>Physical</td><td>Noise, radiation, extreme heat/cold, vibration</td><td>NIHL, sunburn, heat stroke, vibration white finger</td></tr>
<tr><td>Chemical</td><td>Dusts (silica, asbestos, coal), solvents, pesticides</td><td>Silicosis, asbestosis, pneumoconiosis, poisoning</td></tr>
<tr><td>Biological</td><td>Bacteria, viruses, fungi in healthcare, farming, labs</td><td>TB, hepatitis B, Brucellosis</td></tr>
<tr><td>Ergonomic</td><td>Awkward postures, heavy lifting, repetitive movements</td><td>Musculoskeletal disorders, back pain, repetitive strain injury</td></tr>
<tr><td>Psychosocial</td><td>High workload, bullying, shift work</td><td>Stress, burnout, depression</td></tr>
</table>

<h4>Prevention of Occupational Diseases (Hierarchy of Controls)</h4>
<ol>
<li><strong>Elimination:</strong> Remove the hazard completely</li>
<li><strong>Substitution:</strong> Replace with less hazardous material/process</li>
<li><strong>Engineering controls:</strong> Enclosures, ventilation systems, machine guards</li>
<li><strong>Administrative controls:</strong> Job rotation, reduced exposure time, training</li>
<li><strong>Personal Protective Equipment (PPE):</strong> Last resort; gloves, masks, goggles, earplugs</li>
</ol>

<h3>10.8 Waste Management</h3>
<p>The 3Rs hierarchy: <strong>Reduce</strong> (minimize waste generation) - <strong>Reuse</strong> (use items multiple times) - <strong>Recycle</strong> (process waste into new products)</p>

<p><strong>Medical/Healthcare Waste:</strong> Contains infectious agents, sharps, pharmaceuticals, radioactive materials. Must be segregated (colour-coded bags: yellow for infectious, black for general, red for radioactive), treated, and disposed of safely to prevent healthcare worker infection and environmental contamination.</p>

