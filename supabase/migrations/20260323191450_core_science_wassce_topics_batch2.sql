<h3>7.1 Pure Substances vs Mixtures</h3>
<ul>
  <li><strong>Pure substance:</strong> Contains only one type of particle. Has a sharp fixed melting/boiling point. Cannot be separated by physical methods.</li>
  <li><strong>Mixture:</strong> Contains two or more substances physically combined. Has a range of melting/boiling points. Can be separated by physical methods.</li>
</ul>

<h3>7.2 Types of Mixtures</h3>
<ul>
  <li><strong>Homogeneous mixture (solution):</strong> Uniform composition throughout. Components not visible separately. Examples: salt water, sugar solution, air.</li>
  <li><strong>Heterogeneous mixture:</strong> Non-uniform composition. Components may be visible. Examples: soil, sand and water.</li>
  <li><strong>Suspension:</strong> Insoluble particles dispersed in a liquid. Particles settle on standing. Example: muddy water.</li>
  <li><strong>Colloid:</strong> Particles intermediate in size. Does not settle. Example: milk, blood.</li>
</ul>

<h3>7.3 Solutions</h3>
<ul>
  <li><strong>Solute:</strong> The substance that dissolves (usually the smaller amount)</li>
  <li><strong>Solvent:</strong> The substance that does the dissolving (usually the larger amount)</li>
</ul>

<h4>Concentration</h4>
<ul>
  <li><strong>Dilute solution:</strong> Small amount of solute</li>
  <li><strong>Concentrated solution:</strong> Large amount of solute</li>
  <li><strong>Saturated solution:</strong> No more solute can dissolve at that temperature</li>
</ul>

<h4>Factors Affecting Solubility</h4>
<ul>
  <li><strong>Temperature:</strong> Most solids are more soluble at higher temperatures; gases become less soluble at higher temperatures</li>
  <li><strong>Nature of solute and solvent:</strong> Like dissolves like</li>
  <li><strong>Pressure:</strong> Affects gas solubility; higher pressure means more gas dissolves</li>
</ul>

