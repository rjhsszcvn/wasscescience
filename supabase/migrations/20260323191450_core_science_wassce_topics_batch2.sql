  <li>Example: obtaining copper sulphate crystals from solution</li>
</ul>

<h4>4. Simple Distillation</h4>
<ul>
  <li>Used to separate a liquid from a dissolved solid or to obtain a pure liquid</li>
  <li>Solution is heated; vapour is collected and condensed</li>
  <li>Example: obtaining pure water from salt water</li>
</ul>

<h4>5. Fractional Distillation</h4>
<ul>
  <li>Used to separate a mixture of miscible liquids with different boiling points</li>
  <li>Liquid with lower boiling point distils first</li>
  <li>Example: separating alcohol and water; separating crude oil fractions</li>
</ul>

