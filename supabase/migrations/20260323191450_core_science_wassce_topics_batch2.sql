  <li>Filtrate (liquid) passes through; residue (solid) remains on filter paper</li>
  <li>Example: separating sand from water</li>
</ul>

<h4>2. Evaporation</h4>
<ul>
  <li>Used to separate a dissolved solid from a solution</li>
  <li>Solution is heated until the solvent evaporates, leaving the solid behind</li>
  <li>Example: obtaining salt from sea water</li>
</ul>

<h4>3. Crystallisation</h4>
