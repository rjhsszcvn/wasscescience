<h3>5.1 Definition and Overview</h3>
<p><strong>Non-communicable diseases (NCDs)</strong>, also known as chronic diseases, are medical conditions that are not passed from person to person. They are of long duration and generally slow progression. NCDs are the leading cause of death globally, responsible for 74% of all deaths worldwide.</p>

<p><strong>The four major NCDs are:</strong></p>
<ol>
<li>Cardiovascular diseases (heart disease, stroke)</li>
<li>Cancers</li>
<li>Chronic respiratory diseases (COPD, asthma)</li>
<li>Diabetes</li>
</ol>

<p><strong>Shared Risk Factors for NCDs:</strong></p>
<ul>
<li>Tobacco use</li>
<li>Harmful use of alcohol</li>
<li>Physical inactivity</li>
<li>Unhealthy diet (high in saturated fat, salt, sugar)</li>
</ul>

<h3>5.2 Cardiovascular Diseases (CVDs)</h3>
<p>CVDs are diseases of the heart and blood vessels. They are the number one cause of death globally.</p>

<h4>5.2.1 Hypertension (High Blood Pressure)</h4>
<p><strong>Definition:</strong> A persistent elevation of blood pressure at or above 140/90 mmHg (systolic/diastolic).</p>
<p>Normal BP: 120/80 mmHg; Elevated: 120-129 systolic; Stage 1 Hypertension: 130-139/80-89; Stage 2 Hypertension: 140/90 and above</p>

<p><strong>Types:</strong></p>
<ul>
<li><strong>Primary (essential) hypertension:</strong> No identifiable cause; accounts for 90-95% of cases; associated with multiple risk factors</li>
<li><strong>Secondary hypertension:</strong> Due to identifiable cause (kidney disease, hormonal disorders)</li>
</ul>

<p><strong>Risk Factors:</strong></p>
<ul>
<li>Non-modifiable: Age, family history, race (African ancestry has higher risk), sex</li>
<li>Modifiable: Obesity, high salt intake, physical inactivity, alcohol use, smoking, stress, diabetes</li>
</ul>

<p><strong>Complications (Target Organ Damage):</strong></p>
<ul>
<li><strong>Heart:</strong> Coronary artery disease, heart failure, left ventricular hypertrophy</li>
<li><strong>Brain:</strong> Stroke (ischaemic or haemorrhagic)</li>
<li><strong>Kidneys:</strong> Chronic kidney disease (renal failure)</li>
<li><strong>Eyes:</strong> Hypertensive retinopathy (damage to blood vessels of the retina)</li>
</ul>

<p><strong>Management:</strong></p>
<ul>
<li>Lifestyle modification: DASH diet (low sodium, rich in fruits/vegetables), weight loss, exercise (150 min/week), smoking cessation, alcohol reduction</li>
<li>Medications: ACE inhibitors, calcium channel blockers, diuretics, beta-blockers, ARBs</li>
</ul>

<h4>5.2.2 Coronary Artery Disease (CAD)</h4>
<p>CAD occurs when atherosclerosis (plaque buildup of cholesterol, fat, and calcium) narrows the coronary arteries, reducing blood flow to the heart muscle (myocardium).</p>

<p><strong>Atherosclerosis Process:</strong> Endothelial injury leads to lipid accumulation, then foam cell formation, then plaque development, then arterial narrowing, then ischaemia.</p>

<p><strong>Angina Pectoris:</strong> Chest pain/discomfort from inadequate blood supply to the heart (ischaemia); triggered by exertion; relieved by rest or nitroglycerin</p>

<p><strong>Myocardial Infarction (Heart Attack):</strong> Complete blockage of a coronary artery causing death of heart muscle</p>
<ul>
<li>Symptoms: Severe crushing chest pain radiating to left arm/jaw, shortness of breath, sweating, nausea</li>
<li>Emergency treatment: Aspirin, oxygen, nitroglycerin, percutaneous coronary intervention (PCI)</li>
</ul>

<h4>5.2.3 Stroke (Cerebrovascular Accident)</h4>
<p>Sudden interruption of blood supply to the brain causing death of brain cells.</p>
<p><strong>Types:</strong></p>
<ul>
<li><strong>Ischaemic stroke (80%):</strong> Blockage of cerebral artery by thrombus or embolus</li>
<li><strong>Haemorrhagic stroke (20%):</strong> Rupture of cerebral blood vessel causing bleeding into brain</li>
</ul>
<p><strong>FAST acronym for stroke recognition:</strong></p>
<ul>
<li><strong>F</strong>ace drooping (uneven smile)</li>
<li><strong>A</strong>rm weakness (one arm drifts down when raised)</li>
<li><strong>S</strong>peech difficulty (slurred or strange speech)</li>
<li><strong>T</strong>ime to call emergency services immediately</li>
</ul>

<h3>5.3 Diabetes Mellitus</h3>
<p><strong>Diabetes mellitus</strong> is a metabolic disorder characterized by persistent hyperglycaemia (high blood glucose) resulting from defects in insulin secretion, insulin action, or both.</p>

<h4>Types of Diabetes</h4>
<table>
<tr><th>Feature</th><th>Type 1 Diabetes</th><th>Type 2 Diabetes</th><th>Gestational Diabetes</th></tr>
<tr><td>Cause</td><td>Autoimmune destruction of beta cells; no insulin production</td><td>Insulin resistance and relative insulin deficiency</td><td>Hormonal changes in pregnancy causing insulin resistance</td></tr>
<tr><td>Onset</td><td>Usually in childhood/adolescence</td><td>Usually in adults (increasingly in youth)</td><td>During pregnancy</td></tr>
<tr><td>Body type</td><td>Usually thin</td><td>Often overweight/obese</td><td>Variable</td></tr>
<tr><td>Treatment</td><td>Insulin injections (lifelong)</td><td>Lifestyle modification, oral medications, insulin if needed</td><td>Dietary modification, insulin if needed</td></tr>
</table>

<h4>Signs and Symptoms of Diabetes ("3 Ps")</h4>
<ul>
<li><strong>Polyuria:</strong> Frequent urination (osmotic diuresis)</li>
<li><strong>Polydipsia:</strong> Excessive thirst</li>
<li><strong>Polyphagia:</strong> Excessive hunger</li>
<li>Weight loss (especially Type 1), fatigue, blurred vision, slow wound healing, recurrent infections</li>
</ul>

<h4>Diagnosis</h4>
<ul>
<li>Fasting blood glucose 7.0 mmol/L or above (126 mg/dL)</li>
<li>Random blood glucose 11.1 mmol/L or above (200 mg/dL) with symptoms</li>
<li>HbA1c of 6.5% or above (reflects average glucose over 3 months)</li>
</ul>

<h4>Complications of Diabetes</h4>
<ul>
<li><strong>Microvascular:</strong> Diabetic retinopathy (blindness), nephropathy (kidney failure), neuropathy (nerve damage)</li>
<li><strong>Macrovascular:</strong> Coronary artery disease, stroke, peripheral artery disease</li>
<li><strong>Diabetic foot:</strong> Neuropathy plus poor circulation leads to ulcers and possible amputation</li>
</ul>

<h3>5.4 Cancer</h3>
<p><strong>Cancer</strong> is a group of diseases involving abnormal, uncontrolled cell growth (malignant tumour) that can invade surrounding tissues and spread to other parts of the body (metastasis).</p>

<h4>Difference Between Benign and Malignant Tumours</h4>
<table>
<tr><th>Feature</th><th>Benign Tumour</th><th>Malignant Tumour</th></tr>
<tr><td>Growth</td><td>Slow, contained</td><td>Rapid, invasive</td></tr>
<tr><td>Spread</td><td>Does not metastasize</td><td>Can spread to distant organs (metastasis)</td></tr>
<tr><td>Capsule</td><td>Usually encapsulated</td><td>Not encapsulated</td></tr>
<tr><td>Danger</td><td>Generally not life-threatening</td><td>Life-threatening</td></tr>
<tr><td>Recurrence</td><td>Rarely recurs after removal</td><td>May recur after treatment</td></tr>
</table>

<h4>Common Cancers in Ghana/West Africa</h4>
<ul>
<li><strong>Breast cancer:</strong> Most common cancer in women; screening by mammography and self-examination; treatment: surgery, radiotherapy, chemotherapy, hormone therapy</li>
<li><strong>Cervical cancer:</strong> Caused by Human Papillomavirus (HPV); preventable by HPV vaccine; screened by Pap smear</li>
<li><strong>Prostate cancer:</strong> Most common cancer in men; screening by PSA (Prostate Specific Antigen) test and digital rectal examination</li>
<li><strong>Liver cancer:</strong> Often secondary to hepatitis B/C infection and cirrhosis; hepatitis B vaccination is key prevention</li>
<li><strong>Colorectal cancer:</strong> Associated with low-fibre diet, obesity, physical inactivity; screened by colonoscopy</li>
</ul>

<h4>Warning Signs of Cancer (CAUTION)</h4>
<ul>
<li><strong>C</strong>hange in bowel or bladder habits</li>
<li><strong>A</strong> sore that does not heal</li>
<li><strong>U</strong>nusual bleeding or discharge</li>
<li><strong>T</strong>hickening or lump in breast or elsewhere</li>
<li><strong>I</strong>ndigestion or difficulty swallowing</li>
<li><strong>O</strong>bvious change in a wart or mole</li>
<li><strong>N</strong>agging cough or hoarseness</li>
</ul>

<h4>Cancer Prevention</h4>
<ul>
<li>Avoid tobacco (smoking and chewing)</li>
<li>Maintain healthy weight</li>
<li>Be physically active</li>
<li>Eat a healthy diet (rich in fruits and vegetables, low in red/processed meat)</li>
<li>Limit alcohol consumption</li>
<li>Vaccination (Hepatitis B, HPV)</li>
<li>Protect from sun (use sunscreen, avoid peak UV hours)</li>
<li>Regular cancer screenings</li>
</ul>

<h3>5.5 Chronic Respiratory Diseases</h3>

<h4>Asthma</h4>
<p>A chronic inflammatory disease of the airways characterized by reversible airflow obstruction, bronchospasm, and airway hyperresponsiveness.</p>
<p><strong>Triggers:</strong> Allergens (dust mites, pollen, animal dander), exercise, cold air, respiratory infections, tobacco smoke, air pollution</p>
<p><strong>Symptoms:</strong> Wheezing, breathlessness, chest tightness, cough (especially at night/early morning)</p>
<p><strong>Treatment:</strong> Reliever inhalers (short-acting beta-2 agonists like salbutamol), preventer inhalers (corticosteroids), avoid triggers</p>

<h4>Chronic Obstructive Pulmonary Disease (COPD)</h4>
<p>Progressive, irreversible airflow limitation caused by chronic bronchitis and/or emphysema, primarily due to smoking.</p>
<p><strong>Signs:</strong> Chronic productive cough ("smoker cough"), progressive dyspnoea (breathlessness), decreased exercise tolerance</p>
<p><strong>Prevention:</strong> Smoking cessation is the most effective intervention</p>

