## 3. Causes of Rapid Urbanisation in West Africa

### Rural Push Factors (reasons people leave rural areas):

- Lack of employment opportunities.
- Poverty and low income from farming.
- Drought and food insecurity.
- Poor access to education and healthcare.
- Boredom and desire for "city life."
- Land scarcity and family land disputes.

### Urban Pull Factors (attractions of cities):

- More jobs (formal and informal sectors).
- Higher wages.
- Better schools, hospitals, and services.
- Exciting social life.
- Better infrastructure (electricity, water, roads).
- Opportunities for entrepreneurship.

### Natural population growth in cities:

- High birth rates among urban populations.
- Improved healthcare in cities reduces infant mortality.

---

## 4. Primate Cities

**Definition:** A **primate city** is the largest city in a country, which is disproportionately larger than the second city — often more than twice the size.

- In West Africa, capital cities and major cities often dominate to an extreme degree.
- **Example:** Accra has more than twice the population of Kumasi in Ghana.
- **Example:** Lagos (Nigeria's commercial capital — not the official capital, which is Abuja) is roughly 10× the size of Kano.
- **Example:** Monrovia contains nearly 50% of Liberia's entire population.

**Problems of primate city dominance:**
- Over-concentration of resources and investment in one city.
- Other regions are neglected.
- Very poor rural areas exist alongside a very large, dominant city.

---

## 5. Problems of Rapid Urbanisation

### Housing:

- **Slums (informal settlements):** When rural migrants arrive, they cannot afford formal housing. They build makeshift structures on whatever land is available, often illegally.
- **Examples of slums/informal settlements:**
  - **Nima** (Accra, Ghana) — overcrowded, poor sanitation.
  - **Makola** area slums (Accra).
  - **Ajegunle** (Lagos, Nigeria) — one of Africa's largest slums.
  - **West Point** (Monrovia, Liberia).
- **Characteristics of slums:** Overcrowding; poor-quality housing (zinc roofs, mud walls); lack of clean water; inadequate sanitation; poor waste disposal; crime.

### Unemployment and Poverty:

- More people arrive than formal jobs exist → unemployment and underemployment.
- Many people work in the **informal sector** (petty trading, street vending, small-scale artisan work) — no job security, no benefits, irregular income.

### Traffic Congestion:

- Rapid growth without adequate road planning → severe congestion.
- Lagos (Nigeria) is notorious for extreme traffic jams ("go-slows").
- Increases journey times, reduces productivity, increases air pollution.

### Inadequate Services:

- Water supply cannot keep up with growth → many urban dwellers have no piped water.
- Sanitation: many slum areas have no sewage systems → open defecation, waterborne diseases.
- Electricity: frequent blackouts ("dumsor" in Ghana); informal settlements often not connected.
- Healthcare: public hospitals are overwhelmed.
- Schools: overcrowded classrooms; shortage of teachers.

### Environmental Problems:

- Air pollution from vehicles and industry.
- Water pollution from untreated sewage and industrial waste.
- Garbage accumulation — inadequate waste collection.
- Flooding — urbanisation creates impermeable surfaces → increased runoff → flash floods (common in Accra during rainy season).

