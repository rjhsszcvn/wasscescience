## 8. Case Study: Lagos, Nigeria

**Lagos** is Nigeria's largest city and commercial capital (not the official capital — Abuja is). Population: approximately 15–25 million (estimates vary), making it one of the **largest cities in Africa** and the world.

**Characteristics:**
- Located on coastal lagoons — limited space for expansion.
- Extremely rapid growth from <1 million (1960) to 15+ million today.
- One of the highest urban growth rates in the world.
- Major port, financial centre, and cultural hub of West Africa.

**Problems of Lagos:**
1. Extreme traffic congestion ("go-slows").
2. Massive informal settlements (Ajegunle, Makoko — floating slum).
3. Flooding (low-lying coastal/lagoon city).
4. Crime and insecurity.
5. Poor sanitation and pollution.

