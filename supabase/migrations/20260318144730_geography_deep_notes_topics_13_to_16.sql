## 7. Case Study: Accra, Ghana

**Accra** is Ghana's capital city and primate city — population of approximately 2.5–3 million (Greater Accra Region: ~5 million).

**Growth of Accra:**
- Founded as a British colonial port and administrative centre.
- Population growth accelerated after independence (1957).
- Rapid rural-urban migration, especially from Northern Ghana.

**Land use zones in Accra:**
- **CBD:** Makola Market (one of West Africa's busiest markets), banks, government offices, Ridge residential area (colonial-era).
- **Industrial areas:** Tema (adjacent industrial city) — Ghana's main port and industrial zone; Accra industrial area.
- **High-income residential:** East Legon, Labone, Cantonments, Airport residential area.
- **Low-income / informal settlements:** Nima, Maamobi, Chorkor (fishing community), Old Fadama (Ghana's largest slum — built on a floodplain).

**Problems of Accra:**
1. Flooding — Old Fadama is built on the Odaw River floodplain and floods every year during heavy rains.
2. Traffic congestion — particularly on Spintex Road, N1 highway.
3. Inadequate sanitation — open drains, inadequate sewage.
4. Solid waste disposal — inefficient garbage collection.
5. Slum conditions in Nima and Old Fadama.

**Solutions being implemented:**
- Decentralisation — developing secondary cities (Kumasi, Tamale) to reduce pressure on Accra.
- Road construction and expansion.
- Slum upgrading programmes.
- Better waste management (Zoomlion Ghana contracted for waste collection).

