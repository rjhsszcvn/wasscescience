## 1. Key Definitions

**Urban area:** A town or city — a nucleated settlement with a large population, non-agricultural economic activities, and complex infrastructure.

**Rural area:** Countryside — settlements with smaller populations, mainly engaged in farming and primary activities.

**Urbanisation:** The process by which an increasing proportion of a country's or region's population lives in urban areas (towns and cities).

**Urban growth:** An increase in the absolute number of people living in urban areas.

**Urbanisation rate:** The percentage of a country's population living in urban areas.

