## 1. What are Rocks and Minerals?

**Mineral:** A naturally occurring, inorganic substance with a definite chemical composition and crystal structure.
- Examples: quartz, feldspar, mica, calcite, iron ore (haematite), gold.

**Rock:** A natural solid aggregate (mixture) of one or more minerals.
- Rocks form the solid material of the Earth's crust.
- Most rocks are made of several minerals (e.g., granite = quartz + feldspar + mica).
- Some rocks are made of a single mineral (e.g., limestone = mainly calcite; quartzite = quartz).

---

## 2. The Three Rock Groups

All rocks can be classified into three main groups based on how they were formed:

| Group | How Formed | Examples |
|-------|-----------|---------|
| **Igneous** | From cooled and solidified magma (molten rock) | Granite, basalt, dolerite, obsidian |
| **Sedimentary** | From compressed layers of sediment (particles, organic material) | Sandstone, limestone, shale, chalk, coal, conglomerate |
| **Metamorphic** | From existing rocks changed by heat and/or pressure | Marble (from limestone), slate (from shale), quartzite (from sandstone), schist |

---

## 3. Igneous Rocks

**Definition:** Igneous rocks form when magma (molten rock) cools and solidifies.

### A. Intrusive (Plutonic) Igneous Rocks

- Magma cools **slowly underground** (large magma chambers).
- Slow cooling → large crystals form.
- Example: **GRANITE**
  - Large, visible crystals of quartz (glassy, grey), feldspar (pink or white), and mica (shiny, dark).
  - Very hard, resistant rock.
  - Forms the core of many mountain ranges and some of West Africa's ancient shields.
  - Used for: building construction, road stone (aggregate), ornamental stone.

**Intrusive igneous features:**
- **Batholith:** A massive body of granite exposed at the surface after overlying rock is eroded.
- **Dyke:** A vertical sheet of igneous rock that cuts across other rock layers (formed when magma forces its way into a vertical crack).
- **Sill:** A horizontal sheet of igneous rock that intrudes between existing rock layers.

### B. Extrusive (Volcanic) Igneous Rocks

- Magma erupts at the surface (as lava) and cools **rapidly**.
- Rapid cooling → very small crystals (or glassy texture — no crystals).
- Example: **BASALT**
  - Fine-grained, dark grey to black.
  - Forms from runny (low viscosity) lava.
  - Covers large areas of ocean floor and forms shield volcanoes.
  - Weathers to produce fertile soils (basalt soils are among the most fertile in the world).
- **Obsidian:** Natural glass — cooled so fast that no crystals formed.
- **Pumice:** Very porous (full of gas bubbles) — can float on water!

---

## 4. Sedimentary Rocks

**Definition:** Sedimentary rocks form from accumulated layers of sediment that are compacted and cemented (lithification) over millions of years.

### How Sedimentary Rocks Form:

1. Weathering and erosion break down existing rocks into sediment (particles of rock, shells, organic matter).
2. Sediment is transported by water, wind, or ice.
3. Sediment settles (deposits) in layers (**strata**) in seas, lakes, rivers, and deserts.
4. Over time, the weight of overlying sediment compacts and cements the particles → sedimentary rock.

### Types of Sedimentary Rocks:

**1. Clastic (mechanical) — formed from fragments of other rocks:**

| Rock | Particle size | Description |
|------|--------------|-------------|
| Conglomerate | Very coarse (pebbles, cobbles) | Rounded pebbles cemented together |
| Sandstone | Medium (sand grains) | Visible sand grains; porous; good aquifer |
| Mudstone/Shale | Very fine (clay, silt) | Thin layers; soft; splits easily |

**2. Organic — formed from the remains of living organisms:**

| Rock | Origin | Uses |
|------|--------|------|
| Limestone | Marine shells and coral (calcium carbonate) | Cement, building, agricultural lime |
| Chalk | Microscopic marine organisms | Chalk drawings, lime production |
| Coal | Compressed ancient plant material | Fuel (energy), chemical industry |

**3. Chemical — precipitated from mineral-rich water:**

- Rock salt (evaporite — formed when seas evaporate).
- Gypsum.

### Important Characteristics of Sedimentary Rocks:

- **Strata (bedding planes):** Horizontal layers visible in the rock — show the sequence of deposition.
- **Fossils:** Preserved remains or impressions of ancient organisms — found ONLY in sedimentary rocks.
- **Dip:** The angle at which rock strata are tilted from the horizontal.
- **Joints and faults:** Cracks and displacements in the rock.

---

## 5. Metamorphic Rocks

**Definition:** Metamorphic rocks are formed from pre-existing rocks (igneous, sedimentary, or other metamorphic) that have been changed by intense heat, pressure, or hydrothermal fluids — without melting.

"Metamorphic" means "changed form."

| Original Rock | Heat + Pressure | New Metamorphic Rock |
|---------------|----------------|---------------------|
| Limestone | → | Marble |
| Shale/mudstone | → | Slate (low grade) → Phyllite → Schist → Gneiss (high grade) |
| Sandstone | → | Quartzite |
| Coal | → | Graphite / Diamond (extreme pressure) |

**Characteristics:**
- **Marble:** White or coloured, crystalline; harder than limestone; used for buildings, sculptures, floors.
- **Slate:** Dark grey, fine-grained; splits into flat sheets; used for roofing tiles.
- **Quartzite:** Very hard, resistant; used as road stone.
- **Schist:** Has foliation (parallel alignment of minerals); shiny from mica content.

### Types of Metamorphism:

**1. Contact (thermal) metamorphism:**
- Heat from igneous intrusion bakes surrounding rock.
- Produces a metamorphic "aureole" (zone) around the intrusion.

**2. Regional metamorphism:**
- Heat AND pressure during mountain building (plate collision).
- Affects large areas of rock.
- Produces high-grade metamorphic rocks (schist, gneiss).

---

## 6. The Rock Cycle

The rock cycle shows the continuous transformation of rocks from one type to another over geological time:

- Magma → cools → **Igneous rock**
- Igneous rock → weathering + erosion → sediment → compaction → **Sedimentary rock**
- Any rock → heat + pressure → **Metamorphic rock**
- Any rock → melts → **Magma** → new igneous rock
- The cycle has no beginning or end — it is continuous over millions of years.

