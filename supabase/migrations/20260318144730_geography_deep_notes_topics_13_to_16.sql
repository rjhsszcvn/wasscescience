### Key features:

**The River Niger:**
- The 3rd longest river in Africa (after Nile and Congo).
- Unusual curved path — flows NE from Guinea toward the Sahara, then curves SE back to Nigeria.
- Creates the **Inland Niger Delta** (Mali) — a vast seasonally flooded plain, extremely rich in fish and birds.
- The **Niger Delta** (Nigeria) — one of the world's largest deltas; major oil-producing region.

**The Volta System (Ghana):**
- Three main tributaries: Black Volta, White Volta, and Oti (Red Volta).
