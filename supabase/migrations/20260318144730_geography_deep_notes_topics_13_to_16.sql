## 6. Urban Land Use

**Urban land use** refers to the different functions (uses) of land within a city.

### Zone Model of City Structure:

The **Burgess Concentric Zone Model** (developed for industrial cities) shows how land use changes from centre to edge:

1. **Central Business District (CBD):** Centre of the city; land values highest; shops, offices, banks, government offices; highest buildings; most accessible.
2. **Zone of Transition (Inner city):** Old factories, warehouses, poor housing; lower-income groups; often deteriorating.
3. **Working-class residential zone:** Terraced/small houses; working-class families; close to industry.
4. **Middle-class residential zone:** Larger houses, gardens; middle-class.
5. **Commuter zone (suburbs):** Low-density; large houses; wealthy; car-dependent; outskirts.

**For West African cities, this model needs modification:**
- The CBD is present (markets, banks, shops) but often includes a traditional market.
- Wealthy residential areas may be on the periphery (suburbs) OR near the centre (colonial-era houses).
- Slums/informal settlements are often found on the periphery on the cheapest land — not always near the centre.
- A large informal sector operates throughout the city (street traders, hawkers, mechanics).

