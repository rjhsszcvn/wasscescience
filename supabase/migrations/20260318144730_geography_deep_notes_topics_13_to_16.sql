## 9. Solutions to Urban Problems

| Problem | Possible Solutions |
|---------|-------------------|
| Housing shortage/slums | Slum upgrading (improving existing settlements); public housing schemes; microfinance for self-build |
| Traffic congestion | Mass transit systems (BRT buses, metro); road construction; park-and-ride; staggered working hours |
| Unemployment | Developing small business support; skills training; industrial development in secondary cities |
| Poor sanitation | Investing in sewer networks; public toilets; community-based waste management |
| Flooding | Dredging drains and rivers; flood-risk zoning; relocating flood-prone communities |
| Over-centralisation | Developing secondary cities; decentralising government and investment |

