- Located on the border of Nigeria, Niger, Chad, and Cameroon.
- Once one of Africa's largest lakes — has shrunk dramatically (lost over 90% of its surface area since the 1960s) due to climate change (reduced rainfall) and overuse of water for irrigation.
- Important for freshwater fisheries and farming for millions of people.

