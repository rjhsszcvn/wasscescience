## 1. Location and Extent

**West Africa** is the westernmost sub-region of the African continent, roughly bounded by:
- **North:** The Sahara Desert
- **South:** The Gulf of Guinea (Atlantic Ocean)
- **West:** The Atlantic Ocean
- **East:** Lake Chad and the Cameroon Highlands

West Africa covers approximately 5 million km² and includes 16 countries (including island states).

**Countries of West Africa:**
Benin, Burkina Faso, Cabo Verde, Côte d'Ivoire, The Gambia, Ghana, Guinea, Guinea-Bissau, Liberia, Mali, Mauritania, Niger, Nigeria, Senegal, Sierra Leone, Togo.

West Africa lies between approximately **4°N and 28°N latitude** and **17°W and 16°E longitude**.

---

## 2. Relief of West Africa

**Definition:** Relief refers to the height and shape of the land surface.

West Africa's relief is generally LOW-LYING, with vast plains and plateaus, punctuated by some highlands.

### A. Coastal Lowlands

- A narrow strip of lowland along the Gulf of Guinea coast.
- Mostly below 200m above sea level.
- Characterised by: sandy beaches, lagoons, river deltas (especially Niger Delta), mangrove swamps.
- Major cities located here: Lagos, Accra, Abidjan, Freetown, Monrovia.

### B. Interior Plains and Plateaus

- Most of West Africa's interior consists of **flat to gently undulating plains** between 200–500m above sea level.
- **The Sahel Plain** — a flat, semi-arid plain in the far north.
- **The Niger-Benue Trough** (Nigeria) — a broad lowland valley along the Niger and Benue rivers.
- **The Volta Basin** (Ghana) — a large, gently sloping interior basin drained by the Volta river system.

### C. Uplands and Highlands

**1. Fouta Djallon (Guinea Highlands):**
- A highland plateau in Guinea, rising to over 1,500m.
- The "Water Tower of West Africa" — source of major rivers (Niger, Gambia, Senegal rivers all rise here).
- Formed from ancient Precambrian sandstone.

**2. Cameroon Highlands / Adamawa Plateau:**
- Forms the eastern boundary of West Africa.
- Mount Cameroon (4,095m) — the highest peak in West Africa; an active volcano.
- Wet side of the Cameroon Highlands receives extremely high rainfall (Debundsha, on the slope of Mt. Cameroon, is one of the wettest places on Earth).

**3. Jos Plateau (Nigeria):**
- A distinctive elevated plateau in central Nigeria (~1,200m).
- Has a cooler climate than surrounding lowlands.
- Known for tin mining.

**4. Guinea Highlands (Sierra Leone and Guinea):**
- Includes the Loma Mountains (Sierra Leone) — reaching 1,945m at Bintumani Peak (highest point in West Africa outside the Cameroon Highlands).

**5. Akwapim-Togo Ranges (Ghana-Togo):**
- A narrow chain of hills running NE-SW through eastern Ghana and Togo.
- Rises to about 900m.

**6. Atakora Mountains (Benin-Burkina Faso-Togo):**
- Extension of the Akwapim-Togo ranges into Benin.

### D. The Sahara Desert

- Covers the northern parts of Mali, Mauritania, and Niger.
- Vast sandy (erg) and rocky (hammada/reg) desert.
- Below sea level in some parts.

