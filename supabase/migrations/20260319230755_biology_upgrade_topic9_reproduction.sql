### Male Reproductive System
```
            Seminal vesicle (fructose-rich fluid)
                  ↓
Testes (produce sperm + testosterone)
  → epididymis (sperm stored/mature)
    → vas deferens (sperm tube)
      → urethra (carries sperm + urine, but not at same time)
        → penis (deposits sperm in female)

Also: Prostate gland + Cowper''s gland add fluid to semen
```

**Sperm structure:**
```
    ┌────┐
    │Head│ ← acrosome (enzymes to penetrate egg) + nucleus (haploid DNA)
    └──┬─┘
       │  ← midpiece (mitochondria for energy)
       │
       │ ~~ ← tail (flagellum for movement)
       ~~~
```

---

### Female Reproductive System
```
Ovaries (produce eggs/ova + oestrogen + progesterone)
  → Fallopian tube / oviduct (egg travels here; fertilisation occurs here)
    → Uterus (womb) — thick muscular wall; embryo develops here
      → Cervix (neck of uterus)
        → Vagina (birth canal)
```

---

### The Menstrual Cycle (28 days)

```
Day 1-5:  Menstruation — uterine lining shed (if no pregnancy)
Day 1-13: Follicular phase — FSH stimulates follicle to develop in ovary
Day 13:   LH surge triggers OVULATION — egg released from ovary
Day 14:   Ovulation (egg travels down fallopian tube)
Day 15-28: Luteal phase — corpus luteum forms → produces progesterone
           → uterine lining thickens (preparing for implantation)
Day 28:   If no fertilisation → progesterone falls → lining breaks down → menstruation
```

**Hormones of the Menstrual Cycle:**
| Hormone | Source | Role |
|---|---|---|
| FSH (follicle-stimulating hormone) | Pituitary | Stimulates follicle development; triggers oestrogen production |
| LH (luteinising hormone) | Pituitary | Triggers ovulation; forms corpus luteum |
| Oestrogen | Ovary (follicle) | Thickens uterine lining; triggers LH surge |
| Progesterone | Corpus luteum | Maintains uterine lining; inhibits FSH and LH |

---

### Fertilisation
- Sperm meets egg in the **fallopian tube (oviduct)**
- Acrosome of sperm releases enzymes → penetrate zona pellucida of egg
- Sperm nucleus fuses with egg nucleus → **zygote** formed (diploid, 46 chromosomes)
- Fertilisation membrane forms → prevents other sperm entering
- Zygote divides → blastocyst → implants in uterine wall → **implantation** (~7 days after fertilisation)

---

### Development of the Embryo
```
Zygote → Cleavage (mitosis) → Morula → Blastocyst → Implantation
                                                         ↓
                                                     Embryo → Fetus → Birth
```

**The Placenta:**
- Develops in uterus; formed from both embryonic and uterine tissues
- Functions:
  - Exchange of O₂, glucose, amino acids from mother to fetus (by diffusion)
  - Exchange of CO₂, urea from fetus to mother
  - Acts as barrier to most bacteria (but NOT viruses — HIV, rubella can cross)
  - Produces hormones (HCG, oestrogen, progesterone) to maintain pregnancy

