### Worked Example 1: Interpreting the Menstrual Cycle Graph
Q: A graph shows oestrogen peaking on day 12, LH peaking on day 13, progesterone rising from day 15 to day 25, then falling.

**Analysis:**
- Day 12: Oestrogen peak triggers LH surge
- Day 13: LH peak triggers ovulation (around day 14)
- Day 15-25: Corpus luteum forms → releases progesterone → maintains uterine lining
- Day 25-28: Progesterone falls (no fertilisation) → lining not maintained → menstruation begins day 1

---

### Worked Example 2: Comparing Wind and Insect Pollination

| Feature | Wind-pollinated flower | Insect-pollinated flower |
|---|---|---|
| Petals | Small, green, dull | Large, bright, colourful |
| Scent | None | Usually scented |
| Nectar | Absent | Present |
| Pollen | Large quantities, smooth, light | Less pollen, sticky, spiny |
| Stigma | Feathery, hangs outside | Sticky, inside flower |
| Anthers | Long, hang outside flower | Inside flower |
| Example | Maize, rice, grass | Rose, sunflower, cocoa |

---

### Worked Example 3: Calculating from Reproductive Data
Q: A woman has a regular 30-day menstrual cycle. Ovulation typically occurs 14 days BEFORE the next menstruation. On which day does she ovulate?

**Answer:** 30 − 14 = **Day 16** (she ovulates on day 16 of her 30-day cycle)

Q: If sperm survive up to 5 days in the female reproductive tract, what is the "fertile window"?
**Answer:** Days 11-17 (sperm could survive from day 11, and the egg is viable for ~24 hours after ovulation on day 16)

