**Reproduction** is the biological process by which organisms produce new individuals of the same species.

### Types of Reproduction
| Type | Description | Genetic variation? | Examples |
|---|---|---|---|
| **Asexual** | One parent only; offspring genetically identical to parent | No (clones) | Binary fission (bacteria), budding (yeast/Hydra), vegetative propagation (plants), spore formation |
| **Sexual** | Two parents (usually); offspring genetically different | Yes | Mammals, birds, flowering plants |

---

### Advantages and Disadvantages
| | Asexual | Sexual |
|---|---|---|
| **Advantages** | Fast; no mate needed; all offspring reproduce | Genetic variation → adaptation to changing environment |
| **Disadvantages** | No variation → vulnerable to disease or environmental change | Requires mate; slower; energy-intensive |

---

### Asexual Reproduction Methods

**1. Binary fission (Bacteria):**
```
Single cell → DNA replicates → cell elongates → splits into 2 identical cells
```

**2. Budding (Yeast, Hydra):**
```
Small outgrowth (bud) forms on parent → grows → detaches as new individual
```

