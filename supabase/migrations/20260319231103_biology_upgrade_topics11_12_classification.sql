### Division of the Plant Kingdom
```
PLANTS
├── Non-vascular plants (no xylem/phloem)
│   └── Bryophytes (mosses, liverworts, hornworts)
│
└── Vascular plants (have xylem and phloem)
    ├── Seedless vascular plants
    │   └── Pteridophytes (ferns, horsetails, clubmosses)
    │
    └── Seed plants
        ├── Gymnosperms (naked seeds — no fruit)
        │   └── Conifers (pine, cypress)
        └── Angiosperms (seeds enclosed in fruit — flowering plants)
            ├── Monocotyledons (monocots)
            └── Dicotyledons (dicots)
```

---

### Detailed Group Descriptions

**1. Bryophytes (Mosses and Liverworts)**
- No true roots, stems, or leaves (have rhizoids instead)
- No vascular tissue (xylem/phloem) → cannot grow tall
- Reproduce by spores
- Need water for reproduction (swimming sperm)
- Examples: mosses (Bryum), liverworts (Marchantia)
- Habitat: damp, shaded areas

**2. Pteridophytes (Ferns)**
- Have true roots, stems, and leaves (fronds)
- Have vascular tissue (xylem and phloem)
- NO seeds or flowers → reproduce by spores (on underside of fronds = sori)
- Still need water for fertilisation (swimming sperm)
- Examples: Common fern (Dryopteris), bracken fern, tree fern

**3. Gymnosperms (Cone-bearing plants)**
- Have seeds, but seeds are NAKED (not enclosed in fruit)
- Seeds in cones (male cones = pollen, female cones = seeds)
- Mostly trees and shrubs; needle-like leaves
- Wind-pollinated
- Examples: Pine tree (Pinus), cedar, cypress, Ginkgo

**4. Angiosperms (Flowering Plants)**
- Most complex and most widespread plant group
- Seeds enclosed in fruit (ovary wall develops into fruit)
- Flowers for reproduction
- Divided into Monocots and Dicots:

