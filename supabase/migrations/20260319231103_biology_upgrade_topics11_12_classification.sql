### Insects — Life Cycles
**Complete metamorphosis (Holometabolous):**
```
Egg → Larva (caterpillar/maggot) → Pupa (cocoon/chrysalis) → Adult
Examples: Butterfly, moth, housefly, mosquito, bee
```

**Incomplete metamorphosis (Hemimetabolous):**
```
Egg → Nymph (looks like small adult) → Adult (no pupal stage)
Examples: Grasshopper, locust, cockroach, dragonfly
```

