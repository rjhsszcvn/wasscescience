### Features of Animals (Kingdom Animalia)
- Eukaryotic, multicellular organisms
- No cell wall; no chloroplasts
- Heterotrophic (obtain food by ingestion)
- Most can move
- Nervous tissue and muscle tissue present in most

---

### Major Animal Phyla

**INVERTEBRATES (No backbone):**

**1. Phylum Porifera (Sponges)**
- Simplest animals; no true tissues
- Pores throughout body for water flow
- Sessile (fixed) filter feeders
- Example: Bath sponge (Spongia)

**2. Phylum Coelenterata/Cnidaria (Jellyfish, Corals, Hydra)**
- Two cell layers (diploblastic)
- Tentacles with stinging cells (nematocysts)
- Radial symmetry
- Simple nerve net (no brain)
- Example: Hydra, Jellyfish, Sea anemone, Coral

**3. Phylum Platyhelminthes (Flatworms)**
- Flat body; bilateral symmetry
- No coelom; parasitic or free-living
- Examples: Tapeworm (Taenia), liver fluke (Fasciola), planaria

**4. Phylum Nematoda (Roundworms)**
- Cylindrical, unsegmented body
- Parasites or free-living
- Examples: Ascaris (intestinal roundworm), hookworm, guinea worm

**5. Phylum Annelida (Segmented Worms)**
- Body divided into segments (annuli)
- Coelom present; setae for movement
- Closed circulatory system
- Examples: Earthworm (Lumbricus), leech, ragworm

**6. Phylum Mollusca (Molluscs)**
- Soft body; most have shells
- Muscular foot for movement
- Examples: Snail, clam, squid, octopus

**7. Phylum Arthropoda (Arthropods)**
- Largest phylum (80% of all animal species)
- Exoskeleton (chitin); jointed appendages
- Segmented body
- Classes: Insecta, Arachnida, Crustacea, Myriapoda
- Examples: Mosquito, spider, crab, centipede

**8. Phylum Echinodermata (Spiny-skinned)**
- Radial symmetry in adults; spiny skin; tube feet
- Marine only
- Examples: Starfish, sea urchin, sea cucumber

