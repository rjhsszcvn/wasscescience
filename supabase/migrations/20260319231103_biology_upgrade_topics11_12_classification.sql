### Identifying Plant Groups — Key Questions
When identifying which plant group an organism belongs to:

1. Does it have vascular tissue (xylem/phloem)? → No = Bryophyte
2. Does it produce seeds? → No = Pteridophyte
3. Are seeds naked (in cones)? → Yes = Gymnosperm; No = Angiosperm
4. How many cotyledons? → 1 = Monocot; 2 = Dicot

---

### Worked Example 1
**Q:** A plant has true roots, stems, and leaves, reproduces by spores visible on the underside of its leaves, and needs water for reproduction. Which group does it belong to?

**Answer:** Pteridophyte (Fern)
- Has true vascular tissue (roots, stems, leaves) → not Bryophyte
- Reproduces by spores, not seeds → not Gymnosperm or Angiosperm
- Spores on leaf underside (sori) → confirms Fern/Pteridophyte

