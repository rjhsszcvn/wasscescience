<h3>2.1 Personal Hygiene</h3>
<p><strong>Personal hygiene</strong> refers to the set of practices performed to preserve and promote bodily cleanliness and health. It is essential for preventing the spread of diseases and maintaining social acceptability.</p>

<h4>2.1.1 Body Hygiene</h4>
<p>Regular bathing removes sweat, dead skin cells, dirt, and microorganisms from the skin surface. The skin is the largest organ and acts as the first line of defence against pathogens.</p>
<ul>
<li>Bath at least twice daily with soap and water</li>
<li>Dry the body thoroughly, especially between toes and skin folds</li>
<li>Use deodorants to control body odour caused by bacterial decomposition of sweat</li>
<li>Moisturize dry skin to prevent cracking and microbial entry</li>
</ul>

<h4>2.1.2 Hand Hygiene</h4>
<p>Hand washing is the single most effective way to prevent the transmission of infections. The WHO promotes the "Five Moments for Hand Hygiene" in clinical settings.</p>
<p><strong>Proper Hand Washing Technique (7 steps):</strong></p>
<ol>
<li>Wet hands with clean running water</li>
<li>Apply soap and lather well</li>
<li>Rub palms together in circular motions</li>
<li>Clean between fingers and back of hands</li>
<li>Scrub under fingernails</li>
<li>Rinse thoroughly under running water</li>
<li>Dry with clean towel or air dry</li>
</ol>
<p>Duration: At least 20-30 seconds. Critical times to wash hands include before eating, after using the toilet, after handling animals, and after coughing or sneezing.</p>

<h4>2.1.3 Oral Hygiene</h4>
<p>The mouth harbours millions of bacteria. Poor oral hygiene leads to dental caries (tooth decay), periodontal disease, halitosis (bad breath), and can contribute to systemic diseases.</p>
<ul>
<li>Brush teeth at least twice daily, especially after meals and before bed</li>
<li>Use fluoride toothpaste to strengthen enamel and prevent caries</li>
<li>Floss between teeth to remove plaque and food particles</li>
<li>Replace toothbrush every 3 months or after illness</li>
<li>Visit the dentist every 6 months for check-ups and cleaning</li>
<li>Rinse mouth with water after sugary foods</li>
</ul>

<h4>2.1.4 Hair and Scalp Hygiene</h4>
<ul>
<li>Wash hair regularly with appropriate shampoo</li>
<li>Keep hair free of lice (pediculosis capitis) and dandruff</li>
<li>Head lice spread through direct contact and sharing combs/hats</li>
<li>Treatment: medicated shampoos (permethrin or malathion)</li>
</ul>

<h4>2.1.5 Nail Care</h4>
<ul>
<li>Keep nails short and clean to prevent harboring pathogens</li>
<li>Long nails collect dirt and organisms that cause intestinal infections</li>
<li>Use clean nail clippers and files</li>
</ul>

<h4>2.1.6 Clothing and Footwear Hygiene</h4>
<ul>
<li>Wear clean, dry clothes daily</li>
<li>Change undergarments daily to prevent bacterial and fungal growth</li>
<li>Wear shoes to prevent hookworm infection (Necator americanus) which penetrates through bare feet</li>
<li>Do not share personal clothing, towels, or undergarments</li>
<li>Wash clothes regularly and iron to kill parasites and bacteria</li>
</ul>

<h3>2.2 Environmental Sanitation</h3>
<p><strong>Environmental sanitation</strong> refers to the control of environmental factors that affect human health. It includes the provision of safe water, proper waste disposal, food safety, and vector control.</p>

<h4>2.2.1 Safe Water Supply</h4>
<p>Access to safe drinking water is a fundamental human right and a major determinant of health.</p>

<p><strong>Sources of Water:</strong></p>
<ul>
<li><strong>Surface water:</strong> Rivers, lakes, streams - often contaminated but can be treated</li>
<li><strong>Groundwater:</strong> Boreholes, wells - generally cleaner but may contain minerals and microbes</li>
<li><strong>Rainwater:</strong> Clean at source but can be contaminated during collection and storage</li>
<li><strong>Piped water:</strong> Treated and distributed by water authorities - safest if properly maintained</li>
</ul>

<p><strong>Water Treatment Methods:</strong></p>
<ul>
<li><strong>Sedimentation:</strong> Allowing particles to settle to the bottom of a container</li>
<li><strong>Filtration:</strong> Passing water through sand, gravel, or charcoal filters to remove particles and microbes</li>
<li><strong>Boiling:</strong> Most effective household method - boil for at least 1 minute to kill pathogens</li>
<li><strong>Chlorination:</strong> Adding chlorine to water to kill bacteria and viruses (used in pipe-borne systems)</li>
<li><strong>Solar Disinfection (SODIS):</strong> Filling clear plastic bottles with water and leaving in sunlight for 6 hours</li>
</ul>

<p><strong>Water Quality Standards:</strong> Safe water should be colourless, odourless, tasteless, free from pathogens, and within acceptable chemical limits.</p>

<h4>2.2.2 Refuse and Solid Waste Disposal</h4>
<p>Improper waste disposal attracts vermin (rats, flies, cockroaches) that spread disease and creates breeding grounds for mosquitoes.</p>

<p><strong>Types of Refuse:</strong></p>
<ul>
<li><strong>Biodegradable waste:</strong> Food scraps, garden waste - can be composted</li>
<li><strong>Non-biodegradable waste:</strong> Plastics, metals, glass - require recycling or special disposal</li>
<li><strong>Hazardous waste:</strong> Medical waste, chemicals - require special handling and disposal</li>
</ul>

<p><strong>Methods of Refuse Disposal:</strong></p>
<ul>
<li><strong>Open dumping:</strong> Least sanitary, attracts pests, causes pollution - discouraged</li>
<li><strong>Sanitary landfill:</strong> Waste compacted and covered with soil daily - reduces pollution</li>
<li><strong>Incineration:</strong> Burning waste at high temperatures - reduces volume but causes air pollution</li>
<li><strong>Composting:</strong> Decomposing organic waste into fertilizer - environmentally beneficial</li>
<li><strong>Recycling:</strong> Reprocessing waste materials for reuse</li>
</ul>

<h4>2.2.3 Excreta Disposal</h4>
<p>Unsafe excreta disposal is a major cause of diarrhoeal diseases, typhoid, cholera, and soil-transmitted helminths (worm infections).</p>

<p><strong>Types of Latrines:</strong></p>
<ul>
<li><strong>Pit latrine:</strong> Simple hole in the ground with superstructure - common in rural areas</li>
<li><strong>Ventilated Improved Pit (VIP) latrine:</strong> Pit with ventilation pipe to reduce odour and flies</li>
<li><strong>Pour-flush latrine:</strong> Water seal prevents odour and fly access</li>
<li><strong>Water closet (flush toilet):</strong> Connected to sewage system - most hygienic</li>
</ul>

<p><strong>Requirements for a Good Latrine:</strong></p>
<ul>
<li>Located at least 30 metres from water sources</li>
<li>Properly covered to prevent fly access and odour</li>
<li>Regularly cleaned and disinfected</li>
<li>Separate facilities for males and females in public settings</li>
</ul>

<h4>2.2.4 Food Safety and Hygiene</h4>
<p>Contaminated food causes foodborne illnesses (food poisoning) affecting millions globally each year.</p>

<p><strong>The 5 Keys to Safer Food (WHO):</strong></p>
<ol>
<li><strong>Keep clean:</strong> Wash hands and surfaces often</li>
<li><strong>Separate raw and cooked:</strong> Prevent cross-contamination</li>
<li><strong>Cook thoroughly:</strong> Heat kills pathogens (most foods safe at 70 degrees C)</li>
<li><strong>Keep food at safe temperatures:</strong> Below 5 degrees C or above 60 degrees C (danger zone: 5-60 degrees C)</li>
<li><strong>Use safe water and raw materials:</strong> Use treated water and fresh ingredients</li>
</ol>

<p><strong>Common Foodborne Pathogens:</strong></p>
<ul>
<li>Salmonella typhi - typhoid fever (contaminated water and food)</li>
<li>Staphylococcus aureus - staphylococcal food poisoning (improperly stored cooked food)</li>
<li>Vibrio cholerae - cholera (contaminated water and seafood)</li>
<li>Clostridium botulinum - botulism (improperly canned food)</li>
<li>E. coli O157:H7 - bloody diarrhoea (undercooked meat, contaminated produce)</li>
</ul>

<h4>2.2.5 Vector Control</h4>
<p>Vectors are living organisms that transmit infectious pathogens between humans or from animals to humans.</p>

<table>
<tr><th>Vector</th><th>Disease Transmitted</th><th>Control Methods</th></tr>
<tr><td>Mosquito (Anopheles)</td><td>Malaria</td><td>Insecticide-treated nets, indoor residual spraying, eliminating stagnant water</td></tr>
<tr><td>Mosquito (Aedes)</td><td>Dengue, Yellow Fever, Zika</td><td>Removing water containers, larvicides, repellents</td></tr>
<tr><td>Housefly</td><td>Typhoid, cholera, dysentery</td><td>Proper waste disposal, covering food, fly screens</td></tr>
<tr><td>Rat</td><td>Leptospirosis, plague</td><td>Rodent-proofing buildings, traps, poison baits</td></tr>
<tr><td>Tsetse fly</td><td>Sleeping sickness (trypanosomiasis)</td><td>Insecticides, bush clearing, protective clothing</td></tr>
</table>

