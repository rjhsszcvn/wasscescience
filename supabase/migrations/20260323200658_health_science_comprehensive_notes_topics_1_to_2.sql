<h3>1.1 Definition of Health</h3>
<p>The <strong>World Health Organization (WHO)</strong> defines health as <em>"a state of complete physical, mental, and social well-being and not merely the absence of disease or infirmity"</em> (1948). This holistic definition recognizes that health encompasses multiple dimensions beyond the physical body.</p>

<h4>Dimensions of Health</h4>
<ul>
<li><strong>Physical Health:</strong> The proper functioning of the body and its systems. This includes freedom from disease, adequate nutrition, regular exercise, and sufficient rest. Physical health is measured by vital signs, body mass index (BMI), and laboratory investigations.</li>
<li><strong>Mental Health:</strong> A state of well-being in which an individual realizes their own abilities, can cope with normal stresses of life, work productively, and contribute to their community. Mental health includes emotional stability, cognitive functioning, and psychological resilience.</li>
<li><strong>Social Health:</strong> The ability to form satisfying interpersonal relationships with others. It involves effective communication, maintaining healthy relationships, and fulfilling social roles.</li>
<li><strong>Spiritual Health:</strong> Having a sense of purpose, meaning, and inner peace. It involves personal beliefs, values, and connection to something greater than oneself.</li>
<li><strong>Environmental Health:</strong> The relationship between the individual and the environment, including safe water, clean air, and sanitation.</li>
</ul>

<h3>1.2 Concept of Health Science</h3>
<p><strong>Health Science</strong> is the branch of knowledge that deals with human health, disease prevention, and health promotion. It integrates knowledge from biology, chemistry, sociology, and psychology to understand and improve human health.</p>

<h4>Scope of Health Science</h4>
<ul>
<li>Study of the human body structure and function</li>
<li>Prevention and control of diseases</li>
<li>Health promotion and education</li>
<li>Environmental health and sanitation</li>
<li>Nutrition and dietetics</li>
<li>Reproductive health and family planning</li>
<li>Mental health and substance abuse prevention</li>
<li>First aid and emergency care</li>
</ul>

<h3>1.3 Factors Affecting Health</h3>
<p>Health is determined by a complex interaction of biological, environmental, socio-economic, and behavioural factors known as the <strong>determinants of health</strong>.</p>

<h4>Biological Factors</h4>
<ul>
<li><strong>Genetics:</strong> Inherited traits that predispose individuals to certain conditions (e.g., sickle cell disease, hypertension)</li>
<li><strong>Age:</strong> Different age groups face different health challenges</li>
<li><strong>Sex:</strong> Biological differences between males and females affect disease susceptibility</li>
<li><strong>Immune status:</strong> Natural and acquired immunity influence disease resistance</li>
</ul>

<h4>Environmental Factors</h4>
<ul>
<li>Quality of air, water, and soil</li>
<li>Presence of pathogens and vectors</li>
<li>Housing conditions and overcrowding</li>
<li>Climate and weather patterns</li>
</ul>

<h4>Socio-Economic Factors</h4>
<ul>
<li>Income level and poverty</li>
<li>Education and health literacy</li>
<li>Access to healthcare services</li>
<li>Occupation and working conditions</li>
<li>Social support networks</li>
</ul>

<h4>Behavioural Factors</h4>
<ul>
<li>Dietary habits and nutrition</li>
<li>Physical activity levels</li>
<li>Alcohol and tobacco use</li>
<li>Sexual behaviour</li>
<li>Hygiene practices</li>
</ul>

<h3>1.4 Indicators of Health</h3>
<p>Health indicators are statistics used to assess the health status of a population.</p>

<table>
<tr><th>Indicator</th><th>Definition</th><th>Significance</th></tr>
<tr><td>Infant Mortality Rate (IMR)</td><td>Deaths per 1,000 live births in the first year</td><td>Reflects quality of maternal and child healthcare</td></tr>
<tr><td>Maternal Mortality Rate (MMR)</td><td>Deaths per 100,000 live births due to pregnancy complications</td><td>Indicates quality of obstetric care</td></tr>
<tr><td>Life Expectancy</td><td>Average number of years a person is expected to live</td><td>Overall measure of population health</td></tr>
<tr><td>Morbidity Rate</td><td>Proportion of people with a disease in a given period</td><td>Measures disease burden</td></tr>
<tr><td>Mortality Rate</td><td>Deaths per 1,000 population in a given period</td><td>Measures death burden</td></tr>
</table>

<h3>1.5 Health Promotion and Disease Prevention</h3>
<p><strong>Health Promotion</strong> is the process of enabling people to increase control over and improve their health (Ottawa Charter, 1986). It involves:</p>
<ul>
<li>Building healthy public policy</li>
<li>Creating supportive environments</li>
<li>Strengthening community action</li>
<li>Developing personal skills</li>
<li>Reorienting health services</li>
</ul>

<h4>Levels of Disease Prevention</h4>
<ul>
<li><strong>Primary Prevention:</strong> Actions taken before disease occurs to prevent its onset (e.g., vaccination, health education, sanitation improvement)</li>
<li><strong>Secondary Prevention:</strong> Early detection and prompt treatment to halt disease progression (e.g., screening programmes, medical check-ups)</li>
<li><strong>Tertiary Prevention:</strong> Rehabilitation and management of established disease to minimize disability and restore function (e.g., physiotherapy, counselling)</li>
</ul>

<h3>1.6 The Health Field Concept (Lalonde Model)</h3>
<p>Marc Lalonde (1974) proposed four broad determinants of health:</p>
<ol>
<li><strong>Human Biology:</strong> Genetic inheritance, age, sex</li>
<li><strong>Environment:</strong> Physical and social environment</li>
<li><strong>Lifestyle:</strong> Personal behavioural choices</li>
<li><strong>Health Care Organization:</strong> Availability and quality of health services</li>
</ol>

