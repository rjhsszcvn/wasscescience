### Water Absorption in the Large Intestine
- The colon absorbs most of the remaining water from undigested food
- Approximately 1.5 litres of water reabsorbed daily
- Diarrhoea = water not absorbed → body loses water and minerals
- Constipation = too much water absorbed → hard faeces

