### Worked Example 1: Enzyme Activity
**Q:** A student tested the digestion of starch by amylase at different temperatures. Explain why starch digestion was fastest at 37°C and slower at 10°C and 70°C.

**Answer:**
- At **37°C** (body temperature): enzyme has optimal shape — active site perfectly fits substrate; maximum rate of enzyme-substrate complex formation
- At **10°C**: low temperature → molecules have less kinetic energy → fewer successful collisions between enzyme and substrate → slower reaction
- At **70°C**: high temperature denatures the enzyme — heat breaks hydrogen bonds holding the 3D shape → active site changes shape → substrate no longer fits → enzyme permanently inactivated

---

### Worked Example 2: Tracing a Meal
**Q:** Trace the digestion of a meal of rice and beans from mouth to absorption.

**Rice (starch → glucose):**
1. Mouth: salivary amylase begins breaking starch → maltose
2. Stomach: amylase inactivated by HCl (pH too low for amylase)
3. Duodenum: pancreatic amylase continues starch → maltose
4. Ileum: maltase on villus surface → maltose → glucose
5. Glucose absorbed by active transport into blood capillaries

**Beans (protein → amino acids):**
1. Mouth: physical grinding of beans; no protein enzymes here
2. Stomach: pepsin (activated by HCl) breaks proteins → peptides; HCl also kills bacteria and denatures proteins
3. Duodenum: trypsin (from pancreas) further breaks peptides
4. Ileum: erepsin/peptidases on villus → peptides → amino acids
5. Amino acids absorbed by active transport into blood capillaries

---

### Worked Example 3: Interpreting a Food Test
A student tested an unknown food with:
- Iodine → no colour change (blue-black)
- Benedict''s → brick red precipitate after heating
- Biuret → purple colour

**Conclusion:**
- No starch present (no iodine reaction)
- Reducing sugars (glucose, maltose) present (Benedict''s positive)
- Protein present (Biuret positive)
- This food likely contains protein and glucose/maltose but no starch

