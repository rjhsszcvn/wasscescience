Digestion is the breakdown of large, insoluble food molecules into small, soluble molecules that can be absorbed into the blood.

### Two Types of Digestion
- **Physical (mechanical) digestion:** Breaking food into smaller pieces (chewing, churning) — INCREASES surface area
- **Chemical digestion:** Enzymes break chemical bonds in food molecules

---

