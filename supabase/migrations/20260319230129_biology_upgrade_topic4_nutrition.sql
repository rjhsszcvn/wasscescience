### Role of Bile
- Produced by the **liver**, stored in the **gall bladder**
- Contains **bile salts** and bile pigments
- **Emulsifies fats** — breaks large fat droplets into tiny droplets
- This **increases surface area** for lipase to work on
- Bile also **neutralises** the acidic chyme from stomach (bile is alkaline, pH 7-8)

