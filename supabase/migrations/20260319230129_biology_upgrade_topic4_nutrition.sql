### Major Nutritional Deficiency Diseases (WASSCE Exam Staples)

**Kwashiorkor**
- Caused by severe **protein deficiency** (adequate calories but insufficient protein)
- Common in West Africa when children are weaned from breast milk to starchy diet
- Symptoms: swollen belly (oedema due to fluid accumulation), reddish hair, skin lesions, irritability, stunted growth
- Treatment: high protein diet (beans, groundnuts, fish)

**Marasmus**
- Caused by severe **protein AND calorie deficiency**
- "Wasting disease" — extreme thinness, muscle wasting, no body fat
- Skin hangs loosely, "old man face"
- Common in young infants

| Feature | Kwashiorkor | Marasmus |
|---|---|---|
| Cause | Protein deficiency | Protein + calorie deficiency |
| Oedema (swelling) | Yes | No |
| Body fat | Present | Absent |
| Muscle | Present | Wasted |
| Hair | Reddish, sparse | May be sparse |

**Anaemia**
- Iron deficiency → insufficient haemoglobin → reduced O₂ transport
- Symptoms: fatigue, pale skin, breathlessness, dizziness
- Treat with iron-rich foods: liver, spinach, beans, red meat

**Rickets**
- Vitamin D and/or calcium deficiency in children
- Soft, deformed bones — bow legs, enlarged joints
- Treat: sunlight exposure, fortified foods, supplements

**Scurvy**
- Vitamin C deficiency
- Symptoms: bleeding gums, slow wound healing, bruising easily, joint pain
- Treat: citrus fruits, tomatoes, peppers

