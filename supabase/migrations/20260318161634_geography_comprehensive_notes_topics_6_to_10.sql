### 1. Shifting Cultivation (Bush Fallow System)

**How it works:**
1. Farmers identify a plot of land with good vegetation (indicating fertile soil).
2. Trees and bush are cut down — this is the **slash** phase.
3. The vegetation is dried and **burned** — clearing the land and releasing nutrients (potash, calcium) from ash into the soil.
4. Crops are planted — often a mixture (intercropping) of yams, maize, cassava, vegetables.
5. The land is farmed for 2–5 years until yields decline (soil exhausted, weed infestation increases).
6. The plot is **abandoned** and farmers move to a new area.
7. The abandoned plot is left fallow for 10–20+ years to regenerate.

**Advantages:**
- Maintains soil fertility through long fallow periods.
- No artificial fertilisers needed.
- Suitable for low-population-density areas with abundant land.
- Intercropping reduces risk — if one crop fails, others may succeed.
- The system is adapted to fragile tropical soils.

**Disadvantages:**
- Requires large areas of land — as population grows, fallow periods are shortened, soil degrades.
- Low output per hectare.
- Cannot support dense populations.
- Burning destroys soil organisms and can cause erosion.
- Deforestation and environmental damage.
- Cannot generate surplus for export.

**Status in West Africa today:** Still practised in parts of Sierra Leone, Liberia, Ghana, Nigeria, and Cameroon, but land pressure is reducing fallow periods (sometimes to just 2–3 years), making the system unsustainable.

---

