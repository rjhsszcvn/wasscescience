**Agriculture (Farming):** The deliberate cultivation of land to grow crops and/or rear animals for food, fibre, fuel, and other products.

**Subsistence Farming:** Farming primarily to produce food for the farmer's own family, with little or no surplus for sale. Very common in rural West Africa.

**Commercial Farming:** Farming aimed at producing crops or livestock for sale and profit. Includes plantation farming.

**Shifting Cultivation:** A traditional farming system where land is cleared (by slash-and-burn), cultivated for 2–5 years, then abandoned to allow natural vegetation to regenerate and soil to recover, while farmers move to a new plot. Also called **bush fallow** or **swidden agriculture**.

**Intensive Farming:** Farming that uses high inputs (fertilisers, irrigation, machinery, labour) per unit of land to achieve high yields. The opposite of extensive farming.

**Extensive Farming:** Farming that uses large areas of land with relatively low inputs per unit area. Common in areas with large land and small populations.

**Plantation Farming:** Large-scale commercial farming of a single crop (monoculture) for export. Originally established by colonial powers. Requires large capital investment, hired labour, and processing facilities. **Examples:** Cocoa, rubber, oil palm, sugar, cotton.

**Monoculture:** The cultivation of a single crop species over a large area. Maximises efficiency but increases disease risk and soil exhaustion.

**Mixed Farming:** Growing crops AND rearing livestock on the same farm. Provides diet diversity and stability; animal manure fertilises crops.

**Arable Farming:** Crop cultivation only. No livestock.

**Pastoral Farming:** Livestock rearing only. No crops.

**Nomadic Pastoralism:** The movement of herders and their livestock across vast areas in search of water and pasture. Common in the Sahel (Fulani cattle herders, Tuareg).

**Transhumance:** Seasonal movement of livestock between pastures — usually to highland pastures in the dry season and lowland pastures in the wet season.

**Irrigation:** The artificial supply of water to crops using channels, pipes, or sprinklers. Essential in drier parts of West Africa.

**Crop Rotation:** The practice of growing different crops on the same land in successive seasons to maintain soil fertility and break pest/disease cycles.

**Fallow Period:** A period during which land is left uncultivated and allowed to rest so it can recover its fertility naturally.

**Cash Crop:** A crop grown primarily for sale, not for subsistence. Also called an **export crop** or **commercial crop**. Examples: cocoa, groundnuts, coffee, rubber, cotton, palm oil.

**Food Crop:** A crop grown primarily for consumption by the farmer's household. Examples: maize, yam, cassava, rice, millet, sorghum.

**Green Revolution:** The introduction of high-yielding varieties (HYVs) of crops, along with fertilisers, pesticides, and irrigation, to dramatically increase agricultural production. Started in Asia in the 1960s; has had limited success in West Africa.

**Mechanisation:** The use of machines (tractors, harvesters, ploughs) in farming to replace human and animal labour. Increases efficiency and output per worker.

**Land Tenure:** The system by which land is owned, rented, or used. In West Africa, land tenure systems vary widely — some land is communally owned (by the tribe/community), some is privately owned, and some is government-controlled.
