**Question:** Nigeria has enormous oil wealth, yet many Nigerians remain poor. Explain what is meant by the "resource curse" and apply it to Nigeria's situation.

**Model Answer:**
The **resource curse** (or **paradox of plenty**) refers to the tendency for countries with abundant natural resources, especially oil and minerals, to have slower economic growth, less democracy, and worse development outcomes than resource-poor countries.

**Application to Nigeria:**
