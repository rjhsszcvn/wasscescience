3. **Ageing cocoa trees and farmers:** Many Ghanaian cocoa trees are 40–60 years old (past peak productivity) and many farmers are elderly. Young people are leaving cocoa farming for urban employment. This creates a future supply crisis for Ghana's most important export crop.
