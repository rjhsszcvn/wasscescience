**Natural resources** are materials or substances that occur naturally in the environment and can be used by humans. They are the raw materials from which wealth is created.

West Africa is exceptionally rich in natural resources — yet paradoxically, many of its people remain poor. This is sometimes called the **"resource curse"** or **"paradox of plenty"**: abundant natural resources do not automatically lead to development.

## Classification of Natural Resources

### By Renewability

**Renewable Resources:** Can be naturally replenished within a human timescale.
- Solar energy, wind energy, water (hydroelectric), forests (if managed sustainably), fish (if not over-harvested), fertile soil

**Non-Renewable Resources:** Cannot be replenished within a human timescale — once used, they are gone.
- Fossil fuels: crude oil, natural gas, coal
- Minerals: gold, iron ore, bauxite, diamonds, manganese

### By Type

| Type | Examples in West Africa |
|------|------------------------|
| Mineral resources | Gold, diamonds, bauxite, iron ore, manganese, phosphates |
