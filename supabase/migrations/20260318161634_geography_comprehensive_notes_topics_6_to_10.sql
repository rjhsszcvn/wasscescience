**Mineral:** A naturally occurring inorganic substance with a definite chemical composition and crystal structure found in the Earth's crust.

**Ore:** Rock containing minerals in sufficient concentration to make extraction economically worthwhile.

**Mining:** The extraction of minerals from the Earth's crust.
