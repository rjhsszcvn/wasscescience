## Worked Example 2: Problems of the Cocoa Farmer

**Question:** Discuss THREE major problems facing cocoa farmers in Ghana.

**Answer:**
1. **Price fluctuations on the world market:** Cocoa prices are determined on international commodity exchanges (London, New York). When prices fall, Ghanaian cocoa farmers receive lower income even if their costs (labour, inputs) remain high. Ghana has limited ability to influence world cocoa prices despite being the world's 2nd largest producer.

