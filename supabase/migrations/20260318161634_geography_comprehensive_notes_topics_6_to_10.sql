- Family-scale production.
- Simple tools (hoe, cutlass, machete).
- Primarily food crops (yam, maize, cassava, millet, sorghum, plantain).
- Little or no mechanisation.
- No irrigation (rain-fed).
- Vulnerable to weather — one drought = food crisis.

**Problems:**
- Low productivity → food insecurity.
- Cannot generate income for school fees, healthcare.
- Hard physical labour, especially for women.
- No buffer against crop failure.

