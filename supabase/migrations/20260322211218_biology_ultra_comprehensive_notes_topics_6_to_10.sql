## 1. Excretion

Excretion: Removal of metabolic waste products from the body.

Metabolic waste: Substances produced in the body as a result of chemical reactions.

Main excretory products:
- Carbon dioxide (CO₂): From respiration → excreted by lungs
- Urea: From excess amino acids (deamination in liver) → excreted by kidneys
- Water: From respiration and metabolism → excreted by kidneys, skin, lungs
- Salts/mineral ions: Excess salts → excreted by kidneys and sweat glands
- Bile pigments (bilirubin): From haemoglobin breakdown → excreted in bile → feces

Important distinction:
- Egestion/defecation (removal of undigested food = feces) is NOT excretion
- Excretion = removal of metabolic WASTE (made inside body)

---

## 2. Liver Functions

### 2.1 Deamination
- Removal of amino groups (−NH₂) from excess amino acids
- Produces: Urea + Keto acid

Amino acid → NH₃ (toxic) → Urea (less toxic) → excreted by kidneys
Keto acid → entered into respiration for energy or converted to fat/glucose

Ornithine cycle (urea cycle): Series of reactions producing urea from ammonia and CO₂

### 2.2 Other Liver Functions
- Detoxification: Breaks down alcohol, drugs, hormones, toxins
- Glycogen storage: Stores glucose as glycogen; releases glucose when needed
- Protein synthesis: Produces plasma proteins (albumin, fibrinogen, globulin)
- Bile production: Breaks down old haemoglobin → bile pigments + bile salts
- Heat production: High metabolic rate → warms blood
- Cholesterol regulation
- Fat-soluble vitamin storage (A, D, E, K)

---

## 3. The Kidneys — Structure and Function

### 3.1 Kidney Structure
Gross anatomy:
- Bean-shaped organs; positioned at back of abdominal cavity
- Renal artery: Brings blood to kidney
- Renal vein: Carries blood away
- Ureter: Carries urine to bladder
- Bladder: Stores urine
- Urethra: Carries urine out of body

Internal structure:
- Cortex: Outer layer; contains Bowman''s capsules and glomeruli
- Medulla: Inner layer; contains loops of Henle and collecting ducts
- Pelvis: Central space collecting urine → ureter

### 3.2 The Nephron — Functional Unit of the Kidney
Each kidney has ~1 million nephrons.

Parts of the nephron:
1. Bowman''s capsule (glomerular capsule): Cup-shaped; surrounds glomerulus
2. Glomerulus: Knot of capillaries inside Bowman''s capsule
3. Proximal convoluted tubule (PCT): First coiled tube; in cortex
4. Loop of Henle: U-shaped tube; descends into medulla
5. Distal convoluted tubule (DCT): Second coiled tube; in cortex
6. Collecting duct: Final tube; carries urine to pelvis

### 3.3 Urine Formation — Three Processes

Process 1: Ultrafiltration (in Bowman''s capsule and glomerulus)
- Blood forced under HIGH PRESSURE into glomerulus
- High pressure forces small molecules out of blood into Bowman''s capsule
- Filtrate contains: water, glucose, amino acids, urea, salts, uric acid
- Proteins and blood cells too large — STAY in blood
- Volume filtered: ~180 liters per day (99% reabsorbed)

Process 2: Selective Reabsorption (in tubules)
Proximal Convoluted Tubule (PCT):
- ALL glucose and amino acids reabsorbed by active transport
- Large amounts of water reabsorbed by osmosis
- Many salts reabsorbed
- Some urea remains

Loop of Henle:
- Creates concentration gradient in medulla
- Descending limb: Permeable to water; impermeable to salts → water leaves by osmosis
- Ascending limb: Impermeable to water; salts actively pumped out
- Creates hyperosmotic (salty) medulla → important for reabsorbing water from collecting duct

Distal Convoluted Tubule (DCT) and Collecting Duct:
- Variable reabsorption depending on body''s needs
- Water reabsorption controlled by ADH (antidiuretic hormone)
- Salts reabsorbed controlled by aldosterone

Process 3: Tubular Secretion
- Additional waste removed from blood into tubule
- H⁺ ions, K⁺ ions, drugs, creatinine secreted

### 3.4 Composition of Urine
Normal urine contains:
- Water (~95%)
- Urea (~2%)
- Salts (~1%)
- Creatinine, uric acid
- Yellow color from urobilin (from bilirubin breakdown)

Abnormal constituents (indicate disease):
- Glucose (glycosuria): Diabetes mellitus
- Protein (proteinuria): Kidney damage
- Blood (haematuria): Infection, kidney stones
- Ketones (ketonuria): Starvation, uncontrolled diabetes

