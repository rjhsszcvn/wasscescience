## 6. The Endocrine System

### 6.1 Overview

Endocrine system: System of glands that secrete hormones directly into blood.

Hormone: Chemical messenger produced by endocrine gland; travels in blood to target organ.

Differences between nervous and endocrine systems:
| Feature | Nervous System | Endocrine System |
|---|---|---|
| Signal type | Electrical (nerve impulse) | Chemical (hormone) |
| Speed | Very fast (milliseconds) | Slow (seconds to hours) |
| Duration | Short-lived | Long-lasting |
| Transmission | Along nerves | Via bloodstream |
| Response area | Localized | Widespread |

### 6.2 Major Endocrine Glands and Hormones

Pituitary gland ("master gland") — in brain:
- Growth hormone (GH): Stimulates growth of bones and muscles
- TSH (thyroid stimulating hormone): Stimulates thyroid
- ACTH: Stimulates adrenal cortex
- FSH/LH: Control reproductive system
- ADH: Water reabsorption in kidneys
- Oxytocin: Uterine contractions; milk ejection

Thyroid gland — in neck:
- Thyroxine: Regulates metabolic rate; required for normal growth and development
  - Deficiency in children: Cretinism (stunted growth, intellectual disability)
  - Deficiency in adults: Hypothyroidism (weight gain, fatigue, cold intolerance)
  - Excess: Hyperthyroidism (weight loss, rapid heart rate)
- Calcitonin: Lowers blood calcium levels

Parathyroid glands:
- PTH: Raises blood calcium (mobilizes Ca from bones)

Adrenal glands:
- Adrenal medulla: Adrenaline (epinephrine) — "fight or flight"
  - Increases heart rate, dilates pupils, raises blood glucose, dilates bronchioles
- Adrenal cortex: Cortisol, aldosterone (salt/water balance)

Pancreas (Islets of Langerhans):
- Insulin (β-cells): Lowers blood glucose
- Glucagon (α-cells): Raises blood glucose

Gonads:
- Testes: Testosterone — male secondary sex characteristics, sperm production
- Ovaries: Oestrogen, progesterone — female sex characteristics, menstrual cycle

### 6.3 Negative Feedback in Hormone Regulation
Example — Thyroid hormones:
- Hypothalamus releases TRH → pituitary releases TSH → thyroid releases thyroxine
- High thyroxine → inhibits hypothalamus and pituitary (negative feedback) → less TRH, less TSH

