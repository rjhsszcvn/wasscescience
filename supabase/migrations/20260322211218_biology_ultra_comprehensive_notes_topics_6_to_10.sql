## 5. Light-Independent Reactions — Calvin Cycle (In Stroma)

Also called the dark reactions (but NOT restricted to darkness — occur when ATP and NADPH are available).

Occur in the stroma.

Overall: ATP and NADPH used to fix CO₂ into glucose.

The Calvin Cycle:

Step 1: Carbon Fixation
- CO₂ combines with RuBP (ribulose bisphosphate — 5C compound) → unstable 6C compound → 2 molecules of GP (glycerate-3-phosphate, 3C)
- Enzyme: RuBisCO (ribulose bisphosphate carboxylase/oxygenase)

Step 2: Reduction
- GP reduced to G3P (glyceraldehyde-3-phosphate/triose phosphate)
- Requires: ATP and NADPH (from light reactions)

Step 3: Regeneration of RuBP
- Some G3P used to regenerate RuBP (using ATP)
- Maintains supply of CO₂ acceptor molecule

Output:
- For every 3 CO₂ fixed: 1 G3P produced (net)
- G3P used to synthesize: Glucose, starch, cellulose, fatty acids, amino acids

