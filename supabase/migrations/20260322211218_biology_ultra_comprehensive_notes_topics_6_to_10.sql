## 1. Introduction

Photosynthesis: The process by which green plants, algae, and some bacteria use light energy to synthesize organic compounds (glucose) from inorganic compounds (CO₂ and water).

Overall equation:
6CO₂ + 6H₂O + light energy → C₆H₁₂O₆ + 6O₂
Carbon dioxide + Water + Light energy → Glucose + Oxygen

Photosynthesis is the foundation of almost all food chains — producers make food from sunlight.

---

## 2. Chloroplasts — Site of Photosynthesis

Structure:
- Outer double membrane (envelope)
- Thylakoids: Flattened membrane sacs arranged in stacks called grana (singular: granum)
- Granum: Stack of thylakoids (interconnected by lamellae)
- Thylakoid membrane: Contains photosynthetic pigments; site of LIGHT REACTIONS
- Stroma: Fluid matrix surrounding thylakoids; site of DARK REACTIONS (Calvin cycle)
- Stroma lamellae: Membranes connecting different grana

---

## 3. Photosynthetic Pigments

Photosynthetic pigments absorb light energy of specific wavelengths.

Main pigments in plants:
- Chlorophyll a: Main pigment; absorbs red and blue light; reflects green (why leaves look green)
- Chlorophyll b: Accessory pigment; absorbs blue-violet and orange-red
- Carotenoids (carotene and xanthophyll): Absorb blue and green; reflect orange/yellow; autumn leaf colors

Absorption spectrum: Wavelengths of light absorbed by pigments (peaks at red and blue)
Action spectrum: Rate of photosynthesis at different wavelengths (peaks at red and blue — matches absorption spectrum)

