## 1. Need for a Transport System

Small organisms (single cells, small flatworms) can rely on diffusion alone for transport.
Large, complex organisms need a dedicated transport system because:
- Diffusion distance too great (slow process)
- High metabolic demands of active cells
- Need to distribute materials throughout large body
- Need to collect waste from throughout body

---

## 2. Transport in Plants

### 2.1 Xylem — Water and Mineral Transport

Structure:
- Long, hollow tubes formed from dead cells
- Thick walls reinforced with lignin
- No cross walls (allows unobstructed flow)
- Forms continuous tubes from root to leaf

Function:
- Transports water and dissolved minerals from roots to leaves
- Provides structural support to plant

Mechanism — Transpiration Pull (Cohesion-Tension Theory):
1. Evaporation from leaf cells through stomata (transpiration)
2. This creates tension (negative pressure) in the xylem
3. Water is drawn up — cohesion: water molecules stick together (hydrogen bonds)
4. Adhesion: water sticks to xylem walls
5. Water moves from soil into root hairs by osmosis
6. Continuous column of water maintained

Root Pressure:
- Salts actively pumped into xylem in roots
- Water follows by osmosis
- Creates pressure that pushes water upward
- Important when transpiration rate is low

### 2.2 Phloem — Translocation

Structure:
- Living cells (sieve tube elements and companion cells)
- Sieve plates: Perforated end walls allow movement
- Companion cells: Metabolically active, support sieve tubes

Function:
- Transports dissolved organic substances (mainly sucrose, amino acids) from source to sink
- Translocation moves in BOTH directions (up and down)

Source: Where sugar is produced (leaves during photosynthesis) or where it is stored and mobilized (storage roots)
Sink: Where sugar is used or stored (growing tips, roots, fruits, seeds)

Mechanism — Mass Flow (Pressure Flow Hypothesis):
1. Sugars actively loaded into phloem at source (active transport)
2. Water moves into phloem by osmosis → high pressure
3. At sink, sugars unloaded → water leaves phloem → pressure decreases
4. Solution flows from high pressure (source) to low pressure (sink)

### 2.3 Transpiration

Transpiration: Loss of water vapor from plant surfaces, mainly through stomata.

Factors affecting transpiration rate:
- Temperature: Higher temp → faster evaporation → more transpiration
- Humidity: Lower humidity → greater diffusion gradient → more transpiration
- Wind speed: Removes humid air from around leaves → increases gradient → more transpiration
- Light intensity: Opens stomata → more transpiration
- Water availability: Less water → stomata close → less transpiration

Adaptations to reduce water loss (xerophytes):
- Thick, waxy cuticle (cactus)
- Sunken stomata in pits
- Rolled leaves (marram grass)
- Reduced leaf surface area
- Hairy leaves (trap humid air)
- CAM metabolism (open stomata at night)

