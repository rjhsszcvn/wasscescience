## 3. Reflex Arcs

Reflex: Automatic, involuntary response to a stimulus.
Faster than voluntary responses (does not need to go to brain first).

Reflex arc pathway:
Stimulus → Receptor → Sensory neuron → Relay neuron (in spinal cord) → Motor neuron → Effector → Response

Example — Knee jerk reflex:
- Tap below kneecap → stretches patellar tendon → sensory neuron → spinal cord → motor neuron → quadriceps muscle → leg extends
- No relay neuron in this case (monosynaptic reflex)

Example — Withdrawal reflex (touching hot object):
- Hot object → pain receptors in skin → sensory neuron → relay neuron in spinal cord → motor neurons → arm muscles contract → withdraw hand
- Signal also sent to brain (you feel pain after)

