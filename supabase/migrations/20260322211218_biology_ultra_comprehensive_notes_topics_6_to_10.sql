## 9. Investigating Photosynthesis

### 9.1 Testing for Starch in Leaves
Method:
1. Boil leaf in water (kills cells; stops reactions)
2. Boil in ethanol (removes chlorophyll; decolorizes leaf)
3. Soften in hot water
4. Add iodine solution
Positive result: Blue-black color (starch present)

### 9.2 Proving CO₂ is Needed
- Place plant in CO₂-free air (use KOH to absorb CO₂)
- Control plant in normal air
- Test both for starch after light period
- Result: CO₂-deprived plant shows no starch

### 9.3 Proving Light is Needed (Variegated Leaves or Stencils)
- Cover part of leaf with foil → exclude light
- After several hours in light, test for starch
- Result: Covered part = no starch; uncovered part = starch present

### 9.4 Measuring Rate of Photosynthesis (Aquatic Plants — Elodea)
- Count bubbles of O₂ per minute at different light intensities
- Collect gas, test with glowing splint (relights in O₂)
- Or measure volume of O₂ produced

### 9.5 Chromatography of Leaf Pigments
- Extract pigments with solvent (propanone/acetone)
- Run chromatography using paper and solvent (petroleum ether)
- Different pigments travel different distances (different solubility)
- Calculate Rf value: Rf = distance moved by pigment / distance moved by solvent front
- Bands: Carotene (top), xanthophyll, chlorophyll a, chlorophyll b (bottom)' 
