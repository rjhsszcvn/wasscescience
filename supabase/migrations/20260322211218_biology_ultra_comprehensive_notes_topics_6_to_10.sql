## 3. The Human Circulatory System

### 3.1 Overview

Double circulation:
- Pulmonary circulation: Heart → Lungs → Heart (deoxygenated blood picks up O₂)
- Systemic circulation: Heart → Body → Heart (oxygenated blood delivers O₂ to tissues)

Advantages of double circulation:
- Blood pressure maintained at high levels
- Efficient delivery of oxygen to tissues
- Separation of oxygenated and deoxygenated blood

### 3.2 The Heart

Structure:
- Four chambers: Right atrium, right ventricle, left atrium, left ventricle
- Thick muscular walls (myocardium)
- Left ventricle has thicker wall (pumps blood further around body)
- Valves prevent backflow of blood:
  - Atrioventricular (AV) valves: Between atria and ventricles
    - Tricuspid: Right side (3 cusps)
    - Bicuspid (Mitral): Left side (2 cusps)
  - Semilunar valves: In aorta and pulmonary artery

Coronary arteries: Supply heart muscle with blood

Cardiac cycle (one heartbeat):
1. Diastole: Both atria and ventricles relax; heart fills with blood
2. Atrial systole: Atria contract; blood forced into ventricles
3. Ventricular systole: Ventricles contract; blood forced into aorta and pulmonary artery
- Heart rate: ~70 beats per minute at rest
- Stroke volume: Volume of blood per beat (~70 mL)
- Cardiac output = Heart rate × Stroke volume

Cardiac conduction system:
- Sinoatrial (SA) node: Pacemaker; initiates heartbeat (right atrium)
- Atrioventricular (AV) node: Receives impulse; delays it (allows ventricles to fill)
- Bundle of His and Purkinje fibers: Conduct impulse to ventricles

### 3.3 Blood Vessels

| Feature | Arteries | Veins | Capillaries |
|---|---|---|---|
| Direction | Away from heart | To heart | Connect arteries/veins |
| Wall | Thick, muscular | Thin, less muscular | One cell thick |
| Valves | None (except semilunar) | Present | None |
| Lumen | Narrow | Wide | Very narrow |
| Blood pressure | High | Low | Decreasing |
| Blood type | Oxygenated (except pulmonary) | Deoxygenated (except pulmonary) | Mixed |

Capillary exchange:
- Very thin walls → substances easily exchange
- Nutrients and O₂ diffuse out into tissue fluid
- CO₂ and waste diffuse in from tissue fluid
- Tissue fluid: Filtered plasma that surrounds cells

### 3.4 Blood Composition

Red Blood Cells (Erythrocytes):
- Biconcave shape → large surface area
- No nucleus → more space for haemoglobin
- Packed with haemoglobin (O₂ carrier)
- Flexible → can pass through narrow capillaries
- Lifespan: ~120 days; made in red bone marrow

White Blood Cells (Leucocytes):
- Have nucleus
- Part of immune system
- Types:
  - Phagocytes (neutrophils, monocytes): Engulf and destroy pathogens by phagocytosis
  - Lymphocytes: Produce antibodies; involved in specific immunity

Platelets (Thrombocytes):
- Cell fragments (no nucleus)
- Involved in blood clotting

Blood Clotting:
1. Damaged tissue → platelets aggregate → platelet plug
2. Prothrombin → Thrombin (activated by thromboplastin + Ca²⁺)
3. Thrombin converts Fibrinogen → Fibrin
4. Fibrin forms mesh → traps blood cells → clot

Plasma:
- Liquid component (~55% of blood)
- 90% water
- Carries: glucose, amino acids, hormones, antibodies, urea, CO₂, clotting factors, plasma proteins (albumin, globulin, fibrinogen)

ABO Blood Groups:
- Determined by antigens on red blood cells
- A: Antigen A on RBC; antibody b in plasma
- B: Antigen B on RBC; antibody a in plasma
- AB: Both A and B antigens; no antibodies (universal recipient)
- O: No antigens; both a and b antibodies (universal donor)

Rhesus (Rh) factor:
- Rh+ has Rh antigen; Rh- does not
- Important in blood transfusions and pregnancy

### 3.5 Lymphatic System
- Network of vessels that drains tissue fluid
- Lymph: Tissue fluid that has entered lymph capillaries
- Lymph nodes: Filter lymph; contain lymphocytes → immune response
- Returns fluid to blood (at subclavian veins)
- Lacteals in ileum absorb fat' 
