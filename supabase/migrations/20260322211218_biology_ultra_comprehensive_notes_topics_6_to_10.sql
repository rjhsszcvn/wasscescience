## 4. Homeostasis

Homeostasis: Maintenance of a constant internal environment within narrow limits.

Why it matters:
- Enzymes work optimally in specific conditions
- Cells function best in specific pH, temperature, solute concentration
- Survival depends on maintaining stable internal conditions

Parameters regulated:
- Body temperature (thermoregulation)
- Blood glucose concentration
- Blood water potential (osmoregulation)
- Blood pH
- Blood CO₂ levels

### 4.1 Negative Feedback Mechanism
Most homeostatic mechanisms use negative feedback.

Components:
- Receptor: Detects change in internal environment
- Control center: Processes information (usually hypothalamus in brain)
- Effector: Brings about response to correct the change

How it works:
- If parameter rises above set point → effector reduces it
- If parameter falls below set point → effector increases it
- Change is reversed → parameter returns to normal range

---

## 5. Thermoregulation

Body temperature: ~37°C in humans (optimum for enzyme activity)

### 5.1 Hypothalamus: Thermostat of the Body
- Thermoreceptors in hypothalamus detect blood temperature
- Thermoreceptors in skin detect external temperature
- Hypothalamus sends signals to effectors

### 5.2 When Too Hot (Hyperthermia response):
- Vasodilation: Blood vessels in skin dilate → more blood near surface → more heat lost
- Sweating: Sweat glands produce sweat → evaporation cools skin → heat lost
- Piloerection: Hairs lie flat → less insulating air layer (minor in humans)
- Reduced metabolic rate
- Behavioral: Seeking shade, removing clothes

### 5.3 When Too Cold (Hypothermia response):
- Vasoconstriction: Blood vessels in skin constrict → less blood near surface → less heat lost
- Shivering: Rapid involuntary muscle contractions → heat generated by respiration
- Piloerection: Hairs stand up → trap air layer → insulation
- Increased metabolic rate
- Behavioral: Seeking warmth, adding clothes, curling up

### 5.4 Fever
- Pathogens trigger release of pyrogens
- Pyrogens reset hypothalamus thermostat higher
- Moderate fever: Helps immune response (some pathogens die; immune cells more active)
- Very high fever: Dangerous (enzyme denaturation)

