## 1. Introduction to Coordination

Coordination: Integration of activities of different body parts for effective response to stimuli.

Two systems coordinate body activities:
1. Nervous system: Electrical signals; fast, short-lived, localized
2. Endocrine system: Chemical signals (hormones); slower, longer-lasting, widespread

---

## 2. The Nervous System

### 2.1 Organization

Central Nervous System (CNS):
- Brain and spinal cord
- Integration and coordination center

Peripheral Nervous System (PNS):
- All nerves outside CNS
- Somatic nervous system: Controls voluntary movements (skeletal muscles)
- Autonomic nervous system: Controls involuntary functions (heart, glands)
  - Sympathetic: "Fight or flight" response
  - Parasympathetic: "Rest and digest" response

### 2.2 Neurons (Nerve Cells)

Types:
- Sensory neurons: Carry impulses FROM receptors TO CNS
- Motor neurons: Carry impulses FROM CNS TO effectors (muscles/glands)
- Relay neurons (interneurons): Found in CNS; connect sensory and motor neurons

Structure of a motor neuron:
- Cell body (soma): Contains nucleus; metabolic center
- Dendrites: Short extensions; receive signals from other neurons
- Axon: Long extension; carries impulse away from cell body
- Myelin sheath: Fatty insulating layer; produced by Schwann cells; speeds up impulse conduction
- Nodes of Ranvier: Gaps in myelin sheath
- Axon terminals (synaptic knobs): End of axon; release neurotransmitters

Myelinated vs. unmyelinated:
- Myelinated: Saltatory conduction (impulse jumps between nodes) → faster
- Unmyelinated: Impulse travels along entire membrane → slower

### 2.3 Nerve Impulse (Action Potential)

Resting potential:
- At rest, inside of neuron is negatively charged (−70 mV)
- Maintained by Na⁺/K⁺ ATPase pump: 3 Na⁺ out, 2 K⁺ in
- Inside: High K⁺, negative proteins; Outside: High Na⁺, Cl⁻

Action potential (nerve impulse):
1. Stimulus reaches threshold → Na⁺ channels open
2. Na⁺ rushes INTO cell → membrane depolarizes (+40 mV)
3. K⁺ channels open → K⁺ flows OUT → repolarization
4. Hyperpolarization: briefly more negative than resting
5. Na⁺/K⁺ pump restores resting potential

Refractory period:
- Period after action potential when neuron cannot fire again
- Ensures one-way transmission of impulse

All-or-nothing principle:
- Impulse either fires fully or not at all
- Stimulus must reach threshold to generate action potential
- Larger stimuli → higher FREQUENCY of impulses (not larger impulse)

### 2.4 Synaptic Transmission

Synapse: Junction between two neurons (or neuron and effector).

Types:
- Chemical synapse: Uses neurotransmitters
- Electrical synapse: Direct electrical coupling (rare in mammals)

Steps of chemical synaptic transmission:
1. Impulse reaches axon terminal
2. Depolarization causes Ca²⁺ channels to open → Ca²⁺ enters
3. Synaptic vesicles fuse with presynaptic membrane
4. Neurotransmitter released into synaptic cleft by exocytosis
5. Neurotransmitter diffuses across cleft
6. Binds to receptors on postsynaptic membrane
7. Ion channels open → new action potential generated (if threshold reached)
8. Neurotransmitter removed: broken down by enzymes OR reabsorbed by presynaptic neuron

Important neurotransmitters:
- Acetylcholine (ACh): At neuromuscular junctions; in parasympathetic system; broken down by acetylcholinesterase
- Noradrenaline/norepinephrine: In sympathetic nervous system
- Dopamine: Movement, reward, mood
- Serotonin: Mood, sleep
- GABA: Inhibitory

Excitatory synapse: Neurotransmitter depolarizes postsynaptic membrane
Inhibitory synapse: Neurotransmitter hyperpolarizes postsynaptic membrane (harder to fire)

Summation:
- Spatial: Multiple neurons fire simultaneously
- Temporal: Same neuron fires rapidly → effects add up

