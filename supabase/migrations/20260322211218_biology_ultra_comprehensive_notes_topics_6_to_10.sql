## 1. Introduction to Reproduction

Reproduction: The process by which organisms produce offspring.

Types:
- Asexual reproduction: One parent; no gametes; offspring genetically identical (clones)
- Sexual reproduction: Two parents (usually); involves gametes; offspring genetically unique

---

## 2. Asexual Reproduction

Advantages:
- Only one parent needed
- Fast; many offspring produced quickly
- Successful genotype preserved
- No need to find a mate

Disadvantages:
- No genetic variation → less adaptable to environmental change
- Diseases can wipe out entire population

Methods:
- Binary fission: Cell divides into two equal cells (bacteria, Amoeba)
- Budding: New organism grows as outgrowth (yeast, Hydra)
- Fragmentation: Body breaks into pieces, each regenerates (Planaria, sea stars)
- Sporulation: Spores produced (fungi, ferns, mosses)
- Vegetative propagation: New plants from non-reproductive parts

Vegetative propagation in plants:
- Runners (stolons): Horizontal stems; new plants form at nodes (strawberry)
- Bulbs: Swollen leaf bases (onion, daffodil)
- Corms: Swollen stem base (crocus)
- Rhizomes: Underground horizontal stems (ginger, iris)
- Tubers: Swollen underground stems (potato — eyes are buds)
- Cuttings: Stem or leaf cutting grows into new plant (artificial)
- Grafting: Shoot of one plant joined to root of another
- Layering: Branch bent to soil; roots develop

---

## 3. Human Sexual Reproduction

### 3.1 Male Reproductive System

Structures:
- Testes (in scrotum): Produce sperm (spermatogenesis) and testosterone
  - Scrotum: Outside body; temperature 2-3°C below body temperature (necessary for sperm production)
  - Seminiferous tubules: Site of sperm production
  - Interstitial cells (Leydig cells): Produce testosterone
- Epididymis: Sperm mature and stored here
- Vas deferens (sperm duct): Carries sperm from epididymis to urethra
