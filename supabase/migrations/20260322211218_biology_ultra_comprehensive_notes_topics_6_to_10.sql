## 7. Menstrual Cycle

Duration: ~28 days

Day 1-5: Menstruation (endometrium shed)
Day 1-13: Follicular phase (FSH → follicle grows → oestrogen rises → endometrium rebuilds)
Day 14: Ovulation (LH surge → egg released)
Day 15-28: Luteal phase (LH → corpus luteum forms → progesterone → endometrium maintained)
Day 28: If no fertilization → corpus luteum degenerates → progesterone falls → menstruation begins

Key hormones:
- FSH: Stimulates follicle development
- Oestrogen: Stimulates endometrium growth; triggers LH surge
- LH: Triggers ovulation; stimulates corpus luteum
- Progesterone: Maintains endometrium; prepares for implantation' 
