## 8. C3, C4, and CAM Plants

C3 plants (most common):
- First stable product of Calvin cycle = 3C (GP/3-PGA)
- Examples: Wheat, rice, most trees
- Photorespiration at high temperatures (O₂ competes with CO₂ for RuBisCO) → reduced efficiency

C4 plants:
- First stable product = 4C compound (oxaloacetate)
- Mesophyll cells fix CO₂ into 4C compound → transported to bundle sheath cells → CO₂ released → enters Calvin cycle
- Concentrate CO₂ around RuBisCO → minimize photorespiration
- More efficient in hot, high light conditions
- Examples: Maize (corn), sugar cane, sorghum

CAM plants (Crassulacean Acid Metabolism):
- Stomata open at NIGHT → fix CO₂ into organic acids → stored
- Day: Stomata closed → CO₂ released from acids → Calvin cycle
- Adaptation to arid environments → minimize water loss
- Examples: Cacti, succulents, pineapple

