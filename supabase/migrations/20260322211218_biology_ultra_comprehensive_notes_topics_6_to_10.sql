## 7. Osmoregulation

Control of water and salt balance in body.

Antidiuretic Hormone (ADH):
- Produced by hypothalamus; stored and released by posterior pituitary
- Controls water reabsorption in collecting duct

When blood is too concentrated (dehydrated):
- Osmoreceptors in hypothalamus detect low water potential
- More ADH released
- Collecting duct becomes MORE permeable to water
- More water reabsorbed → concentrated urine produced

When blood is too dilute (over-hydrated):
- Less ADH released
- Collecting duct becomes LESS permeable to water
- Less water reabsorbed → dilute, large volume of urine produced

Aldosterone (from adrenal cortex):
- Controls Na⁺ reabsorption in DCT
- Increases Na⁺ reabsorption → water follows → blood volume increases
- Regulated by blood pressure and Na⁺ levels

---

## 8. Osmoregulation in Other Organisms

Freshwater fish:
- Surrounded by hypotonic water (less salty than body fluids)
- Water enters by osmosis; salts lost by diffusion
- Produce large amounts of dilute urine
- Actively absorb salts through gills

Marine (saltwater) fish:
- Surrounded by hypertonic water (saltier than body fluids)
- Lose water by osmosis; gain salt
- Drink seawater; excrete small amounts of concentrated urine
- Actively excrete excess salt through gills' 
