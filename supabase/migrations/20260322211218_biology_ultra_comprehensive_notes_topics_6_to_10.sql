## 6. Regulation of Blood Glucose

Normal blood glucose: ~4–6 mmol/L (80–110 mg/100 mL)

### 6.1 When Blood Glucose is TOO HIGH (after eating):
- Detected by β-cells in islets of Langerhans in pancreas
- Insulin secreted
- Insulin causes:
  - Cells take up glucose from blood
  - Liver and muscle cells convert glucose → glycogen (glycogenesis)
  - Fatty acid synthesis from excess glucose
- Blood glucose returns to normal

### 6.2 When Blood Glucose is TOO LOW (after exercise/fasting):
- Detected by α-cells in islets of Langerhans in pancreas
- Glucagon secreted
- Glucagon causes:
  - Liver converts glycogen → glucose (glycogenolysis)
  - Liver makes glucose from non-carbohydrate sources (gluconeogenesis)
- Blood glucose returns to normal

Adrenaline: Also raises blood glucose (during stress) — mobilizes glycogen stores rapidly

### 6.3 Diabetes Mellitus

Type 1 Diabetes (Insulin-dependent):
- Body does not produce insulin (autoimmune destruction of β-cells)
- Blood glucose remains very high after meals
- Treatment: Insulin injections, diet management

Type 2 Diabetes (Non-insulin dependent):
- Body produces insulin but cells become insulin-resistant
- Associated with obesity, sedentary lifestyle, genetics
- Treatment: Diet, exercise, oral medications, sometimes insulin

Symptoms of diabetes:
- Excessive thirst (polydipsia)
- Frequent urination (polyuria) — glucose in urine draws water osmotically
- Fatigue, weight loss, slow wound healing

