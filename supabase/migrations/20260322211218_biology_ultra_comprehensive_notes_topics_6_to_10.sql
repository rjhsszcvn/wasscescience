## 6. Factors Affecting Photosynthesis

### 6.1 Limiting Factors
A limiting factor is the factor in shortest supply that limits the rate of photosynthesis.

Even if other conditions are ideal, the limiting factor controls the rate.

### 6.2 Light Intensity
- As light increases → photosynthesis rate increases
- Light saturation point: Beyond this, light is no longer limiting
- Too much light can cause photoinhibition (damage to photosystems)
- Low light → light reactions limited → less ATP/NADPH → slower Calvin cycle

Relationship:
- Rate ∝ light intensity (at low intensities)
- At high intensities: Temperature or CO₂ become limiting

### 6.3 Carbon Dioxide Concentration
- Atmospheric CO₂ ≈ 0.04% (400 ppm)
- As CO₂ increases → photosynthesis rate increases (up to saturation)
- CO₂ is substrate for RuBisCO in Calvin cycle
- Greenhouse growers increase CO₂ → higher crop yield

### 6.4 Temperature
- Affects enzyme-catalyzed reactions (Calvin cycle enzymes)
- Optimal temperature: ~25-35°C for most plants
- Above optimum: Enzymes denature → rate falls rapidly
- Below optimum: Enzyme activity slows → rate falls

Note: Light reactions are not enzyme-dependent → temperature has less effect on them directly.

### 6.5 Water
- Water is a raw material (substrate for photolysis)
- Water stress → stomata close → less CO₂ available → rate falls
- Important limiting factor in arid regions

### 6.6 Mineral Salts
- Magnesium (Mg²⁺): Component of chlorophyll → deficiency reduces photosynthesis
- Nitrates: Needed for protein synthesis (including photosynthetic enzymes)

