## 5. Sense Organs

### 5.1 The Eye

Structure:
- Cornea: Transparent front layer; focuses most light
- Iris: Colored part; controls pupil size
- Pupil: Opening that allows light in
- Lens: Fine-focuses light; can change shape (accommodation)
- Ciliary muscle: Changes lens shape
- Suspensory ligaments: Attach lens to ciliary muscle
- Retina: Light-sensitive layer; contains photoreceptors
  - Rods: Sensitive to dim light; black/white vision; more in periphery
  - Cones: Color vision; need bright light; concentrated in fovea
- Fovea (yellow spot): Highest concentration of cones; sharpest vision
- Blind spot (optic disc): Where optic nerve leaves — no photoreceptors
- Optic nerve: Carries impulses to brain (visual cortex)
- Vitreous humor: Jelly-like substance; maintains shape
- Aqueous humor: Liquid in front chamber
- Sclera: White outer layer; protective
- Choroid: Black, pigmented layer; absorbs excess light; blood supply to retina

Accommodation (focusing):
- Far object: Ciliary muscles RELAX → suspensory ligaments taut → lens thin → less refraction
- Near object: Ciliary muscles CONTRACT → suspensory ligaments slack → lens fat → more refraction

Pupil reflex (light reflex):
- Bright light: Circular muscles in iris contract → pupil constricts (less light in)
- Dim light: Radial muscles contract → pupil dilates (more light in)

Eye defects:
- Short-sightedness (myopia): Cannot see far; eyeball too long or lens too curved → corrected by concave lens
- Long-sightedness (hyperopia): Cannot see near; eyeball too short → corrected by convex lens
- Presbyopia: Age-related loss of accommodation (lens loses flexibility)
- Astigmatism: Irregular cornea/lens curvature → blurred vision

### 5.2 The Ear
- Outer ear (pinna, ear canal): Collects and directs sound waves
- Tympanic membrane (eardrum): Vibrates with sound
- Middle ear bones (ossicles): Malleus, incus, stapes amplify vibrations
- Oval window: Transmits vibrations to inner ear
- Cochlea: Fluid-filled; hair cells detect vibrations → nerve impulses
- Semicircular canals: Detect rotational movement (balance)
- Utricle and saccule: Detect linear acceleration and gravity (balance)
- Eustachian tube: Equalizes pressure between middle ear and throat

