## 4. Light-Dependent Reactions (In Thylakoid Membrane)

Occur in thylakoid membranes.

Overall: Light energy splits water → O₂ released; NADPH and ATP produced.

Photosystems:
- Photosystem I (PSI): Contains P700 chlorophyll; produces NADPH
- Photosystem II (PSII): Contains P680 chlorophyll; splits water; produces O₂

Steps:

1. Light absorbed by PSII (P680):
   - Chlorophyll absorbs photons → electrons excited to higher energy level
   - These electrons are passed to electron transport chain

2. Photolysis of water (water splitting):
   - 2H₂O → 4H⁺ + 4e⁻ + O₂
   - Oxygen released as by-product
   - Electrons replace those lost from PSII

3. Electron transport chain (in thylakoid membrane):
   - Excited electrons pass through series of electron carriers
   - Energy used to pump H⁺ across thylakoid membrane
   - H⁺ flow back through ATP synthase → ATP produced (photophosphorylation)

4. Light absorbed by PSI (P700):
   - Electrons re-energized
   - Electrons used to reduce NADP⁺ + H⁺ → NADPH

Products of light-dependent reactions:
- ATP (energy carrier)
- NADPH (reducing agent)
- O₂ (released as waste)

