## 7. Leaf Adaptations for Photosynthesis

- Large surface area: Captures maximum light
- Thin: Short diffusion distance for CO₂ and light
- Transparent cuticle and epidermis: Light penetrates to mesophyll
- Palisade mesophyll: Tall, packed with chloroplasts; maximum light absorption
- Spongy mesophyll: Air spaces → CO₂ diffusion to cells
- Stomata: Allow CO₂ in and O₂ out (and water vapor out)
- Vascular bundles (veins): Supply water (xylem) and remove glucose (phloem)
- Chloroplasts can move: Orient for optimal light absorption

