<h3>14.1 Importance of Oral Health</h3>
<p>The WHO defines <strong>oral health</strong> as a state of being free from mouth and facial pain, oral and throat cancer, oral infection and sores, periodontal (gum) disease, tooth decay, tooth loss, and other diseases and disorders that limit an individual capacity in biting, chewing, smiling, speaking, and psychosocial wellbeing.</p>

<p>Oral health is integral to overall health - oral diseases can affect the entire body through:</p>
<ul>
<li>Bacteraemia: Oral bacteria entering the bloodstream, potentially causing endocarditis (heart infection)</li>
<li>Systemic inflammation contributing to cardiovascular disease</li>
<li>Poor oral health linked to poor glycaemic control in diabetes</li>
<li>Periodontal disease associated with preterm birth and low birth weight</li>
</ul>

<h3>14.2 Structure of the Tooth</h3>
<p><strong>Parts of a Tooth:</strong></p>
<ul>
<li><strong>Crown:</strong> Visible part above the gum</li>
<li><strong>Root:</strong> Embedded in the jawbone</li>
<li><strong>Neck:</strong> Junction between crown and root at the gum line</li>
</ul>

<p><strong>Layers of the Tooth:</strong></p>
<ul>
<li><strong>Enamel:</strong> Hardest substance in the body; covers the crown; protects underlying tissues; cannot regenerate once damaged</li>
<li><strong>Dentine:</strong> Bone-like tissue beneath enamel; makes up bulk of tooth; contains dentinal tubules that transmit pain sensations</li>
<li><strong>Pulp:</strong> Soft inner tissue containing nerves and blood vessels; provides sensation and nourishment to tooth</li>
<li><strong>Cementum:</strong> Covers the root; anchors the tooth to the periodontal ligament</li>
<li><strong>Periodontal ligament:</strong> Fibrous tissue connecting tooth to jawbone (alveolar bone)</li>
</ul>

<p><strong>Types of Teeth:</strong></p>
<table>
<tr><th>Type</th><th>Number (adult)</th><th>Function</th></tr>
<tr><td>Incisors</td><td>8 (4 upper, 4 lower)</td><td>Cutting food</td></tr>
<tr><td>Canines (cuspids)</td><td>4</td><td>Tearing food</td></tr>
<tr><td>Premolars (bicuspids)</td><td>8</td><td>Crushing and grinding</td></tr>
<tr><td>Molars</td><td>12 (including 4 wisdom teeth)</td><td>Grinding food</td></tr>
</table>

<p><strong>Dentition:</strong> Humans have two sets of teeth - primary (deciduous/"milk") teeth (20 total, eruption from 6 months) and permanent (secondary) teeth (32 total, begin erupting around age 6).</p>

<h3>14.3 Dental Caries (Tooth Decay)</h3>
<p><strong>Dental caries</strong> is the most common chronic disease globally. It is an infectious, transmissible disease caused by acid-producing bacteria that destroy tooth structure.</p>

<h4>The Caries Process</h4>
<p>Four factors must be present simultaneously (Keyes circle):</p>
<ol>
<li><strong>Susceptible tooth surface</strong></li>
<li><strong>Cariogenic bacteria</strong> (Streptococcus mutans and Lactobacillus species)</li>
<li><strong>Fermentable carbohydrates</strong> (sugars - especially sucrose)</li>
<li><strong>Time</strong> (bacteria ferment sugars, producing acids; acids demineralize enamel)</li>
</ol>

<p><strong>Progression of Caries:</strong></p>
<ol>
<li>Plaque formation: Bacteria accumulate on tooth surface in a sticky biofilm</li>
<li>Acid production: Bacteria ferment dietary sugars, producing lactic acid</li>
<li>Demineralization: Acid dissolves enamel minerals (calcium and phosphate)</li>
<li>Cavity formation: Progressive destruction through enamel, into dentine, and eventually pulp</li>
<li>Pulpitis/abscess: Pulp infection causing severe pain and possible tooth loss</li>
</ol>

<p><strong>Signs and Symptoms:</strong></p>
<ul>
<li>Initial: White spot lesion on enamel (reversible if remineralized)</li>
<li>Early cavity: Sensitivity to sweet, hot, or cold foods</li>
<li>Advanced: Visible holes (cavities), toothache, abscess (pus-filled swelling)</li>
</ul>

<h4>Prevention of Dental Caries</h4>
<ul>
<li><strong>Reduce sugar intake:</strong> Limit frequency and amount of sugary foods and drinks; avoid between-meal snacking on sugar</li>
<li><strong>Fluoride:</strong> Strengthens enamel (fluorapatite) and inhibits bacterial metabolism; sources: fluoridated water (0.7-1.0 ppm), fluoride toothpaste, professional fluoride treatments</li>
<li><strong>Oral hygiene:</strong> Brush twice daily with fluoride toothpaste; floss daily to remove interproximal plaque</li>
<li><strong>Pit and fissure sealants:</strong> Plastic coating applied to back teeth to prevent plaque accumulation in grooves</li>
<li><strong>Regular dental visits:</strong> Professional cleaning and early detection</li>
</ul>

<h3>14.4 Periodontal Disease</h3>
<p>Diseases affecting the supporting structures of the teeth (gums, alveolar bone, periodontal ligament).</p>

<h4>Gingivitis</h4>
<p>Inflammation of the gingiva (gums) caused by plaque accumulation. Reversible with good oral hygiene.</p>
<p><strong>Signs:</strong> Red, swollen, bleeding gums (especially when brushing); no bone destruction</p>

<h4>Periodontitis</h4>
<p>Advanced gum disease with irreversible destruction of the supporting structures of the teeth.</p>
<p><strong>Signs:</strong> Gum recession, deep pockets between teeth and gums, loose teeth, tooth loss, bad breath (halitosis)</p>
<p><strong>Risk factors:</strong> Smoking (major risk factor), diabetes, hormonal changes (pregnancy), poor oral hygiene, genetic susceptibility</p>

<h3>14.5 Oral Cancer</h3>
<p>Malignant neoplasm of the oral cavity (lip, tongue, floor of mouth, cheek lining, hard palate, gum).</p>

<p><strong>Risk Factors:</strong></p>
<ul>
<li>Tobacco use (smoking and chewing) - single greatest risk factor</li>
<li>Heavy alcohol consumption (synergistic with tobacco)</li>
<li>Human Papillomavirus (HPV) infection - particularly oropharyngeal cancer</li>
<li>Sun exposure (lip cancer)</li>
<li>Betel nut/quid chewing (common in Asia and some African communities)</li>
</ul>

<p><strong>Warning Signs of Oral Cancer (LOCH mnemonic):</strong></p>
<ul>
<li><strong>L</strong>ump or thickening in the mouth</li>
<li><strong>O</strong>re (sore) that does not heal within 2 weeks</li>
<li><strong>C</strong>olour change - white (leukoplakia) or red (erythroplakia) patches</li>
<li><strong>H</strong>oarseness or difficulty swallowing</li>
</ul>
<p>Also: Unexplained pain, numbness, bleeding, loose teeth</p>

<h3>14.6 Oral Health Promotion</h3>
<h4>Community Oral Health Measures</h4>
<ul>
<li>Water fluoridation: Most cost-effective public health measure for caries prevention</li>
<li>Salt fluoridation and fluoridated toothpaste programmes</li>
<li>School dental health programmes including education and fissure sealants</li>
<li>Tobacco control policies</li>
<li>Sugar taxation and marketing restrictions</li>
</ul>

<h4>Individual Oral Health Practices</h4>
<ul>
<li>Brush teeth at least twice daily with fluoride toothpaste (at least 1,000 ppm fluoride); spit, do not rinse, to retain fluoride</li>
<li>Floss or use interdental brushes daily</li>
<li>Limit sugary foods and drinks to mealtimes</li>
<li>Drink fluoridated water when available</li>
<li>Visit dentist every 6 months</li>
<li>Avoid tobacco products</li>
<li>Wear mouthguard during contact sports</li>
</ul>

