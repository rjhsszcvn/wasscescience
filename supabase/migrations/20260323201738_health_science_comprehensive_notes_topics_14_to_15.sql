<h3>15.1 The Eye</h3>

<h4>15.1.1 Structure of the Eye</h4>
<p>The eye is a complex sensory organ responsible for vision. It converts light into electrical impulses that the brain interprets as images.</p>

<p><strong>External Structures:</strong></p>
<ul>
<li><strong>Eyelids:</strong> Protect the eye; spread tears over the cornea; blink reflex protects from injury</li>
<li><strong>Eyelashes:</strong> Trap dust and debris</li>
<li><strong>Conjunctiva:</strong> Thin transparent membrane covering the white of the eye (sclera) and inner eyelids; produces mucus</li>
<li><strong>Lacrimal glands:</strong> Produce tears that lubricate, clean, and protect the eye surface; tears drain through lacrimal ducts to the nose</li>
</ul>

<p><strong>Internal Structures:</strong></p>
<ul>
<li><strong>Cornea:</strong> Transparent curved tissue at front of eye; provides 70% of the refractive power; no blood vessels (avascular) - transparent; major site of corneal disease</li>
<li><strong>Sclera:</strong> White outer layer; tough protective coat of eye; continuous with cornea</li>
<li><strong>Iris:</strong> Coloured muscular diaphragm; controls pupil size (amount of light entering)</li>
<li><strong>Pupil:</strong> Central opening of iris; dilates in dim light (mydriasis), constricts in bright light (miosis)</li>
<li><strong>Lens:</strong> Transparent biconvex structure behind pupil; changes shape (accommodation) to focus at different distances; controlled by ciliary muscle</li>
<li><strong>Ciliary body:</strong> Contains ciliary muscle (for accommodation) and ciliary processes (produce aqueous humour)</li>
<li><strong>Aqueous humour:</strong> Clear fluid in anterior chamber; provides nutrients to avascular structures; maintains intraocular pressure</li>
<li><strong>Vitreous humour:</strong> Gel-like substance filling posterior chamber; maintains shape of eyeball</li>
<li><strong>Retina:</strong> Light-sensitive inner layer; contains photoreceptors</li>
<li><strong>Rods:</strong> Responsible for peripheral and low-light (dim) vision; contain rhodopsin; most numerous (120 million)</li>
<li><strong>Cones:</strong> Responsible for colour vision and fine detail; concentrated in the fovea/macula; require bright light</li>
<li><strong>Macula:</strong> Area of highest visual acuity (sharpest vision); centre of retina</li>
<li><strong>Optic nerve (CN II):</strong> Transmits visual signals from retina to brain; blind spot (optic disc) where nerve exits retina</li>
<li><strong>Choroid:</strong> Vascular layer between sclera and retina; supplies blood to retina; contains melanin (prevents internal reflection)</li>
</ul>

<h4>15.1.2 Common Eye Conditions</h4>

<h4>Refractive Errors</h4>
<p>Occur when the eye cannot focus light properly on the retina.</p>
<table>
<tr><th>Condition</th><th>Description</th><th>Cause</th><th>Management</th></tr>
<tr><td>Myopia (short-sightedness)</td><td>Can see near objects clearly; distant objects blurry</td><td>Eyeball too long or cornea too curved; light focuses in front of retina</td><td>Concave (diverging) lenses</td></tr>
<tr><td>Hyperopia (long-sightedness)</td><td>Can see distant objects clearly; near objects blurry</td><td>Eyeball too short or cornea too flat; light focuses behind retina</td><td>Convex (converging) lenses</td></tr>
<tr><td>Astigmatism</td><td>Blurry or distorted vision at all distances</td><td>Irregular curvature of cornea or lens</td><td>Cylindrical lenses</td></tr>
<tr><td>Presbyopia</td><td>Difficulty reading/near vision (age-related)</td><td>Reduced lens elasticity, usually after age 40</td><td>Reading glasses (convex lenses)</td></tr>
</table>

<h4>Cataracts</h4>
<p>Clouding of the crystalline lens causing progressive painless visual loss. Most common cause of preventable blindness globally.</p>
<p><strong>Risk factors:</strong> Ageing (most common), UV exposure, diabetes, smoking, trauma, steroids, congenital (rubella infection)</p>
<p><strong>Signs:</strong> Gradual painless blurring, glare/halos around lights, faded colours, "white pupil" (leukocoria) in advanced cases</p>
<p><strong>Treatment:</strong> Surgical removal and intraocular lens implant (cataract surgery) - most performed surgery globally</p>

<h4>Glaucoma</h4>
<p>A group of eye conditions causing progressive optic nerve damage, usually associated with elevated intraocular pressure (IOP). Second leading cause of blindness globally; often called the "silent thief of sight."</p>
<p><strong>Types:</strong></p>
<ul>
<li><strong>Open-angle glaucoma (chronic):</strong> Most common; gradual painless peripheral vision loss; IOP elevated due to reduced drainage of aqueous humour through trabecular meshwork</li>
<li><strong>Angle-closure glaucoma (acute):</strong> Sudden blockage of aqueous drainage; sudden severe eye pain, headache, nausea, vomiting, red eye, halos, vision loss - EMERGENCY</li>
</ul>
<p><strong>Risk factors:</strong> Age above 60, family history, African descent (higher risk of primary open-angle glaucoma), high IOP, myopia, diabetes</p>
<p><strong>Management:</strong> Eye drops (reduce IOP), laser therapy, surgery. Once vision is lost, it cannot be recovered - early detection is crucial.</p>

<h4>Conjunctivitis</h4>
<p>Inflammation of the conjunctiva - most common eye problem worldwide.</p>
<p><strong>Types:</strong></p>
<ul>
<li><strong>Viral:</strong> Most common; watery discharge; highly contagious; usually self-limiting</li>
<li><strong>Bacterial:</strong> Yellow-green purulent discharge; matting of eyelids; treated with antibiotic drops</li>
<li><strong>Allergic:</strong> Intense itching, watery discharge; bilateral; antihistamine drops</li>
</ul>
<p><strong>Gonococcal conjunctivitis:</strong> Neonatal eye infection from Neisseria gonorrhoeae during birth - can cause blindness; prevented by erythromycin eye drops at birth (ophthalmia neonatorum prophylaxis)</p>

<h4>Trachoma</h4>
<p>Infectious eye disease caused by Chlamydia trachomatis; leading infectious cause of blindness globally; common in poor communities with inadequate water and sanitation.</p>
<p><strong>Transmission:</strong> Contact with eye/nose discharge; spread by flies; poor hygiene</p>
<p><strong>Signs:</strong> Initially conjunctivitis; repeated infections cause scarring of upper eyelid; inversion of eyelid (entropion); eyelashes rub cornea (trichiasis); corneal scarring and blindness</p>
<p><strong>SAFE strategy (WHO):</strong> Surgery (for trichiasis), Antibiotics (azithromycin), Facial cleanliness, Environmental improvement (water and sanitation)</p>

<h4>Vitamin A Deficiency and Vision</h4>
<p>Vitamin A (retinol) is essential for production of rhodopsin (visual pigment in rods).</p>
<ul>
<li><strong>Night blindness (nyctalopia):</strong> Earliest sign; inability to see in dim light</li>
<li><strong>Xerophthalmia:</strong> Dry eyes, Bitot spots (foamy white patches on conjunctiva), corneal ulceration, keratomalacia (corneal melting) - can cause permanent blindness</li>
<li><strong>Prevention:</strong> Adequate dietary vitamin A (liver, eggs, dairy, orange/yellow fruits and vegetables, dark green leafy vegetables); vitamin A supplementation in children in deficient areas</li>
</ul>

<h3>15.2 The Ear</h3>

<h4>15.2.1 Structure of the Ear</h4>

<p><strong>Outer Ear:</strong></p>
<ul>
<li><strong>Pinna (auricle):</strong> Outer visible part; collects and directs sound waves into ear canal</li>
<li><strong>External auditory canal (meatus):</strong> Canal leading to eardrum; lined with skin containing ceruminous (wax) glands that produce cerumen (earwax) to protect and clean the canal</li>
<li><strong>Tympanic membrane (eardrum):</strong> Thin membrane separating outer and middle ear; vibrates in response to sound waves</li>
</ul>

<p><strong>Middle Ear:</strong></p>
<ul>
<li><strong>Ossicles (3 smallest bones in the body):</strong> Malleus (hammer), Incus (anvil), Stapes (stirrup) - amplify vibrations from eardrum to inner ear (20-fold amplification)</li>
<li><strong>Eustachian tube:</strong> Connects middle ear to nasopharynx; equalizes air pressure on both sides of eardrum; allows mucus drainage</li>
</ul>

<p><strong>Inner Ear:</strong></p>
<ul>
<li><strong>Cochlea:</strong> Snail-shaped structure filled with fluid; contains the organ of Corti with hair cells that convert vibrations to electrical signals (hearing)</li>
<li><strong>Semicircular canals:</strong> Three fluid-filled loops oriented in different planes; detect rotational movements; part of vestibular system (balance)</li>
<li><strong>Vestibule:</strong> Contains utricle and saccule; detects linear acceleration and gravity (balance)</li>
<li><strong>Vestibulocochlear nerve (CN VIII):</strong> Transmits sound and balance information to brain</li>
</ul>

<h4>15.2.2 Common Ear Conditions</h4>

<h4>Types of Hearing Loss</h4>
<ul>
<li><strong>Conductive hearing loss:</strong> Problem in outer or middle ear preventing sound conduction (e.g., earwax impaction, otitis media, perforated eardrum, ossicular damage)</li>
<li><strong>Sensorineural hearing loss:</strong> Damage to inner ear (cochlea/hair cells) or auditory nerve (e.g., noise-induced, age-related, congenital)</li>
<li><strong>Mixed hearing loss:</strong> Both conductive and sensorineural components</li>
</ul>

<h4>Otitis Media (Middle Ear Infection)</h4>
<p>Inflammation of the middle ear; most common in children under 5.</p>
<p><strong>Causes:</strong> Bacterial (Streptococcus pneumoniae, H. influenzae) or viral; often follows upper respiratory tract infection; dysfunction of Eustachian tube</p>
<p><strong>Signs:</strong> Ear pain (otalgia), fever, irritability in children, hearing loss; bulging red eardrum; may rupture (otorrhoea - ear discharge)</p>
<p><strong>Treatment:</strong> Most resolve spontaneously; antibiotics for severe or prolonged cases; analgesics for pain</p>
<p><strong>Complications:</strong> Chronic otitis media with effusion (glue ear), persistent hearing loss, mastoiditis</p>

<h4>Noise-Induced Hearing Loss (NIHL)</h4>
<p>Preventable damage to cochlear hair cells caused by excessive noise exposure. Unlike most hearing loss, it is entirely preventable.</p>
<p><strong>Causes:</strong> Occupational noise, recreational noise (loud music, concerts), impulse noise (gunshots, explosions)</p>
<p><strong>Characteristics:</strong> Bilateral, sensorineural, permanent; initially affects high-frequency sounds (4 kHz notch); associated with tinnitus (ringing)</p>
<p><strong>Prevention:</strong> Reduce noise levels at source, engineering controls, hearing protection devices (earplugs/earmuffs), limit listening time/volume for personal audio devices, regular hearing tests for exposed workers</p>

<h4>Cerumen (Earwax) Impaction</h4>
<p>Excessive buildup of earwax blocking the ear canal, causing conductive hearing loss, tinnitus, earache.</p>
<p><strong>Management:</strong> Ear syringing/irrigation with warm water; softening drops (olive oil, sodium bicarbonate); suction removal</p>
<p><strong>Prevention:</strong> Do NOT insert objects (cotton swabs, keys, fingers) into ears - this pushes wax deeper and may perforate eardrum</p>

<h4>Tinnitus</h4>
<p>Perception of sound (ringing, buzzing, hissing) without external source. Can be temporary (after loud noise) or chronic. Associated with hearing loss, noise exposure, medication (aspirin, quinine), ear infections.</p>

