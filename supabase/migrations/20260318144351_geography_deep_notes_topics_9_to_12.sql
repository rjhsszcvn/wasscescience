## 8. Coastal Management

| Strategy | Description | Advantages | Disadvantages |
|----------|-------------|-----------|---------------|
| **Sea wall** | Concrete/rock wall at cliff base | Strong protection | Expensive; reflects waves causing erosion below; unnatural |
| **Rip-rap (rock armour)** | Large boulders piled at cliff base | Cheaper than sea wall; absorbs wave energy | Not aesthetic; can still fail |
| **Groynes** | Wooden/concrete barriers built perpendicular to beach | Traps beach sediment; maintains beach width | Can cause erosion further along the coast |
| **Beach nourishment** | Pumping sand onto an eroding beach | Maintains natural beach; attractive | Expensive; temporary (needs repeating) |
| **Managed retreat** | Allowing the sea to flood low-value land | Cheapest option; creates natural habitats | Loss of land; displaced communities |

