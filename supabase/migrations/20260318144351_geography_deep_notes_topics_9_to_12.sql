## 7. West African Coastal Features

**The West African coastline:**
- Long sandy beaches — formed by deposition of sediment from rivers (Niger, Volta) and longshore drift.
- **Coastal lagoons:** Very common — formed behind sand bars. E.g., Songor Lagoon, Keta Lagoon (Ghana); Lagos Lagoon (Nigeria).
- **Mangrove swamps:** In river estuaries and sheltered coasts — mangroves (salt-tolerant trees) trap sediment and protect the coast.
- **Cliffs:** Less common — where hard rock exists (e.g., cliffs near Cape Three Points, Ghana).

### Coastal Erosion in Ghana (Case Study — Keta):

- **Keta** (Volta Region, Ghana) is one of West Africa's worst coastal erosion hotspots.
- The town has been losing significant land to the sea for decades.
- **Causes:** Wave erosion (strong destructive waves), Longshore drift removing beach sediment, Reduction in sediment supply after Akosombo Dam was built (dam traps sediment before it reaches the coast), human settlement too close to the shore.
- **Consequences:** Homes, schools, and farmland destroyed; displacement of communities; saltwater intrusion into farmland.
- **Response:** Ghana built a sea wall (Keta Sea Defence Project) — concrete barriers to protect the coast. Helped to protect some areas but is expensive and disrupts natural coastal processes.

