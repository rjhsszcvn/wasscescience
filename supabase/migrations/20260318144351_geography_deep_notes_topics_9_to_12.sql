## 3. Desertification

**Definition:** Desertification is the process by which fertile land becomes desert or semi-desert, due to drought, deforestation, and inappropriate agricultural practices.

**Location:** Mainly affecting the Sahel zone of West Africa (northern Mali, Niger, Burkina Faso, northern Nigeria, northern Senegal, northern Ghana).

