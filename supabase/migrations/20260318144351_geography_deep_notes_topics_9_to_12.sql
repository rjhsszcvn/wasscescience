## 2. Deforestation

**Definition:** Deforestation is the permanent removal of trees and forests to make the land available for other uses.

**Causes in West Africa:**
- Logging (commercial timber extraction).
- Clearing land for agriculture (slash and burn).
- Fuelwood collection (most rural households depend on wood for cooking).
- Charcoal production.
- Urban and infrastructure expansion.
- Mining (clearing forest above mineral deposits).

**Consequences:**

| Environmental | Economic/Social |
|---------------|----------------|
| Soil erosion — exposed soil is washed away by heavy rain | Loss of timber — future economic value destroyed |
| Flooding — less interception, more runoff | Loss of forest-based livelihoods for local communities |
