- **Deforestation** — removing trees exposes soil to wind and rain erosion.
- **Population pressure** — growing populations force farmers onto marginal, vulnerable land.

**Effects:**
- Crop failure and famine.
- Loss of livelihood for pastoralists (nomadic herders).
- Forced migration of communities.
- Loss of biodiversity.
- Sand dunes advancing southward, burying villages and farmland.

**Case Study — The Sahel Drought:**
- The Sahel experienced devastating droughts in 1968–73 and 1984–85.
