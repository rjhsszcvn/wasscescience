## Summary

- Waves erode coasts by hydraulic action, abrasion, attrition, and solution.
- Erosional features: cliffs, wave-cut platforms, caves, arches, stacks, stumps, headlands.
- Destructive waves erode; constructive waves deposit.
- Longshore drift moves sediment along the coast.
- Depositional features: beaches, spits, bars, lagoons.
- West Africa's coast has sandy beaches, lagoons, mangrove swamps, and river deltas.
- Keta (Ghana) is a major example of coastal erosion threatening a community.
- Coastal management includes sea walls, groynes, beach nourishment, and managed retreat.
