## 1. Introduction

**Coasts** are where the land meets the sea. They are dynamic zones, constantly changing due to the action of waves, tides, currents, and human activity.

West Africa has approximately 6,000 km of coastline — home to major cities, ports, fishing communities, and tourist areas.

---

## 2. Waves

**Definition:** Waves are oscillations of water at the sea surface caused by wind blowing over the sea.

**Parts of a wave:**
- **Crest:** The highest point.
- **Trough:** The lowest point.
- **Wave height:** Vertical distance from crest to trough.
- **Wavelength:** Horizontal distance between successive crests.
- **Wave frequency:** Number of waves per minute.

**Wave energy** is determined by:
- Wind speed.
- Duration the wind has been blowing.
- Fetch (the distance of open water over which wind blows — longer fetch = more powerful waves).

### Types of Waves:

**Constructive waves (swell waves):**
- Long wavelength, low frequency (6–8 per minute).
- Strong **swash** (water rushing up the beach) and weak **backwash** (water retreating).
- Build up beaches (deposition is dominant).
- Typical of sheltered bays and beaches.

**Destructive waves (storm waves):**
- Short wavelength, high frequency (10–14 per minute).
- Weak swash and strong backwash.
- Erode coastlines (erosion is dominant).
- Associated with storms; produce dramatic coastal erosion.

---

## 3. Coastal Erosion

### Processes of Coastal Erosion:

| Process | How it works |
|---------|-------------|
| **Hydraulic action** | Waves crash against cliffs; trapped air is compressed in cracks with tremendous force, eventually shattering the rock |
| **Abrasion (corrasion)** | Waves armed with rocks and pebbles grind and scrape away the cliff face (like sandpaper) |
| **Attrition** | Fragments of rock carried by waves collide with each other, breaking into smaller, rounder pieces |
| **Solution (corrosion)** | Seawater dissolves soluble minerals in the rock (especially limestone) |

### Factors Affecting the Rate of Coastal Erosion:

- **Rock hardness:** Soft rocks (clay, sandstone) erode faster; hard rocks (granite, basalt) resist erosion.
- **Rock structure:** Rocks with many joints, faults, and bedding planes erode faster.
- **Fetch:** Long fetch = more powerful waves = more erosion.
- **Wave frequency and height.**
- **Beach width:** Wide beaches absorb wave energy and protect cliffs.
- **Human interference:** Removing beach sediment, building sea walls.

---

## 4. Erosional Coastal Landforms

### A. Cliffs

- Formed where hard rock meets the sea.
- Waves undercut the cliff at the base → a **wave-cut notch** develops.
- As the notch deepens, the overhanging rock above becomes unstable and collapses.
- The cliff retreats landward, leaving behind a flat, gently sloping **wave-cut platform** (exposed at low tide).

### B. Caves

- Waves attack weaknesses (joints, faults) in the cliff face.
- Hydraulic action and abrasion enlarge the crack into a **cave**.

### C. Arch

- If caves on opposite sides of a headland (a piece of land jutting into the sea) meet, they form an **arch**.
- Water flows through the arch.

### D. Stack

- The roof of the arch eventually collapses.
- The seaward pillar of rock is left isolated — this is a **stack**.

### E. Stump

- The stack is eroded at its base and eventually collapses to form a low **stump**.

### Sequence: Cliff → Cave → Arch → Stack → Stump

*This is a classic sequence of coastal erosion that WAEC regularly examines.*

### F. Headlands and Bays

- **Differential erosion** occurs where rocks of different hardness alternate along a coastline.
- Soft rock is eroded faster → **bays** (curved inlets).
- Hard rock resists erosion → **headlands** (points of land jutting into the sea).
- Waves are concentrated (refracted) around headlands → more erosion.
- Waves spread out in bays → less energy → deposition occurs.

---

## 5. Coastal Transportation

Material (sediment) is moved along the coast by **longshore drift**:

1. Waves approach the shore at an angle (driven by prevailing wind direction).
2. **Swash** pushes material up the beach at an angle.
3. **Backwash** pulls material straight back down the beach (perpendicular to shore) under gravity.
4. Material zigzags along the coast in the direction of the prevailing wind.

**Longshore drift** is responsible for building many depositional landforms.

---

## 6. Coastal Deposition and Depositional Landforms

Deposition occurs when waves lose energy and drop their sediment load. This happens:
- In sheltered bays.
- Where the coast turns direction (change in orientation).
- Where longshore drift sediment accumulates.

### A. Beach

- **Definition:** An accumulation of sand, shingle, or pebbles along the shore.
- Sandy beaches: fine material, gentle gradient.
- Shingle beaches: coarser material, steeper gradient.
- **Most important depositional feature in West Africa:** Fine sandy beaches along the Gulf of Guinea coast (e.g., Labadi Beach, Accra; beaches along the Ghanaian coast).

### B. Spit

- A narrow ridge of sand or shingle that extends from the shore into the sea.
- Formed where longshore drift continues past a sudden change in the direction of the coastline (e.g., at a river mouth or bay entrance).
- The spit grows in the direction of longshore drift.
- The end of the spit may curve (recurved spit) due to secondary waves from another direction.
- A **lagoon** (calm, sheltered water) forms behind the spit.
- **Example:** Keta Lagoon spit (Ghana) along the Volta estuary.

### C. Bar (Barrier Beach / Barrier Bar)

- A ridge of sand stretching completely across a bay, connecting two headlands.
- Forms when a spit grows until it reaches the other side of the bay.
- Creates a **lagoon** behind it.
- **Example:** Many coastal lagoons along the West African coast are sealed behind barrier bars.

### D. Tombolo

- A spit that connects an island to the mainland.

### E. Sand Dunes

- Wind-blown sand accumulates above the high tide mark.
- Vegetation (marram grass) traps sand → dunes grow.
- Can be found along West African beaches.

