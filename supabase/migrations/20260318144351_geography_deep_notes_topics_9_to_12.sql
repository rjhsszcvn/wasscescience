## 6. Inselbergs and Bornhardts

**Inselberg** ("island mountain" in German) — an isolated, steep-sided rocky hill rising abruptly from a flat surrounding plain.

**Bornhardt** — a very large, dome-shaped inselberg of resistant granite.

**Formation:**
- Deep chemical weathering along joint lines in granite rock.
- The more resistant, unjointed core of the granite survives intact.
- Surrounding weathered material (regolith) is eroded away over millions of years.
- The hard core is exposed as an inselberg.

**Examples:** Common throughout West African savanna landscapes — Wa (Ghana), Biu Plateau (Nigeria), hills in Burkina Faso.

---

## 7. The Rock Cycle

The rock cycle describes how rocks are continuously formed, broken down, and reformed over geological time:

1. **Igneous rocks** form from cooled magma (e.g., granite, basalt).
2. Igneous rocks are weathered and eroded → sediment.
3. **Sedimentary rocks** form from compressed layers of sediment (e.g., sandstone, limestone, shale).
4. Sedimentary or igneous rocks are subjected to heat and pressure → **metamorphic rocks** (e.g., marble from limestone; quartzite from sandstone; slate from shale).
5. Metamorphic rocks can melt → magma → new igneous rocks.

