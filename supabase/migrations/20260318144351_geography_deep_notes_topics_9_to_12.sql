- Planting shelter belts (rows of trees to block wind and hold soil).
- **The Great Green Wall** initiative — a plan to plant a wall of trees 8,000 km long and 15 km wide from Senegal to Djibouti across the Sahel.
- Introducing drought-resistant crop varieties.
- Reducing herd sizes.
