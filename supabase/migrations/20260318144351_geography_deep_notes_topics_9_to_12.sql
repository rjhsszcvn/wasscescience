## 1. Introduction

**Landforms** are the physical features of the Earth's surface — mountains, valleys, plains, plateaus, etc.

**Denudation** is the collective term for all processes that wear down and lower the Earth's surface. It includes:
1. **Weathering** — the breakdown of rock in situ (in place).
2. **Erosion** — the wearing away and removal of material by moving agents (water, ice, wind).
3. **Mass movement** — the downslope movement of material under gravity.

---

## 2. Weathering

**Definition:** Weathering is the breakdown and decomposition of rocks at or near the Earth's surface, without the material being transported.

There are three main types of weathering:

### A. Physical (Mechanical) Weathering

**Definition:** The physical breakdown of rock into smaller pieces WITHOUT any change in its chemical composition.

**1. Freeze-thaw (frost action):**
- Water enters cracks in rock.
- At 0°C, water freezes and expands by about 9%.
- The expansion forces the cracks apart.
- Over many cycles of freezing and thawing, the rock eventually shatters.
- **Important in:** Cold, mountainous regions; less important in West Africa.

**2. Exfoliation (onion-skin weathering):**
- Most important in hot deserts and semi-arid regions — RELEVANT TO WEST AFRICA.
- During the day, the surface of rocks heats up and expands.
- At night, the surface cools and contracts.
- The outer layers peel off in thin sheets (like peeling an onion).
- Produces rounded boulders called **inselbergs** (isolated rocky hills rising abruptly from plains) — common in West Africa's savanna (e.g., Nzulezo, the rock at Larabanga, Burkina Faso's landscapes).

**3. Pressure release (dilatation):**
- When overlying rock is removed by erosion, pressure on the rock below is reduced.
- The rock expands and fractures parallel to the surface.

**4. Salt crystallisation:**
- Water containing dissolved salts evaporates in hot, arid conditions.
- Salt crystals grow in rock pores and cracks, forcing them apart.
- Common in coastal and desert areas.

---

### B. Chemical Weathering

**Definition:** The decomposition of rock by chemical reactions that change the mineral content.

**Most effective in hot, humid tropical conditions — VERY RELEVANT TO WEST AFRICA.**

**1. Hydrolysis (the most important in the tropics):**
- Water chemically reacts with minerals in the rock.
- Feldspar (a common mineral in granite) is converted to clay minerals (kaolinite).
- Granite → deep layer of rotted, powdery rock (called "weathering mantle" or "regolith").
- The regolith in tropical West Africa can be tens of metres thick.

**2. Carbonation (Solution):**
- Carbon dioxide dissolves in rainwater to form weak **carbonic acid** (H₂CO₃).
- This acid reacts with calcium carbonate (limestone and chalk) and dissolves it.
- Creates **karst landscapes**: caves, sinkholes, stalactites, stalagmites.

**3. Oxidation:**
- Oxygen in water reacts with iron-bearing minerals in rock.
- Iron is converted to iron oxide (rust), weakening the rock.
- Produces red/orange/brown staining on rocks and soils — explains the red colour of West African laterite soils.

**4. Hydration:**
- Water molecules bond with minerals, causing them to swell and weaken the rock structure.

---

### C. Biological Weathering

**Definition:** Breakdown of rocks by living organisms.

**1. Plant roots:**
- Roots grow into cracks, widening them (physical action).
- Roots release chemicals that dissolve rock (chemical action).

**2. Burrowing animals:**
- Earthworms, termites, and rodents break up soil and rock.

**3. Lichens and mosses:**
- Release weak acids that dissolve rock surfaces.

---

## 3. Factors Affecting Weathering

| Factor | Effect |
|--------|--------|
| **Climate** | Hot + wet → intense chemical weathering; Cold + dry → physical weathering dominates |
| **Rock type** | Some rocks are more resistant (granite > limestone > sandstone > shale) |
| **Mineral composition** | Some minerals are more easily attacked by chemicals |
| **Surface area** | Smaller, fractured rocks weather faster (more surface exposed) |
| **Slope** | Steeper slopes — weathered material removed faster; flat areas — deep weathering mantles develop |
| **Time** | Longer exposure → more weathered |

**In West Africa (hot and humid climate):** Chemical weathering dominates, especially hydrolysis. This produces deep weathering profiles (up to 50+ metres of rotted rock). The red laterite soils are largely a product of tropical chemical weathering.

---

## 4. Mass Movement

**Definition:** Mass movement is the downslope movement of weathered material (rock, soil, debris) under the influence of gravity.

**Types of mass movement:**

| Type | Speed | Water content | Description |
|------|-------|---------------|-------------|
| **Rock fall** | Very fast | None | Fragments of rock break off and fall freely from a cliff |
| **Landslide** | Fast | Some | Mass of rock/soil moves quickly along a failure surface |
| **Mudflow** | Fast | Very high | Saturated soil flows rapidly like thick liquid |
| **Earthflow** | Moderate | High | Saturated soil/clay flows more slowly downslope |
| **Soil creep** | Very slow | Moderate | Almost imperceptible gradual movement of surface soil; trees lean, walls tilt |
| **Slumping (rotational slide)** | Moderate | High | Mass of soil rotates backward along a curved failure surface |

**Triggers of mass movement:**
- Heavy rainfall (saturates soil, increasing weight and lubricating failure surface).
- Undercutting of slopes (by rivers or road cutting).
- Earthquakes.
- Removal of vegetation (roots no longer hold soil).
- Building on slopes.

**Mass movement in West Africa:**
- Heavy seasonal rainfall triggers mudflows and landslides on deforested slopes.
- **Sierra Leone Mudslide (August 2017):** A massive mudslide near Freetown killed over 1,000 people. Caused by deforestation of hillsides combined with exceptionally heavy rainfall.

