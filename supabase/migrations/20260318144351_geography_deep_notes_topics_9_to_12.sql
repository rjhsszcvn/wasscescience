### B. Railway Transport

**Advantages:**
- Efficient for carrying heavy, bulky goods (minerals, timber, agricultural produce).
- Can carry large numbers of passengers.
- Less pollution per tonne-km than road transport.

**Disadvantages:**
- High capital cost to build and maintain.
- Inflexible — only goes where tracks are laid.
- Many West African railways were built during the colonial period for export (mines to ports) — not an integrated national network.
- Many lines are now disused or in poor repair.

**Examples:**
- Ghana: Railway from Accra/Takoradi to Kumasi (built to export timber and cocoa).
- Nigeria: Lagos–Kano railway line.
