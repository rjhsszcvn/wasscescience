## 1. Transport

**Definition:** Transport refers to the movement of people, goods, and services from one place to another.

Transport is critical to economic development because it:
- Links producers with markets.
- Enables trade within and between countries.
- Allows movement of raw materials to factories.
- Encourages specialisation (each area produces what it is best at).
- Promotes regional integration.

---

## 2. Modes of Transport

### A. Road Transport

**Most important and widespread mode of transport in West Africa.**

**Advantages:**
- Flexible — can reach almost anywhere, including rural villages.
- Door-to-door delivery.
- Relatively quick for short distances.
- Low infrastructure cost compared to rail.

**Disadvantages:**
- High fuel consumption.
- Roads deteriorate quickly in tropical climate (heavy rain, heat).
- Traffic congestion in cities.
- High accident rate.
- Not suitable for very heavy or bulk goods (less efficient than rail).

**Road networks in West Africa:**
- Trans-West African Highway (Dakar to Lagos) links major cities.
- Most countries have a radial pattern — roads converge on the capital/main city.
- Rural roads are often unpaved (laterite roads) — impassable in wet season.

