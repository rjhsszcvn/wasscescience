### Introduction
In English grammar, words are classified into **eight parts of speech** based on their function in a sentence. Understanding them is essential for constructing correct sentences and for the WASSCE Grammar section.

---

### 1. Nouns
A noun names a **person, place, thing, idea, or quality**.

#### Types of Nouns

| Type | Definition | Examples |
|------|------------|---------|
| **Common noun** | General name for a class | *teacher, city, book, dog* |
| **Proper noun** | Specific name (capitalised) | *Lagos, Monday, Chinua Achebe* |
| **Concrete noun** | Can be perceived by senses | *chair, water, thunder* |
| **Abstract noun** | Idea or quality | *freedom, happiness, courage* |
| **Collective noun** | Group of things/people | *a herd of cattle, a team of players, a flock of birds* |
| **Countable noun** | Can be counted; has plural | *book/books, child/children* |
| **Uncountable noun** | Cannot be counted; no plural | *water, advice, furniture, information* |

#### Noun Functions in a Sentence
- **Subject:** *The **teacher** is absent.*
- **Object:** *She teaches **English**.*
- **Complement:** *She is a **teacher**.*
- **In apposition:** *My friend **Kofi** arrived.*

#### Common Irregular Plurals
| Singular | Plural |
|----------|--------|
| child | children |
| tooth | teeth |
| criterion | criteria |
| phenomenon | phenomena |
| syllabus | syllabi / syllabuses |
| datum | data |
| medium | media |
| analysis | analyses |

---

### 2. Pronouns
A pronoun replaces a noun to avoid repetition.

#### Types of Pronouns

| Type | Examples | Usage |
|------|----------|-------|
| **Personal** | I, you, he, she, it, we, they / me, him, her, us, them | Subject/object positions |
| **Possessive** | mine, yours, his, hers, ours, theirs | Show ownership |
| **Reflexive** | myself, yourself, himself, herself, ourselves, themselves | Refer back to subject |
| **Relative** | who, whom, whose, which, that | Introduce relative clauses |
| **Interrogative** | who, whom, whose, what, which | Ask questions |
| **Demonstrative** | this, that, these, those | Point to specific nouns |
| **Indefinite** | someone, anybody, nothing, everyone, each, neither | Non-specific reference |

#### Subject vs. Object Pronouns
- Subject: I, he, she, we, they, who — used as the **subject** of a verb
- Object: me, him, her, us, them, whom — used as the **object** of a verb or preposition

**Correct:** *It was **she** who called.* (She is subject complement)
**Correct:** *Between **him** and **me**, there are no secrets.* (Objects of preposition)
**Incorrect:** *Between **he** and **I**...*

---

### 3. Adjectives
An adjective **modifies a noun or pronoun**, answering: *What kind? Which one? How many?*

#### Types
- **Descriptive:** *tall, beautiful, ancient, intelligent*
- **Demonstrative:** *this, that, these, those*
- **Possessive:** *my, your, his, her, our, their*
- **Numeral:** *one, first, three, several*
- **Interrogative:** *which, what, whose*
- **Comparative/Superlative:** *taller/tallest, more beautiful/most beautiful*

#### Comparison Rules
| Adjective type | Comparative | Superlative |
|----------------|-------------|-------------|
| 1-syllable | add *-er* | add *-est* |
| 2-syllable (ending -y) | change y to *-ier* | change y to *-iest* |
| 2+ syllables | use *more* | use *most* |
| Irregular | good → better | good → best |

**Irregular:** good/better/best; bad/worse/worst; many/more/most; little/less/least

---

### 4. Verbs
A verb expresses an **action, state, or occurrence**. It is the most essential part of a sentence.

#### Types of Verbs

**Action verbs:** *run, write, eat, speak*
**Stative verbs (state, not action):** *know, believe, love, contain, own* — NOT used in continuous tenses
- **Incorrect:** *I am knowing the answer.*
- **Correct:** *I know the answer.*

**Transitive vs. Intransitive:**
- **Transitive:** Takes a direct object — *She **wrote a letter**.*
- **Intransitive:** No direct object needed — *He **slept**.*

**Auxiliary (helping) verbs:** *be, have, do, can, will, shall, may, might, must, ought to*

**Phrasal verbs (important for WASSCE):**
| Phrasal Verb | Meaning |
|--------------|---------|
| give up | abandon / stop doing |
| put off | postpone |
| look into | investigate |
| call off | cancel |
| break out | start suddenly (war, fire) |
| turn down | refuse / reject |
| bring up | raise (a child or topic) |
| set out | begin a journey / state clearly |

---

### 5. Adverbs
An adverb modifies a **verb, adjective, or another adverb**, answering: *How? When? Where? How much? How often?*

| Type | Examples |
|------|---------|
| **Manner** | quickly, carefully, well, badly |
| **Time** | yesterday, soon, still, already, yet |
| **Place** | here, there, everywhere, abroad |
| **Frequency** | always, often, sometimes, never, rarely |
| **Degree** | very, quite, too, enough, extremely |

**Position of adverbs:**
- Manner adverbs: usually **after** the verb/object — *She sang **beautifully**.*
- Frequency adverbs: usually **before** the main verb but **after** auxiliary — *She **always** sings. / She is **always** singing.*
- Never split verb and object with manner adverb:
  - **Incorrect:** *She sang beautifully the song.*
  - **Correct:** *She beautifully sang the song.* / *She sang the song beautifully.*

---

### 6. Prepositions
A preposition links a **noun/pronoun** to another word, showing relationship of time, place, direction, manner, or cause.

**Common prepositions:** *in, on, at, by, for, with, of, to, from, about, between, among, through, during, before, after, since, until, despite, regarding*

#### Collocations (prepositions fixed with certain words)
| Phrase | Correct preposition |
|--------|-------------------|
| interested **in** | interested in music |
| responsible **for** | responsible for the mistake |
| different **from** | different from what I expected |
| good **at** | good at mathematics |
| depend **on** | depends on the weather |
| congratulate **on** | congratulated him on his success |
| apologise **for** | apologised for being late |
| married **to** | married to a doctor |

---

### 7. Conjunctions
A conjunction **joins words, phrases, or clauses**.

#### Types

**Coordinating conjunctions (FANBOYS):** For, And, Nor, But, Or, Yet, So
- Join equal elements: *She sang **and** danced.*

**Subordinating conjunctions:** Introduce dependent/subordinate clauses
- Time: *when, while, before, after, since, until, as soon as*
- Cause: *because, since, as*
- Condition: *if, unless, provided that, as long as*
- Concession: *although, even though, despite the fact that, whereas*
- Result: *so that, in order that*

**Correlative conjunctions (pairs):**
- *either...or / neither...nor / both...and / not only...but also*
- **Verb agreement:** *Neither the teacher nor the students **were** ready.* (verb agrees with nearer subject)

---

### 8. Interjections
An interjection expresses strong emotion and is grammatically independent.
- *Oh! Alas! Hurray! Ouch! Wow! Indeed!*

---

### Articles: A, An, The

**Indefinite articles (a / an):**
- *a* before consonant sounds: *a book, a university (yoo sound)*
- *an* before vowel sounds: *an apple, an hour (silent h), an honest man*

**Definite article (the):**
- Specific, already known nouns: *The man I met yesterday...*
- Unique things: *the sun, the President*
- Superlatives: *the best student*
- Musical instruments: *She plays the piano*
- Before ordinals: *the first time*

**No article (zero article):**
- Proper nouns (mostly): *Ghana, Accra, Kofi*
- General plural nouns: *Books are expensive.*
- Languages: *He speaks French.*
- Meals: *We had breakfast at 7.*

---

### Common Grammar Errors (WASSCE-focused)

| Error Type | Wrong | Right |
|------------|-------|-------|
| Wrong relative pronoun | The man **which** called | The man **who** called |
| Double negative | I didn't see **nobody** | I didn't see **anybody** |
| Wrong comparative | She is more **taller** | She is **taller** |
| Dangling modifier | **Running fast**, the bus was missed | **Running fast**, **she** missed the bus |
| Misuse of "less/fewer" | **Less** books | **Fewer** books (countable) |
| Gerund vs infinitive | I enjoy **to read** | I enjoy **reading** |
| Split infinitive | to **boldly** go | to go **boldly** (avoid in formal writing) |

