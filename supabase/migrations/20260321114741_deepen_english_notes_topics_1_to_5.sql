### Cloze Tests (Gap-Fill)

WASSCE often presents a passage with numbered gaps to fill with appropriate words.

**Strategy:**
1. Read the entire passage first for overall meaning.
2. Look at the words before AND after the gap.
3. Consider part of speech (noun? verb? adjective?)
4. Check for grammar clues (article before gap suggests noun; auxiliary suggests main verb).
5. Read back with your answer inserted to confirm it makes sense.

**Types of words tested:** conjunctions, prepositions, articles, pronouns, determiners, verb forms.

