### Word Stress

Stress refers to the **syllable(s) given more force, length, and pitch** when a word is spoken.

#### Rules for Word Stress

**Two-syllable nouns and adjectives:** stress usually falls on the **first syllable**
*TAble, PEaceful, CARpet, FOrest, DOctor*

**Two-syllable verbs:** stress usually falls on the **second syllable**
*arRIVE, beGIN, rePAY, deCIDE, reFUSE*

**Noun-Verb Pairs (WASSCE favourite):**
| Noun (stress 1st) | Verb (stress 2nd) |
|------------------|------------------|
| **RE**cord | re**CORD** |
| **PER**mit | per**MIT** |
| **CON**test | con**TEST** |
| **OB**ject | ob**JECT** |
| **PRO**test | pro**TEST** |
| **REF**use | re**FUSE** |
| **IN**crease | in**CREASE** |
| **EX**port | ex**PORT** |
| **IM**port | im**PORT** |
| **IN**sult | in**SULT** |

**Words ending in -tion, -sion, -ic, -ical, -ity:** stress falls on the **syllable before** the suffix
*na**TION**, de**CI**sion, e**CON**omic, e**LEC**trical, hu**MIL**ity*

**Words ending in -tion (3+ syllables):** stress on second-to-last
*edu**CA**tion, in**FOR**mation, com**MU**nication*

---

### Intonation

Intonation is the **rise and fall of the voice** during speech.

**Rising intonation (↑):**
- Yes/no questions: *Are you coming? ↑*
- Incomplete sentences / lists (to signal more to come)
- Polite requests

**Falling intonation (↓):**
- Statements: *The train has arrived. ↓*
- Wh- questions: *Where are you going? ↓*
- Commands: *Sit down. ↓*
- Complete sentences at the end

**Rising-falling (↑↓):** Shows surprise, sarcasm, or doubt
*"Oh, **really**?" (said with disbelief)*

---

### Rhyme and Minimal Pairs

**Rhyming words** end in the same sound:
- *late / fate / great / weight* — all end in /eɪt/
- *though / low / go / know* — all end in /əʊ/

**Minimal pairs** differ by only ONE phoneme:
- *bit / bat / but / bot* — differ in vowel
- *pin / bin / tin / din / kin* — differ in initial consonant
- *cap / cab* — differ in final consonant (voicing)

**WASSCE commonly tests rhyme:** identify which words in a group rhyme with a given word.
- *"Which of these words rhymes with 'though'?"*: *go, shoe, through, cow* → **go** (/əʊ/)

---

### Consonant Clusters

Groups of consonants occurring together without a vowel between them.

**Initial clusters:** /str/ (street), /spl/ (splash), /thr/ (throw), /scr/ (scream)
**Final clusters:** /nts/ (pants), /lps/ (helps), /ndz/ (hands)

West African speakers often need to be careful not to insert a vowel between clusters (epenthesis): "street" should not be pronounced "i-treet."

---

### Features of Connected Speech

When words are spoken together in natural, fluent speech, sounds change:

**Assimilation:** A sound changes to become more like a neighbouring sound.
*"ten boys" → "tem boys"* (/n/ → /m/ before /b/)

**Elision:** A sound is dropped to make speech easier.
*"next day" → "nex day"* (the /t/ is dropped)

**Linking:** Final consonant links to initial vowel of next word.
*"an apple" → "a-napple"*

**Weak forms:** Grammatical words (a, the, and, was, to) are often reduced in connected speech.
*"a" = /ə/ not /eɪ/; "the" = /ðə/ not /ðiː/*

