### Contextual Vocabulary (WASSCE Objective Questions)

WASSCE Paper 1 includes **lexis questions** where you must choose the most appropriate word to complete a sentence:

*"The medicine quickly ______ the pain." (A) alleviated (B) exacerbated (C) provoked (D) heightened*
→ Answer: **A — alleviated** (reduced/relieved)

**Strategy:**
1. Read the complete sentence and identify the context/meaning needed.
2. Eliminate clearly wrong options.
3. Check for collocations — does the word go with the other words naturally?
4. Consider the connotation (positive/negative/neutral).

