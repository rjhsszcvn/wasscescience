### Overview
Essay writing is a core skill tested in WASSCE English Paper 2. You must demonstrate command of language, organisation, coherence, and ability to address the specific task. WASSCE essay questions are of four main types: **argumentative/discursive, narrative, descriptive,** and **expository**.

---

### Types of Essays

#### 1. Argumentative / Discursive Essay
**Purpose:** To present and defend a viewpoint, or to present both sides of an issue.

**Structure:**
- **Introduction:** State the issue clearly; give your position or indicate that you will examine both sides.
- **Body Paragraphs (3–5):** Each paragraph presents ONE main point. Use the **PEEL** structure:
  - **P**oint — State your argument
  - **E**vidence — Support with facts, examples, statistics
  - **E**xplanation — Explain how evidence supports the point
  - **L**ink — Connect back to the question / transition to next point
- **Counter-argument (if discursive):** Acknowledge and then refute the opposing view.
- **Conclusion:** Restate your position; call to action or summarise key points.

**Language Features:**
- Modal verbs: *should, must, ought to, can, will*
- Discourse markers: *Furthermore, However, On the other hand, Despite this, Consequently*
- Rhetorical questions: *"Can we truly afford to ignore this crisis?"*
- Passive voice for objectivity: *"It has been argued that..."*

**Common WASSCE Topics:**
- Examination malpractice, corruption, effects of technology, environmental degradation, brain drain, teenage pregnancy.

**Example Introduction (Argumentative):**
*"The proliferation of social media in modern society has been both a blessing and a curse. While proponents argue that it fosters connectivity and the free exchange of ideas, critics contend that it promotes moral decadence and misinformation among the youth. This essay argues that social media, if left unregulated, poses a grave threat to the moral fabric of society."*

---

#### 2. Narrative Essay
**Purpose:** To tell a story — real or imagined — with a clear sequence of events, vivid descriptions, and a meaningful conclusion.

**Structure:**
- **Introduction:** Set the scene (time, place, characters). Hook the reader.
- **Rising Action:** Build events leading to a climax.
- **Climax:** The most intense or turning-point moment.
- **Falling Action / Resolution:** How the situation is resolved.
- **Conclusion:** Reflect on the significance of the experience or lesson learned.

**Key Techniques:**
- **Show, don't tell:** Instead of "I was scared," write *"My hands trembled and a cold sweat broke over my skin."*
- **Varied sentence length:** Short sentences for drama; longer ones for description.
- **Dialogue:** Brings characters to life. Use correct speech marks and paragraph breaks for each new speaker.
- **Sensory details:** Engage sight, sound, smell, taste, and touch.
- **First person ("I")** is most common, but third person is also acceptable unless specified.

**Tenses:** Use **simple past** as the primary tense with **past perfect** for earlier events: *"By the time I arrived, they had already left."*

**Example Opening Paragraph:**
*"The morning that changed my life began like any other — the crow of the village cockerel, the aroma of my mother's porridge drifting through the compound, and the distant sound of the school bell. I could not have known, as I tied my shoelaces, that before sunset I would be standing before a decision that would define the rest of my days."*

---

#### 3. Descriptive Essay
**Purpose:** To paint a vivid picture of a person, place, object, or event using precise language and sensory details.

**Structure:** More flexible — can move spatially (left to right, near to far) or from general to specific.

**Key Techniques:**
- **Adjectives and adverbs:** Use precise, not vague, descriptors — *"a dilapidated, rust-streaked corrugated roof"* not *"a bad roof"*
- **Figurative language:** Similes, metaphors, personification enrich description.
- **Spatial organisation:** Guide the reader through a space logically.
- **Dominant impression:** Every detail should reinforce the overall atmosphere/mood.

---

#### 4. Expository Essay
**Purpose:** To explain, inform, or analyse a topic objectively. No personal opinion unless asked.

**Structure:** Similar to argumentative but without taking a side. Uses clear, factual language.

**Signal phrases:** *"This means that...", "For example...", "As a result...", "In other words..."*

---

### General Essay Writing Tips

#### Planning (5 minutes)
Before writing, brainstorm and create a quick outline. A well-planned essay is more coherent than one written spontaneously.

#### Introduction Writing
Your introduction must:
1. Attract the reader's attention (rhetorical question, startling fact, relevant quotation, bold statement)
2. Provide context/background
3. State your thesis (main argument or purpose)

**Avoid:** Starting with "In this essay I will..." (too mechanical for WASSCE)

#### Paragraphing
- Each paragraph = one main idea
- Start with a **topic sentence** that introduces the paragraph's idea
- Develop with examples and explanation
- End with a **concluding/linking sentence**
- Aim for **3–5 body paragraphs**

#### Conclusion Writing
- Restate thesis in different words (do NOT copy)
- Summarise key points briefly
- End with a memorable final thought, recommendation, or call to action
- **Never introduce new arguments in the conclusion**

#### Language and Style
- **Vary sentence structures:** Mix simple, compound, and complex sentences.
- **Avoid repetition:** Use synonyms and pronouns.
- **Active voice** is more direct and powerful (generally preferred).
- **Formal register:** Avoid slang, contractions (*don't → do not*), and colloquialisms.
- **Transition words** create flow: *Furthermore, Nevertheless, Consequently, In addition, By contrast*.

#### Common Errors to Avoid
| Error | Incorrect | Correct |
|-------|-----------|---------|
| Run-on sentence | *I went to school it was raining* | *I went to school, but it was raining* |
| Sentence fragment | *Running fast down the road.* | *She was running fast down the road.* |
| Tense inconsistency | *He walked in and says hello* | *He walked in and said hello* |
| Wrong preposition | *I am interested on music* | *I am interested in music* |
| Subject-verb disagreement | *The children was playing* | *The children were playing* |

#### WASSCE Marking Criteria
Essays are marked on:
1. **Content (10 marks):** Relevance, depth, quality of ideas
2. **Organisation (10 marks):** Structure, paragraphing, coherence, logical flow
3. **Expression (10 marks):** Grammar, vocabulary, sentence variety, register
4. **Mechanical Accuracy (10 marks):** Spelling, punctuation, capitalisation

**Total: 40 marks per essay**

---

### Sample Essay Plan
**Question:** *"Social media has done more harm than good. Discuss."*

**Outline:**
- **Intro:** Define social media; acknowledge debate; state position (more harm)
- **Para 1:** Cyberbullying and mental health problems
- **Para 2:** Spread of misinformation and fake news
- **Para 3:** Addiction and reduced productivity
- **Counter:** Social media enables communication and business (but outweighed)
- **Conclusion:** Net effect is harmful; call for regulation and digital literacy

