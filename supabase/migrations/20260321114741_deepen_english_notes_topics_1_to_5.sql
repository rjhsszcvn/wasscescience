### Overview
The Comprehension section in WASSCE tests your ability to read and understand an unseen passage and answer questions demonstrating literal understanding, inference, interpretation, and vocabulary in context. It is worth significant marks in Paper 1.

---

### The SQ3R Reading Method

| Step | What to do |
|------|-----------|
| **S — Survey** | Skim the passage, headings, and questions first (2–3 mins) |
| **Q — Question** | Turn headings into questions you will look for answers to |
| **R — Read** | Read carefully with purpose; underline key ideas |
| **R — Recall** | After reading, recall main ideas in your own words |
| **R — Review** | Check your answers against the passage |

---

### Types of Comprehension Questions

#### 1. Literal/Direct Questions
The answer is **directly stated** in the passage.
**Strategy:** Locate the relevant paragraph, find the exact information, and rephrase it in your own words unless asked to quote directly.

**Key instruction words:**
- *"According to the passage..."* — Find the information directly in the text.
- *"What does the writer say about...?"* — Retrieve stated facts.

#### 2. Inferential Questions
The answer is **implied but not directly stated**. You must read between the lines.
**Strategy:** Find the relevant section; use context clues, tone, and surrounding information to deduce the answer.

**Signal words:** *"What does the writer suggest/imply/indicate?"*

**Example:** If a passage says *"The classroom had cracked walls, torn books, and children sitting on the floor,"* a question might ask: *"What can you infer about the school's conditions?"* — Answer: The school is poorly resourced / in a state of neglect.

#### 3. Vocabulary-in-Context Questions
You are asked what a word or phrase **means as used in the passage** (not its general dictionary definition).
**Strategy:** Read the sentence and surrounding sentences carefully; substitute options to find which fits the context best.

**Common instruction:** *"As used in paragraph 3, the word '...' most nearly means..."*

**Useful approach:** Replace the word with your candidate meaning and re-read the sentence — does it make sense in context?

#### 4. Summary / Reduction Questions
Identify and **restate the main points** of a section in your own words, concisely.

#### 5. Tone and Attitude Questions
Identify the **writer's attitude** toward the subject.

**Common tone words:**

| Positive tones | Negative tones | Neutral tones |
|---------------|----------------|---------------|
| admiring, enthusiastic, optimistic, appreciative | critical, sarcastic, bitter, pessimistic, cynical | objective, matter-of-fact, analytical, detached |

---

### Answering Comprehension Questions — Rules

#### Rule 1: Answer in Complete Sentences
Unless the question specifically says "Write in note form," always write complete grammatical sentences.
- **Wrong:** *Lack of discipline.*
- **Right:** *The writer argues that the major cause of failure in schools is the lack of discipline.*

#### Rule 2: Answer in Your Own Words
Unless asked to *"use words from the passage"*, paraphrase. Direct copying may score zero.

#### Rule 3: Match the Length to the Marks
- 1-mark questions: 1–2 sentences
- 2-mark questions: 2–4 sentences (1 point per mark, or 2 well-developed points)

#### Rule 4: Use Evidence from the Passage
For inferential and interpretive questions, support your answer by referring to what the passage says, even if paraphrasing.

#### Rule 5: Answer What Is Asked
Read each question carefully. If asked for **two reasons**, give exactly two. If asked for **one example**, do not list three.

---

### Dealing with Difficult Vocabulary

When you encounter an unknown word:
1. **Break it down** — look for prefixes/suffixes/root words
   - *"in-" (not) + "evit-" (avoid) + "-able"* → *inevitable* = unavoidable
2. **Use context** — What do surrounding sentences tell you?
3. **Use contrast** — *"Unlike the calm centre, the periphery was chaotic"* → *periphery* = outer edge
4. **Use synonyms** — Sometimes the passage restates an idea in simpler words

---

### Useful Vocabulary for Answering Comprehension Questions
- *"The writer suggests / implies / argues / emphasises / indicates / highlights..."*
- *"According to the passage..."*
- *"In the context of the passage, '...' means..."*
- *"The writer's tone is... because..."*
- *"The effect of this is to..."*
- *"This suggests that the writer believes / feels / is concerned about..."*

---

### Reading Strategies for Different Passage Types

#### Argumentative Passages
- Identify the **thesis** (main argument)
- Identify **supporting points** and **counter-arguments**
- Note **concession words**: *although, however, despite, while, even though*

#### Narrative/Descriptive Passages
- Track the sequence of events
- Note **characterisation** and **mood**
- Understand the **narrative perspective** (first person = "I"; third person = "he/she/they")

#### Expository Passages
- Identify **definitions**, **facts**, and **examples**
- Look for **cause-and-effect** and **problem-solution** structures

---

### Common Comprehension Question Traps
1. **Half-right answers:** The answer contains part of the truth but misses the key point.
2. **Too literal:** Copying directly when paraphrasing is required.
3. **Out of scope:** Adding information not in the passage.
4. **Wrong question answered:** Happens when you don't read questions carefully.

---

### Practice Framework for Comprehension

**When practising, time yourself:**
- Read the passage: 5–7 minutes
- Answer questions: 20–25 minutes
- Review: 5 minutes

Always ask yourself:
- *What is the main idea of this passage?*
- *What is the writer's purpose?*
- *Who is the intended audience?*
- *What is the writer's tone/attitude?*
- *What evidence supports each point?*

