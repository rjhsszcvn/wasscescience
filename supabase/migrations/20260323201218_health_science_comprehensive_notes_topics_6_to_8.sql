<h3>6.4 Fertilization and Pregnancy</h3>
<p><strong>Fertilization:</strong> Union of sperm and egg in the ampulla (outer one-third) of the fallopian tube to form a zygote. Only one sperm penetrates the egg; the zona reaction prevents polyspermy.</p>

<p><strong>Stages of Development:</strong></p>
<ul>
<li><strong>Zygote:</strong> Fertilized egg (days 1-3)</li>
<li><strong>Cleavage:</strong> Rapid cell division as zygote travels towards uterus</li>
<li><strong>Morula:</strong> Solid ball of cells (day 4)</li>
<li><strong>Blastocyst:</strong> Hollow ball of cells (day 5-6)</li>
<li><strong>Implantation:</strong> Blastocyst embeds in endometrium (days 6-10)</li>
<li><strong>Embryo:</strong> Weeks 3-8; major organ systems develop</li>
<li><strong>Foetus:</strong> From week 9 to birth; growth and maturation of organs</li>
</ul>

<p><strong>Duration of pregnancy:</strong> 40 weeks (280 days) from last menstrual period (LMP); divided into three trimesters.</p>

<p><strong>Signs of Pregnancy:</strong> Missed period (amenorrhoea), nausea and vomiting ("morning sickness"), breast tenderness, frequent urination, fatigue, positive pregnancy test (hCG hormone)</p>

