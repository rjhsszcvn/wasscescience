<h3>6.7 Maternal and Child Health</h3>
<h4>Antenatal Care (ANC)</h4>
<p>Regular check-ups during pregnancy to monitor mother and foetal health. WHO recommends a minimum of 8 ANC contacts.</p>
<p><strong>Components:</strong> Blood pressure monitoring, weight and height measurement, fundal height assessment, foetal heart rate, urine testing (protein, glucose), blood tests (Hb, blood group, HIV, syphilis), tetanus toxoid vaccination, iron/folic acid supplementation, health education</p>

<h4>Danger Signs in Pregnancy</h4>
<ul>
<li>Vaginal bleeding</li>
<li>Severe headache with visual disturbances (pre-eclampsia)</li>
<li>Swelling of face, hands, feet (oedema)</li>
<li>Reduced foetal movements</li>
<li>Fever</li>
<li>Difficulty breathing</li>
</ul>

