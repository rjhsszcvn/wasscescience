<h3>7.5 The Respiratory System</h3>
<p>Responsible for gas exchange (oxygen intake, carbon dioxide removal).</p>

<p><strong>Pathway of Air:</strong> Nose/Mouth - Pharynx - Larynx - Trachea - Bronchi - Bronchioles - Alveoli</p>

<p><strong>Structures:</strong></p>
<ul>
<li><strong>Nose:</strong> Filters (mucus and cilia), warms, and humidifies air</li>
<li><strong>Trachea:</strong> Reinforced by C-shaped cartilage rings to prevent collapse</li>
<li><strong>Alveoli:</strong> Tiny air sacs; site of gas exchange; surrounded by capillaries; large surface area (70 m2 in adults)</li>
<li><strong>Diaphragm:</strong> Dome-shaped muscle below lungs; main muscle of inspiration</li>
<li><strong>Pleura:</strong> Double membrane surrounding lungs; reduces friction during breathing</li>
</ul>

<p><strong>Breathing Mechanism:</strong></p>
<ul>
<li><strong>Inspiration (inhalation):</strong> Diaphragm contracts (flattens) + external intercostal muscles contract - thoracic volume increases - pressure decreases - air flows in</li>
<li><strong>Expiration (exhalation):</strong> Diaphragm relaxes + internal intercostal muscles contract - thoracic volume decreases - pressure increases - air flows out</li>
</ul>

<h3>7.6 The Digestive System</h3>
<p>Breaks down food into absorbable nutrients and eliminates waste.</p>

<p><strong>Pathway of Food:</strong> Mouth - Oesophagus - Stomach - Small intestine (duodenum, jejunum, ileum) - Large intestine (colon) - Rectum - Anus</p>

<p><strong>Digestive Processes:</strong></p>
<ul>
<li><strong>Ingestion:</strong> Taking food into the mouth</li>
<li><strong>Mechanical digestion:</strong> Physical breakdown (chewing, churning in stomach)</li>
<li><strong>Chemical digestion:</strong> Enzyme breakdown of large molecules</li>
<li><strong>Absorption:</strong> Nutrients absorbed in small intestine (villi and microvilli increase surface area)</li>
<li><strong>Egestion:</strong> Elimination of undigested waste (faeces)</li>
</ul>

