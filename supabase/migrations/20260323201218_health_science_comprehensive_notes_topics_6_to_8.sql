<h3>7.1 Overview</h3>
<p>The human body is organized into organ systems that work together to maintain homeostasis (a stable internal environment). There are 11 major organ systems.</p>

<h3>7.2 The Skeletal System</h3>
<p>The adult human skeleton has 206 bones, divided into the axial skeleton (80 bones: skull, vertebral column, rib cage) and appendicular skeleton (126 bones: limbs and girdles).</p>

<p><strong>Functions of the Skeletal System:</strong></p>
<ul>
<li>Support: Framework for the body</li>
<li>Protection: Skull protects brain; rib cage protects heart/lungs; vertebral column protects spinal cord</li>
<li>Movement: Bones act as levers for muscle attachment</li>
<li>Mineral storage: Calcium and phosphorus stored in bones</li>
<li>Blood cell production: Red bone marrow produces red blood cells, white blood cells, and platelets (haematopoiesis)</li>
</ul>

<p><strong>Types of Joints:</strong></p>
<ul>
<li><strong>Fixed (fibrous/synostosis):</strong> No movement (e.g., skull sutures)</li>
<li><strong>Slightly moveable (cartilaginous):</strong> Limited movement (e.g., intervertebral discs)</li>
<li><strong>Freely moveable (synovial):</strong> Various movements</li>
</ul>

<p><strong>Types of Synovial Joints:</strong> Ball-and-socket (hip, shoulder - widest range), Hinge (knee, elbow - flexion/extension), Pivot (atlas-axis - rotation), Saddle (thumb), Gliding (wrist bones)</p>

<h3>7.3 The Muscular System</h3>
<p><strong>Types of Muscle:</strong></p>
<ul>
<li><strong>Skeletal (striated/voluntary):</strong> Attached to bones; under conscious control; produces movement</li>
<li><strong>Smooth (visceral/involuntary):</strong> Found in walls of hollow organs (intestines, bladder, blood vessels); under autonomic control</li>
<li><strong>Cardiac:</strong> Found only in the heart; involuntary; has intercalated discs for synchronized contraction</li>
</ul>

<p><strong>Antagonistic Muscle Action:</strong> Muscles work in pairs - when one contracts (agonist), the other relaxes (antagonist). Example: Biceps (flexion) and triceps (extension) at elbow.</p>

<h3>7.4 The Cardiovascular System</h3>
<p>Consists of the heart, blood vessels (arteries, veins, capillaries), and blood. It transports oxygen, nutrients, hormones, and waste products throughout the body.</p>

<h4>The Heart</h4>
<p>Four-chambered muscular pump: right atrium, right ventricle, left atrium, left ventricle. The septum divides right and left sides.</p>
<p><strong>Valves:</strong> Tricuspid (right AV valve), bicuspid/mitral (left AV valve), pulmonary semilunar, aortic semilunar - prevent backflow of blood.</p>

<p><strong>Double Circulation:</strong></p>
<ul>
<li><strong>Pulmonary circulation:</strong> Right heart pumps deoxygenated blood to lungs for oxygenation</li>
<li><strong>Systemic circulation:</strong> Left heart pumps oxygenated blood to all body tissues</li>
</ul>

