<h3>6.1 Definition and Importance</h3>
<p><strong>Reproductive health</strong>, as defined by the WHO, is a state of complete physical, mental, and social well-being in all matters relating to the reproductive system and to its functions and processes - not merely the absence of disease or infirmity.</p>

<p>Reproductive health means that people are able to have a satisfying and safe sex life, the capability to reproduce, and the freedom to decide if, when, and how often to do so.</p>

<h3>6.2 The Human Reproductive System</h3>

<h4>6.2.1 Male Reproductive System</h4>
<p><strong>Organs and Functions:</strong></p>
<ul>
<li><strong>Testes:</strong> Paired organs in the scrotum; produce sperm (spermatogenesis) and testosterone (male sex hormone)</li>
<li><strong>Epididymis:</strong> Coiled tube on each testis where sperm mature and are stored</li>
<li><strong>Vas deferens (ductus deferens):</strong> Muscular tube that carries sperm from the epididymis to the urethra during ejaculation</li>
<li><strong>Seminal vesicles:</strong> Glands that produce seminal fluid (fructose for sperm energy, prostaglandins)</li>
<li><strong>Prostate gland:</strong> Produces alkaline fluid that neutralizes vaginal acidity to protect sperm</li>
<li><strong>Cowper glands (bulbourethral glands):</strong> Produce pre-ejaculatory fluid to lubricate and neutralize the urethra</li>
<li><strong>Urethra:</strong> Common tube for urine and semen (cannot both flow simultaneously)</li>
<li><strong>Penis:</strong> External organ for copulation and urination; becomes erect due to blood engorgement</li>
<li><strong>Scrotum:</strong> External pouch housing testes; maintains temperature 2-3 degrees C below body temperature (optimal for spermatogenesis)</li>
</ul>

<p><strong>Spermatogenesis:</strong> Production of sperm cells in the seminiferous tubules of the testes; controlled by FSH (follicle-stimulating hormone) and testosterone; begins at puberty and continues throughout life.</p>

<h4>6.2.2 Female Reproductive System</h4>
<p><strong>Organs and Functions:</strong></p>
<ul>
<li><strong>Ovaries:</strong> Paired organs that produce eggs (oogenesis), oestrogen, and progesterone</li>
<li><strong>Fallopian tubes (uterine tubes):</strong> Tubes connecting ovaries to the uterus; site of fertilization; cilia sweep the egg towards the uterus</li>
<li><strong>Uterus (womb):</strong> Muscular pear-shaped organ where the foetus develops; endometrium (inner lining) prepares for implantation monthly</li>
<li><strong>Cervix:</strong> Lower narrow part of the uterus connecting to the vagina; produces mucus that varies with menstrual cycle</li>
<li><strong>Vagina:</strong> Muscular canal connecting cervix to external genitalia; birth canal and receives penis during copulation</li>
<li><strong>Vulva:</strong> External female genitalia (labia majora, labia minora, clitoris, vaginal opening)</li>
<li><strong>Bartholin glands:</strong> Produce lubricating fluid during sexual arousal</li>
<li><strong>Breasts:</strong> Accessory reproductive organs; contain mammary glands for milk production (lactation)</li>
</ul>

<h3>6.3 The Menstrual Cycle</h3>
<p>The menstrual cycle is a monthly series of hormonal changes that prepare the female body for potential pregnancy. Average duration: 28 days (ranges from 21-35 days).</p>

