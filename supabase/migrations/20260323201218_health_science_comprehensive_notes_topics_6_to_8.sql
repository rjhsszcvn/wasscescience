<h3>7.7 The Nervous System</h3>
<p>Controls and coordinates body functions; responds to stimuli.</p>

<p><strong>Divisions:</strong></p>
<ul>
<li><strong>Central Nervous System (CNS):</strong> Brain and spinal cord - processes information</li>
<li><strong>Peripheral Nervous System (PNS):</strong> Cranial nerves and spinal nerves - carries information to/from CNS</li>
<li><strong>Somatic nervous system:</strong> Voluntary control of skeletal muscles</li>
<li><strong>Autonomic nervous system:</strong> Involuntary control (sympathetic: fight-or-flight; parasympathetic: rest-and-digest)</li>
</ul>

<p><strong>The Neuron (Nerve Cell):</strong> Cell body (nucleus, organelles) - Dendrites (receive signals) - Axon (conducts impulse away from cell body) - Myelin sheath (speeds transmission) - Axon terminals (synapse with next neuron)</p>

<p><strong>The Reflex Arc:</strong> Receptor - Sensory neuron - Spinal cord (integration) - Motor neuron - Effector (muscle/gland). Reflex actions are automatic, rapid, and do not require conscious thought.</p>

