<h3>8.1 Definition and Principles of First Aid</h3>
<p><strong>First aid</strong> is the immediate, temporary assistance given to a person who has been injured or who is suddenly taken ill, before the arrival of professional medical help.</p>

<p><strong>The 3 Aims of First Aid (3 Ps):</strong></p>
<ul>
<li><strong>Preserve life:</strong> Keep the casualty, bystanders, and yourself alive</li>
<li><strong>Prevent deterioration:</strong> Stop the condition from getting worse</li>
<li><strong>Promote recovery:</strong> Help the casualty recover and get medical help</li>
</ul>

<p><strong>The ABC/DRABC Assessment:</strong></p>
<ul>
<li><strong>D</strong>anger - Check for danger to yourself, bystanders, and casualty</li>
<li><strong>R</strong>esponse - Check if the casualty is conscious (shout and tap shoulders)</li>
<li><strong>A</strong>irway - Open and maintain airway (head-tilt, chin-lift manoeuvre)</li>
<li><strong>B</strong>reathing - Check for breathing (look, listen, feel for 10 seconds)</li>
<li><strong>C</strong>irculation/Compressions - Begin CPR if no breathing</li>
</ul>

<h3>8.2 Cardiopulmonary Resuscitation (CPR)</h3>
<p>CPR is an emergency procedure performed when the heart stops beating (cardiac arrest) or breathing stops.</p>

<h4>Adult CPR Procedure (2020 AHA Guidelines)</h4>
<ol>
<li>Confirm unresponsiveness and call for help (or ask someone to call emergency services)</li>
<li>Position casualty on back on firm, flat surface</li>
<li>Chest compressions:
  <ul>
  <li>Place heel of one hand on centre of chest (lower half of sternum)</li>
  <li>Place other hand on top; fingers interlocked</li>
  <li>Keep arms straight; compress down at least 5 cm (2 inches)</li>
  <li>Rate: 100-120 compressions per minute</li>
  <li>Allow full chest recoil after each compression</li>
  </ul>
</li>
<li>Rescue breaths (if trained):
  <ul>
  <li>Head-tilt, chin-lift to open airway</li>
  <li>Pinch nostrils, create seal with mouth</li>
  <li>Give 2 breaths, each over 1 second</li>
  <li>Watch for chest rise</li>
  </ul>
</li>
<li>Continue cycle of 30 compressions : 2 breaths until AED available, casualty recovers, or help arrives</li>
</ol>

<p><strong>CPR ratios:</strong></p>
<ul>
<li>Adults: 30 compressions : 2 breaths</li>
<li>Children (1-8 years): 30:2 (one rescuer), 15:2 (two rescuers)</li>
<li>Infants (under 1 year): 30:2 with 2 fingers for compressions; depth 4 cm</li>
</ul>

<h3>8.3 Managing Bleeding (Haemorrhage Control)</h3>
<p><strong>Types of Bleeding:</strong></p>
<ul>
<li><strong>Arterial:</strong> Bright red blood spurts in pulses with heartbeat - most dangerous</li>
<li><strong>Venous:</strong> Dark red blood flows steadily</li>
<li><strong>Capillary:</strong> Oozes slowly; clots easily</li>
</ul>

<p><strong>Management of External Bleeding:</strong></p>
<ol>
<li>Apply direct pressure with clean cloth or bandage</li>
<li>Maintain pressure for at least 10-15 minutes without removing</li>
<li>Elevate the injured part above the level of the heart (if no fracture)</li>
<li>Apply pressure to the proximal artery (pressure point) if needed</li>
<li>Apply tourniquet only as last resort for life-threatening limb haemorrhage</li>
<li>Do NOT remove embedded objects; pack around them</li>
</ol>

<p><strong>Signs of Shock (from blood loss):</strong> Pale, cold, clammy skin; rapid weak pulse; rapid shallow breathing; dizziness; confusion; unconsciousness. Treat by: lay flat, elevate legs, keep warm, do not give food/drink, get emergency help.</p>

<h3>8.4 Fractures and Dislocations</h3>
<h4>Types of Fractures</h4>
<ul>
<li><strong>Closed (simple) fracture:</strong> Bone broken but skin intact</li>
<li><strong>Open (compound) fracture:</strong> Bone pierces through skin - higher risk of infection</li>
<li><strong>Greenstick fracture:</strong> Incomplete fracture where bone bends; common in children</li>
<li><strong>Comminuted fracture:</strong> Bone shattered into multiple fragments</li>
<li><strong>Stress fracture:</strong> Hairline crack from repeated stress</li>
</ul>

<p><strong>Signs and Symptoms of Fractures (SHARP):</strong></p>
<ul>
<li><strong>S</strong>welling at injury site</li>
<li><strong>H</strong>aemorrhage (bleeding if open)</li>
<li><strong>A</strong>bnormal deformity (unnatural angle)</li>
<li><strong>R</strong>edness and bruising</li>
<li><strong>P</strong>ain and tenderness at site</li>
</ul>
<p>Also: inability to use the limb, crepitus (grating sound)</p>

<p><strong>First Aid for Fractures:</strong></p>
<ul>
<li>Do NOT move the casualty unnecessarily</li>
<li>Immobilize the fracture using a splint (padded, extend one joint above and below fracture)</li>
<li>Cover open fractures with sterile dressing; do not push bone back</li>
<li>Elevate if possible; apply ice wrapped in cloth to reduce swelling</li>
<li>Monitor for signs of shock</li>
<li>Transport to hospital</li>
</ul>

<h3>8.5 Burns</h3>
<p><strong>Classification of Burns by Depth:</strong></p>
<ul>
<li><strong>Superficial (1st degree):</strong> Epidermis only; redness, pain, dry (e.g., sunburn)</li>
<li><strong>Partial thickness (2nd degree):</strong> Epidermis and dermis; blisters, moist, very painful</li>
<li><strong>Full thickness (3rd degree):</strong> All skin layers; leathery/charred, painless (nerve damage), requires skin grafting</li>
</ul>

<p><strong>Rule of Nines (estimating burn area in adults):</strong></p>
<ul>
<li>Head and neck: 9%</li>
<li>Each arm: 9%</li>
<li>Chest (front trunk): 18%</li>
<li>Back (posterior trunk): 18%</li>
<li>Each leg: 18%</li>
<li>Genitalia: 1%</li>
</ul>

<p><strong>First Aid for Burns:</strong></p>
<ol>
<li>Remove casualty from source of burn</li>
<li>Cool the burn with cool (not cold/icy) running water for at least 10-20 minutes</li>
<li>Remove jewellery and clothing from burned area (unless stuck)</li>
<li>Cover loosely with clean non-fluffy material (cling film or clean plastic bag)</li>
<li>Do NOT burst blisters; do NOT apply butter, toothpaste, or home remedies</li>
<li>Seek medical attention for all significant burns</li>
</ol>

<h3>8.6 Choking (Airway Obstruction)</h3>
<p><strong>Signs of Choking:</strong> Clutching throat (universal choking sign), inability to speak or cry, high-pitched noisy breathing, bluish discolouration (cyanosis), loss of consciousness if unrelieved</p>

<p><strong>Management (Heimlich Manoeuvre for adults and children over 1 year):</strong></p>
<ol>
<li>Encourage casualty to cough forcefully</li>
<li>Give 5 firm back blows between shoulder blades with heel of hand</li>
<li>If unsuccessful: 5 abdominal thrusts (Heimlich manoeuvre) - stand behind, fist below xiphisternum, pull sharply inward and upward</li>
<li>Alternate 5 back blows and 5 abdominal thrusts until obstruction relieved or casualty loses consciousness</li>
<li>If unconscious: begin CPR (compressions may dislodge obstruction)</li>
</ol>

<p><strong>For infants (under 1 year):</strong> 5 back blows + 5 chest thrusts (NOT abdominal thrusts)</p>

<h3>8.7 Poisoning</h3>
<p><strong>Routes of Poisoning:</strong> Ingestion (swallowing), inhalation (breathing in), absorption (skin/eye contact), injection</p>

<p><strong>General Management:</strong></p>
<ol>
<li>Ensure safety; remove casualty from source if inhalation</li>
<li>Call Poison Control Centre or emergency services</li>
<li>Identify the poison if possible</li>
<li>Do NOT induce vomiting unless specifically instructed (e.g., corrosive substances can cause more damage on the way back up)</li>
<li>If casualty is unconscious but breathing: place in recovery position</li>
<li>If breathing stops: begin CPR</li>
</ol>

<h3>8.8 Drowning and Near-Drowning</h3>
<p><strong>Management:</strong></p>
<ol>
<li>Rescue safely - do not endanger yourself (use a rope, lifebuoy, or extend an object)</li>
<li>Remove casualty from water</li>
<li>Begin CPR immediately if not breathing (5 initial rescue breaths, then 30:2)</li>
<li>Keep casualty warm (hypothermia risk)</li>
<li>All near-drowning victims need medical evaluation even if they appear to recover</li>
</ol>

