## 8. Land Use and Land Degradation

**Deforestation causes:**
- Loss of soil structure → erosion.
- Reduced rainfall (trees contribute to water cycle).
- Loss of biodiversity.

**Overgrazing causes:**
- Removal of vegetation cover → bare soil.
- Soil compaction → reduced infiltration, increased runoff.
- Desertification (spread of desert-like conditions).

**Soil erosion types:**
- **Sheet erosion:** Thin layer of topsoil removed across a wide area by rain.
- **Rill erosion:** Small channels cut by running water.
- **Gully erosion:** Deep gullies carved by concentrated runoff — most severe form.

