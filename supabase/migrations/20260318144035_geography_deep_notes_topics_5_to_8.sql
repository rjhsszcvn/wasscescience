## 7. River Flooding

**Causes of flooding:**
- Prolonged or very heavy rainfall.
- Snowmelt (in higher latitudes).
- Deforestation (reduces interception, increases runoff).
- Urbanisation (impermeable surfaces increase runoff).
- Building on floodplains (no natural storage).
- River overflow from tributaries.

**Effects of flooding in West Africa:**
- Loss of life and property.
- Destruction of crops and farmland.
- Spread of waterborne diseases (cholera, typhoid).
- Displacement of people.
- BUT: flooding deposits fertile alluvium on floodplains → good for farming.

**Flood management:**
- Building levées/embankments (to contain floodwater).
- Dredging rivers (to increase capacity).
- Reforestation (to reduce runoff).
- Building dams and reservoirs.
- Flood warning systems.
- Zoning laws (to prevent building on floodplains).

