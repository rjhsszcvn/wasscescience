## 1. Key Definitions

**River:** A natural flow of fresh water following a defined course (channel) from its source to its mouth.

**Drainage:** The removal of water from the land surface through rivers, streams, and groundwater.

**Drainage basin (catchment area):** The area of land drained by a river and all its tributaries. Bounded by a **watershed** (the ridge of high land separating neighbouring drainage basins).

**Tributary:** A smaller river or stream that flows into the main river.

**Confluence:** The point where two rivers join.

**Estuary:** The wide, tidal mouth of a river where it meets the sea.

**Delta:** A low-lying deposit of sediment at the mouth of a river, where the river splits into distributaries before entering the sea.

---

## 2. The Drainage Basin Hydrological Cycle

The movement of water through a drainage basin:

1. **Precipitation** — Rain or snow falls on the drainage basin.
2. **Interception** — Vegetation catches some rainfall before it reaches the ground.
3. **Surface runoff (overland flow)** — Water flows across the ground surface into streams.
4. **Infiltration** — Water soaks into the soil.
5. **Throughflow** — Water moves slowly through the soil to the river.
6. **Groundwater flow (baseflow)** — Water moves very slowly through rock to the river.
7. **Evapotranspiration** — Water evaporates from soil and transpires from plants back to the atmosphere.
8. **Channel flow** — Water flows along the river.

**Factors affecting runoff:**
- Heavy rainfall (more runoff).
- Impermeable rock or soil (more runoff, less infiltration).
- Steep slopes (faster runoff).
- Urban surfaces (concrete, tarmac) — greatly increase runoff.
- Deforestation — removes interception, increases runoff and flooding.

---

## 3. The Long Profile of a River

The **long profile** shows the change in gradient (slope) of a river from source (start) to mouth (end).

| Stage | Location | Gradient | Velocity | Width/Depth | Main Process |
|-------|----------|----------|----------|-------------|--------------|
| Upper course | Mountains/highlands | Steep | Slow (narrow, rough channel) | Narrow, shallow | Vertical erosion (downcutting) |
| Middle course | Lower hills | Moderate | Medium | Wider, deeper | Lateral erosion + deposition |
| Lower course | Lowlands/plain | Gentle | Faster (smooth, wide channel) | Very wide, deep | Deposition |

Note: Although the gradient decreases, the velocity actually increases downstream because the channel becomes smoother and wider — less friction.

---

## 4. River Processes

### A. Erosion

The wearing away and removal of material. Four types:

| Process | How it works |
|---------|-------------|
| **Hydraulic action** | The force of moving water wears away the river bank and bed |
| **Abrasion (corrasion)** | Rocks and sediment carried by the river scrape and wear away the channel |
| **Attrition** | Rocks carried by the river collide with each other, breaking into smaller, smoother pieces |
| **Solution (corrosion)** | River water dissolves soluble minerals in the rock (e.g., limestone) |

### B. Transportation

How the river carries its load. Four methods:

| Method | How it works | Type of material |
|--------|-------------|-----------------|
| **Traction** | Large boulders rolled along the bed | Very heavy material |
| **Saltation** | Smaller stones bounced along the bed | Medium-sized material |
| **Suspension** | Fine material carried within the water (makes water look muddy) | Fine sand, silt, clay |
| **Solution** | Dissolved minerals carried invisibly in the water | Soluble minerals |

### C. Deposition

When the river drops its load. Occurs when:
- The river slows down (loses energy).
- The river enters a lake, sea, or calm water.
- Flood waters spread across the floodplain.

Heaviest material is deposited first; finest material (clay, silt) is deposited last/furthest.

---

## 5. River Landforms

### Upper Course Landforms

**1. V-shaped Valley:**
- Formed by vertical erosion cutting downward.
- Interlocking spurs of rock project from alternate sides of the valley.
- Narrow valley with steep sides.

**2. Waterfall:**
- Formed where a river crosses a band of hard rock lying over soft rock.
- Soft rock is eroded faster, leaving hard rock as an overhang.
- A plunge pool forms at the base from hydraulic action and abrasion.
- The overhang eventually collapses and the waterfall retreats upstream.
- **Example:** Kintampo Falls (Ghana), Victoria Falls (Zambia/Zimbabwe).

**3. Gorge:**
- A deep, steep-sided valley left behind as a waterfall retreats.

### Middle Course Landforms

**4. Meanders:**
- Wide, sweeping bends in a river.
- Fastest water (maximum erosion) on the **outside bend** → **river cliff** (steep bank).
- Slowest water (deposition) on the **inside bend** → **slip-off slope / point bar** (gentle, sandy bank).
- Meanders migrate downstream and sideways over time.

**5. Ox-bow Lake (Cut-off):**
- When a meander becomes very tight, the river cuts through the narrow neck of land during a flood.
- The river takes the shorter, straight route.
- The abandoned meander loop becomes an **ox-bow lake**, gradually silting up.

### Lower Course Landforms

**6. Floodplain:**
- Wide, flat valley floor formed by deposition of sediment (alluvium) during floods.
- Alluvium (river silt) is very fertile — excellent for farming.
- Rivers in West Africa deposit fertile alluvium on floodplains each year.

**7. Levées:**
- Natural embankments of coarse sediment along the river banks.
- Formed when flood water spills over and loses velocity, depositing its heaviest load immediately beside the channel.
- Levées raise the channel above the surrounding floodplain.

**8. Delta:**
- Formed where a river enters the sea in a sheltered, low-energy environment.
- The river drops its load of fine sediment (silt and clay).
- The river splits into many distributaries.
- Land builds up above sea level.
- **Example:** Niger Delta (Nigeria) — one of the largest deltas in the world; important for oil production.

