## 6. Problems Facing Agriculture in West Africa

### Physical Problems:
- **Rainfall variability:** Droughts and floods destroy crops.
- **Poor soils:** Laterisation (leaching of nutrients) under heavy tropical rainfall leaves soils infertile.
- **Pests and diseases:** Locusts, stem borers, crop diseases.
- **Erosion:** Heavy rainfall on bare or cultivated soils causes severe erosion.

### Human/Economic Problems:
- **Lack of capital:** Farmers cannot afford improved seeds, fertilisers, or machinery.
- **Poor infrastructure:** Bad roads make it difficult to transport produce to market; crops rot.
- **Land tenure problems:** Communal land ownership discourages long-term investment.
- **Lack of storage facilities:** Post-harvest losses are very high due to poor storage.
- **Low market prices:** Middlemen take most of the profit from farmers.
- **Lack of education:** Many farmers use traditional methods with low yields.

