## 1. Introduction to Vegetation

**Vegetation** refers to the plant life or plant cover found in an area. It is determined primarily by:
- Climate (temperature and rainfall — the most important factors).
- Soils.
- Relief.
- Human activities (farming, logging, burning).

The natural (undisturbed) vegetation of an area is called the **natural (climax) vegetation**. When humans alter it, the result is called **derived vegetation**.

---

## 2. Vegetation Zones of West Africa

West Africa's vegetation changes in roughly parallel belts from south to north, closely following the rainfall pattern (controlled by the ITCZ).

### Zone 1: Tropical Rainforest (Equatorial Forest)

**Location:** Southern coastal areas — Liberia, Sierra Leone (south), Côte d'Ivoire (south), Ghana (south-west), and southern Nigeria.

**Climate:** Annual rainfall 1,500–4,000 mm; no dry season (or very short); temperatures 25–30°C all year.

**Characteristics:**
- Dense, multi-layered (stratified) forest:
  - **Emergent layer** (giant trees 45–60m tall poke above the canopy)
  - **Canopy layer** (main continuous layer, 25–40m) — blocks most sunlight
  - **Sub-canopy** (smaller trees, 15–25m)
  - **Shrub/understory layer** (shrubs and young trees)
  - **Ground/herb layer** (very little light reaches ground — few plants)
- Trees are tall and straight (competing for light), with **buttress roots** for support.
- Leaves are large, waxy, and dark green — drip tips allow rain to run off.
- Trees are **evergreen** (do not shed all leaves at one time — always in leaf).
- High biodiversity — thousands of species of plants, animals, insects.
- Lianas (climbing plants) and epiphytes (plants growing on other plants) are common.

**Important trees:**
- Mahogany, iroko, odum, ebony, wawa, sapele — valuable timber trees.
- Kola nut, oil palm, raffia palm.

**Soils under rainforest:**
- Leached (nutrients washed deep by heavy rain) → **laterite** soils.
- Reddish in colour (iron and aluminium oxides remain after leaching).
- Thin layer of organic matter (humus) — quickly decomposed in heat.
- Relatively infertile once forest is cleared.

---

### Zone 2: Derived Savanna / Forest-Savanna Mosaic

**Location:** Transition zone between rainforest and savanna.

**Characteristics:**
- Mixture of forest patches and grassland.
- Mostly created by human activity (burning and clearing of original forest).
- Farms, secondary vegetation, fallow land.

---

### Zone 3: Guinea Savanna (Woodland Savanna)

**Location:** Middle belt of West Africa — central Ghana, central Nigeria, parts of Côte d'Ivoire.

**Climate:** Rainfall 1,000–1,500 mm; distinct wet and dry seasons; temperatures 25–35°C.

**Characteristics:**
- Tall grasses (elephant grass, up to 3m tall) with scattered medium-sized trees.
- Trees are spaced apart (not a continuous canopy).
- Trees are **deciduous** — shed leaves in the dry season to reduce water loss.
- Trees have fire-resistant, thick, rough bark.
- Trees have deep roots to reach water in the dry season.
- Common trees: shea (karité), locust bean, acacia, baobab.

**Soils (savanna):**
- Red-brown or reddish-yellow laterite soils.
- Less leached than rainforest soils.
- Adequate fertility during the wet season.
- Prone to erosion if vegetation is removed (heavy wet season rains on bare soil in dry season).

---

### Zone 4: Sudan Savanna (Short Grass Savanna)

**Location:** Further north — northern Ghana, northern Nigeria, Mali (south), Burkina Faso.

**Climate:** Rainfall 500–1,000 mm; very long dry season (6–8 months); temperatures can be very high.

**Characteristics:**
- Shorter, sparser grasses.
- Fewer, smaller trees with wider spacing.
- Many trees are drought-adapted: acacia, baobab, shea, neem.
- Grasses turn brown and die back completely in the dry season; fresh green growth returns with rain.
- **Baobab tree:** Very distinctive — huge, water-storing trunk; loses all leaves in the dry season; sometimes called "the upside-down tree"; can live for thousands of years. Used for fruit (baobab fruit), leaves (eaten as vegetables), bark (rope, cloth).
- **Acacia tree:** Thorny; flat-topped crown; drought-resistant. Leaves are small to reduce water loss. Important for pasture and gum arabic.

---

### Zone 5: Sahel

**Location:** The narrow belt immediately south of the Sahara — northern Mali, Niger, Burkina Faso, northern Senegal, northern Nigeria (far north).

**Climate:** Rainfall under 500 mm; extremely unreliable; very long dry season; extreme heat.

**Characteristics:**
- Very sparse, thorny shrubs.
- Short, coarse grasses that disappear in the dry season.
- Only very drought-resistant trees survive (acacia species, desert date).
- Vegetation is patchy and disappears completely in severe droughts.
- **Desertification** — the spread of desert-like conditions into the Sahel — is a major problem.

---

### Zone 6: Desert (Sahara)

**Location:** Far north of the region.

**Climate:** Under 250 mm rainfall per year; extreme heat by day (up to 50°C), cold at night; very dry.

**Vegetation:**
- Almost no vegetation except at **oases** (areas with underground water).
- Desert plants (xerophytes) have special adaptations: deep roots, fleshy stems (water storage), small leaves (or no leaves), waxy coating, thorns.

---

## 3. Vegetation Adaptations

### Adaptations to dry conditions (xerophytes):

- **Deep roots** — reach water deep underground.
- **Fleshy stems (succulents)** — store water (e.g., cacti — not native to Africa, but a useful example).
- **Small or no leaves** — reduce surface area for water loss through transpiration.
- **Waxy/hairy leaf coating** — reduces water loss.
- **Thorns instead of leaves** — many savanna and desert plants (acacia).
- **Deciduous** — drop leaves in dry season to conserve water.
- **Thick bark** — protects against fire and desiccation.

### Adaptations to high rainfall (equatorial forest):

- **Drip tips** on large leaves — allow rapid drainage so fungal growth is prevented.
- **Buttress roots** — large triangular buttresses support tall trees in shallow, nutrient-poor soils.
- **Evergreen** — take advantage of year-round growing conditions.
- **Lianas** (climbing plants) — use other trees for support to reach light.

---

## 4. Soils

**Soil** is the uppermost layer of the Earth's surface, consisting of mineral particles (from weathered rock), organic matter (humus), water, air, and living organisms.

### Soil Profile

A soil profile shows the horizontal layers (horizons) of soil from surface to bedrock:

| Horizon | Name | Description |
|---------|------|-------------|
| O | Organic/Humus | Dead leaves, decomposing plant material |
| A | Topsoil | Dark; rich in humus and minerals; most biological activity |
| B | Subsoil | Lighter; minerals washed down from A; less organic matter |
| C | Parent material | Partially weathered rock |
| R | Bedrock | Solid, unweathered rock |

### Factors Affecting Soil Formation:

- **Climate:** Rainfall and temperature control weathering rates and leaching.
- **Parent material (rock type):** Determines mineral content.
- **Vegetation:** Provides organic matter (humus).
- **Relief:** Affects drainage, erosion, and depth.
- **Time:** Older soils are more developed.
- **Living organisms:** Earthworms, bacteria, and fungi help break down organic matter.

### Main Soil Types of West Africa:

**1. Laterite (Latosol):**
- Dominant in the humid tropics (rainforest and Guinea savanna zones).
- Formed under high temperatures and high rainfall.
- Very heavily leached — most nutrients washed away.
- Rich in iron and aluminium oxides → red/orange colour.
- Hard pan (laterite crust) can form at the surface, making it impermeable.
- LOW fertility once forest is cleared; poor structure.

**2. Savanna Soils (Ferruginous soils):**
- Found in Guinea and Sudan savanna zones.
- Less leached than laterite; moderate fertility.
- Red or brownish-red.
- Seasonal cracking in dry season; waterlogging in wet season.
- Can be productive with proper management.

**3. Alluvial Soils:**
- Found in river floodplains and deltas.
- Deposited by rivers (very fertile silt and clay).
- **Highly productive** — ideal for farming (yam, rice, vegetables).
- Examples: Niger Delta, Volta floodplain.

**4. Sahel and Desert Soils:**
- Sandy, nutrient-poor, very little organic matter.
- Prone to wind erosion.
- Low water-holding capacity.

---

## 5. Soil Erosion and Conservation

**Soil erosion** is the removal and transport of topsoil by water (rainfall) or wind.

**Causes of soil erosion in West Africa:**
- Heavy tropical rainfall on bare soil.
- Deforestation (removes protective vegetation cover).
- Overgrazing (removes vegetation, compacts soil).
- Steep slopes (fast runoff).
- Cultivation on slopes without protective measures.

**Types of erosion:**
- **Sheet erosion:** Even removal across a wide surface area.
- **Rill erosion:** Small channels cut by running water.
- **Gully erosion:** Deep channels; most damaging form.
- **Wind erosion:** Common in Sahel and desert areas.

**Soil conservation methods:**

| Method | How it helps |
|--------|-------------|
| Contour ploughing | Ploughing along slopes (not up/down) — reduces runoff speed |
| Terracing | Cutting horizontal steps into steep slopes — reduces runoff |
| Mulching | Covering soil with organic material — protects surface |
| Afforestation/reforestation | Tree roots hold soil; canopy breaks rainfall impact |
| Strip cropping | Alternating strips of crops and grass — slows runoff |
| Cover crops | Fast-growing plants cover bare soil between main crops |

