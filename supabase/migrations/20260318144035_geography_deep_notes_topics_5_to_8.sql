## 1. Introduction to Agriculture

**Agriculture** is the science and practice of farming, including the cultivation of crops and the raising of livestock for food, raw materials, and economic purposes.

Agriculture is the most important economic activity in West Africa:
- Employs over 60–70% of the working population in most West African countries.
- Contributes 30–50% of GDP in many countries.
- Provides food for local consumption and cash crops for export.

---

## 2. Types of Farming

### A. Subsistence Farming

**Definition:** Farming primarily to feed the farmer's family, with little or no surplus for sale.

**Characteristics:**
- Small plots of land.
- Simple, traditional tools (hoes, cutlasses/machetes).
- Low capital investment.
- Labour-intensive (relies on family labour).
- Low yields.
- Food crops: maize, yam, cassava, plantain, millet, sorghum, rice.
- Widespread in rural West Africa.

**Types of subsistence farming:**

**1. Shifting Cultivation:**
- Farmers clear a plot of forest by burning (slash and burn).
- The land is cultivated for 2–4 years until soil fertility declines.
- The farmer moves to a new plot; the old plot is left to regenerate (fallow period of 10–20 years).
- **Advantages:** Allows soil to recover; no chemical fertilisers needed.
- **Disadvantages:** Needs large areas of land; causes deforestation; not suitable for dense populations.
- Common in forest zones of West Africa.

**2. Mixed Farming:**
- Growing crops AND rearing livestock on the same farm.
- Animal manure fertilises the soil; crop residues feed animals.
- More sustainable than monoculture.
- Common in savanna zones.

### B. Commercial Farming

**Definition:** Farming primarily to produce crops or livestock for sale (profit).

**Characteristics:**
- Large-scale operations.
- Modern machinery and technology.
- High capital investment.
- Improved seeds, chemical fertilisers, pesticides.
- Aimed at maximum profit.

**Types include:**
- **Cash crop farming:** Growing crops specifically for sale/export.
- **Plantation farming:** Large estates growing a single export crop.
- **Mechanised farming:** Uses tractors, combine harvesters, etc.

