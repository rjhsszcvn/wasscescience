## 7. Solutions and Agricultural Improvement

| Problem | Solution |
|---------|---------|
| Low yields | Introduce high-yielding variety (HYV) seeds |
| Soil infertility | Apply fertilisers; use crop rotation; green manure |
| Drought | Irrigation schemes; drought-resistant crop varieties |
| Poor transport | Build and maintain rural roads |
| Poor storage | Build grain silos and cold storage facilities |
| Low prices | Form farmer cooperatives for collective bargaining |
| Lack of capital | Government subsidies; microfinance for farmers |

### Irrigation in West Africa

**Definition:** Irrigation is the artificial supply of water to agricultural land.

Used in drier northern areas (e.g., Sahel, Sudan savanna) to grow crops during the dry season.

**Types of irrigation:**
- **Flood irrigation:** Water flows freely over the field.
- **Drip irrigation:** Water is delivered directly to plant roots through pipes (efficient but expensive).
- **Sprinkler irrigation:** Water is sprayed over crops.

**Example:** The Gezira Irrigation Scheme (Sudan/Sahel); Irrigation in the Volta Basin (Ghana) for rice growing.

