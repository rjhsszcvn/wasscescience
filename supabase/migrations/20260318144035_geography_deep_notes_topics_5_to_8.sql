## 4. Ghana's Cocoa Industry (Case Study)

**Why Ghana is ideal for cocoa:**
- Forest zone has the right climate: temperatures of 24–28°C, annual rainfall of 1,500–2,000 mm.
- Rich, well-drained loam soils.
- Protection from direct sunlight (shade trees grown alongside cocoa).
- Long tradition of cocoa farming.

**Importance of cocoa to Ghana:**
- Major export earner (cocoa is Ghana's second largest export after gold).
- Employs millions of farmers.
- Provides foreign exchange for development.

**Problems facing cocoa farming:**
- Declining soil fertility.
- Plant diseases (e.g., swollen shoot disease).
- Fluctuating world cocoa prices (farmers have no control over price).
- Ageing farming population (young people prefer city life).
