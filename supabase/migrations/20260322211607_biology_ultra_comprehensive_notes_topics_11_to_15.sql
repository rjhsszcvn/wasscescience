## 5. Muscles

### 5.1 Types of Muscle
- Skeletal (striated/voluntary): Attached to bones; conscious control; striated appearance; fast, fatiguable
- Smooth (visceral/involuntary): In walls of internal organs (gut, blood vessels); not conscious control; slow, sustained
- Cardiac: Heart muscle; involuntary; rhythmic; never fatiguable; self-excitatory; intercalated discs

### 5.2 Antagonistic Muscle Pairs

Muscles can only PULL (contract), not push.

Antagonistic muscles: Work in opposite directions.
- Flexor: Bends joint (decreases angle)
- Extensor: Straightens joint (increases angle)

Example — Biceps and triceps at elbow:
- Biceps brachii (flexor): Contracts → bends elbow (flexion)
- Triceps brachii (extensor): Contracts → straightens elbow (extension)
- When one contracts, the other relaxes

### 5.3 Sliding Filament Theory of Muscle Contraction

Muscle fiber (cell) structure:
- Myofibrils: Made of sarcomeres (repeating units)
- Sarcomere: Functional unit of muscle
  - Z lines: Boundaries of sarcomere
  - A band: Dark band (thick filaments — myosin)
  - I band: Light band (thin filaments — actin only)
  - H zone: Contains only myosin (middle of A band)

Mechanism:
1. Nerve impulse → motor end plate → acetylcholine released
2. Muscle fiber depolarizes → Ca²⁺ released from sarcoplasmic reticulum
3. Ca²⁺ binds to troponin on actin filament → tropomyosin shifts → exposes binding sites
4. Myosin heads bind to actin → cross-bridge forms
5. Power stroke: Myosin head tilts → pulls actin filament toward center of sarcomere
6. ATP binds to myosin → cross-bridge breaks
7. ATP hydrolyzed → myosin head returns to original position
8. Process repeats → actin slides inward → sarcomere shortens → muscle contracts
9. Ca²⁺ pumped back → tropomyosin covers binding sites → muscle relaxes

Energy for contraction:
- ATP (from aerobic or anaerobic respiration)
- Creatine phosphate: Rapid ATP regeneration (short bursts)

