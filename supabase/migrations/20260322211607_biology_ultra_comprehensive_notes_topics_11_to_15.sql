## 3. Vertebrates (Animals with a Backbone)

Phylum Chordata — Characteristics:
- Notochord (flexible supporting rod) — at some stage
- Dorsal hollow nerve cord
- Pharyngeal gill slits — at some stage
- Post-anal tail — at some stage

