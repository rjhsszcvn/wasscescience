## 7. Antibiotics

Antibiotics: Chemicals that kill or inhibit bacteria WITHOUT harming human cells.

Mechanisms of action:
- Inhibit cell wall synthesis (penicillin, ampicillin): Bacteria burst
- Inhibit protein synthesis (streptomycin, erythromycin): Bacteria cannot grow
- Inhibit DNA synthesis (ciprofloxacin): Bacteria cannot replicate
- Disrupt cell membrane (polymyxin)

Important points:
- Antibiotics DO NOT work against viruses
- Should complete full course → prevent resistance developing
- Overuse/misuse → antibiotic-resistant strains (e.g., MRSA — methicillin-resistant Staphylococcus aureus)

Antibiotic resistance:
- Random mutations in bacteria → some survive antibiotic
- Resistant bacteria survive, reproduce → resistance spreads
- Horizontal gene transfer: Bacteria share resistance genes
- Solutions: Complete courses; no unnecessary use; develop new antibiotics; phage therapy

