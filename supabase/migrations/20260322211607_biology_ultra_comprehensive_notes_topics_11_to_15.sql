## 3. The Human Skeletal System

### 3.1 Functions of the Skeleton
1. Support: Framework for body
2. Protection: Skull (brain), ribcage (heart, lungs), vertebral column (spinal cord), pelvis (reproductive organs)
3. Movement: Bones act as levers; muscles attached to bones cause movement
4. Blood cell production (haemopoiesis): Red bone marrow produces RBCs, WBCs, platelets
5. Mineral storage: Calcium and phosphorus stored in bones
6. Attachment for muscles

### 3.2 Types of Bone

Compact bone:
- Dense, hard outer layer
- Haversian systems (osteons): Concentric rings of bone matrix
- Contains osteocytes (bone cells) in lacunae
- Central Haversian canal: Contains blood vessels and nerves

Spongy (cancellous) bone:
- Inner, lattice-like structure
- Spaces filled with red or yellow bone marrow
- Lighter than compact bone but still strong
- Found at ends of long bones and in flat bones

Bone composition:
- 35% organic matrix (collagen fibers → flexibility)
- 65% inorganic minerals (hydroxyapatite — calcium phosphate → hardness)

Bone cells:
- Osteoblasts: Form new bone (bone deposition)
- Osteoclasts: Break down bone (bone resorption)
- Osteocytes: Mature bone cells; maintain bone matrix

### 3.3 Classification of Bones

Long bones:
- Longer than wide; act as levers
- Examples: Femur, humerus, tibia, fibula, ulna, radius
- Structure: Diaphysis (shaft), epiphysis (end), periosteum, medullary cavity, articular cartilage

Short bones:
- Cube-shaped; stability and some movement
- Examples: Carpals (wrist), tarsals (ankle)

Flat bones:
- Thin, flat; protection and muscle attachment
- Examples: Skull bones, scapula, sternum, ribs, pelvis

Irregular bones:
- Complex shapes; vertebrae, facial bones

Sesamoid bones:
- Found within tendons
- Example: Patella (kneecap)

### 3.4 The Axial Skeleton
- Forms the central axis of the body
- Skull (cranium + facial bones)
- Vertebral column (spine)
- Thoracic cage (ribs + sternum)

Vertebral column:
- 33 vertebrae (26 functional):
  - Cervical: 7 (neck) — C1 (atlas) supports skull; C2 (axis) allows rotation
  - Thoracic: 12 (chest) — attached to ribs
  - Lumbar: 5 (lower back) — largest; bear most weight
  - Sacral: 5 (fused = sacrum) — forms back of pelvis
  - Coccygeal: 4 (fused = coccyx) — vestigial tail

Structure of a typical vertebra:
- Body (centrum): Weight-bearing
- Neural arch: Surrounds spinal cord
- Neural canal: Passage for spinal cord
- Transverse processes: Muscle attachment
- Neural spine (spinous process): Muscle attachment
- Intervertebral discs: Cartilage pads between vertebrae; shock absorption

### 3.5 The Appendicular Skeleton
- Limb bones and girdles

Pectoral girdle: Clavicle + scapula (attaches arms to axial skeleton)
Pelvic girdle: Ilium + ischium + pubis (fused = os coxa); attaches legs; broader in females (childbirth)

Upper limb: Humerus, radius, ulna, 8 carpals, 5 metacarpals, 14 phalanges
Lower limb: Femur, patella, tibia, fibula, 7 tarsals, 5 metatarsals, 14 phalanges

