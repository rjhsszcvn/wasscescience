## 4. Joints

Joint (articulation): Where two bones meet.

### 4.1 Types of Joints

Fixed (fibrous) joints:
- No movement
- Examples: Skull sutures, teeth in jaw

Slightly movable (cartilaginous) joints:
- Limited movement
- Examples: Vertebral joints (intervertebral discs), pubic symphysis, ribs to sternum

Freely movable (synovial) joints:
- Wide range of movement
- Structure: Joint cavity filled with synovial fluid; articular cartilage; synovial membrane; ligaments

Types of synovial joints:
- Hinge joints: Movement in one plane (flexion/extension)
  - Examples: Knee, elbow, finger joints
- Ball-and-socket joints: Movement in all planes (flexion, extension, abduction, adduction, rotation)
  - Examples: Shoulder, hip
- Pivot joints: Rotation
  - Examples: Atlas/axis (head rotation), radius/ulna (pronation/supination)
- Gliding joints: Sliding movement
  - Examples: Carpals, tarsals
- Saddle joints: Two-way movement
  - Example: Thumb base
- Condyloid joints: Biaxial movement
  - Example: Wrist

### 4.2 Synovial Joint Structure
- Articular cartilage: Smooth; reduces friction; cushions impact
- Synovial membrane: Lines joint capsule; secretes synovial fluid
- Synovial fluid: Lubricates joint; nourishes cartilage
- Joint capsule: Fibrous; encloses joint
- Ligaments: Bone to bone; stabilize joint

