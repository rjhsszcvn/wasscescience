## 1. Introduction to Classification

Classification: Grouping organisms based on similarities and differences.
Taxonomy: Science of naming and classifying organisms.

Why classify:
- Makes study of organisms manageable
- Helps understand evolutionary relationships
- Helps communication among scientists
- Predicts properties of newly discovered organisms

### 1.1 Taxonomic Hierarchy (from broadest to most specific)
Domain → Kingdom → Phylum → Class → Order → Family → Genus → Species

Mnemonic: "King Philip Came Over For Good Soup" (Kingdom, Phylum, Class, Order, Family, Genus, Species)

Species: Group of organisms that can interbreed and produce fertile offspring.

Binomial nomenclature (two-name system):
- Genus + species (in italics; or underlined when handwritten)
- Examples: Homo sapiens, Zea mays (maize), Rosa rosa (rose)
- First letter of genus = capital; species = lowercase

---

## 2. Five Kingdom Classification

Kingdom Monera (Prokaryotae):
- Prokaryotes (no nucleus)
- Bacteria and cyanobacteria

Kingdom Protista:
- Eukaryotes; mostly single-celled
- Amoeba, Euglena, Paramecium, algae

Kingdom Fungi:
- Eukaryotes; cell walls of chitin
- Saprophytic or parasitic
- Mushrooms, yeasts, moulds (Penicillium, Rhizopus)

Kingdom Plantae:
- Eukaryotes; cell walls of cellulose; chlorophyll
- Photosynthetic (autotrophs)
- Includes mosses, ferns, conifers, flowering plants

Kingdom Animalia:
- Eukaryotes; no cell wall; heterotrophic
- Includes sponges, worms, insects, fish, mammals

