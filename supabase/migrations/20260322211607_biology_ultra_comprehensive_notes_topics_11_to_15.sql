## 2. Invertebrates (Animals without a Backbone)

### 2.1 Phylum Porifera (Sponges)
- Simplest animals; no true tissues or organs
- Body full of pores (pori = pores)
- Sessile (attached to substrate)
- Filter feeders: Water flows through pores; particles filtered
- Asymmetrical body
- Examples: Bath sponge, Sycon

### 2.2 Phylum Cnidaria (Coelenterates)
- Simple; radially symmetrical
- Two cell layers (diploblastic): Epidermis + gastrodermis
- Hollow body cavity (gastrovascular cavity)
- Tentacles with stinging cells (nematocysts) for defense and prey capture
- Two body forms: polyp (attached — e.g., Hydra) and medusa (free-swimming — e.g., jellyfish)
- Examples: Hydra, jellyfish, sea anemone, coral

Coral reefs:
- Built by coral polyps secreting calcium carbonate skeletons
- Most biodiverse marine ecosystems
- Threatened by climate change and ocean acidification

### 2.3 Phylum Platyhelminthes (Flatworms)
- Flattened, bilaterally symmetrical
- Three cell layers (triploblastic)
- No body cavity (acoelomate)
- No circulatory or respiratory system (diffusion)
- Simple nervous system

Classes:
- Turbellaria: Free-living flatworms (Planaria)
- Trematoda (flukes): Parasites (liver fluke — Fasciola hepatica)
- Cestoda (tapeworms): Intestinal parasites (Taenia solium, Taenia saginata)

Tapeworm:
- Scolex (head): Suckers and hooks for attachment
- Proglottids: Segments containing reproductive organs
- No digestive system → absorbs nutrients through skin
- Causes weight loss, nutritional deficiency

### 2.4 Phylum Nematoda (Roundworms)
- Cylindrical, tapered, bilaterally symmetrical
- Pseudocoelomate (false body cavity)
- Non-segmented
- Complete digestive tract (mouth and anus)
- Many are parasites

Examples:
- Ascaris lumbricoides: Intestinal roundworm in humans
- Wuchereria bancrofti: Causes filariasis (elephantiasis)
- Ancylostoma: Hookworm
- Dracunculus: Guinea worm

### 2.5 Phylum Annelida (Segmented Worms)
- True coelom (body cavity)
- Body divided into segments (metameres)
- Setae (bristles) for movement
- Closed circulatory system
- Excretion by nephridia

Classes:
- Oligochaeta: Earthworms (Lumbricus terrestris) — no distinct head; hermaphrodite
- Polychaeta: Marine worms (Nereis) — paddle-like parapodia
- Hirudinea: Leeches — ectoparasites; secrete hirudin (anticoagulant)

Earthworm importance:
- Aerate and mix soil
- Improve drainage
- Increase soil fertility by organic matter breakdown
- Charles Darwin: "The plow of nature"

### 2.6 Phylum Mollusca
- Second largest animal phylum
- Soft-bodied; usually have a shell (calcium carbonate)
- Mantle: Fold of skin that secretes shell
- Foot: Muscular organ for movement
- Radula: Tongue-like feeding organ (not bivalves)

Classes:
- Gastropoda: Snails (spiral shell), slugs (no shell), limpets
- Bivalvia: Clams, mussels, oysters — two shells; filter feeders
- Cephalopoda: Octopus, squid, cuttlefish — highly intelligent; no external shell (usually); tentacles

### 2.7 Phylum Arthropoda (Largest Animal Phylum)
Characteristics:
- Exoskeleton made of chitin
- Jointed appendages (limbs)
- Segmented body
- Open circulatory system (blood in haemocoel)
- Bilateral symmetry

Classes:

Insecta (Insects):
- 3 body regions: Head, thorax, abdomen
- 3 pairs of legs (6 legs)
- 2 pairs of wings (usually)
- 1 pair of antennae
- Most diverse group of animals
- Metamorphosis: Complete (holometabolous: egg, larva, pupa, adult — butterfly) or Incomplete (hemimetabolous: egg, nymph, adult — grasshopper)
- Examples: Butterfly, bee, mosquito, housefly, grasshopper, beetle

Arachnida (Spiders, scorpions, mites, ticks):
- 4 pairs of legs (8 legs)
- No antennae, no wings
- 2 body regions: Cephalothorax, abdomen
- Examples: Spider, scorpion, tick, mite

Crustacea:
- 5+ pairs of legs
- 2 pairs of antennae
- Hard exoskeleton often impregnated with calcium
- Examples: Crab, lobster, shrimp, barnacle, woodlouse

Myriapoda:
- Many legs
- Centipedes (Chilopoda): One pair of legs per segment; carnivorous
- Millipedes (Diplopoda): Two pairs of legs per segment; decomposers

### 2.8 Phylum Echinodermata (Spiny Skinned)
- Marine organisms only
- Radial symmetry (5-fold) in adults
- Water vascular system: Hydraulic system of tubes → tube feet for movement, feeding, respiration
- Endoskeleton of calcium carbonate plates
- Regeneration (some can regrow lost arms)
- Examples: Starfish (sea star), sea urchin, sea cucumber, brittle star

