## 1. Need for Support and Movement

Support: Required to maintain body structure against gravity and mechanical stress.
Movement: Required for feeding, escaping predators, finding mates, etc.

---

## 2. Support in Plants

Plants must support themselves against gravity to:
- Hold leaves up to sunlight
- Allow gas exchange
- Hold flowers/seeds for pollination and dispersal

Methods of support:
- Turgor pressure: Water-filled vacuoles push against cell walls → rigidity (in non-woody plants)
- Cellulose cell walls: Provide rigid framework
- Lignification (xylem): Deposit of lignin in cell walls → rigid, waterproof (in woody plants)
- Collenchyma: Thickened cell walls; flexible support in growing parts
- Sclerenchyma: Heavily lignified dead cells; maximum rigidity (fibers and sclereids)

Consequences of water loss:
- Plasmolysis: Cell membrane pulls away from wall → cell loses rigidity → wilting
- Wilting: Plant droops when cells lose turgor

