## 5. Development and Differentiation

Differentiation: Process where cells become specialized for specific functions.
- All cells have the same DNA
- Different genes switched on/off → different proteins → different structure and function

Stem cells:
- Undifferentiated cells that can divide and differentiate into various cell types
