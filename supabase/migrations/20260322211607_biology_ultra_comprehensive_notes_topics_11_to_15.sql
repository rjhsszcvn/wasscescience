- Cold-blooded
- Mostly terrestrial
- Dry, scaly skin (prevent water loss)
- Three-chambered heart (crocodiles: 4-chambered)
- Amniotic egg (internal membrane protects embryo on land)
- Internal fertilization
- Examples: Lizard, snake, crocodile, turtle, tortoise

### 3.4 Class Aves (Birds)
- Warm-blooded (endothermic/homeothermic)
- Feathers (modified scales)
- Forelimbs modified into wings
- Beak (no teeth)
- Four-chambered heart (complete separation)
- Lay amniotic eggs with hard shell
- High metabolic rate
- Bones hollow (reduce weight for flight)
- Air sacs connected to lungs (efficient respiration)
- Examples: Eagle, ostrich, penguin, parrot

### 3.5 Class Mammalia (Mammals)
- Warm-blooded
- Hair/fur on body
- Females have mammary glands (produce milk for offspring)
- Four-chambered heart
- Give birth to live young (except monotremes — platypus, echidna, which lay eggs)
- Highly developed nervous system
- Teeth differentiated (incisors, canines, premolars, molars)
- Diaphragm separates thorax and abdomen

Subclasses:
- Monotremata: Egg-laying mammals (platypus, echidna)
- Marsupialia: Young born undeveloped; complete development in pouch (kangaroo, koala, opossum)
- Placentalia (Eutheria): Most mammals; young develop in uterus attached to placenta (humans, elephants, whales, cats)

Orders of placental mammals (examples):
- Primates: Humans, monkeys, apes, lemurs
- Carnivora: Dogs, cats, lions, bears
- Rodentia: Mice, rats, squirrels
- Cetacea: Whales, dolphins
- Chiroptera: Bats
- Artiodactyla: Cattle, sheep, pigs, deer

