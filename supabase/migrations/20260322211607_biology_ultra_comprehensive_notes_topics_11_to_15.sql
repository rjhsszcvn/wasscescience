## 6. Vaccination (Immunization)

Vaccine: Contains antigens (killed/weakened pathogen, fragments, or toxoids) that stimulate immune response without causing disease.

How vaccines work:
1. Antigen introduced → primary immune response
2. Memory cells formed
3. On real infection → rapid secondary response → disease prevented or mild

Types of vaccines:
- Live attenuated (weakened): Measles, MMR, oral polio, BCG — strongest immunity
- Killed (inactivated): Flu vaccine, hepatitis A — safer but weaker response; booster needed
- Subunit: Uses specific antigens only (hepatitis B, whooping cough)
- Toxoid: Inactivated toxin (tetanus, diphtheria)
- mRNA vaccines: mRNA codes for antigen; cell makes antigen → immune response (COVID-19)

Herd immunity:
- When enough population is immune → pathogen cannot spread
- Protects those who cannot be vaccinated (immunocompromised, infants)
- Herd immunity threshold varies by disease (measles: ~95%)

