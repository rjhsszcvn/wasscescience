## 5. Fungi Kingdom

Classification of fungi:
- Zygomycota: Rhizopus (bread mould)
- Ascomycota: Yeast (Saccharomyces), Penicillium, Aspergillus
- Basidiomycota: Mushrooms, toadstools
- Deuteromycota: Imperfect fungi

Characteristics:
- Cell walls of chitin
- Heterotrophic (saprophytic or parasitic)
- Reproduce by spores (sexual and asexual)
- Hyphae: Thread-like structures; network = mycelium
- No chlorophyll

Economic importance:
- Fermentation: Yeast → alcohol, bread
- Antibiotics: Penicillium → penicillin
- Food: Mushrooms, truffles, Quorn
- Harmful: Plant diseases (rust, blight), food spoilage, human infections (ringworm, candida)

