## 5. The Immune System

### 5.1 Non-Specific (Innate) Defenses

First line of defense (physical and chemical barriers):
- Skin: Tough keratinized outer layer; barrier to pathogens; sebum (acidic, antimicrobial)
- Mucus membranes: Line respiratory, digestive, urogenital tracts; trap pathogens
- Cilia: Sweep mucus with trapped pathogens away from lungs
- Stomach acid (HCl): Kills most ingested pathogens
- Tears, saliva, sweat: Contain lysozyme (enzyme that destroys bacterial cell walls)
- Normal flora: Beneficial bacteria compete with pathogens

Second line of defense (internal non-specific responses):
- Phagocytosis: Phagocytes (neutrophils, macrophages) engulf and digest pathogens
- Inflammation: Damaged tissue releases histamine → blood vessels dilate → redness, heat, swelling, pain; brings more immune cells to site
- Fever: Higher temperature inhibits pathogen reproduction; enhances immune activity
- Interferon: Proteins released by virus-infected cells; warn neighboring cells; inhibit viral replication
- Complement system: Proteins that lyse bacteria, attract phagocytes, enhance phagocytosis

### 5.2 Specific (Adaptive) Immunity

Involves lymphocytes; responds to specific antigens.

Antigen: Foreign molecule (usually protein) on pathogen surface that triggers immune response.
Antibody: Y-shaped protein produced by B cells; specifically binds antigen.

Types of lymphocytes:

B lymphocytes (B cells):
- Produced and mature in bone marrow
- Activated by antigen → clonal expansion → plasma cells + memory cells
- Plasma cells: Produce antibodies (immunoglobulins)
- Memory B cells: Long-lived; rapid response on re-exposure (immunological memory)

T lymphocytes (T cells):
- Produced in bone marrow; mature in thymus
- Types:
  - T helper cells (CD4+): Activate B cells and cytotoxic T cells; release cytokines
  - Cytotoxic T cells (CD8+, killer T cells): Kill infected cells by releasing perforin
  - T regulatory cells: Suppress immune response (prevent autoimmunity)
  - Memory T cells: Long-lived; rapid response on re-exposure

### 5.3 Primary and Secondary Immune Response

Primary response (first exposure):
- Takes 10-17 days to produce maximum antibody levels
- Antibody levels relatively low
- Memory cells formed

Secondary response (re-exposure):
- Faster (2-3 days)
- Higher antibody levels (more plasma cells from memory cells)
- More effective at neutralizing antigen
- This is the basis of vaccination and immunological memory

### 5.4 Antibodies — Structure and Function

Y-shaped (immunoglobulin) structure:
- Two heavy chains + Two light chains
- Variable regions (tips of Y): Antigen-binding sites; unique for each antibody
- Constant regions: Same in each antibody class; determine antibody function

How antibodies work:
- Neutralization: Block pathogen from entering cells
- Agglutination: Clump pathogens together for phagocytosis
- Opsonization: Coat pathogens → easier for phagocytes to recognize and eat
- Activation of complement: Triggers complement cascade → lysis
- Precipitation: Cause soluble antigens to precipitate

