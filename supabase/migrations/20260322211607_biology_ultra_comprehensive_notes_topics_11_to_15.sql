## 3. Malaria — Detailed Study

Causative organism: Plasmodium (4 species; P. falciparum most deadly)
Vector: Female Anopheles mosquito (male mosquitoes feed on nectar only)

Life cycle:
1. Infected mosquito bites human → sporozoites injected into blood
2. Sporozoites travel to LIVER → multiply in liver cells (asexual)
3. Liver cells burst → merozoites released into blood
4. Merozoites infect RED BLOOD CELLS → multiply → RBCs burst → more merozoites released
5. Some develop into gametocytes (sexual stage)
6. Mosquito bites infected person → takes up gametocytes
7. In mosquito gut: Gametocytes form gametes → fertilization → oocysts → sporozoites
8. Sporozoites migrate to salivary glands → mosquito infects new human

Symptoms: Cyclical fever (every 48-72 hours as RBCs burst), chills, sweating, anaemia, splenomegaly (enlarged spleen), cerebral malaria (severe)

Prevention:
- Mosquito nets (bed nets, especially insecticide-treated ITNs)
- Insect repellents (DEET)
- Draining stagnant water (breeding sites)
- Prophylactic antimalarial drugs (chloroquine, mefloquine)
- Spraying insecticides (DDT, malathion)
- Vaccines (RTS,S/AS01 — limited efficacy)

Treatment: Artemisinin-based combination therapies (ACTs); quinine

