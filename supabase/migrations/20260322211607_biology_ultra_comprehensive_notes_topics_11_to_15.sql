## 3. Plant Kingdom — Major Divisions

### 3.1 Algae (not true plants — often placed in Kingdom Protista)
- Simple, aquatic, no true roots/stems/leaves
- Photosynthetic; produce most of Earth''s oxygen
- Examples: Spirogyra, Chlamydomonas, Chlorella, seaweeds
- Unicellular or multicellular

### 3.2 Bryophyta (Mosses and Liverworts)

Characteristics:
- Non-vascular (no xylem or phloem)
- No true roots (have rhizoids for anchorage)
- No true leaves or stems (thallus in liverworts)
- Restricted to moist, damp environments (need water for reproduction)
- Small plants; dependent on water for sexual reproduction (swimming sperm)
- Dominant generation: Gametophyte (haploid)

Examples: Mosses (Polytrichum), Liverworts (Marchantia)

Economic/ecological importance:
- First colonizers on bare rock (pioneer species in succession)
- Peat bogs (Sphagnum moss) — carbon storage

### 3.3 Pteridophyta (Ferns and Horsetails)

Characteristics:
- Vascular plants (have xylem and phloem)
- No seeds
- Reproduce by spores
- True roots, stems, leaves
- Need water for sexual reproduction
- Dominant generation: Sporophyte (diploid)

Fern life cycle:
- Sporophyte produces spores in sporangia (on underside of leaves in clusters called sori)
- Spore germinates → prothallus (gametophyte; heart-shaped; tiny)
- Prothallus produces gametes; fertilization → new sporophyte

Examples: Ferns (Dryopteris, Pteridium/bracken), horsetails (Equisetum), club mosses

### 3.4 Gymnosperms (Naked Seed Plants)

Characteristics:
- Vascular plants
- Produce seeds NOT enclosed in fruit (naked seeds)
- Seeds in cones (male cones produce pollen; female cones produce seeds)
- Wind-pollinated
- Do NOT produce flowers
- Mostly evergreen; needle-like leaves (reduce water loss)
- Dominant generation: Sporophyte

Examples: Conifers (pine, fir, spruce, cedar), cycads, ginkgo

Economic importance:
- Timber (pine, cedar)
- Resin, turpentine
- Ornamental plants

### 3.5 Angiosperms (Flowering Plants)

Characteristics:
- Most successful plant group
- Seeds enclosed in fruits (ovary wall)
- Produce flowers (for sexual reproduction)
- Variety of pollination mechanisms
- True roots, stems, leaves, flowers, fruits, seeds
- Dominant generation: Sporophyte

Two classes:

Monocotyledons (Monocots):
- 1 cotyledon
- Parallel leaf venation
- Fibrous root system
- Flower parts in multiples of 3
- Scattered vascular bundles in stem
- Examples: Maize, rice, wheat, grass, onion, palm, banana, lily

Dicotyledons (Dicots):
- 2 cotyledons
- Branched/net leaf venation
- Taproot system
- Flower parts in multiples of 4 or 5
- Vascular bundles in ring in stem
- Examples: Bean, sunflower, mango, tomato, orange, rose, oak

