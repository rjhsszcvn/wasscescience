## 6. Locomotion in Different Animals

Hydrostatic skeleton:
- Fluid-filled body cavity provides resistance for muscle action
- Found in: Earthworms, starfish, squid
- Earthworm: Circular muscles and longitudinal muscles work antagonistically
  - Circular muscles contract → body elongates → setae anchor back
  - Longitudinal muscles contract → body shortens → setae anchor front

Exoskeleton:
- Arthropods: Hard outer covering; muscles attached inside
- Advantage: Protection; support
- Disadvantage: Must molt (ecdysis) to grow; limits size

Endoskeleton:
- Vertebrates: Internal skeleton
- Advantage: Can grow; supports large size
- Muscles attached outside

Flight in insects:
- Direct muscles: Attach to wings directly
- Indirect muscles: Deform thorax → wings move
- High wingbeat frequency

Swimming in fish:
- Undulatory body movements generated by myotomes (blocks of muscle)
- Fins for steering and stability' 
