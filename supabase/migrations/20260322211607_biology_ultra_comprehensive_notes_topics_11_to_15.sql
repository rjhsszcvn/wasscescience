## 6. Plant Tissues and Organs

Root:
- Functions: Absorbs water and minerals; anchors plant
- Types: Taproot (dicot) and fibrous root (monocot)
- Root hair cells: Increase surface area for absorption
- Root tip zones: Root cap, meristematic zone, elongation zone, differentiation zone

Stem:
- Functions: Supports plant; transports water and food; photosynthesis (green stems)
- Contains vascular bundles (xylem and phloem)
- Arrangement: Ring (dicot) vs. scattered (monocot)

Leaf:
- Functions: Photosynthesis, gas exchange, transpiration
- Structure: Epidermis (upper and lower), mesophyll (palisade + spongy), veins, stomata, guard cells' 
