## 4. HIV/AIDS — Detailed Study

HIV (Human Immunodeficiency Virus): Retrovirus
AIDS (Acquired Immunodeficiency Syndrome): Late stage of HIV infection

Transmission:
- Unprotected sexual intercourse
- Sharing contaminated needles (intravenous drug users)
- Blood transfusions (contaminated blood)
- Mother to child: Pregnancy, childbirth, breastfeeding

Target cell: CD4+ T helper lymphocytes (T4 cells)

Mechanism:
1. HIV attaches to CD4 receptor on T helper cell
2. Viral RNA injected into cell
3. Reverse transcriptase: Viral RNA → DNA
4. Viral DNA integrates into host chromosome (provirus)
5. Viral DNA replicated with host DNA; new viruses assembled
6. New viruses bud off; destroy T cell
7. T cell count drops → immune system weakened

Stages:
- Acute HIV infection: Flu-like symptoms weeks after infection; very contagious
- Asymptomatic phase (clinical latency): 10+ years; few symptoms; virus still replicating
- AIDS: CD4 count < 200 cells/mL; susceptible to opportunistic infections (TB, pneumocystis pneumonia, Kaposi''s sarcoma, CMV)

Diagnosis:
- ELISA test: Detects antibodies to HIV (takes 3-12 weeks to develop)
- PCR: Detects viral RNA directly
- CD4 count and viral load monitoring

Treatment:
- Antiretroviral therapy (ART): Combination of drugs targeting different stages (NRTIs, NNRTIs, protease inhibitors, integrase inhibitors)
- Highly Active Antiretroviral Therapy (HAART): Suppresses viral load; prevents AIDS
- No cure currently

Prevention:
- Safe sex (condoms)
- Not sharing needles
- Blood screening
- PrEP (pre-exposure prophylaxis)
- PMTCT (preventing mother-to-child transmission — antiretrovirals during pregnancy)
- Education and awareness

