## 1. What is Growth?

Growth: Permanent, irreversible increase in size or mass of an organism.

Types of growth measurement:
- Increase in dry mass (best indicator — not affected by water content)
- Increase in fresh mass (affected by water)
- Increase in height/length
- Increase in cell number

Dry mass: Mass after removing all water by heating.

Growth requires:
- Cell division (mitosis): Increase in cell number
- Cell enlargement: Increase in cell size
- Cell differentiation: Specialization of cells

---

## 2. Growth Curves

Sigmoid (S-shaped) growth curve:
- Lag phase: Slow growth at start (preparation, adaptation)
- Log/exponential phase: Rapid growth (plentiful resources)
- Stationary phase: Growth rate = death rate (limiting factors)
- Decline phase: Death rate > growth rate (resource depletion)

Intermittent growth (in arthropods):
- Exoskeleton restricts growth
- Grow rapidly after molting (ecdysis)
- Produces stepwise growth curve

---

## 3. Human Growth and Development

### 3.1 Human Growth Curve
- Rapid growth after birth
- Slower growth in childhood
- Pubertal growth spurt
- Growth stops in early adulthood

Growth rate: Rate of change in size (cm/year or kg/year)
- Two peaks: Infancy and puberty

### 3.2 Puberty

Puberty: Period of sexual maturation; secondary sex characteristics develop.

Females (typically 10-14 years):
- Ovaries mature; menstruation begins (menarche)
- Breast development
- Body hair (pubic and underarm)
- Widening of hips (for childbirth)
- Increase in height (growth spurt)
- Fatty deposits (female shape)
- Hormones: FSH, LH, oestrogen, progesterone

Males (typically 12-16 years):
- Testes produce sperm; ejaculation possible
- Penis and testes enlarge
- Body hair (face, pubic, underarm, chest)
- Voice deepens (larynx enlarges)
- Increase in muscle mass
- Growth spurt
- Hormones: FSH, LH, testosterone

### 3.3 Factors Affecting Human Growth
- Genetics: Inherited height potential
- Nutrition: Adequate protein, calories, vitamins, minerals
- Hormones: Growth hormone (pituitary), thyroxine, insulin, sex hormones
- Exercise: Stimulates bone and muscle growth
- Disease: Chronic illness stunts growth
- Sleep: Growth hormone released during sleep

---

## 4. Growth in Plants

### 4.1 Regions of Growth in Plants
Plants grow mainly from meristems (regions of actively dividing cells).

Apical meristems:
- Located at root and shoot tips
- Primary growth: Increase in LENGTH
- Root apical meristem: Produces new root cells
- Shoot apical meristem: Produces new leaves and branches

Lateral meristems:
- Vascular cambium: Produces xylem and phloem → increases girth (wood)
- Cork cambium: Produces bark
- Secondary growth: Increase in GIRTH (width)

Intercalary meristems:
- Found at nodes in grasses
- Growth between joints (allows grasses to recover from grazing)

### 4.2 Primary Growth (in root tip)
Zones in root tip:
1. Root cap: Protects apical meristem; secretes mucilage (lubricates soil penetration)
2. Cell division zone (meristematic zone): Cells divide by mitosis
3. Cell elongation zone: Cells enlarge (water uptake); pushes root through soil
4. Cell differentiation zone (maturation zone): Cells specialize (root hair cells form here)

### 4.3 Secondary Growth (in dicot stems and roots)
- Vascular cambium produces secondary xylem (wood) inward and secondary phloem outward
- Annual rings (tree rings): Each ring = 1 year of growth
  - Wide ring = favorable growing season
  - Narrow ring = poor growing season
- Dendrochronology: Dating trees by counting rings

