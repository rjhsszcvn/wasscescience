**Question:** Explain why Nigeria has not benefited more from its enormous oil wealth. (10 marks)

**Model Answer:**
Nigeria has been producing oil since 1956 and has earned over USD 1 trillion from oil exports since independence. Yet, by most development indicators, Nigeria has not achieved its potential. Key reasons:

1. **Over-dependence (Dutch Disease):** Oil revenues flooded the economy, strengthening the Naira. This made Nigeria's other exports (agricultural products, manufactured goods) expensive and uncompetitive internationally. Agriculture (formerly the economy's backbone) and manufacturing declined as oil became dominant. Nigeria now imports food that it once exported.

2. **Corruption:** A substantial portion of oil revenues has been misappropriated through corruption at all levels. Various Nigerian government investigations have estimated that tens or hundreds of billions of dollars have been stolen or mismanaged.

3. **Lack of value addition:** Nigeria exports crude oil but imports refined petroleum products — petrol, kerosene, diesel — because its refineries are dysfunctional. This means Nigeria is simultaneously one of Africa's largest oil producers AND one of its largest importers of refined petroleum. The value of refining (which could employ thousands and keep more money in the economy) goes abroad.

4. **Neglect of non-oil sectors:** Government focus on oil revenues led to neglect of agriculture, education, and manufacturing. When oil prices fall (as in 2014–16), the entire economy suffers.

5. **Infrastructure failure:** Despite enormous revenues, Nigeria's roads, railways, electricity, and schools remain woefully inadequate. Power outages ("NEPA/PHCN problem") mean businesses run expensive generators — adding to production costs.

6. **Niger Delta conflict:** Oil production in the Niger Delta has been repeatedly disrupted by armed militancy — driven by local communities' resentment at environmental destruction and lack of development benefit from "their" oil. Oil theft ("bunkering") is also endemic.

