## Urban Land Use Patterns in West Africa

### The Central Business District (CBD)

- Located at the geographic and functional heart of the city.
- **Characteristics:** Highest land values, tallest buildings, maximum pedestrian and vehicular traffic, concentration of retail (shops, markets), offices (banks, law firms, government), entertainment, hotels.
- **West African examples:** Victoria Island and Lagos Island (Lagos); the Commercial District around Kwame Nkrumah Avenue (Accra); Freetown city centre.
- **Problems in West African CBDs:** Severe traffic congestion; inadequate infrastructure (electricity cuts, water shortages); flooding in low-lying areas; too many informal traders (hawkers) on pavements; poor solid waste management.

### Industrial Zones

- Areas where factories, workshops, and warehouses are located.
- Usually on the outskirts of the city, near transport links (roads, ports, railways).
