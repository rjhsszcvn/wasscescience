### 1. Rural-Urban Migration (Most Important Cause)

Millions of West Africans move from the countryside to cities each year, drawn by:

**Push factors (from rural areas):**
- Poverty — rural incomes are very low
- Unemployment — limited non-farm jobs in rural areas
- Drought and crop failure — especially in the Sahel
- Lack of schools, hospitals, electricity, clean water
- Limited entertainment and social opportunities
- Agricultural mechanisation reducing need for farm labour
- Land pressure — growing population dividing smaller farms

**Pull factors (to cities):**
- Employment opportunities — factories, services, government
- Higher wages — even informal jobs pay more than subsistence farming
- Better schools and universities
- Better hospitals and clinics
- Electricity, piped water, modern amenities
- Entertainment — cinema, music, social life
- Perceived opportunity — the "bright lights" of the city

### 2. Natural Population Increase Within Cities

Cities also grow because people living in them have children — and the birth rate in cities, though lower than in rural areas, still exceeds the death rate.

### 3. Reclassification of Rural Settlements

As settlements grow, what was once a village becomes a town; what was a town becomes a city. This reclassification contributes to urbanisation statistics.

