Wind transports material in three ways:
1. **Suspension:** The finest dust particles (clay, fine silt) are lifted high into the atmosphere and carried thousands of km. Saharan dust regularly crosses the Atlantic to South America or reaches Europe.
2. **Saltation:** Sand grains (0.2–1 mm) are bounced along the surface in a hopping motion. Most sand transport occurs by saltation.
3. **Surface creep:** The largest particles (coarse sand, small pebbles) are too heavy to bounce — they are rolled or pushed along the surface by the impact of saltating grains.

### Erosion by Wind

**Deflation:** Wind removes loose fine particles from the surface:
- Creates **deflation hollows** or **blowouts** — depressions where material has been removed.
- Leaves behind a **lag gravel** of coarser particles too heavy to be moved — the **reg**.

**Abrasion:** Wind carrying sand particles sandblasts exposed rock:
- Creates smooth, polished surfaces on rock.
- Carves **ventifacts** (smooth-faced rocks), **yardangs** (streamlined ridges), **zeugen** (mushroom rocks/pedestal rocks).
- Most effective near the ground where sand concentration is highest — this is why zeugen have narrow bases (abraded near ground) and wider tops (less abrasion at height).

---

## Wind Deposition — Sand Dunes

Sand dunes form when:
1. Wind picks up and transports sand.
2. An obstacle (rock, plant, dune itself) reduces wind speed.
3. Sand is deposited on the leeward (sheltered) side.
4. As the deposit grows, it becomes its own obstacle, growing into a dune.

### How a Barchan Dune Migrates

1. Wind picks up sand from the windward side (gentle slope, called the **stoss slope**).
2. Sand is carried over the **crest** (top of the dune).
3. Sand is deposited on the sheltered **lee slope** (also called the **slip face** or **avalanche face**) — which is steep, at the angle of repose (~34°).
4. As sand is added to the lee slope, the entire dune slowly migrates in the wind direction.
5. Barchans migrate at 10–20+ metres per year — they can engulf roads, villages, and oases.

---

## Water Processes in Deserts

Despite the aridity, water is STILL an important geomorphic agent in deserts — because when rain does fall, it falls in INTENSE downpours on bare, unprotected rock and soil (no vegetation to slow runoff).

### Flash Floods and Wadi Formation

1. A heavy rainstorm (rare but intense) falls on a desert mountain or plateau.
2. With no vegetation to intercept rain and poor soil infiltration (hard, compacted surface), most water runs off immediately.
3. Water rushes down steep slopes, concentrating in any depression or channel.
4. A **flash flood** — a sudden, powerful torrent — fills the dry valley.
5. The flood carries an enormous load of sediment, boulders, and rock fragments.
6. The flood sweeps down the valley (wadi), eroding it rapidly.
7. When the rainstorm ends, the wadi quickly dries out — leaving only the channel behind.

### Pediments and Alluvial Fans

When flash floods emerge from a mountain canyon onto the open desert plain:
- The water spreads out, slows dramatically, and deposits its load in a **fan** shape.
- This deposit of sediment is an **alluvial fan**.
- The gentle, eroded ramp at the mountain's base is a **pediment**.
- Multiple alluvial fans can merge to form a **bajada** (a continuous apron of sediment along a mountain front).

