## Problems of Rapid Urbanisation in West Africa

### 1. Housing Shortage and Slums

- West African cities cannot house their rapidly growing populations in decent, affordable accommodation.
- **Lagos** has over 70 slum areas; Makoko alone houses an estimated 100,000–300,000 people in structures built over a lagoon.
- In **Accra**, areas like Nima and Old Fadama have hundreds of thousands of people in densely packed, inadequate housing.
- In **Freetown**, Susan's Bay, Kroo Bay, and other informal settlements house a large proportion of the city's population in extremely poor conditions.

### 2. Inadequate Infrastructure

- **Water:** Many city residents do not have piped water — they rely on expensive water sellers, wells, or contaminated sources.
- **Sanitation:** Open defecation is common where sewage systems are absent or inadequate — contributing to cholera and other disease outbreaks.
- **Electricity:** Load-shedding ("dumsor" in Ghana) is frequent — businesses and residents rely on expensive generators.
- **Roads:** Traffic congestion is severe; road maintenance often inadequate.

### 3. Unemployment and Underemployment

- Cities attract migrants with the promise of work, but formal employment is insufficient.
- Large proportions work in the **informal economy** — street hawking, kiosks, casual labour — with low, insecure incomes.
- **Youth unemployment** is particularly acute — many educated young people cannot find jobs matching their qualifications.

### 4. Environmental Problems

- **Air pollution:** Vehicle exhaust, industry, biomass burning, waste burning.
- **Water pollution:** Inadequate sewage, industrial effluents, dumping in rivers and lagoons.
- **Flooding:** Concrete and tarmac surfaces prevent infiltration; rivers and drainage channels are often blocked with rubbish — heavy rains cause devastating floods (Accra flooding annually during rains).
- **Solid waste:** West African cities generate enormous amounts of waste; collection and disposal are often inadequate — illegal dumping, open landfills.

### 5. Social Problems

- **Crime:** Inequality and poverty drive theft, armed robbery, drug trafficking.
- **Ethnic conflict:** Urban areas concentrate diverse ethnic groups — tensions can erupt into violence.
- **Health:** Crowded slums are breeding grounds for infectious disease — cholera, typhoid, meningitis, COVID-19.

---

## Solutions to Urban Problems

1. **Planned urban development:** Master plans that designate zones for different land uses; regulate building; provide infrastructure before people move in.
2. **Slum upgrading:** Rather than demolishing slums, improving them — providing water, sanitation, electricity, roads. More humane and cost-effective.
3. **Site and services:** Providing serviced plots (water, sanitation) for people to build on.
4. **Decentralisation:** Moving government offices and economic activities out of capital cities to reduce overcrowding.
5. **Rural development:** Investing in rural areas — jobs, schools, hospitals, roads — to reduce push factors driving rural-urban migration.
6. **Mass transit systems:** BRT (Bus Rapid Transit), metro systems to reduce road congestion. Lagos has a BRT system and a developing light rail network.
7. **Solid waste management:** Improved collection, recycling, composting, and landfill management.
