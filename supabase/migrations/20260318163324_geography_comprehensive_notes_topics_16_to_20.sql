**Urbanisation:** The process by which the proportion of a country's population living in urban areas (towns and cities) increases over time.

**Urban area:** A densely populated settlement with a high proportion of non-agricultural economic activities (commerce, industry, services).

**Rural area:** A sparsely populated area dominated by agricultural land use.

**Rural-urban migration:** The movement of people from the countryside to cities, driven by push factors (poverty, drought, lack of services in rural areas) and pull factors (employment, education, services in cities).

**Urban sprawl:** The uncontrolled outward expansion of urban areas into surrounding rural land — creating low-density suburbs and consuming agricultural land.

**Primate city:** A city that is disproportionately large compared to other urban centres in a country, dominating its economy, politics, and culture. Lagos is Nigeria's primate city.

**Central Business District (CBD):** The commercial and economic core of a city — concentrated retail, offices, banks, entertainment. Characterised by high land values, multi-storey buildings, maximum accessibility.

**Industrial zone:** Area within or adjacent to a city where manufacturing, processing, and storage activities are concentrated.

**Residential zone:** Area dominated by housing for city residents.

**Urban land use:** The various ways in which land within a city is used — commercial, industrial, residential, recreational, institutional.

**Concentric zone model:** A model of urban land use showing the city as a series of concentric rings — CBD in the centre, surrounded by transition zone, working-class housing, middle-class housing, commuter zone.

**Slum:** A densely populated urban area characterised by substandard housing, inadequate infrastructure, poverty, and social deprivation. Also called **shanty towns, squatter settlements, informal settlements**.

**Shanty town:** An informal settlement built from makeshift materials (cardboard, corrugated iron, wood scraps). Residents often lack legal title to land.

**Self-help housing:** A strategy where residents gradually improve their own homes using their own labour and materials over time, often with minimal external support.

**Site and services scheme:** A government programme providing basic infrastructure (roads, water, sanitation) in an area and allowing residents to build their own homes on allocated plots.

**Gentrification:** The process by which wealthier people move into a previously poor urban area, renovating properties and displacing lower-income residents.

**Traffic congestion:** The situation where traffic volume exceeds road capacity, causing slow movement or gridlock. A major urban problem in Lagos, Accra, Abidjan.

**Infrastructure:** Basic systems needed for urban functioning: water supply, sewage, electricity, roads, schools, hospitals, telecommunications.

**Bid rent theory:** The concept that land values and land use in cities are determined by how much different users (commercial, industrial, residential) are willing to pay for different locations. Land closest to the CBD has highest value; value decreases with distance.
