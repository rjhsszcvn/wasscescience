**GDP (Gross Domestic Product):** The total monetary value of all goods and services produced within a country in one year. The standard measure of a country's economic output.

**GNP (Gross National Product):** The total monetary value of all goods and services produced by a country's residents, regardless of where in the world they are.

**GDP per capita:** GDP divided by population — a rough measure of average income or living standard.

**Developed country (MEDC):** A country with a high HDI, high GDP per capita, advanced technology, diversified economy. Most of Europe, North America, Japan, Australia.

**Developing country (LEDC):** A country with a lower HDI, lower GDP per capita, often reliant on primary sector. Most of West Africa falls in this category.

**Least Developed Country (LDC):** The UN's official designation for the world's poorest and most vulnerable countries. Sierra Leone, Liberia, Burkina Faso, Mali, Niger, Gambia, Guinea-Bissau, Senegal are on this list.

