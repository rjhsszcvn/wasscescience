**Question 7:** With reference to ONE West African country, assess the effectiveness of foreign aid in promoting development. (10 marks)

**Model Answer — Ghana:**

**Ghana has received substantial foreign aid since independence (1957)** from bilateral donors (UK, USA, Germany) and multilateral institutions (World Bank, IMF, EU).

**Where aid has been effective:**
1. **Infrastructure:** Aid financed the **Akosombo Dam** (partially), road building, and rural electrification projects that would not have been possible from domestic revenues alone. These have directly improved livelihoods.

2. **Health:** PEPFAR (US HIV/AIDS programme) support, Global Fund investments, and bilateral aid have dramatically reduced HIV/AIDS prevalence, improved maternal health, and controlled malaria in Ghana.

3. **Education:** Aid-financed schools, teacher training, and the Free Compulsory Universal Basic Education (FCUBE) programme have dramatically improved school enrolment — Ghana has one of the highest primary school enrolment rates in sub-Saharan Africa.

4. **Emergency response:** Aid provides critical humanitarian response to floods, droughts, and disease outbreaks.

**Where aid has been less effective:**
1. **Dependency:** Continued large aid flows can create government dependency — reducing the urgency of developing domestic revenue (taxes) and sustainable institutions.

2. **Tied aid:** Some aid is "tied" — Ghana must purchase goods or hire consultants from the donor country, increasing costs and reducing efficiency.

3. **Conditionality:** IMF/World Bank structural adjustment conditions in the 1980s–90s required Ghana to cut public spending — which harmed healthcare and education provision and increased poverty in the short term.

4. **Coordination problems:** Multiple donors operating parallel programmes creates inefficiencies. Aid is sometimes poorly coordinated with Ghana's own development plans.

**Overall assessment:** Foreign aid has played a positive but limited role in Ghana's development. Ghana's most impressive development gains (discovery of oil in 2007, economic growth, reduced poverty) have been primarily driven by domestic factors — economic policy, natural resources, and governance improvements. Aid has been a supplement, not a substitute, for domestic-led development. The most effective aid is that which builds Ghana's own capacity (education, health, institutions) rather than creating dependency.
