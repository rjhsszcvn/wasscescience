**Economic geography** examines how and where economic activities are distributed across space, and why they are located where they are. It asks: Why is cocoa farming concentrated in southern Ghana and not the north? Why is Nigeria's oil industry in the Niger Delta? Why is Accra Ghana's main commercial centre?

Economic geography looks at:
- **Primary activities:** Extracting raw materials (farming, mining, fishing, forestry)
- **Secondary activities:** Processing raw materials (manufacturing, construction)
- **Tertiary activities:** Services (trade, transport, banking, healthcare, education)
- **Quaternary activities:** Knowledge-based (research, IT, finance, consulting)

Understanding economic geography helps explain:
- Why some regions develop and others remain poor
- How economic activities cluster in specific locations
- The relationship between geography and wealth

