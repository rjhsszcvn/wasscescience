### What Is Register?
**Register** is the variety of language appropriate to a **specific social situation or context**. It involves choices about vocabulary, grammar, level of formality, and style. Using the wrong register (e.g., informal language in a formal letter) is a serious error in WASSCE.

---

### Factors Determining Register

| Factor | Questions to ask |
|--------|----------------|
| **Audience** | Who are you writing for? (boss, friend, examiner, public) |
| **Purpose** | What is the goal? (inform, persuade, entertain, request) |
| **Medium** | How is it delivered? (letter, speech, email, essay) |
| **Topic** | How serious/technical is the subject? |
| **Relationship** | What is your relationship to the audience? (formal/informal) |

---

### The Formality Spectrum

| Level | Context | Features |
|-------|---------|---------|
| **Formal** | Official letters, essays, reports, speeches, academic writing | Complex sentences, polished vocabulary, passive voice, no contractions |
| **Semi-formal** | Emails to colleagues, letters to known professionals | Moderate formality, some contractions acceptable |
| **Informal** | Conversations, texts, diary entries, letters to friends | Contractions, slang, simple sentences, idioms, first name basis |

---

### Formal vs. Informal Language

| Informal | Formal Equivalent |
|----------|-----------------|
| kids | children |
| loads of | numerous; a significant number of |
| sort out | resolve; address |
| a lot | considerably; substantially; a great deal |
| start | commence; initiate |
| end | conclude; terminate |
| help | assist; aid |
| get | obtain; acquire; receive |
| show | demonstrate; illustrate; indicate |
| think | believe; argue; contend; assert |
| find out | discover; ascertain; establish |
| put off | postpone; defer |
| go up | increase; rise; escalate |
| go down | decrease; decline; fall |
| make better | improve; enhance; ameliorate |
| because | as a result of; owing to; due to; since |
| but | however; nevertheless; nonetheless; yet |
| also | in addition; furthermore; moreover |

**Other formal features:**
- Third person references: *"one may argue..."* / *"it is suggested that..."*
- Passive voice for objectivity: *"It has been recommended that..."*
- Long, complex sentences with subordinate clauses
- Technical vocabulary specific to the topic
- Avoidance of contractions: *"do not"* not *"don't"*

---

### Types of English by Purpose (Functional Varieties)

#### 1. Legal English
- Precise, unambiguous, and archaic
- Uses: *heretofore, whereas, hereinafter, the aforementioned*
- Avoids pronouns for absolute clarity (names repeated)
- Long, complex sentence structures

#### 2. Medical / Scientific English
- Technical terminology: *hypertension, aetiology, contraindication*
- Formal, objective, passive voice frequently used
- *"The patient was administered a dose of..."*

#### 3. Journalistic English
- Clear, concise, active voice
- Inverted pyramid structure (most important facts first)
- Direct language: short sentences
- Use of quotations for authority

#### 4. Literary English
- Rich vocabulary, figurative language
- Deliberate deviation from norms for effect
- May include colloquial language for character authenticity

#### 5. Religious English
- Archaic forms in traditional texts: *thou, thy, hath, doth, verily*
- Repetition, parallelism, and elevated vocabulary

#### 6. Advertising English
- Persuasive, punchy, often uses slogans
- Imperative mood: *"Buy now! Try today!"*
- Positive adjectives and superlatives

---

### Standard English vs. Non-Standard English

**Standard English:** The variety of English codified in grammars and dictionaries; accepted in formal, official, and educational contexts worldwide.

**Non-Standard English:** Regional dialects, pidgins, creoles, and informal varieties.

**West African varieties:**
- **Nigerian English / Ghanaian English:** Varieties of English shaped by indigenous languages, with distinct vocabulary, pronunciation, and sometimes grammatical features.
  - *"I am coming"* (used to mean "I'll be back") is understood locally but non-standard globally.
- **West African Pidgin:** A simplified contact language used across West Africa for communication between people with different mother tongues.

**For WASSCE purposes:** Always write in **Standard English** in examinations.

---

### Code-Switching and Code-Mixing

**Code-switching:** Moving between two or more languages or language varieties in conversation.
- *"She told me — and this is the truth o — that she didn't know."* (Switching to include local expression *"o"*)

**Code-mixing:** Integrating elements of one language into another within the same sentence.
- Common in informal West African communication but inappropriate for formal WASSCE writing.

---

