### What Is Directed Writing?
Directed Writing involves producing a **specific text type** for a defined **purpose and audience**, following given instructions or using provided information. WASSCE Paper 2 includes directed writing tasks that test your ability to write accurately, appropriately, and purposefully in formats such as letters, speeches, articles, and reports.

---

### Why Directed Writing Is Important in WASSCE
- Tests understanding of **text type conventions** (format, tone, language)
- Assesses ability to write for a specific purpose and audience
- Requires using **information provided** in the question rather than pure invention
- Marked on: content, format, register, organisation, and language accuracy

---

### Common Directed Writing Text Types

#### 1. Formal Letter
**When used:** Applying for a job/scholarship, writing to a government official, making a complaint, writing to a newspaper editor.

**Format:**
```
[Your Address]                    [Top right corner]
[Town/City]
[Date (written in full: 14th March, 2024)]

[Recipient's Name/Title]         [Left side, below date]
[Recipient's Position]
[Organisation]
[Address]

Dear Sir/Madam / Dear Mr./Mrs. [Surname],

[Subject line (underlined or in bold) — optional but recommended]

[Body — 3–5 paragraphs]

Yours faithfully,       [if "Dear Sir/Madam" — unnamed recipient]
Yours sincerely,        [if recipient's name used — "Dear Mr. Mensah"]

[Signature]
[Full Name (printed)]
```

**Opening paragraph:** State your purpose clearly and briefly.
**Middle paragraphs:** Develop your points logically with evidence.
**Closing paragraph:** Summarise; state what you expect/request.

**Language:** Formal, polite, professional. No contractions.

---

#### 2. Informal Letter
**When used:** Writing to a friend, relative, or pen-pal.

**Format:**
```
[Your Address]
[Date]

Dear [First Name],

[Body — conversational, friendly]

Yours affectionately / Lots of love / Best wishes,
[First Name / Nickname]
```

**Language:** Warm, conversational, may include contractions and idioms.
**Content:** Personal, expressive; can include questions to the recipient.

---

#### 3. Speech / Talk
**When used:** A head girl/boy addressing a school, a valedictory speech, a debate contribution.

**Format:**
- **Opening address:** *Mr. Chairman / Madam President / Principal, teachers, and students...*
- **Self-introduction (if required)**
- **Body:** Well-organised points with discourse markers
- **Conclusion:** Memorable closing line, thank-you

**Language features:**
- Rhetorical questions: *"Can we afford to sit and watch?"*
- Direct address to audience: *"My fellow students..."*
- Repetition and parallelism for emphasis
- Varies between formal and semi-formal depending on audience
- Inclusive pronouns: *"We must act. Together, we can change this."*

**Opening example:**
*"Good morning, Mr. Principal, distinguished teachers, and my fellow students. It is a great honour to stand before you today to speak on an issue that affects each and every one of us..."*

---

#### 4. Newspaper/Magazine Article
**Format:**
- **Headline** (catchy, concise, in CAPS or bold)
- **By-line:** *By [Your Name]* (if required)
- **Lead paragraph:** Answers WHO, WHAT, WHERE, WHEN, WHY, HOW in the first paragraph
- **Body:** Develops the story/argument in inverted pyramid structure (most to least important)
- **Conclusion:** Wider implications or call to action

**Language:** Clear, direct, engaging; active voice preferred; quotations add authority.

---

#### 5. Report
**When used:** School prefect reporting an incident, a student council reporting on a trip, an environmental report.

**Format:**
```
REPORT ON [TOPIC — in caps or bold]
To:    [Recipient]
From:  [Author/Position]
Date:  [Date]
Re:    [Subject] (optional alternative)

1.0 INTRODUCTION
...

2.0 FINDINGS / OBSERVATIONS
2.1 ...
2.2 ...

3.0 CONCLUSIONS
...

4.0 RECOMMENDATIONS
...

[Signature/Name]
```

**Language:** Formal, impersonal, objective. Uses third person. No emotional language.
**Headings and sub-headings** are essential for organisation.

---

#### 6. Dialogue
A written conversation between two or more people.
- Use speech marks correctly
- New speaker = new paragraph
- Show contrasting points of view if the task involves debate/discussion
- Include stage directions if required: *(Kofi enters, looking worried)*

