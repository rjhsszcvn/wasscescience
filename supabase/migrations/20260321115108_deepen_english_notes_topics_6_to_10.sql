### Introduction
Figures of speech are expressions that depart from the ordinary use of language to achieve a special effect — emphasis, clarity, beauty, or emotional impact. They are heavily tested in WASSCE comprehension, poetry analysis, and literary essays.

---

### Comparison Devices

#### 1. Simile
A **direct comparison** of two unlike things using *"like"* or *"as"*.

**Structure:** A is **like** B / A is **as** [adjective] **as** B

**Examples:**
- *His voice was **like** thunder rolling across the sky.*
- *She was **as** patient **as** a saint.*
- *The children scattered **like** startled birds.*
- *Her smile was **as** warm **as** the midday sun.*

**Effect:** Creates a vivid, concrete image; makes abstract ideas more understandable.

---

#### 2. Metaphor
An **implied comparison** stating one thing IS another, without using *"like"* or *"as"*.

**Examples:**
- *Life is a **journey** with no map.*
- *He was a **lion** on the battlefield.*
- *Time is a **thief** that steals our youth.*
- *Her words were **daggers** that cut deep.*

**Extended metaphor:** A metaphor sustained throughout a poem or passage.
*"Life is a game. We are all players, and death is the final whistle."*

---

#### 3. Personification
**Giving human qualities** (feelings, actions, characteristics) to non-human things.

**Examples:**
- *The sun **smiled** down on the village.*
- *Opportunity **knocked** at his door only once.*
- *The wind **whispered** secrets through the trees.*
- *Poverty **gripped** the village with iron hands.*

**Effect:** Makes descriptions vivid and relatable; creates emotional connection.

---

#### 4. Apostrophe
**Addressing** an absent person, a dead person, an abstract idea, or an inanimate object directly as if it could hear.

**Examples:**
- *O Death, **where is thy sting?***
- *Frailty, **thy name is woman!** (Shakespeare)*
- *O Africa, **rise and shine again!***

**Note:** Do NOT confuse with the punctuation apostrophe (').

---

### Exaggeration and Understatement

#### 5. Hyperbole
**Deliberate exaggeration** for emphasis or effect (not meant to be taken literally).

**Examples:**
- *I've told you a **million times**.*
- *He was so tall, his head **touched the clouds**.*
- *I'm so hungry I could **eat a horse**.*
- *The bag weighed **a ton**.*

**Effect:** Creates emphasis; adds humour; expresses intense emotion.

---

#### 6. Litotes
**Deliberate understatement** using a negative to express a positive, often with irony.

**Examples:**
- *"Not bad"* (meaning quite good)
- *"She is no ordinary woman"* (meaning she is exceptional)
- *"It's not the warmest of days"* (about extreme cold)

---

#### 7. Meiosis (Understatement)
Making something seem **less important or serious** than it is.
*"I have a slight headache"* (when one is in severe pain)

---

### Sound Devices

#### 8. Alliteration
The **repetition of the same initial consonant sound** in closely connected words.

**Examples:**
- ***Peter Piper picked** a peck of **pickled peppers**.*
- *The **strong, sturdy soldier** stood still.*
- *The **cool, calm, collected** captain commanded.*

**Effect:** Creates rhythm, musicality; emphasises ideas; aids memory.

---

#### 9. Assonance
The **repetition of vowel sounds** within nearby words (not necessarily at the start).

**Examples:**
- *"I like **bikes** and **nights** and **bright lights**."* (/aɪ/ sound)
- *"The **rain** in **Spain** falls **mainly** on the **plain**."* (/eɪ/ sound)

**Effect:** Creates internal rhyme and musicality.

---

#### 10. Consonance
The **repetition of consonant sounds** within or at the end of words.

**Examples:**
- *"**F**irst and la**st**, fa**st** and lu**st**"* (repeated /st/ and /st/)
- *"The black **b**ack tire trac**k** of the ri**ck** sha**ck**"*

---

#### 11. Onomatopoeia
Words that **imitate the sound** they describe.

**Examples:**
- *The bees **buzzed**. The water **gurgled**. The fire **crackled**.*
- *The tyres **screeched** as the car stopped.*
- *The clock **ticked** loudly in the silence.*

**Common onomatopoeia:** buzz, hiss, crash, bang, splash, whisper, murmur, rustle, clatter, sizzle

---

### Irony and Related Devices

#### 12. Irony
Saying one thing but **meaning the opposite**, or a situation that is the **reverse of what is expected**.

**Types:**
- **Verbal irony:** Words mean the opposite — *"Oh great, another exam!"* (said with frustration)
- **Dramatic irony:** The audience knows something the characters do not (common in plays/novels)
- **Situational irony:** What happens is the opposite of what is expected — *A fire station burns down.*

---

#### 13. Sarcasm
A **sharp, bitter form of verbal irony** intended to mock or hurt.
*"Oh, how clever of you to forget the only thing I asked you to do."*

---

#### 14. Satire
Using **humour, irony, and exaggeration** to criticise and expose the foolishness or vices of people, society, or institutions.
- Targets: politicians, corruption, hypocrisy, social norms
- Works: *Animal Farm* (Orwell), *A Modest Proposal* (Swift)

---

### Structure and Repetition Devices

#### 15. Parallelism
Using **similar grammatical structures** in successive phrases or sentences for balance and rhythm.

*"Government of the people, by the people, for the people."* — Lincoln
*"We shall fight on the beaches, we shall fight on the landing grounds, we shall fight in the fields."* — Churchill

---

#### 16. Anaphora
**Repetition of a word or phrase at the beginning** of successive clauses.
*"Every day we wake up. Every day we struggle. Every day we persevere."*

---

#### 17. Epistrophe
**Repetition at the end** of successive clauses.
*"When I was a child, I spoke as a child, I understood as a child, I thought as **a child**."*

---

#### 18. Oxymoron
Two **contradictory terms** placed together.
- *deafening silence / sweet sorrow / bitter sweet / living death / cruel kindness*

**Effect:** Creates a paradox that captures complex, contradictory realities.

---

#### 19. Paradox
A statement that **seems contradictory or absurd but contains a deeper truth**.
- *"The child is father of the man."* (Wordsworth — our childhood shapes who we become)
- *"I must be cruel only to be kind."* (Shakespeare)

---

### Other Important Devices

#### 20. Euphemism
A **mild, indirect expression** substituted for something harsh or unpleasant.
- *"passed away"* (died) / *"collateral damage"* (civilian deaths) / *"letting someone go"* (firing an employee)

#### 21. Rhetoric / Rhetorical Question
A **question asked for effect**, not expecting an answer.
- *"Can we stand by and watch our nation crumble?"*
- *"Who would want to live in such misery?"*

**Effect:** Engages the audience; emphasises a point; creates emotional impact.

---

#### 22. Antithesis
**Contrasting ideas placed in parallel** to highlight the difference.
- *"It was the best of times, it was the worst of times."* (Dickens)
- *"To err is human; to forgive, divine."* (Pope)

---

#### 23. Symbolism
Using an **object, person, or event to represent something beyond its literal meaning**.
- *Dove = peace / Lion = courage or Britain / Fire = passion or destruction*
- *White = purity or death (context-dependent)*

---

#### 24. Allusion
An **indirect reference** to a person, place, event, or other text (often Biblical, historical, or literary).
- *"He is a modern-day Judas."* (betrayer — allusion to Judas Iscariot)
- *"She faced her Goliath."* (allusion to David and Goliath)

---

### Quick Reference Summary Table

| Device | Key feature | Example |
|--------|-------------|---------|
| Simile | comparison using "like/as" | *as brave as a lion* |
| Metaphor | direct identification | *life is a journey* |
| Personification | human qualities to non-human | *the sun smiled* |
| Hyperbole | exaggeration | *a million times* |
| Alliteration | repeated initial consonant | *Peter Piper* |
| Onomatopoeia | word sounds like meaning | *buzz, crash* |
| Irony | opposite meaning intended | *"What lovely weather!"* (in rain) |
| Oxymoron | contradictory terms together | *deafening silence* |
| Paradox | contradictory but true | *"cruel to be kind"* |
| Anaphora | repetition at start of clauses | *"We shall fight...we shall fight"* |

---

### Answering "Effect" Questions in WASSCE
When asked *"What is the effect of [figure of speech]?"*, use this pattern:

**"The writer uses [figure of speech] to [purpose/effect]. This creates a sense of [emotion/image/idea], which helps the reader [understand/feel/visualise]..."**

Example:
*"The writer uses personification — 'poverty gripped the village' — to make an abstract concept feel physical and menacing. This creates a vivid impression of powerlessness and suffering, helping the reader understand how devastating the economic conditions were."*

