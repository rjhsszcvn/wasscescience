| Text Type | Expected Register |
|-----------|-----------------|
| Formal letter (to official/employer) | Formal |
| Informal letter (to friend/relative) | Informal |
| Report (to headmaster/boss) | Formal |
| Speech (to school assembly) | Semi-formal to formal |
| Article for newspaper | Semi-formal to formal |
| Diary entry | Informal/personal |
| Narrative essay | Semi-formal; can include dialogue in informal register |
| Argumentative essay | Formal |

---

### WASSCE Common Register Mistakes

| Mistake | Explanation |
|---------|------------|
| Using contractions in formal writing | "Don't" → "Do not" in formal essays and letters |
| Using slang in essays | *"The issue is super serious"* → *"The issue is extremely serious"* |
| Wrong salutation tone | Starting a formal letter with *"Hey Boss"* |
| Mixing registers | Starting formally then becoming casual mid-essay |
| Using emotive/exaggerated language in a report | Reports should be objective and factual |

---

### English Across Cultures

English is a **global language** spoken in many varieties:
- **British English** (standard reference for WASSCE)
- **American English** (different vocabulary: *lift/elevator, flat/apartment*)
- **Australian English**, **Indian English**, etc.

**Spelling differences to note:**
