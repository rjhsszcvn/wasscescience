### Overview
Correct punctuation and spelling are tested under **Mechanical Accuracy** in WASSCE essays (up to 10 marks) and in the Lexis and Structure section. Errors in these areas significantly reduce your score.

---

### Punctuation Marks — Full Reference

#### 1. Full Stop (.)
**Uses:**
- End of a declarative (statement) sentence: *The sun sets in the west.*
- End of an imperative sentence: *Close the door.*
- After abbreviations (British English varies): *Dr., etc., e.g., i.e., Mr., Mrs.*
- NOT after acronyms: *UNESCO, WAEC, WHO*

---

#### 2. Comma (,)
**Uses:**
1. **Separating items in a list:** *She bought bread, milk, eggs, and butter.*
   - The serial/Oxford comma before "and" is optional but recommended for clarity.
2. **After introductory elements:** *Although it was raining, we continued.*
3. **Setting off non-defining relative clauses:** *My sister, **who lives in Accra**, called yesterday.* (extra info, removable)
4. **Separating coordinate adjectives:** *a tall, handsome man* (both modify the noun equally)
5. **Before coordinating conjunctions joining main clauses:** *She worked hard, **but** she failed.*
6. **After transitional phrases:** *However, the results were encouraging.*
7. **In direct address:** *"Thank you, **John**."*

**Do NOT use comma:**
- To separate subject from verb: ~~*The man who won, received a prize.*~~
- In defining relative clauses: *The man **who won** received a prize.* (no commas — defines which man)

---

#### 3. Semicolon (;)
**Uses:**
1. **Joining two related independent clauses** (without a conjunction): *I love reading; she prefers writing.*
2. **Separating items in a list when items themselves contain commas:** *The committee included Ama, the chair; Kofi, the secretary; and Yaw, the treasurer.*

**Tip:** A semicolon is stronger than a comma but weaker than a full stop.

---

#### 4. Colon (:)
**Uses:**
1. **Introducing a list:** *He packed three things: a torch, food, and water.*
2. **Introducing a quotation or explanation:** *She had one goal: to pass her exams.*
3. **After a salutation in formal letters:** *Dear Sir:*
4. **Introducing a definition or elaboration:** *Love is simple: it is putting others before yourself.*

---

#### 5. Apostrophe (')
**Uses:**
1. **Possession:**
   - Singular: add 's — *the **boy's** book*, *the **teacher's** pen*
   - Plural ending in -s: add ' only — *the **students'** books*, *the **teachers'** meeting*
   - Irregular plural: add 's — *the **children's** toys*, *the **women's** rights*
2. **Contraction** (missing letters): *don't = do not*, *it's = it is*, *I've = I have*, *she'd = she would/had*

**Common Errors:**
- **Its vs. It's:** *its* (possessive of "it") vs. *it's* (it is/it has)
- **Your vs. You're:** *your* (possessive) vs. *you're* (you are)
- **Their vs. They're vs. There:** possession / they are / place

---

#### 6. Question Mark (?)
- After direct questions: *Where are you going?*
- NOT after indirect questions: *He asked **where she was going**.*

---

#### 7. Exclamation Mark (!)
- After exclamations: *What a wonderful idea!*
- After interjections: *Oh! Alas! Bravo!*
- **WASSCE advice:** Use sparingly in formal writing — at most once.

---

#### 8. Quotation Marks (" " or ' ')
**Uses:**
1. **Direct speech:** *She said, "I will be there on time."*
2. **Titles of shorter works:** short stories, articles, poems — *"The Jaguar" is a vivid poem.*
3. **Quoting from a text**
4. **Highlighting a specific term:** *The term "globalisation" means different things to different people.*

**Rules for punctuating dialogue:**
- Punctuation goes **inside** the closing quotation mark: *"I am ready," she said.*
- New speaker = new paragraph
- Reporting clause can come before, in the middle, or after direct speech

---

#### 9. Hyphen (-) and Dash (—)

**Hyphen:** joins two words acting as one modifier — *a **well-known** author, a **ten-year-old** child*
- Also in compound nouns: *mother-in-law, self-confidence, twenty-one*

**Dash (em dash):** marks a break in thought or adds an emphatic aside:
*She achieved everything she wanted — wealth, fame, and happiness — but felt empty inside.*

---

#### 10. Brackets / Parentheses ( )
Add extra, non-essential information: *The population of the city (estimated at five million) is growing rapidly.*

---

#### 11. Ellipsis (...)
Indicates omission or a trailing off: *"I wanted to go, but..."*
In quoting: indicates words omitted from a quotation.

---

### Capitalisation Rules

Always capitalise:
- First word of a sentence
- Proper nouns: names of people, places, organisations, titles — *President Akufo-Addo, River Volta, ECOWAS*
- Days of the week and months: *Monday, January*
- Titles before names: *Dr. Mensah, Professor Asante* (but not after: *Kofi Mensah, a professor*)
- The pronoun "I"
- First word of direct speech: *He said, "**T**his is important."*

---

### Spelling Rules and Patterns

#### The -ie / -ei Rule
*"I before E except after C (when the sound is /iː/)"*
- ie words: believe, achieve, grief, niece, field, piece
- ei words after C: receive, perceive, deceive, ceiling, receipt
- Exceptions: weird, seize, neither, leisure, foreign

#### Doubling Consonants Before Suffixes
Double the final consonant when the word:
1. Has one syllable
2. Ends in a single consonant
3. After a single vowel

*run → running, sit → sitting, stop → stopped*
BUT: *visit → visited* (two syllables, stress on first), *rain → rained* (two vowels before consonant)

#### Dropping the Final -e
Drop the -e before a vowel suffix: *write → writing, love → lovable*
Keep the -e before a consonant suffix: *love → lovely, hope → hopeful*
Exceptions: *argue → argument, judge → judgement*

#### Adding -ly
- Usually just add: *careful → carefully, slow → slowly*
- Words ending in -le: change to -ly → *simple → simply, gentle → gently*
- Words ending in -y: change y to i → *happy → happily, easy → easily*

