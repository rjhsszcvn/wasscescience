### Proofreading Strategy

Before submitting any written work in WASSCE:
1. **Read slowly** — do not read what you *meant* to write
2. Check every sentence ends with correct punctuation
3. Check every proper noun is capitalised
4. Check apostrophes (possession vs. contraction)
5. Read for commonly confused words (its/it's, their/there/they're, affect/effect)
6. Check subject-verb agreement in each sentence
7. Verify spelling of any words you are unsure about

