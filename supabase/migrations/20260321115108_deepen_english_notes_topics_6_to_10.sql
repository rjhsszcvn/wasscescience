### Directed Writing Strategy

**Step 1: Analyse the question**
- What TEXT TYPE is required? (letter, article, speech, report?)
- Who is the AUDIENCE? (formal/informal?)
- What is the PURPOSE? (inform, persuade, complain, congratulate?)
- What INFORMATION is given to you that you must include?
- What is the WORD LIMIT?

**Step 2: Plan**
- Note the format conventions for the text type
- List the key points you will make
- Identify appropriate register and language features

**Step 3: Write**
- Follow the format precisely — marks are given for correct format
- Use appropriate opening and closing conventions
- Organise body paragraphs logically
- Match tone and register to audience

**Step 4: Review**
- Check format elements (address, date, salutation, sign-off)
- Check register consistency
- Proofread for grammar, spelling, punctuation

