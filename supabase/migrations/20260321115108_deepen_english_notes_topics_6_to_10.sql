### What Is a Summary?
A summary is a **concise restatement of the key information** from a passage, written in your own words, without opinion or irrelevant detail. WASSCE Summary questions test your ability to identify main ideas, distinguish them from supporting details, and communicate them precisely.

---

### Why Summary Writing Matters in WASSCE
- Tested in **Paper 2 (Section B)**
- Requires selecting and condensing information from a passage (usually 400–600 words) into a much shorter form (often 80–120 words)
- Tests: reading comprehension, vocabulary, grammar, and conciseness

---

### Steps for Writing an Excellent Summary

#### Step 1: Read the Passage Thoroughly
- Read once for overall meaning
- Read again and annotate/underline main ideas in each paragraph
- Ask: *"What is this passage mainly about?"*

#### Step 2: Identify the Question Focus
WASSCE summary questions are usually **focused** — not a general summary of everything, but summary of *specific aspects* (e.g., "Summarise the effects of deforestation mentioned in the passage").
- Circle the key instruction words in the question
- Only include points **relevant** to what is asked

#### Step 3: List the Main Points
- Write the main ideas **in your own words** as a numbered list (rough notes)
- Aim for 6–10 points depending on the word limit and marks allocated
- **Omit:** examples, repetitions, illustrations, quotations, and anecdotes — unless they contain unique factual information

#### Step 4: Write the Summary in Continuous Prose
- Begin with a sentence that introduces the topic: *"The passage discusses..."* / *"According to the passage..."*
- Connect points using discourse markers: *Furthermore, In addition, However, Moreover, Finally*
- **Do not copy long phrases** from the original — paraphrase
- Keep it within the **specified word limit**

#### Step 5: Count and Review
- Count words carefully
- Ensure you have covered the required number of points
- Check grammar, punctuation, and spelling

---

### What to Include and What to Omit

| INCLUDE | OMIT |
|---------|------|
| Main ideas and arguments | Examples and illustrations |
| Key facts and findings | Direct quotations |
| Causes and effects stated | Repetitions of the same point |
| Important conclusions | Opinions not in the passage |
| Specific instructions if asked | Background information / introductory remarks |

---

### Summary Writing Rules

**1. Use YOUR OWN words**
The most common error is lifting sentences directly from the passage. WASSCE markers deduct heavily for this. Paraphrase by:
- Using synonyms: *"important" → "significant", "crucial"*
- Changing sentence structure: passive → active, or vice versa
- Combining ideas from two sentences into one

**2. Maintain the Meaning**
Do not alter the meaning while paraphrasing. A summary that changes facts or introduces new ideas is incorrect.

**3. Write in Complete Sentences**
Unless asked for notes/points, write in continuous prose.

**4. Stay Within the Word Limit**
WASSCE imposes strict limits. Going significantly over or under can cost marks.

**5. Do Not Include Your Opinion**
A summary is entirely based on the original text. Do not add your views.

---

### Language for Summaries

**Introducing:**
- *The passage discusses / explains / argues that...*
- *According to the writer...*
- *The author identifies / highlights / points out...*

**Sequencing:**
- *Firstly... Secondly... Thirdly...*
- *In addition to this... Furthermore... Moreover...*
- *Finally... Lastly...*

**Contrasting:**
- *However... On the other hand... Nevertheless...*

**Concluding:**
- *In conclusion, the writer asserts that...*
- *The passage ends by noting that...*

---

### Common Summary Mistakes

| Mistake | How to Avoid |
|---------|-------------|
| Copying phrases directly | Paraphrase using synonyms and different structures |
| Including examples | Focus on the point the example illustrates, not the example itself |
| Going over the word limit | Plan and count; cut less important points |
| Missing key points | Re-read question to confirm you addressed all required aspects |
| Changing the meaning | Check paraphrase against the original |
| Writing in note form when not asked | Always write complete sentences unless told otherwise |
| Adding personal opinion | Only report what is in the passage |

---

### Worked Example

**Passage extract (shortened):**
*"Deforestation has had devastating consequences for the environment. Firstly, it has led to widespread soil erosion because trees that previously held the soil in place are gone. Heavy rains now wash away the fertile topsoil, leaving behind barren land unable to support crops. Secondly, the loss of trees has significantly reduced rainfall in many regions, as forests play a crucial role in the water cycle by absorbing and releasing moisture. Farmers who depended on consistent rainfall for their crops now face unpredictable seasons and poor harvests."*

**Question:** *"In not more than 60 words, summarise the effects of deforestation described in the passage."*

**Sample Answer (55 words):**
*According to the passage, deforestation causes serious environmental harm. Without trees to anchor the soil, heavy rains erode fertile topsoil, rendering farmland infertile. Additionally, the removal of forests disrupts the water cycle, resulting in reduced and unpredictable rainfall. Consequently, farmers suffer poor harvests as they can no longer rely on consistent rains to sustain their crops.*

**Analysis:** Paraphrased (no direct copying), covers both main effects (soil erosion + reduced rainfall), within word limit, complete sentences.

---

### Marking Scheme (Typical WASSCE)
- **Points (content):** Usually 1 mark per valid, distinct point (up to 8–10 points available)
- **Expression:** Up to 4–5 marks for quality of paraphrasing, grammar, and flow
- **Penalty:** Marks deducted for exceeding word limit (after a grace of a few words)

