### Common Directed Writing Errors

| Error | How to Avoid |
|-------|-------------|
| Wrong salutation | Formal = "Dear Sir/Madam"; Informal = "Dear Kofi" |
| Wrong sign-off | "Yours faithfully" (unnamed recipient); "Yours sincerely" (named) |
| Ignoring the given information | Re-read question — use ALL provided information |
| No proper format | Letters need address, date; reports need headings |
| Wrong register | Formal letter should NOT sound like a text message |
| Forgetting the audience | Always ask: who am I writing to? |
| No clear purpose in opening | State your purpose in the first paragraph |

---

### Marking Rubric (WASSCE Directed Writing)

| Criteria | What Markers Look For |
|----------|----------------------|
| **Format (5 marks)** | Correct layout, headings, address, date, salutation, sign-off |
| **Content (10 marks)** | Relevance, completeness, use of provided information |
| **Organisation (10 marks)** | Logical flow, paragraphing, coherence |
| **Register & Language (15 marks)** | Appropriate formality, vocabulary, grammar, punctuation |

