### Sample Question and Response Plan

**Question:** *"Write a letter to the Minister of Education recommending three improvements to the secondary school system in your country. Use the information provided below and add your own ideas."*

**Plan:**
- **Format:** Formal letter (your address, date, minister's address, "Dear Minister," subject line, "Yours faithfully")
- **Audience:** Senior government official — very formal
- **Purpose:** Recommend improvements
- **Para 1:** Purpose of letter — writing to respectfully recommend improvements
- **Para 2:** First recommendation (from provided info + own elaboration)
- **Para 3:** Second recommendation
- **Para 4:** Third recommendation
- **Para 5:** Conclude — express hope for action, offer further information

