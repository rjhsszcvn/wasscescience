## 10. Interpreting Land Use from Maps

Land use can be inferred from map evidence:

| Map Evidence | Likely Land Use |
|-------------|----------------|
| Many houses close together, streets, roads | Urban residential |
| Large buildings with car parks | Commercial/Industrial |
| Green areas with no buildings | Forest, farmland, or parkland |
| Blue (water) areas | Rivers, lakes, reservoirs |
| Contour lines only, no buildings | Rural, possibly agricultural |
| Dotted areas with isolated buildings | Farmsteads, scattered settlement |

