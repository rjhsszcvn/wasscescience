## 4. Population Density Calculations

**Formula:**

Population Density = Total Population ÷ Total Area (km²)

**Example:** If Nigeria has a population of 220 million people and an area of 923,768 km²:

Population density = 220,000,000 ÷ 923,768 = approximately 238 persons/km²

