## 1. Introduction to Maps

**Definition:** A map is a flat (two-dimensional) representation of all or part of the Earth's surface drawn to scale from above.

Maps are essential tools in geography for:
- Showing the location of places and features.
- Calculating distances and areas.
- Understanding relief (shape of the land).
- Planning routes and land use.

---

## 2. Types of Maps

| Type | Description | Examples |
|------|-------------|---------|
| Topographic map | Shows physical features (relief, rivers, vegetation) and human features (roads, settlements) | Ghana Survey Map 1:50,000 |
| Physical map | Emphasises natural features — relief, rivers, climate | Atlas physical maps |
| Political map | Shows countries, capitals, borders | World political maps |
| Thematic map | Shows distribution of a specific theme | Population density, rainfall maps |
| Sketch map | A rough, freehand map drawn to approximate scale | Field study maps |

---

## 3. Map Scale

**Definition:** Scale is the relationship between distance on a map and the actual distance on the ground.

### Types of Scale:

**1. Statement Scale (Verbal Scale):**
Written in words.
Example: "One centimetre represents two kilometres" or "1 cm to 2 km"

**2. Representative Fraction (RF) / Ratio Scale:**
Written as a fraction or ratio.
Example: 1:50,000 means 1 cm on the map = 50,000 cm (500 m) on the ground.
Example: 1:250,000 means 1 cm = 2.5 km on the ground.

**3. Linear Scale (Bar Scale):**
A line drawn on the map, divided into segments representing actual distances.
Useful because it remains accurate even if the map is enlarged or reduced.

### Converting RF to Statement Scale:

1:50,000 → 50,000 cm = 500 m = 0.5 km
So: 1 cm on map = 0.5 km on ground
Statement: "One centimetre represents half a kilometre"

### Calculating Distances on a Map:

**Straight-line distance:**
1. Use a ruler to measure the distance in cm on the map.
2. Multiply by the scale to get the actual distance.

**Example:** If two towns are 6 cm apart on a 1:50,000 map:
Actual distance = 6 × 50,000 cm = 300,000 cm = 3,000 m = **3 km**

**Winding distance (road/river):**
1. Use a piece of string or thin paper strip, following the curves of the road/river.
2. Straighten the string/paper against the linear scale.
3. Read off the distance.

---

## 4. Direction

Direction is expressed using:

**1. The Compass Rose:**
- 4 Cardinal points: North (N), South (S), East (E), West (W).
- 4 Intercardinal points: NE, NW, SE, SW.
- 8 Secondary points: NNE, ENE, ESE, SSE, SSW, WSW, WNW, NNW.

**2. Bearings (Three-figure bearings):**
- Measured clockwise from North (000°).
- Always written as three figures.
- North = 000°, East = 090°, South = 180°, West = 270°.

**Example:** 
- NE = 045°
- SW = 225°
- If you are facing 135°, you are facing SE.

