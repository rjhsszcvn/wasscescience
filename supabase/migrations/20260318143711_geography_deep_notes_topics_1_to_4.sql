## 2. Population Distribution in West Africa

**Definition:** Population distribution refers to how people are spread across an area — it is rarely even (uniform).

### Densely Populated Areas in West Africa:

1. **Coastal areas** — e.g., Lagos, Accra, Freetown, Monrovia. Good ports, trade, employment.
2. **River valleys** — fertile land for farming, water supply.
3. **Urban/industrial centres** — employment opportunities attract people.
4. **Fertile savanna zones** — good for agriculture.

### Sparsely Populated Areas in West Africa:

1. **The Sahara Desert and Sahel** — extreme heat, very little rainfall, poor soils.
2. **Dense rainforests** — difficult to clear, disease (malaria), poor soils under forest.
3. **Flood-prone river areas** — uninhabitable during floods.
4. **Areas with poor soils** — limited agricultural potential.

