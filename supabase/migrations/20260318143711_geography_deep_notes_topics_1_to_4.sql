## 8. Cross Sections and Profiles

A **cross section** (profile) is a side view of the land along a straight line on a map, showing the shape of the relief.

**How to draw a cross section:**
1. Draw a line between two points on the map.
2. Place the edge of paper along this line and mark where each contour line crosses.
3. Transfer these marks to graph paper; the x-axis represents horizontal distance and the y-axis represents height.
4. Plot each point at its correct height.
5. Join the points with a smooth curve.

**Vertical exaggeration:** Cross sections are often drawn with a vertical scale larger than horizontal — this exaggerates the height differences to make the shape clearer. Always state the vertical exaggeration.

**Formula:** Vertical Exaggeration = Vertical Scale ÷ Horizontal Scale

