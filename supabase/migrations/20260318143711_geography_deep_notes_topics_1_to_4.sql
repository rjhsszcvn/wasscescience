## 1. Introduction to the Earth's Structure

The Earth is made up of four distinct layers:

| Layer | Depth | Description |
|-------|-------|-------------|
| Crust | 0–70 km | Thin outermost layer; oceanic (denser, basaltic) and continental (lighter, granitic) |
| Mantle | 70–2,900 km | Semi-molten rock (magma); convection currents drive plate movement |
| Outer Core | 2,900–5,100 km | Liquid iron and nickel; generates Earth's magnetic field |
| Inner Core | 5,100–6,371 km | Solid iron and nickel; extremely hot (~5,500°C) |

**Key Definition:** The **lithosphere** is the rigid outer shell of the Earth consisting of the crust and the uppermost mantle. It is broken into large segments called **tectonic plates**.

---

## 2. Tectonic Plates

**Definition:** Tectonic plates are large, rigid slabs of rock that make up the Earth's lithosphere. There are approximately 15 major plates and several minor ones.

### Major Tectonic Plates

- African Plate
- Eurasian Plate
- North American Plate
- South American Plate
- Indo-Australian Plate
- Pacific Plate
- Antarctic Plate

### Why Plates Move

Plates move because of **convection currents** in the mantle. Heat from the Earth's core causes mantle rock to rise, spread out, cool, and sink — creating a continuous circular motion that drags the plates above.

**Average speed of plate movement:** 2–15 cm per year (about the rate your fingernails grow).

---

## 3. Types of Plate Boundaries

### A. Convergent Boundaries (Plates Moving Together)

Two plates move towards each other. Three subtypes:

**1. Oceanic-Continental Convergence:**
- The denser oceanic plate is forced under the lighter continental plate — this is called **subduction**.
- The subducting plate melts and forms **magma**.
- Results in: deep ocean trenches, fold mountains, volcanoes.
- **Example:** Andes Mountains (South America), Peru-Chile Trench.

**2. Oceanic-Oceanic Convergence:**
- One oceanic plate subducts beneath another.
- Results in: ocean trenches, island arcs (chains of volcanic islands).
- **Example:** Mariana Trench (deepest point on Earth), Japanese island arc.

**3. Continental-Continental Convergence:**
- Neither plate subducts (both are too light/buoyant).
- Rocks are compressed, buckled, and pushed up to form **fold mountains**.
- Results in: no volcanoes, but severe earthquakes and the highest mountains.
- **Example:** Himalayas (Indian Plate colliding with Eurasian Plate).

---

### B. Divergent Boundaries (Plates Moving Apart)

Two plates move away from each other.

**At mid-ocean ridges:**
- Magma rises from the mantle to fill the gap, creating new oceanic crust.
- This process is called **sea-floor spreading**.
- Results in: mid-ocean ridges, rift valleys, volcanic activity.
- **Example:** Mid-Atlantic Ridge (Iceland sits on this ridge and is volcanically active).

**On land:**
- Results in: rift valleys, lakes in the valley floor.
- **Example:** East African Rift Valley (Great Rift Valley) — stretching from Ethiopia to Mozambique.

---

### C. Transform/Conservative Boundaries (Plates Sliding Past)

Two plates slide horizontally past each other.

- No crust is created or destroyed.
- Results in: severe earthquakes, fault lines.
- **No volcanic activity.**
- **Example:** San Andreas Fault (California, USA) — Pacific Plate sliding past North American Plate.

---

## 4. Volcanoes

**Definition:** A volcano is an opening or rupture in the Earth's crust through which hot lava, volcanic ash, and gases escape.

### Types of Volcanoes

| Type | Shape | Eruption | Example |
|------|-------|----------|---------|
| Shield Volcano | Broad, flat, dome-shaped | Gentle, flows of basaltic lava | Mauna Loa (Hawaii) |
| Composite/Strato-volcano | Steep-sided cone | Violent, explosive | Mount Fuji (Japan), Mount St. Helens |
| Cinder Cone | Small, steep | Moderate, ash and cinders | Paricutin (Mexico) |

### Products of Volcanic Eruptions

- **Lava:** Molten rock that reaches the surface.
- **Pyroclasts:** Fragments of rock ejected (ash, cinders, bombs).
- **Gases:** Water vapour, carbon dioxide, sulphur dioxide.
- **Lahar:** A volcanic mudflow — extremely destructive.

### Benefits of Volcanoes

1. Volcanic soil (from weathered lava) is extremely fertile — good for farming.
2. Geothermal energy (e.g., Iceland generates most electricity from geothermal sources).
3. Tourism (e.g., Yellowstone, Hawaii, Vesuvius attract millions of visitors).
4. Creation of new land (e.g., Hawaiian Islands).
5. Mineral deposits — valuable minerals are found near volcanic regions.

### Hazards of Volcanoes

1. Destruction of settlements, farmland, and infrastructure.
2. Loss of life from lava flows, ash falls, and lahars.
3. Air pollution from volcanic gases.
4. Disruption of aviation (ash clouds).
5. Tsunamis triggered by undersea eruptions.

---

## 5. Earthquakes

**Definition:** An earthquake is a sudden, rapid shaking of the ground caused by the release of energy stored in rocks as tectonic plates move.

### Key Vocabulary

- **Focus (Hypocentre):** The point inside the Earth where the earthquake originates.
- **Epicentre:** The point on the Earth's surface directly above the focus.
- **Seismic waves:** Vibrations that travel outward from the focus through the Earth.
- **Seismograph:** Instrument used to detect and record seismic waves.
- **Richter Scale:** A logarithmic scale (1–10) measuring earthquake magnitude. Each step is 10× more powerful.
- **Mercalli Scale:** Measures the intensity/effects of an earthquake at a specific location.

### Types of Seismic Waves

- **P-waves (Primary/Compressional):** Fastest; travel through solids and liquids; push-pull motion.
- **S-waves (Secondary/Shear):** Slower; only travel through solids; side-to-side motion.
- **Surface waves (L-waves):** Slowest; cause most damage at the surface.

### Effects of Earthquakes

**Primary effects (direct):**
- Ground shaking, surface rupture, landslides.
- Buildings and bridges collapse.
- Deaths and injuries.

**Secondary effects (indirect):**
- Fires from broken gas pipes.
- Tsunamis (if epicentre is under the ocean).
- Flooding from burst water mains.
- Disease outbreaks from contaminated water.

### Tsunamis

**Definition:** A tsunami is a series of enormous ocean waves caused by an underwater earthquake, volcanic eruption, or landslide.

- Waves can travel at speeds of 800 km/h in the open ocean.
- Can reach heights of 30+ metres when they reach shallow coastal water.
- **Example:** 2004 Indian Ocean Tsunami (caused by a 9.1 magnitude earthquake off Sumatra) — killed over 230,000 people.

---

## 6. Distribution of Earthquakes and Volcanoes

Most earthquakes and volcanoes occur:
1. Along plate boundaries — especially around the **Pacific Ring of Fire**.
2. At mid-ocean ridges (divergent boundaries).
3. At hot spots (e.g., Hawaii).

**The Pacific Ring of Fire** is a horseshoe-shaped zone around the Pacific Ocean where about 75% of the world's volcanoes and 90% of the world's earthquakes occur.

---

## 7. Plate Tectonics in West Africa

- West Africa sits on the **African Plate**.
- The African Plate is moving northward, causing the Mediterranean Sea to narrow.
- The **East African Rift Valley** is a divergent boundary on the African continent — evidence that Africa is slowly splitting apart.
- West Africa itself is relatively tectonically stable (far from active plate boundaries), explaining the low seismic activity in the region.

