## 5. Population Growth

### Factors Increasing Population:

- High birth rates (large families, cultural norms, lack of family planning).
- Falling death rates (improved healthcare, clean water, better nutrition).
- Immigration (people moving in from other areas).

### Factors Decreasing Population:

- High death rates (disease, famine, conflict).
- Low birth rates (education of women, access to contraception).
- Emigration (people moving out — e.g., brain drain in Ghana and Nigeria).

### The Demographic Transition Model (DTM)

The DTM shows how population changes over time as a country develops:

| Stage | Birth Rate | Death Rate | Population Change | Countries |
|-------|-----------|-----------|-------------------|-----------|
| Stage 1 | High | High | Stable (low) | Historical (pre-industrial) |
| Stage 2 | High | Falling | Rapid growth | Many African countries |
| Stage 3 | Falling | Low | Slowing growth | Brazil, India |
| Stage 4 | Low | Low | Stable (high) | UK, USA, Europe |
| Stage 5 | Very low | Low | Slight decline | Japan, some European countries |

