## 9. Area Calculation

To calculate the area of a feature on a map:

**1. Regular shapes:** Use the formula (length × width) and convert using scale.

**2. Irregular shapes (grid square method):**
- Count all complete grid squares within the area = A.
- Count all partial squares and divide by 2 = B.
- Total squares = A + B.
- Multiply by the area of one grid square (in km²).

**Example:** On a 1:50,000 map, one grid square = 1 km × 1 km = 1 km².

