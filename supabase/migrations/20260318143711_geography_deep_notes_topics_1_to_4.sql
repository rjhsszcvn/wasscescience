## 3. Factors Affecting Population Distribution

### Physical Factors:

- **Climate:** Areas with moderate, reliable rainfall attract more people (farming).
- **Relief:** Flat, low-lying areas are easier to settle and farm; steep mountains are less populated.
- **Water supply:** Rivers, lakes, and rainfall ensure populations concentrate near water.
- **Soils:** Fertile soils attract farming communities.
- **Natural hazards:** Areas prone to floods, volcanoes, or drought are less populated.

### Human Factors:

- **Employment:** Industrial and commercial centres attract workers.
- **Transport:** Areas with good roads and railways grow faster.
- **Historical:** Some areas were settled early for trade, defense, or religion.
- **Politics:** Capital cities and government centres attract population.

