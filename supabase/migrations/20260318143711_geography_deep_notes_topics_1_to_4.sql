## 1. Key Definitions

**Weather** is the day-to-day condition of the atmosphere at a specific place and time, including temperature, rainfall, humidity, wind, and cloud cover.

**Climate** is the average weather conditions of a place over a long period of time (usually 30 years or more).

**Microclimate** is the climate of a very small, local area (e.g., the climate inside a valley or forest) which differs from the surrounding region.

---

## 2. Elements of Weather and Climate

| Element | Definition | How Measured | Instrument |
|---------|-----------|--------------|------------|
| Temperature | Degree of hotness or coldness | Degrees Celsius (°C) | Thermometer |
| Rainfall/Precipitation | Water falling from atmosphere | Millimetres (mm) | Rain gauge |
| Humidity | Amount of moisture in the air | Percentage (%) | Hygrometer |
| Atmospheric Pressure | Weight of air pressing down | Millibars (mb) | Barometer |
| Wind Speed | Rate of air movement | Km/h or Beaufort scale | Anemometer |
| Wind Direction | Direction from which wind blows | Compass points (N, S, E, W) | Wind vane |
| Cloud Cover | Amount of sky covered by cloud | Oktas (0–8) | Observation |
| Sunshine Hours | Duration of bright sunshine | Hours | Campbell-Stokes recorder |

---

## 3. Factors Affecting Climate

### A. Latitude

- The higher the latitude (further from the equator), the colder the climate.
- At the equator, the Sun's rays strike the Earth at a high angle (more concentrated energy) — so temperatures are high.
- At the poles, the Sun's rays are spread over a larger area (low angle) — so temperatures are cold.
- This is why West Africa, being close to the equator, is generally hot throughout the year.

### B. Altitude (Height Above Sea Level)

- Temperature decreases with altitude at a rate of approximately 6.5°C per 1,000 metres — this is the **environmental lapse rate**.
- High mountains are cold even near the equator (e.g., Mount Kilimanjaro in Tanzania has permanent snow despite being near the equator).
- Higher altitudes receive more rainfall (orographic/relief rainfall).

### C. Distance from the Sea (Continentality)

- Coastal areas have a **maritime climate** — mild summers, mild winters, and rainfall throughout the year. The sea moderates temperatures.
- Areas far inland have a **continental climate** — hot summers, very cold winters, low rainfall.
- **Example:** Accra (coastal) has a more moderate temperature range than Tamale (inland northern Ghana).

### D. Ocean Currents

- **Warm ocean currents** raise air temperatures and increase rainfall along coasts they pass.
- **Cold ocean currents** lower air temperatures and reduce rainfall, causing coastal deserts.
- **Example:** The cold Benguela Current along the Namibian coast creates the Namib Desert.
- **Example:** The warm Guinea Current along West Africa's coast contributes to high humidity.

### E. Prevailing Winds

- Winds carry moisture or dryness from their source region.
- **The Harmattan** — a dry, dusty north-easterly wind from the Sahara Desert — blows over West Africa from November to March, bringing dry, dusty, and hazy conditions.
- **The South-West Monsoon** — a moisture-laden wind from the Atlantic Ocean — brings heavy rain to West Africa from April/May to October.

### F. Aspect

- The direction a slope faces (its aspect) affects temperature.
- In the Northern Hemisphere, south-facing slopes receive more sun.
- In West Africa (Northern Hemisphere), slopes facing south are warmer and drier.

---

## 4. Types of Rainfall

### A. Convectional Rainfall (Common in West Africa)

1. The Sun heats the ground intensely.
2. Air near the ground becomes warm and rises rapidly (convection).
3. As the air rises, it cools and water vapour condenses to form cumulonimbus clouds.
4. Heavy thunderstorms and rainfall occur, usually in the afternoon.
5. Common in equatorial regions and during West Africa's wet season.

### B. Relief (Orographic) Rainfall

1. Moist air from the sea is forced upward by a mountain or hill.
2. As the air rises, it cools below the dew point — clouds form.
3. Rain falls on the **windward** side (facing the wind).
4. As air descends on the **leeward** side (away from wind), it warms and dries — creating a **rain shadow**.
5. **Example:** The south-facing slopes of the Cameroon Highlands receive very heavy rainfall.

### C. Frontal (Cyclonic) Rainfall

1. A mass of warm, moist air meets a mass of cold, dense air.
2. The lighter warm air is forced to rise over the cold air at a **front**.
3. As warm air rises, it cools, condenses, and produces rainfall.
4. Common in temperate regions (UK, Europe).

---

## 5. Climatic Zones of West Africa

West Africa has several distinct climatic zones arranged in roughly parallel bands from south to north:

| Zone | Location | Rainfall | Temperature |
|------|----------|---------- |-------------|
| Equatorial/Rainforest | Coastal south (Sierra Leone, Liberia, south Ghana/Nigeria) | 2,000–4,000 mm/year; no dry season | 25–30°C all year |
| Tropical Wet-Dry (Guinea Savanna) | Middle belt | 1,000–2,000 mm; clear wet and dry seasons | 25–35°C |
| Sudan Savanna | Further north | 500–1,000 mm; long dry season | Hot; very hot dry season |
| Sahel | Near Sahara border | Under 500 mm; very unreliable | Extreme heat; cold nights |
| Desert | Sahara | Under 250 mm | Extreme heat (up to 50°C) |

---

## 6. The Inter-Tropical Convergence Zone (ITCZ)

**Definition:** The ITCZ is a belt of low pressure near the equator where the trade winds from the Northern and Southern Hemispheres converge (meet). It is also called the **Intertropical Front (ITF)** in West Africa.

**How it controls West Africa's seasons:**
- When the ITCZ moves northward (May–October), it brings the south-west monsoon winds and the **wet season** to most of West Africa.
- When the ITCZ moves southward (November–April), the dry Harmattan winds dominate — this is the **dry season**.
- The further north you go, the shorter the wet season and the longer the dry season.

---

## 7. The Harmattan Wind

- A dry, dusty, cool north-east trade wind.
- Originates over the Sahara Desert.
- Blows across West Africa from November to March.
- Carries large quantities of fine dust (the "harmattan haze").
- Effects: poor visibility, cracked skin and lips, respiratory problems, dry vegetation, risk of bush fires.
- In coastal areas, the Harmattan may reduce temperatures noticeably.

---

## 8. Humidity and Condensation

- **Absolute humidity:** The actual amount of water vapour in the air (g/m³).
- **Relative humidity:** The amount of water vapour in the air as a percentage of the maximum it could hold at that temperature.
- When relative humidity reaches **100%**, the air is saturated — this is the **dew point**.
- Condensation occurs when air cools below the dew point → forms dew, mist, fog, or clouds.

---

## 9. Reading Climate Graphs (Climographs)

A climate graph shows monthly temperature (line graph) and monthly rainfall (bar graph) on the same diagram.

**How to read a climate graph:**
1. Identify the highest and lowest temperatures — the difference is the **temperature range**.
2. Identify the wettest and driest months.
3. Determine the number of dry months (below 60mm rainfall is often used as the threshold).
4. Use these patterns to identify the climate type.

**For an equatorial climate:** High temperatures all year (25–30°C), small temperature range, rainfall every month (no dry season), two rainfall peaks.

**For a savanna climate:** High temperatures all year, large temperature range, distinct wet and dry seasons.

