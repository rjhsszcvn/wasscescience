## 5. Grid References

Most topographic maps use a **grid system** — a network of horizontal and vertical lines dividing the map into squares.

**Grid squares** are numbered along the bottom (eastings) and up the side (northings).

**Four-figure grid reference:** Identifies a whole grid square.
- Read the easting first (along the bottom), then the northing (up the side).
- Memory tip: **"Along the corridor, then up the stairs"** (Easting first, Northing second).
- Example: Grid reference 3452 → easting 34, northing 52.

**Six-figure grid reference:** Identifies a precise point within a square.
- Divide each grid square into 10 × 10 imaginary sub-squares.
- Add a third digit to easting and northing.
- Example: 342527 → easting 34.2, northing 52.7.

