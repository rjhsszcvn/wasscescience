## 6. Relief and Contour Lines

**Relief** refers to the shape and height of the land.

**Contour lines** are lines on a map that join places of equal height (altitude) above sea level.

### Rules of Contour Lines:

1. Every point on a contour line is at the same height.
2. Contour lines never cross each other (two different heights cannot occupy the same point).
3. **Closely spaced contours** = steep slope.
4. **Widely spaced contours** = gentle slope.
5. **Concentric (closed) circles** = hill or mountain peak.
6. Contour lines that cross a valley form a **V-shape pointing upstream** (uphill).
7. The vertical difference between adjacent contour lines is called the **contour interval** (commonly 10m, 20m, or 40m).

### Identifying Relief Features from Contours:

| Feature | Contour Pattern |
|---------|----------------|
| Hill / Mountain | Closed circles (innermost = summit) |
| Valley | V-shapes pointing upstream |
| Ridge | Elongated oval; high in middle |
| Escarpment | Very close contours on one side, wide on other |
| Plateau | Large flat area with closely spaced contours at the edges |
| Spur | V-shapes pointing downstream |
| Col / Saddle | Low point between two hills |

