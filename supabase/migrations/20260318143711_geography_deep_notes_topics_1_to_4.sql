## 6. Population Pyramids

A population pyramid is a double bar graph showing the age and sex structure of a population.

**Characteristics of a Stage 2 (West African type) pyramid:**
- Wide base — high birth rate, many young children.
- Narrow top — low life expectancy, few elderly people.
- Roughly triangular shape.
- More males than females at young ages; more females at older ages.

**Characteristics of a Stage 4 (developed country) pyramid:**
- Narrow base — low birth rate.
- Wide top — many elderly people (high life expectancy).
- More rectangular shape.

